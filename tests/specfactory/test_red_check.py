"""Tests for scripts/specfactory/red_check.py --forbid: a red test that is red
on a forbidden exception class (a dropped keyword, a wrong ctypes row, a
missing symbol) is listed and fails the check; a red test that is red on an
assertion passes it; a placeholder control (gen_controls.py marker) is
excluded; a passing test still fails the check."""
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
RED_CHECK = REPO / "scripts" / "specfactory" / "red_check.py"

PLACEHOLDER = '''"""Positive control for OM_BUG_FIXTURE.

Generated by scripts/specfactory/gen_controls.py. Requires OM_BUG_FIXTURE.
"""


class OMBug:
    pass


def test_control_fixture_trips_the_detector():
    OMBug.FIXTURE
    raise NotImplementedError("fill in")
'''


def _run(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(RED_CHECK), *args], capture_output=True, text=True)


def test_forbidden_class_is_listed_and_assertion_failure_is_not(tmp_path):
    f = tmp_path / "test_fixture_forbid.py"
    f.write_text(
        "def test_missing_symbol():\n"
        "    class Lib: pass\n"
        "    Lib().om_nothing(1)\n"
        "\n"
        "def test_red_on_assertion():\n"
        "    assert 1 == 2\n"
        "\n"
        "def test_dropped_keyword():\n"
        "    def f(a): return a\n"
        "    f(1, chapter=2)\n"
    )
    proc = _run("--forbid", "TypeError,ArgumentError,AttributeError", str(f))
    assert proc.returncode == 1, proc.stdout + proc.stderr
    assert "forbidden=2" in proc.stdout
    assert "FORBIDDEN" in proc.stdout and "test_missing_symbol" in proc.stdout and "test_dropped_keyword" in proc.stdout
    forbidden_lines = [ln for ln in proc.stdout.splitlines() if ln.startswith("FORBIDDEN")]
    assert not any("test_red_on_assertion" in ln for ln in forbidden_lines)


def test_assertion_only_red_suite_passes_the_forbid_check(tmp_path):
    f = tmp_path / "test_fixture_assert.py"
    f.write_text("def test_red():\n    assert 0 > 1\n")
    proc = _run("--forbid", "TypeError,ArgumentError,AttributeError", str(f))
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "RED CHECK OK" in proc.stdout


def test_placeholder_control_is_excluded_by_marker_and_by_list(tmp_path):
    f = tmp_path / "test_control_fixture.py"
    f.write_text(PLACEHOLDER)
    listed = _run("--list-placeholders", str(tmp_path))
    assert listed.returncode == 0 and str(f) in listed.stdout
    proc = _run("--forbid", "AttributeError", str(f))
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "placeholders_excluded=1" in proc.stdout

    plain = tmp_path / "test_plain.py"
    plain.write_text("def test_attr():\n    (1).nope\n")
    listing = tmp_path / "placeholders.txt"
    listing.write_text(str(plain) + "\n")
    proc = _run("--forbid", "AttributeError", "--placeholder-list", str(listing), str(plain))
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "placeholders_excluded=1" in proc.stdout
    proc = _run("--forbid", "AttributeError", str(plain))
    assert proc.returncode == 1


def test_a_passing_test_still_fails_the_red_check(tmp_path):
    f = tmp_path / "test_fixture_pass.py"
    f.write_text("def test_green():\n    assert True\n")
    proc = _run("--forbid", "AttributeError", str(f))
    assert proc.returncode == 1
    assert "passed=1" in proc.stdout and "PASSED" in proc.stdout
