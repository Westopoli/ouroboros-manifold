# --------------------------------------------------------------- the gate script (fake candidate)

def _git(repo: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=repo, check=True, capture_output=True, text=True)


def _gate(tmp_path: Path, controls: dict[str, str], listed=(), revert=False):
    repo = _project(tmp_path / "cand", controls)
    (repo / "csrc").mkdir()
    (repo / "csrc" / "stub.c").write_text("int om_stub(void) { return 0; }\n")
    (repo / "Makefile").write_text("libouroboros.so:\n\ttouch $@\nlibouroboros_dbg.so:\n\ttouch $@\n")
    _git(repo, "init", "-q")
    _git(repo, "config", "user.email", "gate@test")
    _git(repo, "config", "user.name", "gate")
    write_story(repo, "H1")  # H-020
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "base")
    _git(repo, "remote", "add", "origin", str(repo))
    _git(repo, "update-ref", "refs/remotes/origin/main", "HEAD")
    pieces = tmp_path / "pieces.toml"
    pieces.write_text('[[piece]]\nid = "H1"\nowns = ["csrc/H1.c"]\nacceptance = []\ndepends_on = []\n')
    env = {"MERGE_GATE_PIECES": str(pieces),
           "MERGE_GATE_PLACEHOLDERS": str(_list(tmp_path, *listed)),
           "PATH": "/usr/bin:/bin:/home/westopoli/Projects/agora/.venv/bin"}
    cmd = ["bash", str(GATE)] + (["--revert"] if revert else []) + [str(repo), "HEAD", "H1"]
    return subprocess.run(cmd, capture_output=True, text=True, env=env, timeout=300)


