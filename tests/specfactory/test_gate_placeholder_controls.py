"""The merge gate counts the placeholder controls in their own line against placeholder_controls.txt.

Contract these tests pin (the step does not exist yet, so the new-step tests are red). Step name, matching
rule and the unlisted/listed definitions are PINNED here and listed as ambiguities in the unit report:

  Step and line: `GATE placeholder_controls OK|REJECT <detail>`, printed by merge_gate.sh in the merge
  profile only (never under --revert), right after `control_liveness`. It judges the CANDIDATE's whole
  tests/csim/controls tree, not just the attaching piece's epics (the list is repo-wide). The detail
  always starts `placeholders: N unlisted=U stale=S`, N = placeholder controls found in the candidate,
  and then, on reject, `: ` and the offending repo-relative paths, each tagged `UNLISTED <path>` or
  `STALE <path>`.

  Placeholder: a file tests/csim/controls/**/test_*.py containing BOTH marker strings
  `Generated by scripts/specfactory/gen_controls.py` and `raise NotImplementedError(`
  (red_check.is_placeholder_control; `red_check.py --list-placeholders` prints them). Nothing is run:
  the step never starts pytest, so it is fast and needs no build.

  Matching rule: a list line is a repo-relative posix path; blank lines and `#` comments are ignored;
  a control matches iff its candidate-relative posix path equals a line exactly (no globs, no basenames).

  Unlisted (rejects): a placeholder whose path matches no line.
  Stale (rejects): a listed path that is not a placeholder in the candidate, i.e. the file is missing
  or no longer carries both markers. This covers "a listed one that starts passing": a filled-in
  control that passes and is LIVE is stale, and so is one that was filled in but is dead or failing
  (control_liveness skips listed ids, so leaving it listed would hide it).

  Harness API (merge_gate_support.py):
    placeholder_controls_check(project, placeholders_path) -> (ok, detail)
  CLI: `merge_gate_support.py placeholder-controls <project> --placeholders P`, exit 1 on any reject,
  detail on stdout. Env override for the list is the existing MERGE_GATE_PLACEHOLDERS.

Owners for the implementing unit: scripts/specfactory/merge_gate.sh (HARNESS-sigblocked),
scripts/specfactory/merge_gate_support.py (HARNESS-symown), scripts/specfactory/control_liveness.py
(A94-harness; only if the placeholder marker test is shared from it). The unit touches all three.
"""
