def _project(root: Path, controls: dict[str, str]) -> Path:
    (root / CONTROLS).mkdir(parents=True)
    for name, body in controls.items():
        (root / CONTROLS / name).write_text(body)
    return root


def _list(tmp_path: Path, *lines: str) -> Path:
    p = tmp_path / "placeholder_controls.txt"
    p.write_text("".join(ln + "\n" for ln in lines))
    return p


def _rel(name: str) -> str:
    return f"{CONTROLS}/{name}"


