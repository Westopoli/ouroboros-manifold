# ---- S5: --write-line -------------------------------------------------------------------------------------

def test_write_line_adds_a_pins_line_after_the_shebang_or_extends_line(tmp_path):
    root = _root(tmp_path)
    _put(root, "tests/test_s.py", "#!/usr/bin/env python3\ndef test_x():\n    \"\"\"R-990-01\"\"\"\n")
    _put(root, "tests/test_e.gd", "extends SceneTree\n# proves R-990-01\n")
    for rel in ("tests/test_s.py", "tests/test_e.gd"):
        res = _tool(root, "--write-line", rel)
        assert res.returncode == 0, res.stdout + res.stderr
    py = (root / "tests/test_s.py").read_text().splitlines()
    gd = (root / "tests/test_e.gd").read_text().splitlines()
    assert py[0] == "#!/usr/bin/env python3" and py[1] == f"# Rule pins: R-990-01@{PIN}", py
    assert gd[0] == "extends SceneTree" and gd[1] == f"# Rule pins: R-990-01@{PIN}", gd
    after = _check(root, "tests/test_s.py", "tests/test_e.gd")
    assert after.returncode == 0 and not _with_prefix(after, "PINS REJECT"), after.stdout + after.stderr
