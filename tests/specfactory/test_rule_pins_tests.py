def test_file_without_a_line_passes_from_the_sidecar_and_rejects_when_named_in_only(tmp_path):
    root = _root(tmp_path)
    _put(root, "tests/test_b.py", "def test_x():\n    \"\"\"R-990-01\"\"\"\n")
    _sidecar(root, {"tests/test_b.py": [f"R-990-01@{PIN}"]})
