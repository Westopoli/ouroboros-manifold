# Rule pins: R-990-01@?, R-999-05@?
"""Tests for scripts/specfactory/rule_pins_tests.py (piece HARNESS-C1b, test writer pass; the tool is C1b's, new).

Spec sentences proved (HARNESS-C1b paragraph, rev 3a), each case names its sentence:
  S1 "A test names its pins on one line, marker `Rule pins:` ... as a comment anywhere in the first 40 lines, or
     inside the module docstring."
  S2 "Existing tests have theirs in the sidecar `scripts/specfactory/rule_pins.toml`: `[[file]] path = ...
     pins = [...]`, generated by `rule_pins_tests.py --write-sidecar`, no test file edited."
  S3 "`rule_pins_tests.py check <repo> [--only <file>...]`: for every `.py` and `.gd` under `tests/` that contains
     an `R-\\d{3}-\\d{2}` token (`.c` and `.md` excluded ...), the pins come from the file's own `Rule pins:` line
     if it has one, else from the sidecar; every id mentioned in the file must be pinned there and every pin must
     match; an id with no rule line in the epics (the fixtures' R-990-xx, R-999-xx) is `PINS WARN unknown rule
     <id> in <file>`, never a reject."
  S4 "A pin `R-990-01@?` on a `Rule pins:` line means a fixture id, not a rule, and is accepted only when the
     epics have no rule line for that id (a real id pinned `@?` is REJECT; R3)."
  S5 "A file named in `--only` (the landing's diff) that has no `Rule pins:` line of its own is `PINS REJECT
     <file> has no Rule pins line` (... `--write-line <file>` adds one after the shebang or `extends` line ...)."
  S6 "Output `PINS OK|WARN|REJECT`, exit 1 only on REJECT."
  Tests first: "a fixture tree with one `.py` test citing R-990-01 with a correct `Rule pins:` line passes, a stale
  one rejects naming the file, a file without a line passes from the sidecar and rejects when named in `--only`,
  R-999-05 gives WARN from the sidecar and passes `@?` on an own line, while `R-990-01@?` with a rule line present
  rejects; `--write-sidecar` writes the toml and a second run is byte-identical".
  Pin (section 3): sha256(" ".join(rule_line_after_id.split()).encode("utf-8")).hexdigest()[:6] (DRAFT-pin-hex 6).

Fixture tree: the one of test_spec_provenance.py:34-60 (rule R-990-01 in docs/bible/epics/E-99-test.md), imported
from that file; tests live in <root>/tests/, the sidecar in <root>/scripts/specfactory/rule_pins.toml.

UNSTATED INTERFACES (reported to the Architect, taken here as written so the builder can veto by a test-defect
stop): (1) the sidecar of a checked repo is <repo>/scripts/specfactory/rule_pins.toml; (2) `--write-sidecar <repo>`
takes the repo as its argument and writes that sidecar, paths relative to the repo; (3) `--write-line <file>` is run
with cwd = the repo root; (4) --only paths are relative to the repo root and the tool runs with cwd = the repo
root; (5) the exact REJECT wording other than "has no Rule pins line" is free: the tests read the prefix
`PINS REJECT`, the file name and the id.

Red reason on the built tree: scripts/specfactory/rule_pins_tests.py does not exist; _tool raises the
FileNotFoundError itself so every case below the controls is red for that one reason.
"""
import hashlib
import subprocess
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from test_spec_provenance import EPIC_TEXT, _tree  # noqa: E402

REPO = Path(__file__).resolve().parent.parent.parent
SCRIPT = REPO / "scripts" / "specfactory" / "rule_pins_tests.py"
RULE_PINS = REPO / "scripts" / "specfactory" / "rule_pins.py"

RULE_AFTER_ID = "  Given a town, When it grows, Then it never form rings around the core."
PIN = "b2a3c8"  # section 3 formula on the fixture rule line, computed once (the first control proves it)
STALE = "000000"
SIDECAR = "scripts/specfactory/rule_pins.toml"


def _pin(text_after_id: str) -> str:
    return hashlib.sha256(" ".join(text_after_id.split()).encode("utf-8")).hexdigest()[:6]


def _tool(root: Path, *args) -> subprocess.CompletedProcess:
    if not SCRIPT.is_file():
        raise FileNotFoundError(f"[Errno 2] No such file or directory: '{SCRIPT}' (rule_pins_tests.py is not built)")
    return subprocess.run([sys.executable, str(SCRIPT), *[str(a) for a in args]], cwd=root,
                          capture_output=True, text=True)


def _check(root: Path, *only: str) -> subprocess.CompletedProcess:
    return _tool(root, "check", root, *(["--only", *only] if only else []))


def _root(tmp_path: Path) -> Path:
    """The fixture tree of test_spec_provenance.py plus an empty tests/ and scripts/specfactory/."""
    root = _tree(tmp_path, "# Test spec\n").parent
    (root / "tests").mkdir()
    (root / "scripts" / "specfactory").mkdir(parents=True)
    return root


def _put(root: Path, rel: str, text: str) -> str:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
    return rel


def _sidecar(root: Path, entries: dict) -> None:
    text = "".join(f'[[file]]\npath = "{p}"\npins = [{", ".join(chr(34) + x + chr(34) for x in pins)}]\n\n'
                   for p, pins in entries.items())
    (root / SIDECAR).write_text(text)


def _out(res) -> list:
    return res.stdout.splitlines()


def _with_prefix(res, prefix: str) -> list:
    return [l for l in _out(res) if l.startswith(prefix)]


# ---- positive controls: green on the base tree, no rule_pins_tests.py needed ------------------------------

def test_control_pin_formula_matches_the_literal_and_the_c1a_tool(tmp_path):
    assert _pin(RULE_AFTER_ID) == PIN
    root = _root(tmp_path)
    res = subprocess.run([sys.executable, str(RULE_PINS), "pin", "R-990-01"], cwd=root,
                         capture_output=True, text=True)
    assert res.stdout.splitlines() == [f"R-990-01@{PIN}"], res.stdout + res.stderr


def test_control_fixture_rule_line_present_and_999_has_none(tmp_path):
    root = _root(tmp_path)
    epic = (root / "docs" / "bible" / "epics" / "E-99-test.md").read_text()
    assert epic == EPIC_TEXT
    assert [l for l in epic.splitlines() if l.startswith("- R-990-01 ")] == ["- R-990-01" + RULE_AFTER_ID]
    assert "R-999-05" not in epic


def test_control_planted_stale_tag_is_flagged_by_the_c1a_tool_clean_one_passes(tmp_path):
    """The detector family exists today: rule_pins.py check flags a stale [B] tag and passes the right one."""
    root = _root(tmp_path)
    _put(root, "good.md", f"# S\n\nThe lot draws 7 rows. [B R-990-01@{PIN}: words]\n")
    _put(root, "bad.md", f"# S\n\nThe lot draws 7 rows. [B R-990-01@{STALE}: words]\n")
    good = subprocess.run([sys.executable, str(RULE_PINS), "check", "good.md"], cwd=root, capture_output=True, text=True)
    bad = subprocess.run([sys.executable, str(RULE_PINS), "check", "bad.md"], cwd=root, capture_output=True, text=True)
    assert good.returncode == 0 and good.stdout.startswith("PINS OK"), good.stdout + good.stderr
    assert bad.returncode == 1 and "PINS REJECT" in bad.stdout and "stale" in bad.stdout, bad.stdout + bad.stderr


