def test_pins_line_beyond_line_40_as_a_comment_does_not_count_but_in_the_docstring_it_does(tmp_path):
    root = _root(tmp_path)
    pad = "".join(f"# pad {i}\n" for i in range(44))
    _put(root, "tests/test_late.py", pad + f"# Rule pins: R-990-01@{PIN}\ndef test_x():\n    \"\"\"R-990-01\"\"\"\n")
    doc = '"""Module doc.\n' + "".join(f"pad {i}\n" for i in range(44)) + f"Rule pins: R-990-01@{PIN}\n\"\"\"\n"
    _put(root, "tests/test_doc.py", doc + "def test_x():\n    \"\"\"R-990-01\"\"\"\n")
    late = _check(root)
    assert late.returncode == 1 and any("test_late.py" in l for l in _with_prefix(late, "PINS REJECT")), late.stdout
    assert not any("test_doc.py" in l for l in _with_prefix(late, "PINS REJECT")), late.stdout
    (root / "tests" / "test_late.py").unlink()
    ok = _check(root)
    assert ok.returncode == 0 and _out(ok) == ["PINS OK 1 files 1 ids"], ok.stdout + ok.stderr


