def test_own_line_wins_over_the_sidecar(tmp_path):
    root = _root(tmp_path)
    _put(root, "tests/test_ok.py", f"# Rule pins: R-990-01@{PIN}\n\"\"\"R-990-01\"\"\"\n")
    _put(root, "tests/test_bad.py", f"# Rule pins: R-990-01@{STALE}\n\"\"\"R-990-01\"\"\"\n")
    _sidecar(root, {"tests/test_ok.py": [f"R-990-01@{STALE}"], "tests/test_bad.py": [f"R-990-01@{PIN}"]})
    res = _check(root)
    rej = _with_prefix(res, "PINS REJECT")
    assert res.returncode == 1, res.stdout + res.stderr
    assert any("test_bad.py" in l for l in rej) and not any("test_ok.py" in l for l in rej), res.stdout


def test_only_restricts_rejects_to_the_named_files(tmp_path):
    root = _root(tmp_path)
    _put(root, "tests/test_ok.py", f"# Rule pins: R-990-01@{PIN}\n\"\"\"R-990-01\"\"\"\n")
    _put(root, "tests/test_old.py", f"# Rule pins: R-990-01@{STALE}\n\"\"\"R-990-01\"\"\"\n")
    named = _check(root, "tests/test_ok.py")
    assert named.returncode == 0 and not _with_prefix(named, "PINS REJECT"), named.stdout + named.stderr
    assert _with_prefix(named, "PINS WARN") or _with_prefix(named, "PINS OK"), named.stdout
    whole = _check(root)
    assert whole.returncode == 1 and any("test_old.py" in l for l in _with_prefix(whole, "PINS REJECT")), whole.stdout


def test_write_sidecar_writes_the_toml_and_a_second_run_is_byte_identical(tmp_path):
    root = _root(tmp_path)
    _put(root, "tests/test_d.py", "def test_x():\n    \"\"\"R-990-01 and R-999-05\"\"\"\n")
    first = _tool(root, "--write-sidecar", root)
    assert first.returncode == 0, first.stdout + first.stderr
    data = tomllib.loads((root / SIDECAR).read_text())
    entry = {f["path"]: f["pins"] for f in data["file"]}
    assert set(entry) == {"tests/test_d.py"}, entry
    assert sorted(entry["tests/test_d.py"]) == sorted([f"R-990-01@{PIN}", "R-999-05@?"]), entry
    before = (root / SIDECAR).read_bytes()
    second = _tool(root, "--write-sidecar", root)
    assert second.returncode == 0, second.stdout + second.stderr
    assert (root / SIDECAR).read_bytes() == before


