"""Stage 4 fix F3, the layouts: L-0080 and L-0083, end to end under `--sight on`.

Westley 2026-11-06: "inside walls box, move out, blue times the attack such that all 3 forces are attacking red at the same time and 2 of red's forces are *initially*
out of red's vision (if red decides to move up the hill, blue should become in vision as soon as they crest over the half-way point up the hill, as the rules of the
game are defined)". The layouts are Claude's (`trap()` in scripts/skilllab/catalogue/round3.py), regenerated by that producer; red starts inside the pocket box, blue's
two hill groups and rear arc hold (guard) until any red unit is within DRAFT-trap-release-radius of the centre point of the three forces, then all three attack-move
to red's centroid. The catalogue files are compared with the producer's own output (they are generated, not hand-edited).

Unit ids are the runner's spawn order: side A (blue) 1.., side B (red) after it; the groups' ids are read from the fight file's `orders.groups`."""
import math
import tomllib
from pathlib import Path

import pytest

import h063_fixtures as fx
from scripts.skilllab.catalogue import produce, round3
from scripts.skilllab.engine import Engine

ROOT = Path(__file__).resolve().parents[3]
CATALOGUE = ROOT / "docs" / "northstar" / "research" / "layer_dynamics" / "catalogue"
POCKET = (1700.0, 1600.0, 2300.0, 2400.0)   # the inside of the walls box: x0, y0, x1, y1 (walls at x 1500-1700 and 2300-2500, back wall y 1400-1600, mouth open at y 2400)
SPREAD_TICKS = 600   # DRAFT, set from the run (Test-defect commit): the most ticks between the first target of any blue group and the first of any other after the release
CAP = 150


def _toml(name):
    with open(CATALOGUE / (name + ".toml"), "rb") as f:
        return tomllib.load(f)


@pytest.fixture(scope="module", params=["L-0080", "L-0083"])
def played(request, tmp_path_factory):
    """(layout, fight doc, per-tick record) of one trap fight, seed 1, `--sight on`, CAP seconds. The per-tick record: {tick: {"red_sees_hill": bool, "targets": {id: target}, "pos": {id: (x, y)}}}."""
    name = request.param
    rec, state = {}, {"tick": 0}
    real = Engine.step
    layout = _toml(name)
    hill_ids = []   # filled once the fight file exists; the can_see check runs on side A ids 1..nA flagged layer 1 at spawn
    na = len(layout["side_a"]["units"])
    hills = [i + 1 for i, u in enumerate(layout["side_a"]["units"]) if u["layer"] == 1]
    reds = list(range(na + 1, na + 1 + len(layout["side_b"]["units"])))

    def step(self, w):
        real(self, w)
        state["tick"] += 1
        t = state["tick"]
        rec[t] = {"red_sees_hill": t <= 1500 and any(self.can_see(w, r, h) for r in reds if self.unit_alive(w, r) for h in hills),
                  "targets": {i: self.unit_target(w, i) for i in range(1, na + 1) if self.unit_alive(w, i)},
                  "pos": {i: self.unit_pos(w, i) for i in range(1, na + len(reds) + 1) if self.unit_alive(w, i)}}
    Engine.step = step
    try:
        out = tmp_path_factory.mktemp(name)
        proc = fx.run(CATALOGUE / (name + ".toml"), out, 1, "--sight", "on", "--cap-seconds", CAP)
    finally:
        Engine.step = real
    assert proc.returncode == 0, proc.stdout + proc.stderr
    from scripts.skilllab.arena import snapshot
    return layout, snapshot.read(out / (name + "-s1.fight.json")), rec


def test_the_catalogue_files_are_the_producers_output():
    """The trap layouts are generated: round3.build(55) reproduces L-0080 and L-0083 exactly (TOML text), so nothing was hand-edited."""
    built, rejected = round3.build(55)
    assert not rejected
    by_id = {l["id"]: l for _, l in built}
    for name in ("L-0080", "L-0083"):
        assert produce.dump_toml(by_id[name]) == (CATALOGUE / (name + ".toml")).read_text()


def test_red_starts_inside_the_pocket_box_and_blue_has_three_groups():
    for name in ("L-0080", "L-0083"):
        lay = _toml(name)
        x0, y0, x1, y1 = POCKET
        assert all(x0 + 15 <= u["x"] <= x1 - 15 and y0 + 15 <= u["y"] <= y1 - 15 for u in lay["side_b"]["units"]), name
        assert lay["orders"] == "groups" and {u["group"] for u in lay["side_a"]["units"]} == {"hill_w", "hill_e", "arc"}
        assert {g["group"] for g in lay["order_groups"] if g["side"] == "A"} == {"hill_w", "hill_e", "arc"}
        assert all(g["release"]["radius"] == produce_release_radius() for g in lay["order_groups"] if g["side"] == "A")


def produce_release_radius():
    return round3.TRAP_RELEASE_RADIUS   # DRAFT-trap-release-radius


def test_the_hill_groups_hold_unseen_until_the_release_and_red_moves_out_toward_the_mouth(played):
    """Ruling 1: until the release the hill forces hold their ground on the rise and no red unit sees them (R-005-09: red is on the low layer); red moves out, so its
    centroid y grows toward the mouth (y 2400) before the release."""
    lay, doc, rec = played
    groups = {g["group"]: g for g in doc["orders"]["groups"] if g["side"] == "A"}
    released = {g["released_at"] for g in groups.values()}
    assert len(released) == 1 and None not in released, groups
    t = released.pop()
    assert t > 0 and not any(rec[k]["red_sees_hill"] for k in range(1, min(t, 1500) + 1)), "a red unit saw a hill unit before the release"
    start = {u["id"]: (u["x"], u["y"]) for u in doc["frames"][0]["units"]}
    for g in ("hill_w", "hill_e"):
        assert all(math.dist(rec[t]["pos"][i], start[i]) <= 5.0 for i in groups[g]["units"] if i in rec[t]["pos"]), g + " moved before the release"
    reds = [u["id"] for u in doc["frames"][0]["units"] if u["side"] == "B"]
    assert sum(rec[t]["pos"][i][1] for i in reds) / len(reds) > sum(start[i][1] for i in reds) / len(reds) + 100.0


def test_all_three_blue_groups_have_a_target_within_a_stated_number_of_ticks_of_one_another(played):
    """Ruling 1: all 3 forces attack red at the same time. After the release each blue group's first held target comes within SPREAD_TICKS of the others'."""
    lay, doc, rec = played
    groups = {g["group"]: g for g in doc["orders"]["groups"] if g["side"] == "A"}
    t = next(iter(groups.values()))["released_at"]
    first = {}
    for name, g in groups.items():
        hit = next((k for k in range(t + 1, max(rec) + 1) if any(rec[k]["targets"].get(i) for i in g["units"])), None)
        assert hit is not None, "%s never held a target after the release" % name
        first[name] = hit
    assert max(first.values()) - min(first.values()) <= SPREAD_TICKS, first
