    for r in range(3):
        set_region(lib, w, r, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0, faction_id=0)
        set_owner(lib, w, r, 0, held_since=-1)

    # Edges touching Region 0 set as TRADE and BOTH
    set_edge(lib, w, 0, 1, OMEdge.TRADE)
    set_edge(lib, w, 0, 2, OMEdge.BOTH)

    queue_external(lib, w, 0, template_id(lib, w, "Revolt Entrenched"), due_tick=1, probability=1.0)
    force_draws(lib, w, [0.99, 0.50, 0.10, 0.50])
    lib.om_world_step(w)

    # When ownership changes to breakaway, every edge touching Region 0 becomes border
    import ctypes
    edge_01 = ctypes.c_int()
    rc1 = lib.om_region_edge(w, 0, 1, ctypes.byref(edge_01))
    assert rc1 != 0
    assert edge_01.value == OMEdge.BORDER

    edge_02 = ctypes.c_int()
    rc2 = lib.om_region_edge(w, 0, 2, ctypes.byref(edge_02))
    assert rc2 != 0
    assert edge_02.value == OMEdge.BORDER

