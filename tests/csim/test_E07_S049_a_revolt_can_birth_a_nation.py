class OmRevoltRecord(ctypes.Structure):
    _fields_ = [
        ("tick", ctypes.c_uint64),
        ("region_idx", ctypes.c_uint32),
        ("original_faction", ctypes.c_int32),
        ("success_rate", ctypes.c_double),
        ("draw", ctypes.c_double),
        ("faction_created", ctypes.c_uint32),
        ("new_faction_id", ctypes.c_int32),
        ("military_stolen", ctypes.c_double),
        ("economy_stolen", ctypes.c_double),
        ("reverted_faction", ctypes.c_int32),
    ]


def read_revolts(lib, w, max_records=64):
    buf = (OmRevoltRecord * max_records)()
    n = lib.om_tick_revolts(w, buf, max_records)
    return [buf[i] for i in range(n)]


def test_R_049_01_one_draw_sets_success_rate(lib, world_factory):
    """Given Revolt Entrenched fires in an owned region, When resolved, Then one draw sets the success rate uniform in [0.50, 0.95] and a second draw must be ≤ that rate, else no faction forms."""
    # Case A: second draw > rate -> no faction forms
    w_fail = world_factory(n_regions=2)
    isolate_agents(lib, w_fail)
    lib.om_world_set_feature(w_fail, OMFeature.FACTIONS, 0)
    load_only_templates(lib, w_fail, "Revolt Entrenched")
    lib.om_world_set_feature(w_fail, OMFeature.EVENTS, 1)
    lib.om_world_set_feature(w_fail, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w_fail, 0, OMArchetype.DEFAULT, budget=0.0, tech=10.0, confidence=5.0)
    set_tech_multipliers(lib, w_fail, 0, 1.0, 1.0, 1.0)
    set_region(lib, w_fail, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=70.0, population=50.0, faction_id=0)
    set_owner(lib, w_fail, 0, 0, held_since=-1)
    set_region(lib, w_fail, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w_fail, 1, 0, held_since=-1)

    # Queue Revolt Entrenched (template_id 100 or external event) due tick 2
    queue_external(lib, w_fail, 0, template_id(lib, w_fail, "Revolt Entrenched"), due_tick=1, probability=1.0)

    # Draw 1: 0.50 -> rate = 0.50 + (0.95 - 0.50) * 0.50 = 0.725
    # Draw 2: 0.80 > 0.725 -> fails, no faction forms
    force_draws(lib, w_fail, [0.99, 0.50, 0.80])
    lib.om_world_step(w_fail)

    revolts_fail = read_revolts(lib, w_fail)
    assert len(revolts_fail) == 1
    assert revolts_fail[0].faction_created == 0
    assert lib.om_faction_count(w_fail) == 1
    assert lib.om_region_owner(w_fail, 0) == 0

    # Case B: second draw <= rate -> faction forms
    w_pass = world_factory(n_regions=2)
    isolate_agents(lib, w_pass)
    lib.om_world_set_feature(w_pass, OMFeature.FACTIONS, 0)
    load_only_templates(lib, w_pass, "Revolt Entrenched")
    lib.om_world_set_feature(w_pass, OMFeature.EVENTS, 1)
    lib.om_world_set_feature(w_pass, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w_pass, 0, OMArchetype.DEFAULT, budget=0.0, tech=10.0, confidence=5.0)
    set_tech_multipliers(lib, w_pass, 0, 1.0, 1.0, 1.0)
    set_region(lib, w_pass, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=70.0, population=50.0, faction_id=0)
    set_owner(lib, w_pass, 0, 0, held_since=-1)
    set_region(lib, w_pass, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w_pass, 1, 0, held_since=-1)

    queue_external(lib, w_pass, 0, template_id(lib, w_pass, "Revolt Entrenched"), due_tick=1, probability=1.0)

    # Draw 1: 0.50 -> rate = 0.725; Draw 2: 0.50 <= 0.725 -> passes
    force_draws(lib, w_pass, [0.99, 0.50, 0.50, 0.50])  # queue-fire, rate, check, confidence draw
    lib.om_world_step(w_pass)

    revolts_pass = read_revolts(lib, w_pass)
    assert len(revolts_pass) == 1
    assert revolts_pass[0].faction_created == 1
    assert lib.om_faction_count(w_pass) == 2
    assert lib.om_region_owner(w_pass, 0) != 0



