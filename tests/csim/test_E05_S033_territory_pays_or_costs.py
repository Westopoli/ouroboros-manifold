def test_R_033_01_budget_66_8_40_8(lib, world_factory):
    """Given a faction owning regions with economy 66, 40, and 9, When budget accumulates for one tick, Then Δbudget = ((66 − 8) + (40 − 8) + (9 − 8)) · 0.025 = 2.275."""
    w = world_factory(n_regions=3)
    isolate_agents(lib, w)

    # Given a faction (neutral archetype DEFAULT, neutral starting budget 0.0, neutral confidence 5.0)
    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    # Neutral tech multipliers 1.0 (no tech)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)

    # Neutral values for unstated fields: tier HOME, military 50.0, tension 0.0, population 50.0
    # Region 0: economy 66
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=66.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)

    # Region 1: economy 40
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=40.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 1, 0, held_since=-1)  # neutral held_since -1 (held since world began)

    # Region 2: economy 9
    set_region(lib, w, 2, tier=OMTier.HOME, military=50.0, economy=9.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 2, 0, held_since=-1)  # neutral held_since -1 (held since world began)

    # Neutral edges between adjacent owned regions
    set_edge(lib, w, 0, 1, OMEdge.BOTH)
    set_edge(lib, w, 1, 2, OMEdge.BOTH)

    initial_budget = lib.om_faction_budget(w, 0)
    assert initial_budget == pytest.approx(0.0, abs=1e-6)

    # When budget accumulates for one tick
    lib.om_world_step(w)

    # Then Δbudget = ((66 − 8) + (40 − 8) + (9 − 8)) · 0.025 = 2.275
    budget_after = lib.om_faction_budget(w, 0)
    delta_budget = budget_after - initial_budget
    expected_delta = ((66.0 - 8.0) + (40.0 - 8.0) + (9.0 - 8.0)) * 0.025
    assert expected_delta == pytest.approx(2.275, abs=1e-6)
    assert delta_budget == pytest.approx(2.275, abs=1e-6)
    assert budget_after == pytest.approx(2.275, abs=1e-6)

    # With no enemies or uncolonized regions, faction accumulates and commits 0
    decisions = read_decisions(lib, w)
    assert len(decisions) >= 1  # one record per faction that ran 3d; faction 0 is first (ascending id)
    assert decisions[0].faction_id == 0
    assert decisions[0].action == OMAction.ACCUMULATE
    assert decisions[0].commit == pytest.approx(0.0, abs=1e-6)


def test_R_033_02_budget_0_budget_never_goes(lib, world_factory):
    """Given a faction owning one region at economy 8.0, When budget accumulates, Then Δbudget = 0 and budget never goes below 0."""
    w = world_factory(n_regions=1)
    isolate_agents(lib, w)

    # Given a faction owning one region at economy 8.0 (neutral starting budget 0.0)
    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    # Neutral tech multipliers 1.0 (no tech)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    # Neutral values for unstated fields: tier HOME, military 50.0, tension 0.0, population 50.0
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)

    initial_budget = lib.om_faction_budget(w, 0)
    assert initial_budget == pytest.approx(0.0, abs=1e-6)

    # When budget accumulates
    lib.om_world_step(w)

    # Then Δbudget = (8.0 − 8.0) · 0.025 = 0 and budget never goes below 0
    budget_after = lib.om_faction_budget(w, 0)
    delta_budget = budget_after - initial_budget
    assert delta_budget == pytest.approx(0.0, abs=1e-6)
    assert budget_after == pytest.approx(0.0, abs=1e-6)
    assert budget_after >= 0.0

    # Accumulate another tick to confirm budget stays at 0 and never goes below 0
    lib.om_world_step(w)
    assert lib.om_faction_budget(w, 0) == pytest.approx(0.0, abs=1e-6)
    assert lib.om_faction_budget(w, 0) >= 0.0

    # Also verify existing positive budget with economy 8.0: Δbudget remains 0
    w_pos = world_factory(n_regions=1)
    isolate_agents(lib, w_pos)
    set_faction(lib, w_pos, 0, OMArchetype.DEFAULT, budget=10.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w_pos, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0
    set_region(lib, w_pos, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w_pos, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)
    init_pos = lib.om_faction_budget(w_pos, 0)
    lib.om_world_step(w_pos)
    after_pos = lib.om_faction_budget(w_pos, 0)
    assert after_pos - init_pos == pytest.approx(0.0, abs=1e-6)
    assert after_pos == pytest.approx(10.0, abs=1e-6)

    # Boundary verification for clamp: economy below baseline maintenance (< 8.0, e.g. 5.0 after conquest disruption).
    # Net delta is negative: (5.0 − 8.0) · 0.025 = −0.075.
    # Starting at budget 0.0, runtime accumulation clamps at 0 (ALG-17: max(0, budget + Δbudget)) so budget never goes below 0.
    w_below = world_factory(n_regions=1)
    isolate_agents(lib, w_below)
    set_faction(lib, w_below, 0, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w_below, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0
    set_region(lib, w_below, 0, tier=OMTier.HOME, military=50.0, economy=5.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w_below, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)
    lib.om_world_step(w_below)
    budget_below = lib.om_faction_budget(w_below, 0)
    assert budget_below == pytest.approx(0.0, abs=1e-6)
    assert budget_below >= 0.0

    # Deficit exceeding existing budget: starting budget 0.05 with deficit -0.075 -> clamps at 0.0
    w_clamp = world_factory(n_regions=1)
    isolate_agents(lib, w_clamp)
    set_faction(lib, w_clamp, 0, OMArchetype.DEFAULT, budget=0.05, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w_clamp, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0
    set_region(lib, w_clamp, 0, tier=OMTier.HOME, military=50.0, economy=5.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w_clamp, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)
    lib.om_world_step(w_clamp)
    budget_clamp = lib.om_faction_budget(w_clamp, 0)
    assert budget_clamp == pytest.approx(0.0, abs=1e-6)
    assert budget_clamp >= 0.0


def test_R_033_03_budget_0(lib, world_factory):
    """Given a faction owning no regions, When budget accumulates, Then Δbudget = 0."""
    w = world_factory(n_regions=1)
    isolate_agents(lib, w)

    # Given a faction owning no regions (starting budget 0.0 per R-032-01)
    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    # Neutral tech multipliers 1.0 (no tech)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)

    # Another faction owns region 0
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)
    # Neutral unstated stance
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)

    # Neutral values for unstated fields: tier HOME, military 50.0, tension 0.0, population 50.0, held_since -1
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=1)
    set_owner(lib, w, 0, 1, held_since=-1)  # owned by faction 1, so faction 0 owns 0 regions

    # Confirm faction 0 owns 0 territory
    assert lib.om_faction_territory(w, 0) == 0

    initial_budget = lib.om_faction_budget(w, 0)
    assert initial_budget == pytest.approx(0.0, abs=1e-6)

    # When budget accumulates
    lib.om_world_step(w)

    # Then Δbudget = 0
    budget_after = lib.om_faction_budget(w, 0)
    delta_budget = budget_after - initial_budget
    assert delta_budget == pytest.approx(0.0, abs=1e-6)
    assert budget_after == pytest.approx(0.0, abs=1e-6)

    # Also verify with a positive existing budget: a landless faction neither gains nor loses budget
    w_pos = world_factory(n_regions=1)
    isolate_agents(lib, w_pos)
    set_faction(lib, w_pos, 0, OMArchetype.DEFAULT, budget=50.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w_pos, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0
    set_faction(lib, w_pos, 1, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w_pos, 1, 1.0, 1.0, 1.0)
    set_stance(lib, w_pos, 0, 1, OMStance.HOSTILE)  # neutral unstated stance
    set_region(lib, w_pos, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=1)
    set_owner(lib, w_pos, 0, 1, held_since=-1)

    assert lib.om_faction_territory(w_pos, 0) == 0
    init_pos = lib.om_faction_budget(w_pos, 0)
    assert init_pos == pytest.approx(50.0, abs=1e-6)

    lib.om_world_step(w_pos)

    after_pos = lib.om_faction_budget(w_pos, 0)
    delta_pos = after_pos - init_pos
    assert delta_pos == pytest.approx(0.0, abs=1e-6)
    assert after_pos == pytest.approx(50.0, abs=1e-6)
