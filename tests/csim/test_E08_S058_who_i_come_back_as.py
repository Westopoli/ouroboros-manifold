def test_R_058_05_every_named_enemy_faction_character(lib, world_factory):
    """Given a mission ends, When rivals are tagged, Then every named enemy-faction character in the mission region gains a rival tag pointing at the player's commander."""
    w = world_factory(n_regions=4)

    # Player commander in mission region 1
    lib.om_character_create(w, character_id=10, lineage_id=1, region_idx=1, rank=3, birth_tick=0, lifespan=100)
    lib.om_character_set_faction(w, 10, faction_id=0)  # player faction

    # Named enemy characters in mission region 1
    lib.om_character_create(w, character_id=20, lineage_id=2, region_idx=1, rank=1, birth_tick=10, lifespan=100)
    lib.om_character_set_faction(w, 20, faction_id=1)  # enemy faction

    # Friendly character in same region
    lib.om_character_create(w, character_id=30, lineage_id=1, region_idx=1, rank=1, birth_tick=15, lifespan=100)
    lib.om_character_set_faction(w, 30, faction_id=0)

    # Mission ends
    lib.om_mission_tag_rivals(w, mission_region=1, commander_id=10)

    # Enemy character gained rival tag pointing at commander 10
    assert lib.om_character_has_rival_tag(w, character_id=20, target_commander_id=10) == 1

    # Friendly character did NOT gain rival tag
    assert lib.om_character_has_rival_tag(w, character_id=30, target_commander_id=10) == 0


