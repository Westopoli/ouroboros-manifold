class OMPoolType:
    PREVIOUS = 0
    NEMESIS = 1
    UNRELATED = 2


def test_R_058_01_one_draw_picks_previous_descendant(lib, world_factory):
    """Given a rotation, When the pool is rolled, Then one draw picks previous-descendant with probability 0.70, nemesis-descendant 0.20, unrelated 0.10; if the rolled pool is empty the search falls through in the order previous, nemesis, unrelated."""
    w = world_factory(n_regions=4)

    # Draw < 0.70 rolls PREVIOUS
    pool_prev = lib.om_selector_roll_pool(w, draw=0.50)
    assert pool_prev == OMPoolType.PREVIOUS

    # Draw in [0.70, 0.90) rolls NEMESIS
    pool_nem = lib.om_selector_roll_pool(w, draw=0.75)
    assert pool_nem == OMPoolType.NEMESIS

    # Draw >= 0.90 rolls UNRELATED
    pool_unrel = lib.om_selector_roll_pool(w, draw=0.95)
    assert pool_unrel == OMPoolType.UNRELATED

    # Fallthrough: if PREVIOUS rolled but empty, falls through to NEMESIS, then UNRELATED
    lib.om_selector_clear_pools(w)
    actual_pool = lib.om_selector_resolve_fallback_pool(w, initial_pool=OMPoolType.PREVIOUS)
    assert actual_pool == OMPoolType.UNRELATED  # Both previous & nemesis empty


