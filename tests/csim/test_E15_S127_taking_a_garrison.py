def test_R_127_01_capture_progress_rises_by_dt(lib, world_factory):
    """Given units of exactly one non-owner faction inside a structure's 300 wu radius and no owner units, When ticks pass, Then capture progress rises by dt / 10 s; at 1.0 the owner flips and progress resets."""
    w = world_factory(n_regions=1)
    lib.om_structure_init(w, 0, 0, ctypes.c_double(100.0))
    lib.om_structure_set_owner(w, 0, 2)  # owner = enemy (2)

    # 10s at 20 ticks/sec = 200 ticks.
    # Put player (faction 1) units inside 300 wu radius, no owner units
    lib.om_structure_set_capturing_faction(w, 0, 1)  # faction 1 unopposed

    # Advance 100 ticks (5 s) -> progress = 0.5
    for _ in range(100):
        lib.om_structure_tick_capture(w, 0)
    progress_5s = lib.om_structure_get_capture_progress(w, 0)
    assert ctypes.c_double(progress_5s).value == pytest.approx(0.5, abs=1e-3)

    # Advance another 100 ticks (total 200 ticks = 10 s) -> flips owner and resets progress
    for _ in range(100):
        lib.om_structure_tick_capture(w, 0)

    assert lib.om_structure_get_owner(w, 0) == 1
    assert ctypes.c_double(lib.om_structure_get_capture_progress(w, 0)).value == pytest.approx(0.0, abs=1e-5)


