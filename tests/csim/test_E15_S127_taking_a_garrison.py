def test_R_127_04_structure_captured_or_structure_lost(lib, world_factory):
    """Given a structure changes owner, When the ticker runs, Then "structure captured" or "structure lost" appears (E-16 R-104-01)."""
    w = world_factory(n_regions=1)
    lib.om_structure_init(w, 0, 0, ctypes.c_double(100.0))
    lib.om_structure_set_owner(w, 0, 2)  # enemy owned

    # Player captures it
    lib.om_structure_on_owner_changed(w, 0, 2, 1)  # old 2, new 1
    ticker_text = ctypes.create_string_buffer(256)
    lib.om_ticker_pop_message(w, ticker_text, 256)
    msg = ticker_text.value.decode("utf-8").lower()
    assert "structure captured" in msg

    # Enemy captures it back from player
    lib.om_structure_on_owner_changed(w, 0, 1, 2)  # old 1, new 2
    lib.om_ticker_pop_message(w, ticker_text, 256)
    msg_lost = ticker_text.value.decode("utf-8").lower()
    assert "structure lost" in msg_lost


