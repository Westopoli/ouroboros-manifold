    """Given an archetype base time B in tactical ticks and urgency u, When the limit is set, Then limit = max(B · (1 − 0.2 · u), 0.6 · B)."""
    base_ticks = 45000  # DEFENSIVE_STAND: 37.5 min × 60 s × 20 ticks/s

    # u = 0.0 -> limit = 45000 * (1 - 0) = 45000
