def test_R_076_03_current_objective_completion_values_final(lib, world_factory):
    """Given the deadline passes, When the mission ends, Then the current objective completion values are final; finishing early never raises the score."""
    w = world_factory(n_regions=1)

    lib.om_mission_setup_tactical(w, 0, 1000)  # limit = 1000 ticks
    lib.om_mission_set_objective_completion(w, 0, ctypes.c_double(0.75))

    # om_tactical_step is a no-op (and never advances the clock) with zero
    # units in play, so a unit must be spawned to drive the tactical tick.
    lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, 0.0, 0)

    # Advance to deadline
    for _ in range(1000):
        lib.om_tactical_step(w)

    assert lib.om_mission_is_ended(w) == 1
    score_at_deadline = lib.om_mission_get_objective_score(w)
    assert score_at_deadline == pytest.approx(0.75, abs=1e-5)

    # Finishing early with the same completion should yield the exact same score (no time bonus)
    w2 = world_factory(n_regions=1)
    lib.om_mission_setup_tactical(w2, 0, 1000)
    lib.om_mission_set_objective_completion(w2, 0, ctypes.c_double(0.75))
    lib.om_tactical_tick(w2)  # finished at tick 1
    lib.om_mission_end(w2)

    score_early = lib.om_mission_get_objective_score(w2)
    assert score_early == pytest.approx(score_at_deadline, abs=1e-5)

