class OMFogTreatment:
    REVEALED = 0
    FOGGED = 1
    INTERFERENCE = 2


class OMUnitType:
    RAIDER = 0
    INTERCEPTOR = 1
    VANGUARD = 2
    WARDEN = 3
    BOMBARD = 4
