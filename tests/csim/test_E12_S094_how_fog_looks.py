def test_R_094_01_revealed_area_fogged_area_interference(lib, world_factory):
    """Given a T2 screenshot, When inspected, Then revealed area, fogged area, and interference zones are three distinguishable treatments."""
    w = world_factory(n_regions=1)

    # Setup 3 areas:
    # 1. Revealed area: unit standing at (0, 0)
    lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, 0.0, 0)

    # 2. Interference zone at (1000, 0)
    lib.om_map_add_interference_zone(w, 1000.0, 0.0, 0, 0.7, 200.0)

    # 3. Unexplored/fogged area at (2000, 2000)

    lib.om_visibility_compute(w)

    treatment_revealed = lib.om_fog_get_treatment_at(w, 0.0, 0.0, 0)
    treatment_interference = lib.om_fog_get_treatment_at(w, 1000.0, 0.0, 0)
    treatment_fogged = lib.om_fog_get_treatment_at(w, 2000.0, 2000.0, 0)

    # Assert the three treatments are distinguishable (mutually distinct)
    assert treatment_revealed != treatment_fogged
    assert treatment_fogged != treatment_interference
    assert treatment_revealed != treatment_interference

    assert treatment_revealed == OMFogTreatment.REVEALED
    assert treatment_fogged == OMFogTreatment.FOGGED
    assert treatment_interference == OMFogTreatment.INTERFERENCE


def test_R_094_02_its_own_sensor_circle_visibly(lib, world_factory):
    """Given a unit inside interference, When drawn, Then its own sensor circle is visibly smaller."""
    w = world_factory(n_regions=1)

    # Vanguard base sensor radius = 700.0 wu
    # Unit 1 outside interference (i = 0.0)
    u_outside = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, 0.0, 0)

    # Unit 2 inside interference zone (i = 0.4)
    lib.om_map_add_interference_zone(w, 2000.0, 0.0, 0, 0.4, 300.0)
    u_inside = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 2000.0, 0.0, 0)

    lib.om_visibility_compute(w)

    r_outside = lib.om_fog_get_drawn_sensor_circle_radius(w, u_outside)
    r_inside = lib.om_fog_get_drawn_sensor_circle_radius(w, u_inside)

    # Outside interference: full radius 700.0 wu
    assert pytest.approx(r_outside, abs=1e-4) == 700.0

    # Inside interference (i = 0.4): scaled by (1 - 0.4) = 0.6 -> 700 * 0.6 = 420.0 wu
    assert pytest.approx(r_inside, abs=1e-4) == 420.0

    # Visibly smaller
    assert r_inside < r_outside

