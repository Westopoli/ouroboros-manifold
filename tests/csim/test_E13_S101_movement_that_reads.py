def test_R_101_01_no_unit_overlaps_another_no(lib, world_factory):
    """Given a T2 clip of a 20-unit move, When reviewed, Then no unit overlaps another, no unit teleports, and units arrive within 2 s of each other."""
    w = world_factory(n_regions=1)

    # Spawn 20 units in a 4x5 formation
    units = []
    for r in range(4):
        for c in range(5):
            uid = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, r * 35.0, c * 35.0, 0)
            units.append(uid)

    arr_type = ctypes.c_uint32 * 20
    selection = arr_type(*units)

    # Group move 1000 wu along x
    lib.om_command_group_move(w, selection, 20, 1000.0, 70.0)

    arrival_ticks = {}
    prev_positions = {uid: lib.om_unit_get_pos(w, uid) for uid in units}

    # Simulate move (up to 200 ticks = 10 seconds)
    for tick in range(200):
        lib.om_world_step(w)

        # 1. No unit overlaps another: all pairs distance >= 30 wu (within small floating-point eps)
        current_positions = {uid: lib.om_unit_get_pos(w, uid) for uid in units}
        for i in range(len(units)):
            p1 = current_positions[units[i]]
            for j in range(i + 1, len(units)):
                p2 = current_positions[units[j]]
                dist = math.hypot(p2[0] - p1[0], p2[1] - p1[1])
                assert dist >= 30.0 - 0.1  # Westley, 2026-10-02 (A148): the Python's own collision residual is 29.92; was 30.0 - 1e-2

        # 2. No unit teleports: max distance moved per tick <= native speed / 20 * 1.5
        for uid in units:
            prev_p = prev_positions[uid]
            curr_p = current_positions[uid]
            tick_disp = math.hypot(curr_p[0] - prev_p[0], curr_p[1] - prev_p[1])
            # Raider speed is 150 wu/s = 7.5 wu/tick. No teleport > 12.0 wu in one tick
            assert tick_disp <= 12.0

            # Record arrival tick (within 22.5 wu of destination slot)
            if uid not in arrival_ticks:
                dest_x, dest_y = lib.om_unit_get_destination(w, uid)
                if math.hypot(curr_p[0] - dest_x, curr_p[1] - dest_y) <= 22.5:
                    arrival_ticks[uid] = tick

        prev_positions = current_positions
        if len(arrival_ticks) == 20:
            break

    # 3. Units arrive within 2 s of each other (at 20 tps, 2 s = 40 ticks)
    assert len(arrival_ticks) == 20
    first_arrival = min(arrival_ticks.values())
    last_arrival = max(arrival_ticks.values())
    assert (last_arrival - first_arrival) <= 40  # 40 ticks = 2.0 seconds


def test_R_101_02_position_facing_linearly_interpolated_from(lib, world_factory):
    """Given the renderer, When it draws between ticks, Then position and facing are linearly interpolated from the last two ticks."""
    w = world_factory(n_regions=1)

    u = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 0.0, 0.0, 0)
    lib.om_command_move(w, u, 1000.0, 0.0)

    # Tick 0: unit at (0, 0) facing 0.0 rad
    p0_x, p0_y = lib.om_unit_get_pos(w, u)
    f0 = lib.om_unit_get_facing(w, u)

    # Step to Tick 1
    lib.om_world_step(w)
    p1_x, p1_y = lib.om_unit_get_pos(w, u)
    f1 = lib.om_unit_get_facing(w, u)

    # om_unit_get_pos always returning (0, 0) would make the midpoint of two
    # zeros zero, satisfying the interpolation checks below by coincidence.
    assert p1_x != p0_x, "unit must have actually moved between the two ticks"

    # Sample sub-tick interpolation at alpha = 0.5
    render_x, render_y = lib.om_renderer_interpolate_position(w, u, 0.5)
    render_facing = lib.om_renderer_interpolate_facing(w, u, 0.5)

    # Expected position is exact midpoint
    expected_x = p0_x + 0.5 * (p1_x - p0_x)
    expected_y = p0_y + 0.5 * (p1_y - p0_y)
    assert pytest.approx(render_x, abs=1e-4) == expected_x
    assert pytest.approx(render_y, abs=1e-4) == expected_y

    # Expected facing is exact linear angle interpolation
    expected_facing = f0 + 0.5 * (f1 - f0)
    assert pytest.approx(render_facing, abs=1e-4) == expected_facing

