def test_R_102_02_order_fixed_documented_no_wall(lib, world_factory):
    """Given the steering sweep, When angles are tried, Then the order is fixed and documented; no wall-clock or hash-order input reaches movement."""
    w1 = world_factory(seed=42, n_regions=1)
    w2 = world_factory(seed=9999, n_regions=1)

    # Query the steering sweep angles sequence from both worlds
    # The sweep order is fixed and documented (e.g. [0, +delta, -delta, +2delta, -2delta, ...])
    count = lib.om_steering_get_sweep_angle_count(w1)
    assert count > 0

    angles_w1 = [lib.om_steering_get_sweep_angle_at(w1, i) for i in range(count)]
    angles_w2 = [lib.om_steering_get_sweep_angle_at(w2, i) for i in range(count)]

    # Exactly identical across different world seeds and independent runs
    assert angles_w1 == angles_w2

    # Verify fixed alternating pattern: first angle is forward (0.0), second is positive (+), third is negative (-)
    assert pytest.approx(angles_w1[0], abs=1e-5) == 0.0
    if count >= 3:
        assert angles_w1[1] > 0.0
        assert angles_w1[2] < 0.0
        assert pytest.approx(abs(angles_w1[1]), abs=1e-5) == abs(angles_w1[2])

