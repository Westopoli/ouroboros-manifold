    # Spawn identical forces in both simulations
    u1_w1 = lib.om_unit_spawn(w1, OMUnitType.RAIDER, 0, 100.0, 100.0, 0)
    u2_w1 = lib.om_unit_spawn(w1, OMUnitType.VANGUARD, 1, 300.0, 100.0, 0)

    u1_w2 = lib.om_unit_spawn(w2, OMUnitType.RAIDER, 0, 100.0, 100.0, 0)
    u2_w2 = lib.om_unit_spawn(w2, OMUnitType.VANGUARD, 1, 300.0, 100.0, 0)

    # Identical command stream
    lib.om_command_attack_move(w1, u1_w1, 500.0, 100.0)
    lib.om_command_attack_move(w1, u2_w1, 0.0, 100.0)

    lib.om_command_attack_move(w2, u1_w2, 500.0, 100.0)
    lib.om_command_attack_move(w2, u2_w2, 0.0, 100.0)

