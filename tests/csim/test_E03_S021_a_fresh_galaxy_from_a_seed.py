def test_R_021_04_it_one_isolated_twin_colony(lib, world_factory):
    """Given the player, When they set a template preference before generation, Then it is one of Isolated, Twin Colony, Archipelago, or no preference; a set preference gives that template probability `WORLD_PLAYER_PREFERENCE_WEIGHT`, default 0.50, and the other two templates split the remainder equally (default 0.25 each), in the player faction's own roll only — configurable for playtesting, never locking the outcome, never affecting any NPC faction's roll."""
    # Set preference: Twin Colony.
    # Player buckets: Isolated [0, 0.25), Twin Colony [0.25, 0.75), Archipelago [0.75, 1.0).
    # NPC buckets: Isolated [0, 1/3), Twin Colony [1/3, 2/3), Archipelago [2/3, 1.0).
    w = world_factory(n_regions=0, seed=1)
    gen_set_player_preference(lib, w, OMTemplate.TWIN_COLONY)
    # Draw 0.30 for player falls in [0.25, 0.75) -> Twin Colony
    # Draw 0.30 for NPC 1 falls in [0, 1/3) -> Isolated
    force_draws(lib, w, [0.5, 0.30, 0.30] + [0.10] * 13)
    rc = generate(lib, w)
    assert rc == 1
    assert faction_template(lib, w, 0) == OMTemplate.TWIN_COLONY
    assert faction_template(lib, w, 1) == OMTemplate.ISOLATED

    # Configurable preference weight test:
    w2 = world_factory(n_regions=0, seed=2)
    gen_set_player_preference(lib, w2, OMTemplate.ARCHIPELAGO)
    gen_set_preference_weight(lib, w2, 0.60)  # Archipelago [0.40, 1.0), Isolated [0, 0.20), Twin [0.20, 0.40)
    force_draws(lib, w2, [0.5, 0.35, 0.35] + [0.10] * 13)
    rc2 = generate(lib, w2)
    assert rc2 == 1
    assert faction_template(lib, w2, 0) == OMTemplate.TWIN_COLONY
    assert faction_template(lib, w2, 1) == OMTemplate.TWIN_COLONY


def test_R_021_05_isolated_one_home_region_plus(lib, world_factory):
    """Given a faction's rolled template, When its regions are placed, Then: Isolated is one home region plus two frontier regions, both adjacent to the home; Twin Colony is two home regions adjacent to each other, each with its own count of 1 or 2 frontier regions (drawn uniformly per home) adjacent to that home; Archipelago is one home region plus three frontier regions, arranged so at least one frontier is not adjacent to the home or to another frontier (reached only through a chain of frontiers). Every region outside a faction's template is empty with no owner and no fields."""
    w = world_factory(n_regions=0, seed=1)
    gen_set_extra_edges_enabled(lib, w, 0)
    force_draws(lib, w, [0.5, 0.10, 0.40, 0.80] + [0.10] * 12)
    rc = generate(lib, w)
    assert rc == 1
    N = lib.om_region_count(w)

    # Check Faction 0 (Isolated)
    f0_regions = [r for r in range(N) if lib.om_region_owner(w, r) == 0]
    assert len(f0_regions) == 3
    f0_homes = [r for r in f0_regions if lib.om_region_tier(w, r) == OMTier.HOME]
    f0_frontiers = [r for r in f0_regions if lib.om_region_tier(w, r) == OMTier.FRONTIER]
    assert len(f0_homes) == 1
    assert len(f0_frontiers) == 2
    h0 = f0_homes[0]
    for fr in f0_frontiers:
        assert h0 in region_neighbors(lib, w, fr)

    # Check Faction 1 (Twin Colony)
    f1_regions = [r for r in range(N) if lib.om_region_owner(w, r) == 1]
    f1_homes = [r for r in f1_regions if lib.om_region_tier(w, r) == OMTier.HOME]
    f1_frontiers = [r for r in f1_regions if lib.om_region_tier(w, r) == OMTier.FRONTIER]
    assert len(f1_homes) == 2
    assert f1_homes[0] in region_neighbors(lib, w, f1_homes[1])
    assert 2 <= len(f1_frontiers) <= 4
    for fr in f1_frontiers:
        nbrs = region_neighbors(lib, w, fr)
        assert (f1_homes[0] in nbrs) or (f1_homes[1] in nbrs)

    # Check Faction 2 (Archipelago)
    f2_regions = [r for r in range(N) if lib.om_region_owner(w, r) == 2]
    assert len(f2_regions) == 4
    f2_homes = [r for r in f2_regions if lib.om_region_tier(w, r) == OMTier.HOME]
    f2_frontiers = [r for r in f2_regions if lib.om_region_tier(w, r) == OMTier.FRONTIER]
    assert len(f2_homes) == 1
    assert len(f2_frontiers) == 3
    h2 = f2_homes[0]
    has_sparse_frontier = any(h2 not in region_neighbors(lib, w, fr) for fr in f2_frontiers)
    assert has_sparse_frontier

    # Regions outside factions are empty with no owner and no fields
    for r in range(N):
        if lib.om_region_owner(w, r) == -1:
            assert lib.om_region_tier(w, r) == OMTier.EMPTY
            for field in (OMField.MILITARY, OMField.ECONOMY, OMField.TENSION, OMField.POPULATION):
                assert lib.om_region_field(w, r, field) == 0.0


def _unlinked_corridor_pairs(lib, w, n_regions):
    """Faction ids whose corridor end is not linked to the next faction's corridor end.
    The corridor end is a random pick from the empty pool (not an index-order guarantee), and
    R-021-07 may attach further empties to the same frontier, so it cannot be named from public
    data. With extra edges off, an empty attached by R-021-07 has exactly one edge (to the region
    it attached to), so an empty neighbour of one faction's highest frontier can touch an empty
    neighbour of the next faction's only through the corridor link. Returns (bad_fids, pairs),
    pairs[fid] = the (a, b) empty pairs that form that link."""
    ends = []
    for fid in range(15):
        f_frontiers = [r for r in range(n_regions)
                       if lib.om_region_owner(w, r) == fid and lib.om_region_tier(w, r) == OMTier.FRONTIER]
        highest_frontier = max(f_frontiers)
        empty_nbrs = [nbr for nbr in region_neighbors(lib, w, highest_frontier)
                      if lib.om_region_owner(w, nbr) == -1]
        assert len(empty_nbrs) >= 1
        ends.append(empty_nbrs)
    bad, pairs = [], {}
    for fid in range(14):
        found = [(c, n) for c in ends[fid] for n in ends[fid + 1]
                 if n in region_neighbors(lib, w, c) or c in region_neighbors(lib, w, n)]
        pairs[fid] = found
        if not found:
            bad.append(fid)
    return bad, pairs


def _cut_link(lib, w, a, b):
    """Remove the undirected edge (a, b): a negative type is "no edge" to om_region_edge."""
    lib.om_region_set_edge(w, a, b, -1)


@pytest.mark.parametrize("seed", [42, 7, 777, 2024])
def test_R_021_06_its_highest_numbered_frontier_region(lib, world_factory, seed):
    """Given a faction's template is placed, When corridors are laid, Then its highest-numbered frontier region (Isolated/Archipelago: numbered in placement order; Twin Colony: the second home's highest-numbered frontier) links to a chain of exactly 1 empty region, and the 15 factions' corridor ends are linked in faction order into one chain.

    Test-defect fix (Architect rulings 2, A28): the old form took the first empty neighbour as
    the corridor end, which held only by seed luck. Some empty neighbour of each faction's
    highest frontier is linked to some empty neighbour of the next faction's; a positive control
    cuts one corridor link and the check must then fail."""
    w = world_factory(n_regions=0, seed=seed)
    gen_set_extra_edges_enabled(lib, w, 0)
    rc = generate(lib, w)
    assert rc == 1
    N = lib.om_region_count(w)

    bad, pairs = _unlinked_corridor_pairs(lib, w, N)
    assert bad == [], f"corridor link missing after faction(s) {bad}"

    # positive control: cut every candidate pair of one corridor link; the check must fail on it
    cut_fid = 6
    for a, b in pairs[cut_fid]:
        _cut_link(lib, w, a, b)
    bad_after, _ = _unlinked_corridor_pairs(lib, w, N)
    assert bad_after == [cut_fid], "cutting a corridor link must make the check fail on exactly that link"


