def test_R_021_09_every_region_reachable_from_every(lib, world_factory):
    """Given any generated world, When connectivity is checked, Then every region is reachable from every other."""
    w = world_factory(n_regions=0, seed=777)
    rc = generate(lib, w)
    assert rc == 1
    N = lib.om_region_count(w)
    visited = set()
    queue = [0]
    visited.add(0)
    while queue:
        curr = queue.pop(0)
        for nbr in region_neighbors(lib, w, curr):
            if nbr not in visited:
                visited.add(nbr)
                queue.append(nbr)
    assert len(visited) == N, f"only {len(visited)} of {N} regions reachable"


def test_R_021_10_every_faction_s_template_roll(lib, world_factory):
    """Given the same seed, When generated twice, Then every faction's template roll, the region ids, adjacency lists, edge types, and starting fields are identical."""
    seed = 99999
    w1 = world_factory(n_regions=0, seed=seed)
    w2 = world_factory(n_regions=0, seed=seed)
    rc1 = generate(lib, w1)
    rc2 = generate(lib, w2)
    assert rc1 == 1 and rc2 == 1
    N1 = lib.om_region_count(w1)
    N2 = lib.om_region_count(w2)
    assert N1 == N2
    assert world_edge_count(lib, w1) == world_edge_count(lib, w2)
    for f in range(15):
        assert faction_template(lib, w1, f) == faction_template(lib, w2, f)
        assert lib.om_faction_archetype(w1, f) == lib.om_faction_archetype(w2, f)
        assert lib.om_faction_tech(w1, f) == pytest.approx(lib.om_faction_tech(w2, f), abs=1e-6)
    for r in range(N1):
        assert lib.om_region_tier(w1, r) == lib.om_region_tier(w2, r)
        assert lib.om_region_owner(w1, r) == lib.om_region_owner(w2, r)
        for field in (OMField.MILITARY, OMField.ECONOMY, OMField.TENSION, OMField.POPULATION):
            assert lib.om_region_field(w1, r, field) == pytest.approx(lib.om_region_field(w2, r, field), abs=1e-6)
        nbrs1 = region_neighbors(lib, w1, r)
        nbrs2 = region_neighbors(lib, w2, r)
        assert nbrs1 == nbrs2
        out1 = ctypes.c_int()
        out2 = ctypes.c_int()
        for nbr in nbrs1:
            lib.om_region_edge(w1, r, nbr, ctypes.byref(out1))
            lib.om_region_edge(w2, r, nbr, ctypes.byref(out2))
            assert out1.value == out2.value
