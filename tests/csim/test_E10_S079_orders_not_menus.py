def test_R_079_02_only_controls_accept_refuse_there(lib, world_factory):
    """Given the briefing, When shown, Then the only controls are Accept and Refuse; there is no loadout or force editing."""
    w = world_factory(n_regions=1)
    lib.om_mission_setup_tactical(w, 0, 1000)

    # Allowed controls bitmask: ACCEPT (1), REFUSE (2). EDIT_LOADOUT (4) must be 0.
    controls = lib.om_mission_get_briefing_controls(w)
    accept_mask = 1 << 0
    refuse_mask = 1 << 1
    edit_mask = 1 << 2

    assert (controls & accept_mask) != 0
    assert (controls & refuse_mask) != 0
    assert (controls & edit_mask) == 0

    # Force editing check
    can_edit = lib.om_mission_can_edit_loadout(w)
    assert can_edit == 0


def test_R_079_03_it_shows_band_objectives_with(lib, world_factory):
    """Given the mission ends, When the debrief is shown, Then it shows the band, the objectives with completion, force retention, and commander fate."""
    w = world_factory(n_regions=1)
    lib.om_mission_setup_tactical(w, 0, 1000)

    # Force a specific outcome: every objective fully complete, none failed.
    # A zeroed debrief struct would satisfy the range checks below with no
    # mission having run at all, so pin an exact expected score.
    lib.om_mission_build_objectives(w, 0)
    n_obj = lib.om_mission_objective_count(w)
    for i in range(n_obj):
        lib.om_mission_set_objective_completion(w, i, 1.0)

    lib.om_mission_end(w)

    debrief = OMDebrief()
    lib.om_mission_get_debrief(w, ctypes.byref(debrief))

    # ALG-58: objective_score = Sum(weight * completion) with none failed;
    # weights sum to 1.0 (R-075-01), all completions forced to 1.0 above.
    assert debrief.objective_score == pytest.approx(1.0, abs=1e-5)
    assert debrief.band >= 0
    assert 0.0 <= debrief.objective_score <= 1.0
    assert 0.0 <= debrief.retention <= 1.0
    assert debrief.commander_fate in (0, 1, 2)  # killed, wounded, survived


def test_R_079_04_it_contains_no_raw_field(lib, world_factory):
    """Given any briefing or debrief text, When rendered, Then it contains no raw field numbers."""
    w = world_factory(n_regions=1)
    set_region(lib, w, 0, military=23.456, economy=78.910, tension=34.567, population=89.012)
    lib.om_mission_setup_tactical(w, 0, 1000)

    briefing = OMBriefing()
    lib.om_mission_assemble_briefing(w, ctypes.byref(briefing))

    briefing_full = (briefing.situation_text + b" " + briefing.objective_text + b" " + briefing.assets_text).decode("utf-8")

    # None of the raw floats like 23.456 or 78.910 should be present
    assert "23.456" not in briefing_full
    assert "78.910" not in briefing_full
    assert "34.567" not in briefing_full
    assert "89.012" not in briefing_full

    lib.om_mission_end(w)
    debrief = OMDebrief()
    lib.om_mission_get_debrief(w, ctypes.byref(debrief))
    debrief_text = debrief.text.decode("utf-8")

    assert "23.456" not in debrief_text
    assert "78.910" not in debrief_text

