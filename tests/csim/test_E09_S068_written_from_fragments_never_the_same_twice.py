def test_R_068_04_it_reads_region_held_by(lib, world_factory):
    """Given a region's first mention in a scroll, When rendered, Then it reads "<region>, held by <faction display name>", and later mentions use the bare name; an unowned region gets no qualifier."""
    w = world_factory(n_regions=4)
    set_owner(lib, w, 1, faction_id=2)
    set_owner(lib, w, 2, faction_id=-1)  # unowned

    # Owned region 1 first mention has qualifier ", held by <Faction>"
    first_mention_owned = lib.om_chronicle_render_region_mention(w, region_idx=1, is_first_mention=1)
    first_str = ctypes.string_at(first_mention_owned).decode("utf-8")
    assert ", held by " in first_str

    # Later mention uses bare name
    later_mention_owned = lib.om_chronicle_render_region_mention(w, region_idx=1, is_first_mention=0)
    later_str = ctypes.string_at(later_mention_owned).decode("utf-8")
    assert ", held by " not in later_str

    # Unowned region gets no qualifier on first mention
    first_mention_unowned = lib.om_chronicle_render_region_mention(w, region_idx=2, is_first_mention=1)
    unowned_str = ctypes.string_at(first_mention_unowned).decode("utf-8")
    assert ", held by " not in unowned_str


