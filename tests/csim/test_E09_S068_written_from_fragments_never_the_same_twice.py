def test_R_068_07_later_one_dropped_first_always(lib, world_factory):
    """Given the finished entries in order, When two entries share 40 percent or more of their content words (relative to the shorter), Then the later one is dropped; the first always survives."""
    w = world_factory(n_regions=2)

    # Entry 1 and Entry 2 share > 40% content words
    lib.om_chronicle_add_raw_entry(w, entry_id=1, text=b"soldiers fought bravely across the mountain valley to defend their homeland")
    lib.om_chronicle_add_raw_entry(w, entry_id=2, text=b"soldiers fought bravely across the mountain valley to claim victory")

    lib.om_chronicle_dedup_content_words(w, threshold=0.40)

    # Entry 1 kept, Entry 2 dropped
    assert lib.om_chronicle_entry_is_retained(w, entry_id=1) == 1
    assert lib.om_chronicle_entry_is_retained(w, entry_id=2) == 0


def test_R_068_08_text_identical(lib, world_factory):
    """Given the assembler seed equals the jump's start tick, When run twice on the same clusters, Then the text is identical."""
    w1 = world_factory(n_regions=4, seed=100)
    w2 = world_factory(n_regions=4, seed=100)

    jump_start_tick = 50
    lib.om_chronicle_assemble_with_seed(w1, seed=jump_start_tick)
    lib.om_chronicle_assemble_with_seed(w2, seed=jump_start_tick)

    text1 = lib.om_chronicle_get_full_scroll_text(w1)
    text2 = lib.om_chronicle_get_full_scroll_text(w2)

    # Two empty scrolls are trivially equal; require real text first.
    assert len(ctypes.string_at(text1)) > 0
    assert ctypes.string_at(text1) == ctypes.string_at(text2)
