def test_R_068_01_opening_detail_closing_each_drawn(lib, world_factory):
    """Given a cluster with category C, When its entry is assembled, Then an opening, a detail, and a closing are each drawn uniformly from C's pools among fragments whose required slots resolve from the cluster; base form = opening + detail, expanded form = opening + detail + closing."""
    w = world_factory(n_regions=2)

