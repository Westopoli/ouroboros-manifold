def _get_tech_tier(lib, w, faction_id):
    if hasattr(lib, "om_faction_tech_tier"):
        return lib.om_faction_tech_tier(w, faction_id)
    return lib.om_tech_tier(lib.om_faction_tech(w, faction_id))


def test_R_048_01_it_1_in_34_67(lib, world_factory):
    """Given tech in [0, 34), When the tier is read, Then it is 1; in [34, 67) it is 2; in [67, 100] it is 3."""
    w = world_factory(n_regions=1)

    # Test [0, 34) -> tier 1
    for t in (0.0, 10.0, 33.9, 33.99):
        set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=t)
        assert _get_tech_tier(lib, w, 0) == 1, f"tech {t} should be tier 1"

    # Test [34, 67) -> tier 2
    for t in (34.0, 50.0, 66.9, 66.99):
        set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=t)
        assert _get_tech_tier(lib, w, 0) == 2, f"tech {t} should be tier 2"

    # Test [67, 100] -> tier 3
    for t in (67.0, 80.0, 99.9, 100.0):
        set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=t)
        assert _get_tech_tier(lib, w, 0) == 3, f"tech {t} should be tier 3"


def test_R_048_02_units_use_tier_2_profile(lib, world_factory):
    """Given a faction crosses from 33.9 to 34.1, When the next mission generates its forces, Then units use the tier 2 profile; units already fielded in a running mission do not change."""
    w = world_factory(n_regions=1)
    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=100.0, tech=33.9)
    assert _get_tech_tier(lib, w, 0) == 1

    # Active mission running with fielded forces at tier 1
    running_mission_id = lib.om_mission_start(w, 0) if hasattr(lib, "om_mission_start") else 0
    if hasattr(lib, "om_mission_unit_tier"):
        assert lib.om_mission_unit_tier(w, running_mission_id) == 1

    # Cross tier boundary: tech 33.9 -> 34.1
    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=100.0, tech=34.1)
    assert _get_tech_tier(lib, w, 0) == 2

    # Next mission generates forces with tier 2 profile
    next_mission_tier = (
        lib.om_faction_next_mission_unit_tier(w, 0)
        if hasattr(lib, "om_faction_next_mission_unit_tier")
        else lib.om_faction_unit_tier(w, 0)
    )
    assert next_mission_tier == 2

    # Running mission forces remain at tier 1
    if hasattr(lib, "om_mission_unit_tier"):
        assert lib.om_mission_unit_tier(w, running_mission_id) == 1


