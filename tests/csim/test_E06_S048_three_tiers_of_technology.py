def test_R_048_04_tier_transition_entry_candidate_e(lib, world_factory):
    """Given a tier change on tick t, When the chronicle distills the window containing t, Then a tier-transition entry is a candidate (E-09)."""
    w = world_factory(n_regions=1)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.TECHNOLOGY, 1)

    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=33.9)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=60.0, tension=10.0, population=50.0)
    set_owner(lib, w, 0, 0)

    # Cross tier boundary on this step (growth = 0.105 pushes 33.9 -> 34.005 >= 34.0)
    lib.om_world_step(w)
    assert _get_tech_tier(lib, w, 0) == 2

    # Distill window containing current tick: tier transition candidate should be present
    candidates = []
    if hasattr(lib, "om_chronicle_distill_candidates"):
        buf = (ctypes.c_uint32 * 32)()
        n = lib.om_chronicle_distill_candidates(w, buf, 32)
        candidates = [buf[i] for i in range(n)]
    elif hasattr(lib, "om_tier_transition_candidate_exists"):
        candidates = [1] if lib.om_tier_transition_candidate_exists(w, 0) else []
    else:
        # Check through standard distillation reader
        candidates = [lib.om_faction_tier_transition_candidate(w, 0)]

    assert len(candidates) >= 1

