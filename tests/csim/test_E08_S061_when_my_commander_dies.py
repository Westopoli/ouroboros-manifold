def test_R_061_01_living_lineage_member_not_supreme(lib, world_factory):
    """Given the commander died in the mission, When the next selection runs, Then a living lineage member (not a supreme commander) in the mission region is chosen first, then one in an adjacent region, then, only if the lineage has fewer than 2 chapters played, any living member anywhere."""
    w = world_factory(n_regions=4)
    set_edge(lib, w, 0, 1)
    set_edge(lib, w, 1, 2)
    set_edge(lib, w, 2, 3)

    lib.om_lineage_create(w, lineage_id=1, home_region=0)
    lib.om_lineage_set_chapter_count(w, lineage_id=1, chapters=1)

    # Commander died in mission region 0
    lib.om_character_create(w, character_id=1, lineage_id=1, region_idx=0, rank=OMRank.LINEAGE_MEMBER, birth_tick=0, lifespan=50)
    lib.om_character_kill(w, character_id=1, tick=50)

    # Supreme commander in region 0 (MUST NOT be chosen)
    lib.om_character_create(w, character_id=2, lineage_id=1, region_idx=0, rank=OMRank.SUPREME_COMMANDER, birth_tick=10, lifespan=100)

    # Living lineage member in mission region 0
    lib.om_character_create(w, character_id=3, lineage_id=1, region_idx=0, rank=OMRank.LINEAGE_MEMBER, birth_tick=15, lifespan=100)

    # Priority 1: chooses member 3 in mission region 0
    rec = OmSelectionRecord()
    lib.om_character_selector_resolve_commander_death(w, lineage_id=1, mission_region=0, out_record=ctypes.byref(rec))
    assert rec.rotated == 0
    assert rec.commander_id == 3

    # Priority 2: member in adjacent region 1 chosen if none in mission region 0
    lib.om_character_kill(w, character_id=3, tick=50)
    lib.om_character_create(w, character_id=4, lineage_id=1, region_idx=1, rank=OMRank.LINEAGE_MEMBER, birth_tick=20, lifespan=100)
    lib.om_character_selector_resolve_commander_death(w, lineage_id=1, mission_region=0, out_record=ctypes.byref(rec))
    assert rec.rotated == 0
    assert rec.commander_id == 4

    # Priority 3: member in far region 3 chosen only if chapters < 2
    lib.om_character_kill(w, character_id=4, tick=50)
    lib.om_character_create(w, character_id=5, lineage_id=1, region_idx=3, rank=OMRank.LINEAGE_MEMBER, birth_tick=25, lifespan=100)
    lib.om_character_selector_resolve_commander_death(w, lineage_id=1, mission_region=0, out_record=ctypes.byref(rec))
    assert rec.rotated == 0
    assert rec.commander_id == 5


