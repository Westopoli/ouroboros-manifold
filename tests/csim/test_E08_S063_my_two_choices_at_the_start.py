class OMDifficulty:
    EASY = 0
    MEDIUM = 1
    HARD = 2


class OmOnboardingConfig(ctypes.Structure):
    _fields_ = [
        ("difficulty", ctypes.c_uint32),
        ("weights", ctypes.c_double * 10),
        ("rare_marks", ctypes.c_uint32 * 10),
    ]


def test_R_063_01_it_offers_difficulty_easy_medium(lib, world_factory):
    """Given the onboarding screen, When shown, Then it offers difficulty (easy, medium, hard) and, for each of the 10 mission archetypes, a preference weight with a "rare" mark; at least one archetype must stay unmarked [Q-063-01: bible says at most two rare marks, code allows up to nine]."""
    w = world_factory(n_regions=4)

    cfg = OmOnboardingConfig()
    cfg.difficulty = OMDifficulty.MEDIUM
    for i in range(10):
        cfg.weights[i] = 0.5
        cfg.rare_marks[i] = 1 if i < 9 else 0  # 9 rare marks, 1 unmarked -> valid

    valid_rc = lib.om_onboarding_validate(ctypes.byref(cfg))
    assert valid_rc == 0

    # Invalid: all 10 marked rare (none unmarked) -> rejection
    cfg.rare_marks[9] = 1
    invalid_rc = lib.om_onboarding_validate(ctypes.byref(cfg))
    assert invalid_rc != 0


def test_R_063_02_choices_stored_per_save_slot(lib, world_factory):
    """Given the player confirms, When saved, Then the choices are stored per save slot and read by the mission generator (E-10) and difficulty scaling."""
    w = world_factory(n_regions=4)

    cfg = OmOnboardingConfig()
    cfg.difficulty = OMDifficulty.HARD
    for i in range(10):
        cfg.weights[i] = 0.1 * (i + 1)
        cfg.rare_marks[i] = 0

    lib.om_onboarding_save_to_slot(w, slot_id=1, cfg=ctypes.byref(cfg))

    read_cfg = OmOnboardingConfig()
    lib.om_onboarding_load_from_slot(w, slot_id=1, out_cfg=ctypes.byref(read_cfg))

    assert read_cfg.difficulty == OMDifficulty.HARD
    assert read_cfg.weights[0] == pytest.approx(0.1, abs=1e-5)


