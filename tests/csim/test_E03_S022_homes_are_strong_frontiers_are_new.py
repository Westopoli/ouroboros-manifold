def test_R_022_01_population_uniform_in_55_75(lib, world_factory):
    """Given a home region, When its fields are rolled, Then population is uniform in [55, 75]; Given a frontier region, Then population is uniform in [25, 50]."""
    w = world_factory(n_regions=0, seed=123)
    rc = generate(lib, w)
    assert rc == 1, "world generation failed"
    N = lib.om_region_count(w)
    home_found = False
    frontier_found = False
    for r in range(N):
        tier = lib.om_region_tier(w, r)
        pop = lib.om_region_field(w, r, OMField.POPULATION)
        if tier == OMTier.HOME:
            assert 55.0 <= pop <= 75.0, f"home region {r} population {pop} outside [55, 75]"
            home_found = True
        elif tier == OMTier.FRONTIER:
            assert 25.0 <= pop <= 50.0, f"frontier region {r} population {pop} outside [25, 50]"
            frontier_found = True
    assert home_found and frontier_found, "expected both home and frontier regions in generated world"


