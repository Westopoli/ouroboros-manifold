def test_R_022_03_economy_phase_tension_phase_independent(lib, world_factory):
    """Given a region, When phase offsets are drawn, Then economy phase and tension phase are independent uniform draws in [0, 2π)."""
    w = world_factory(n_regions=0, seed=42)
    rc = generate(lib, w)
    assert rc == 1
    N = lib.om_region_count(w)
    lib.om_world_step(w)
    observed_econ_deltas = set()
    observed_tension_deltas = set()
    for r in range(N):
        if lib.om_region_tier(w, r) != OMTier.EMPTY:
            rc, drift = read_drift(lib, w, r)
            assert rc == 0
            assert -6.0 <= drift.economy_osc_delta <= 6.0
            assert -2.0 <= drift.tension_osc_delta <= 2.0
            observed_econ_deltas.add(round(drift.economy_osc_delta, 4))
            observed_tension_deltas.add(round(drift.tension_osc_delta, 4))
    assert len(observed_econ_deltas) > 1, "regions unexpectedly share identical economy phases"
    assert len(observed_tension_deltas) > 1, "regions unexpectedly share identical tension phases"


def test_R_022_04_rng_consumed_in_exactly_that(lib, world_factory):
    """Given the draw order population, j₁, j₂, j₃, economy phase, tension phase, When a region is generated, Then the RNG is consumed in exactly that order (determinism contract)."""
    w = world_factory(n_regions=0, seed=1)
    region_draws = [0.50, 0.50, 0.50, 0.50, 0.25, 0.50]
    force_draws(lib, w, [0.50] + [0.10] * 15 + region_draws)
    rc = generate(lib, w)
    assert rc == 1
    assert lib.om_region_owner(w, 0) == 0
    assert lib.om_region_tier(w, 0) == OMTier.HOME
    assert lib.om_region_field(w, 0, OMField.POPULATION) == pytest.approx(65.0, abs=1e-4)
    assert lib.om_region_field(w, 0, OMField.ECONOMY) == pytest.approx(71.5, abs=1e-4)
    assert lib.om_region_field(w, 0, OMField.MILITARY) == pytest.approx(45.5, abs=1e-4)
    assert lib.om_region_field(w, 0, OMField.TENSION) == pytest.approx(19.5, abs=1e-4)


def test_R_022_05_archetype_s_own_range_replaces(lib, world_factory):
    """Given a home region, When its military and economy are rolled, Then the archetype's own range replaces R-022-02's general clamp targets: Conqueror military 50–65, economy 40–55; Fortifier military 40–50, economy 50–65; Opportunist military 45–55, economy 45–55; the player faction and tension/population keep R-022-01/R-022-02's general ranges. Frontier regions keep R-022-01's newly-settled ranges regardless of archetype. Starting tech = average starting population of its regions · 0.25."""
    w = world_factory(n_regions=0, seed=42)
    rc = generate(lib, w)
    assert rc == 1
    N = lib.om_region_count(w)
    for fid in range(15):
        arch = lib.om_faction_archetype(w, fid)
        f_regions = [r for r in range(N) if lib.om_region_owner(w, r) == fid]
        assert len(f_regions) >= 3
        f_homes = [r for r in f_regions if lib.om_region_tier(w, r) == OMTier.HOME]
        for hr in f_homes:
            mil = lib.om_region_field(w, hr, OMField.MILITARY)
            eco = lib.om_region_field(w, hr, OMField.ECONOMY)
            if arch == OMArchetype.CONQUEROR:
                assert 50.0 <= mil <= 65.0, f"Conqueror home military {mil} outside [50, 65]"
                assert 40.0 <= eco <= 55.0, f"Conqueror home economy {eco} outside [40, 55]"
            elif arch == OMArchetype.FORTIFIER:
                assert 40.0 <= mil <= 50.0, f"Fortifier home military {mil} outside [40, 50]"
                assert 50.0 <= eco <= 65.0, f"Fortifier home economy {eco} outside [50, 65]"
            elif arch == OMArchetype.OPPORTUNIST:
                assert 45.0 <= mil <= 55.0, f"Opportunist home military {mil} outside [45, 55]"
                assert 45.0 <= eco <= 55.0, f"Opportunist home economy {eco} outside [45, 55]"
            elif arch == OMArchetype.PLAYER:
                pop = lib.om_region_field(w, hr, OMField.POPULATION)
                assert max(0.0, min(100.0, pop * 0.7 - 5.0)) <= mil <= max(0.0, min(100.0, pop * 0.7 + 5.0))
                assert max(0.0, min(100.0, pop * 1.1 - 5.0)) <= eco <= max(0.0, min(100.0, pop * 1.1 + 5.0))
        f_frontiers = [r for r in f_regions if lib.om_region_tier(w, r) == OMTier.FRONTIER]
        for fr in f_frontiers:
            fpop = lib.om_region_field(w, fr, OMField.POPULATION)
            assert 25.0 <= fpop <= 50.0, f"frontier pop {fpop} outside [25, 50]"
        avg_pop = sum(lib.om_region_field(w, r, OMField.POPULATION) for r in f_regions) / len(f_regions)
        expected_tech = avg_pop * 0.25
        assert lib.om_faction_tech(w, fid) == pytest.approx(expected_tech, abs=1e-5)
