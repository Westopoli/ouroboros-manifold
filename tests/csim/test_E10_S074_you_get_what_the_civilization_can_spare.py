def test_R_074_01_it_attacker_s_committed_budget(lib, world_factory):
    """Given an archetype driven by an attack, When enemy power is set, Then it is the attacker's committed budget × 300; given an insurgent archetype (suppression, counterinsurgency), Then it is a rolled insurgent military × 2000, where the roll is uniform in a range interpolated by population from [20, 50] at population ≤ 25 to [40, 70] at ≥ 70; otherwise it is the region's military × 2000."""
    w = world_factory(n_regions=3)
    set_faction(lib, w, 0, OMArchetype.PLAYER, budget=50.0)

    # 1. Attack-driven (Defensive Stand): committed budget 40.0 -> 40.0 * 300 = 12,000.0
    power_attack = lib.om_mission_compute_enemy_power(w, OMMissionArchetype.DEFENSIVE_STAND, 40.0, 50.0, 50.0)
    assert power_attack == pytest.approx(12000.0, abs=1e-6)

    # 2. Insurgent archetype (Suppression) at population <= 25 (range [20, 50])
    # Pin uniform draw at 0.5 -> insurgent_m = 20 + 0.5 * 30 = 35.0 -> power = 35.0 * 2000 = 70,000.0
    force_draws(lib, w, [0.5])
    power_insurgent_low = lib.om_mission_compute_enemy_power(w, OMMissionArchetype.SUPPRESSION, 0.0, 20.0, 25.0)
    assert power_insurgent_low == pytest.approx(70000.0, abs=1e-6)

    # Insurgent at population >= 70 (range [40, 70])
    # Pin uniform draw at 0.5 -> insurgent_m = 40 + 0.5 * 30 = 55.0 -> power = 55.0 * 2000 = 110,000.0
    force_draws(lib, w, [0.5])
    power_insurgent_high = lib.om_mission_compute_enemy_power(w, OMMissionArchetype.SUPPRESSION, 0.0, 20.0, 70.0)
    assert power_insurgent_high == pytest.approx(110000.0, abs=1e-6)

    # 3. Otherwise (Siege Breaking): region military 35.0 -> 35.0 * 2000 = 70,000.0
    power_other = lib.om_mission_compute_enemy_power(w, OMMissionArchetype.SIEGE_BREAKING, 0.0, 35.0, 50.0)
    assert power_other == pytest.approx(70000.0, abs=1e-6)


