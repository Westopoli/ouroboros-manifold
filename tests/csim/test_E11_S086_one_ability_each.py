def test_R_086_03_it_immobile_at_once_has(lib, world_factory):
    """Given a Vanguard with Brace ready, When activated, Then it is immobile at once, has no bonus for 40 ticks (2 s windup), then takes 50 percent less damage and deals 1.3× while braced; activating again cancels with the same 40-tick windup; cooldown 700 ticks (35 s) starts at activation."""
    w = world_factory(n_regions=1)

    vanguard = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, 0.0, 0)
    lib.om_command_activate_ability(w, [vanguard], 1, 0.0, 0.0)

    # Immobile at once
    assert lib.om_unit_effective_speed(w, vanguard) == 0.0

    # 40 ticks windup: no bonus
    for _ in range(40):
        lib.om_tactical_step(w)
        assert lib.om_unit_effective_speed(w, vanguard) == 0.0
        assert lib.om_unit_damage_reduction(w, vanguard) == 0.0
        assert lib.om_unit_output_multiplier(w, vanguard) == 1.0

    # After 40 ticks: active braced state -> 50% less damage, 1.3x output
    lib.om_tactical_step(w)
    assert lib.om_unit_damage_reduction(w, vanguard) == pytest.approx(0.50, abs=1e-6)
    assert lib.om_unit_output_multiplier(w, vanguard) == pytest.approx(1.3, abs=1e-6)

    # Cooldown 700 ticks started at activation
    assert lib.om_unit_ability_cooldown(w, vanguard) <= 700.0

    # Activating again cancels with same 40-tick windup
    lib.om_command_activate_ability(w, [vanguard], 1, 0.0, 0.0)
    for _ in range(40):
        lib.om_tactical_step(w)
        assert lib.om_unit_damage_reduction(w, vanguard) == pytest.approx(0.50, abs=1e-6)

    lib.om_tactical_step(w)
    assert lib.om_unit_damage_reduction(w, vanguard) == 0.0


def test_R_086_04_every_friendly_unit_within_400(lib, world_factory):
    """Given a Warden with Rally ready, When activated, Then every friendly unit within 400 wu regains 112 HP at once, capped at max HP; cooldown 1,500 ticks (75 s)."""
    w = world_factory(n_regions=1)

    warden = lib.om_unit_spawn(w, OMUnitType.WARDEN, 0, 0.0, 0.0, 0)

    # Friendly Vanguard (max 500 HP, current 300 HP) at 350 wu (within 400 wu)
    f_in = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 350.0, 0.0, 0)
    lib.om_unit_set_hp(w, f_in, 300.0)

    # Friendly Vanguard near max (max 500 HP, current 450 HP) at 200 wu -> capped at 500
    f_cap = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 200.0, 0.0, 0)
    lib.om_unit_set_hp(w, f_cap, 450.0)

    # Friendly Vanguard outside 400 wu (at 450 wu) -> no heal
    f_out = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 450.0, 0.0, 0)
    lib.om_unit_set_hp(w, f_out, 300.0)

    lib.om_command_activate_ability(w, [warden], 1, 0.0, 0.0)

    assert lib.om_unit_hp(w, f_in) == pytest.approx(300.0 + 112.0, abs=1e-6)
    assert lib.om_unit_hp(w, f_cap) == pytest.approx(500.0, abs=1e-6)  # capped at max HP
    assert lib.om_unit_hp(w, f_out) == pytest.approx(300.0, abs=1e-6)
    assert lib.om_unit_ability_cooldown(w, warden) == pytest.approx(1500.0, abs=1.0)


def test_R_086_05_after_30_tick_1_5(lib, world_factory):
    """Given a Bombard with Barrage ready and a target position, When activated, Then after a 30-tick (1.5 s) telegraph visible to both sides, every enemy within 100 wu of the position on the Bombard's layer takes base × 3.0, subject to the AoE cap at 4 × (base × 3.0); cooldown 1,800 ticks (90 s)."""
    w = world_factory(n_regions=1)

    bombard = lib.om_unit_spawn(w, OMUnitType.BOMBARD, 0, 0.0, 0.0, 0)
    target_x, target_y = 500.0, 0.0

    # 3 enemies within 100 wu of target position
    enemies = [
        lib.om_unit_spawn(w, OMUnitType.VANGUARD, 1, target_x + float(i * 20), target_y, 0)
        for i in range(3)
    ]
    initial_hps = [lib.om_unit_hp(w, u) for u in enemies]

    lib.om_command_activate_ability(w, [bombard], 1, target_x, target_y)

    # 30 ticks telegraph: no damage yet, telegraph visible
    for tick in range(30):
        lib.om_tactical_step(w)
        assert lib.om_tactical_telegraph_active(w, target_x, target_y) == 1
        for i, u in enumerate(enemies):
            assert lib.om_unit_hp(w, u) == initial_hps[i]

    # Tick 31: damage lands! Base 17.5 * 3.0 = 52.5. Matchup Siege->Line = 1.5 -> per-target = 52.5 * 1.5 = 78.75.
    # Cap = 4 * (base * 3.0) = 4 * 52.5 = 210.0.
    lib.om_tactical_step(w)
    total_dmg = sum(initial_hps[i] - lib.om_unit_hp(w, enemies[i]) for i in range(3))
    assert total_dmg <= 210.0
    assert lib.om_unit_ability_cooldown(w, bombard) == pytest.approx(1800.0, abs=1.0)


