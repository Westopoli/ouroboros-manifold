def test_R_086_08_it_activates_no_other_enemy(lib, world_factory):
    """Given an enemy unit, When its ability is ready and the threshold condition holds (an enemy in range for Surge, Brace, Barrage; a damaged friendly in radius for Rally; two or more friendlies in radius for Fortify), Then it activates; no other enemy timing logic exists."""
