def test_R_096_07_all_them_applied_before_any(lib, world_factory):
    """Given commands for tick t, When the tick runs, Then all of them are applied before any state advances, in arrival order, and recorded with the tick number for replay."""
    w = world_factory(n_regions=1)

    u = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 100.0, 100.0, 0)

    # Queue two commands for tick t:
    # Command 1: Move to (300, 100)
    # Command 2: Attack-move to (800, 100)
    lib.om_command_queue_move(w, u, 300.0, 100.0)
    lib.om_command_queue_attack_move(w, u, 800.0, 100.0)

    # Run the tick
    lib.om_world_step(w)

    # In arrival order, Command 2 was applied after Command 1 before state advanced
    order_kind = lib.om_unit_get_order_kind(w, u)
    assert order_kind == OMOrderKind.ATTACK_MOVE
    dest_x, dest_y = lib.om_unit_get_destination(w, u)
    assert pytest.approx(dest_x, abs=1e-4) == 800.0

    # Both commands recorded with tick number for deterministic replay
    replay_count = lib.om_replay_get_command_count_at_tick(w, 0)
    assert replay_count == 2

