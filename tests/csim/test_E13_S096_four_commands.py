def test_R_096_01_it_acquires_no_target_returns(lib, world_factory):
    """Given a plain move, When the unit travels, Then it acquires no target, returns no fire, and does not stop when hit."""
    w = world_factory(n_regions=1)

    # Friendly Vanguard given plain move from (0, 0) to (1000, 0)
