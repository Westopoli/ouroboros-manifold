def test_R_096_05_each_unit_with_its_ability(lib, world_factory):
    """Given activate-ability, When issued to a selection, Then each unit with its ability ready activates it; Brace toggles."""
    w = world_factory(n_regions=1)

    vanguard = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 100.0, 100.0, 0)
    raider = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 150.0, 100.0, 0)

    selection = (ctypes.c_uint32 * 2)(vanguard, raider)

    # First activate-ability: Raider activates Surge, Vanguard toggles Brace ON
    lib.om_command_activate_ability(w, selection, 2)
    assert lib.om_unit_is_braced(w, vanguard) == 1
    assert lib.om_unit_has_active_buff(w, raider, b"surge") == 1

    # Second activate-ability: Vanguard toggles Brace OFF
    lib.om_command_activate_ability(w, selection, 2)
    assert lib.om_unit_is_braced(w, vanguard) == 0


