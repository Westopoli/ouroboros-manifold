def test_R_081_01_damage_base_damage_m_b(lib, world_factory):
    """Given an attacker of category A and a target of category B, When damage is dealt, Then damage = base damage × M[A][B] with M: Strike→Strike 1.0, Strike→Line 0.75, Strike→Siege 1.5; Line→Strike 1.5, Line→Line 1.0, Line→Siege 0.75; Siege→Strike [Q-081-01: 0.20 in code, 0.75 in the bible], Siege→Line 1.5, Siege→Siege 1.0."""
    w = world_factory(n_regions=1)

    expected_m = {
        (OMCategory.STRIKE, OMCategory.STRIKE): 1.0,
        (OMCategory.STRIKE, OMCategory.LINE): 0.75,
        (OMCategory.STRIKE, OMCategory.SIEGE): 1.5,
        (OMCategory.LINE, OMCategory.STRIKE): 1.5,
        (OMCategory.LINE, OMCategory.LINE): 1.0,
        (OMCategory.LINE, OMCategory.SIEGE): 0.75,
        (OMCategory.SIEGE, OMCategory.STRIKE): 0.20,  # Q-081-01: confirmed 0.20
        (OMCategory.SIEGE, OMCategory.LINE): 1.5,
        (OMCategory.SIEGE, OMCategory.SIEGE): 1.0,
    }

    base_damage = 20.0
    for (cat_a, cat_b), mult in expected_m.items():
        # Query matrix directly from C sim ABI and verify through single-hit resolution
        c_mult = lib.om_tactical_category_multiplier(w, cat_a, cat_b)
        assert c_mult == pytest.approx(mult, abs=1e-6)

        # Verify applied damage on spawned attacker and target
        u_atk = lib.om_unit_spawn_for_category(w, cat_a, 0, 0.0, 0.0, 0)
        u_tgt = lib.om_unit_spawn_for_category(w, cat_b, 1, 50.0, 0.0, 0)
        initial_hp = lib.om_unit_hp(w, u_tgt)

        lib.om_unit_deal_damage(w, u_atk, u_tgt, base_damage)
        damage_dealt = initial_hp - lib.om_unit_hp(w, u_tgt)
        assert damage_dealt == pytest.approx(base_damage * mult, abs=1e-6)


def test_R_081_02_line_wins_with_at_least(lib, world_factory):
    """Given equal power of Line versus Strike in a straight fight, When resolved, Then Line wins with at least 30 percent of its HP remaining; the same for Siege versus Line and Strike versus Siege from the flank."""
    w = world_factory(n_regions=1)

    # 1. Line vs Strike in a straight fight: Line wins with >= 30% HP remaining
    # Line: 10 Vanguards (power 10 * 50 = 500), Strike: Raiders of equal power
    u_line = [lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, float(i * 30), 0) for i in range(10)]
    u_strike = [lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 250.0, float(i * 30), 0) for i in range(10)]
    initial_line_hp = sum(lib.om_unit_hp(w, u) for u in u_line)
    # om_unit_hp/om_unit_alive are hard stubs (0.0/0), so a 0 initial HP would
    # make the >= 0.3 * 0 check below hold trivially. Require a real roster.
    assert initial_line_hp > 0

    # Resolve straight fight until one side is eliminated
    lib.om_tactical_run_until_eliminated(w)
    surviving_line_hp = sum(lib.om_unit_hp(w, u) for u in u_line if lib.om_unit_alive(w, u))
    surviving_strike_hp = sum(lib.om_unit_hp(w, u) for u in u_strike if lib.om_unit_alive(w, u))

    assert surviving_strike_hp == 0.0
    assert surviving_line_hp >= 0.30 * initial_line_hp

    # 2. Siege vs Line in a straight fight: Siege wins with >= 30% HP remaining
    lib.om_tactical_reset(w)
    u_siege = [lib.om_unit_spawn(w, OMUnitType.BOMBARD, 0, 0.0, float(i * 40), 0) for i in range(6)]
    u_line2 = [lib.om_unit_spawn(w, OMUnitType.VANGUARD, 1, 1000.0, float(i * 40), 0) for i in range(6)]
    initial_siege_hp = sum(lib.om_unit_hp(w, u) for u in u_siege)
    assert initial_siege_hp > 0

    lib.om_tactical_run_until_eliminated(w)
    surviving_siege_hp = sum(lib.om_unit_hp(w, u) for u in u_siege if lib.om_unit_alive(w, u))
    surviving_line2_hp = sum(lib.om_unit_hp(w, u) for u in u_line2 if lib.om_unit_alive(w, u))

    assert surviving_line2_hp == 0.0
    assert surviving_siege_hp >= 0.30 * initial_siege_hp

    # 3. Strike vs Siege from the flank: Strike wins with >= 30% HP remaining
    lib.om_tactical_reset(w)
    u_siege2 = [lib.om_unit_spawn(w, OMUnitType.BOMBARD, 1, 500.0, 500.0 + float(i * 40), 0) for i in range(4)]
    # Flank spawn: 90 degrees offset, short approach distance
    u_strike2 = [lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 500.0 + float(i * 30), 250.0, 0) for i in range(4)]
    initial_strike2_hp = sum(lib.om_unit_hp(w, u) for u in u_strike2)
    assert initial_strike2_hp > 0

    lib.om_tactical_run_until_eliminated(w)
    surviving_strike2_hp = sum(lib.om_unit_hp(w, u) for u in u_strike2 if lib.om_unit_alive(w, u))
    surviving_siege2_hp = sum(lib.om_unit_hp(w, u) for u in u_siege2 if lib.om_unit_alive(w, u))

    assert surviving_siege2_hp == 0.0
    assert surviving_strike2_hp >= 0.30 * initial_strike2_hp


def test_R_081_03_bastion_survives_at_least_20(lib, world_factory):
    """Given a Bastion attacked by 4 Raiders from the flank, When resolved, Then the Bastion survives at least 20 s (the Siege exception to Strike-beats-Siege)."""
    w = world_factory(n_regions=1)

    # 1 Bastion (Siege anchor, HP 1050) attacked by 4 Raiders from the flank
    bastion = lib.om_unit_spawn(w, OMUnitType.BASTION, 0, 500.0, 500.0, 0)
    raiders = [lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 500.0 + float(i * 25), 350.0, 0) for i in range(4)]

    for r in raiders:
        lib.om_command_attack_target(w, r, bastion)

    # 20 seconds = 400 tactical ticks (at 20 ticks/sec)
    lib.om_tactical_run(w, 400)

    assert lib.om_unit_alive(w, bastion) == 1
    assert lib.om_unit_hp(w, bastion) > 0.0


def test_R_081_04_time_to_kill_at_1(lib, world_factory):
    """Given any matchup, When resolved, Then time to kill at a 1.5× advantage is 30 to 40 percent shorter than at 1.0×."""
    w = world_factory(n_regions=1)

    # Baseline matchup: 10 Vanguards vs 10 Vanguards (1.0x advantage)
    u_a1 = [lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, float(i * 30), 0) for i in range(10)]
    u_b1 = [lib.om_unit_spawn(w, OMUnitType.VANGUARD, 1, 200.0, float(i * 30), 0) for i in range(10)]
    ttk_1_0 = lib.om_tactical_run_until_eliminated(w)

    # 1.5x advantage matchup: 15 Vanguards vs 10 Vanguards
    lib.om_tactical_reset(w)
    u_a2 = [lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, float(i * 20), 0) for i in range(15)]
    u_b2 = [lib.om_unit_spawn(w, OMUnitType.VANGUARD, 1, 200.0, float(i * 30), 0) for i in range(10)]
    ttk_1_5 = lib.om_tactical_run_until_eliminated(w)

    # Time to kill reduction must be between 30% and 40%
    reduction = (ttk_1_0 - ttk_1_5) / ttk_1_0
    assert 0.30 <= reduction <= 0.40

