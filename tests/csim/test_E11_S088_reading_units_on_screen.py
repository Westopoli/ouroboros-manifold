def test_R_088_01_it_appears_as_3_to(lib, world_factory):
    """Given a Raider or Interceptor, When drawn, Then it appears as 3 to 5 small craft in formation sharing one HP bar and one position; the sim tracks one entity."""
    w = world_factory(n_regions=1)

    for utype in (OMUnitType.RAIDER, OMUnitType.INTERCEPTOR):
        u = lib.om_unit_spawn(w, utype, 0, 100.0, 200.0, 0)

        # The sim tracks exactly one entity: 1 unit id, single HP, single position
        assert lib.om_unit_alive(w, u) == 1
        assert lib.om_unit_hp(w, u) > 0.0
        assert lib.om_unit_position_x(w, u) == pytest.approx(100.0, abs=1e-6)
        assert lib.om_unit_position_y(w, u) == pytest.approx(200.0, abs=1e-6)

        # Squad display metadata defines 3 to 5 small craft for Strike squads
        craft_count = lib.om_unit_render_craft_count(w, utype)
        assert 3 <= craft_count <= 5


def test_R_088_02_cue_plays_at_that_tick(lib, world_factory):
    """Given an ability event, When received by the renderer, Then a cue plays at that tick for the event's duration (Barrage shows its telegraph ring at the target for 1.5 s before impact; Fortify shows its zone; Brace shows a planted state)."""
    w = world_factory(n_regions=1)

    bombard = lib.om_unit_spawn(w, OMUnitType.BOMBARD, 0, 0.0, 0.0, 0)
    lib.om_command_activate_ability(w, [bombard], 1, 300.0, 0.0)
    lib.om_tactical_step(w)

    # Renderer cue emitted in tick delta
    events = lib.om_tick_read_ability_events(w)
    assert len(events) >= 1
    barrage_evt = events[0]
    # Barrage telegraph duration: 1.5 s = 30 ticks
    assert barrage_evt.telegraph_ticks == 30
    assert barrage_evt.cue_id == lib.om_cue_lookup(b"cue_barrage_telegraph")

    # Fortify cue
    bastion = lib.om_unit_spawn(w, OMUnitType.BASTION, 0, 500.0, 0.0, 0)
    lib.om_command_activate_ability(w, [bastion], 1, 0.0, 0.0)
    lib.om_tactical_step(w)
    events2 = lib.om_tick_read_ability_events(w)
    fortify_evt = next(e for e in events2 if e.unit_id == bastion)
    assert fortify_evt.duration == 400
    assert fortify_evt.radius == pytest.approx(350.0, abs=1e-6)


def test_R_088_03_category_distinguishable_by_silhouette_size(lib, world_factory):
    """Given a T2 screenshot of a mixed force, When inspected, Then category is distinguishable by silhouette size: Strike smallest, Siege largest."""
    w = world_factory(n_regions=1)

    strike_size = min(
        lib.om_unit_render_silhouette_size(w, OMUnitType.RAIDER),
        lib.om_unit_render_silhouette_size(w, OMUnitType.INTERCEPTOR),
    )
    line_size = min(
        lib.om_unit_render_silhouette_size(w, OMUnitType.VANGUARD),
        lib.om_unit_render_silhouette_size(w, OMUnitType.WARDEN),
    )
    siege_size = min(
        lib.om_unit_render_silhouette_size(w, OMUnitType.BOMBARD),
        lib.om_unit_render_silhouette_size(w, OMUnitType.BASTION),
    )

    # Category hierarchy: Strike smallest, Siege largest
    assert strike_size < line_size
    assert line_size < siege_size

