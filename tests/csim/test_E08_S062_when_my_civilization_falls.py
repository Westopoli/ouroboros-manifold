def test_R_062_01_chapter_ends_with_reason_faction(lib, world_factory):
    """Given the player's faction has zero regions or no longer exists at the end of a time jump, When collapse is checked, Then the chapter ends with reason `faction_collapsed`."""
    w = world_factory(n_regions=4)

    # Player is faction 0, but owns 0 regions (other factions own them)
    set_owner(lib, w, 0, faction_id=1)
    set_owner(lib, w, 1, faction_id=1)
    set_owner(lib, w, 2, faction_id=2)
    set_owner(lib, w, 3, faction_id=2)

    collapsed = lib.om_player_faction_check_collapse(w, player_faction=0)
    assert collapsed == 1

    end_reason = lib.om_chapter_end_reason_for_collapse(w, player_faction=0)
    assert end_reason == OMChapterEndReason.FACTION_COLLAPSED


