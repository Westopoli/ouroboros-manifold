def test_R_024_01_every_edge_between_their_regions(lib, world_factory):
    """Given two factions form a cooperative peace, When it resolves, Then every edge between their regions becomes `both`."""
    w = world_factory(n_regions=4)
    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=0.0)
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=0.0, tech=0.0)
    set_owner(lib, w, 0, 0, held_since=-1)
    set_owner(lib, w, 1, 0, held_since=-1)
    set_owner(lib, w, 2, 1, held_since=-1)
    set_owner(lib, w, 3, 1, held_since=-1)
    set_edge(lib, w, 0, 2, OMEdge.BORDER)
    set_edge(lib, w, 1, 3, OMEdge.BORDER)

    set_stance(lib, w, 0, 1, OMStance.COOPERATIVE)
    lib.om_world_set_feature(w, OMFeature.DIPLOMACY, 1)
    lib.om_world_step(w)

    out = ctypes.c_int()
    lib.om_region_edge(w, 0, 2, ctypes.byref(out))
    assert out.value == OMEdge.BOTH, f"expected BOTH between cooperative regions (0, 2), got {out.value}"
    lib.om_region_edge(w, 1, 3, ctypes.byref(out))
    assert out.value == OMEdge.BOTH, f"expected BOTH between cooperative regions (1, 3), got {out.value}"


