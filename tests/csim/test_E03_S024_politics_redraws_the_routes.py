def test_R_024_05_no_edge_type_changed(lib, world_factory):
    """Given no diplomatic or ownership change on a tick, When the tick ends, Then no edge type changed."""
    w = world_factory(n_regions=0, seed=42)
    rc = generate(lib, w)
    assert rc == 1
    N = lib.om_region_count(w)
    assert N >= 60
    before = {}
    for u in range(N):
        for v in region_neighbors(lib, w, u):
            if u < v:
                out = ctypes.c_int()
                lib.om_region_edge(w, u, v, ctypes.byref(out))
                before[(u, v)] = out.value
    lib.om_world_step(w)
    assert len(before) >= 30
    for (u, v), et in before.items():
        out = ctypes.c_int()
        lib.om_region_edge(w, u, v, ctypes.byref(out))
        assert out.value == et

