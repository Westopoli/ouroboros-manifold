def test_R_024_03_its_edges_to_conqueror_s(lib, world_factory):
    """Given a region is conquered, When ownership changes, Then its edges to the conqueror's own regions become `both`, its edges to the former owner's regions become `border`, and its edges to regions of the conqueror's cooperative partners become `both`."""
    w = world_factory(n_regions=4)
    isolate_agents(lib, w)
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=100.0, tech=0.0)
    set_faction(lib, w, 1, OMArchetype.FORTIFIER, budget=0.0, tech=0.0)
    set_faction(lib, w, 2, OMArchetype.FORTIFIER, budget=0.0, tech=0.0)

    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    set_stance(lib, w, 0, 2, OMStance.COOPERATIVE)
    set_stance(lib, w, 1, 2, OMStance.HOSTILE)

    set_region(lib, w, 0, tier=OMTier.HOME, military=80.0, economy=50.0, tension=0.0, population=50.0)
    set_region(lib, w, 1, tier=OMTier.FRONTIER, military=1.0, economy=50.0, tension=0.0, population=50.0)
    set_region(lib, w, 2, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0)
    set_region(lib, w, 3, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0)

    set_owner(lib, w, 0, 0, held_since=-1)
    set_owner(lib, w, 1, 1, held_since=-1)
    set_owner(lib, w, 2, 1, held_since=-1)
    set_owner(lib, w, 3, 2, held_since=-1)

    set_edge(lib, w, 0, 1, OMEdge.BORDER)
    set_edge(lib, w, 1, 2, OMEdge.BOTH)
    set_edge(lib, w, 1, 3, OMEdge.BORDER)

    inject_intent(lib, w, 0, OMAction.ATTACK, 1, 0, 60.0, OMMode.SURPRISE)
    force_draws(lib, w, [1.0, 0.99])
    lib.om_world_step(w)

    assert lib.om_region_owner(w, 1) == 0

    out = ctypes.c_int()
    lib.om_region_edge(w, 1, 0, ctypes.byref(out))
    assert out.value == OMEdge.BOTH, f"conqueror edge (1, 0) expected BOTH, got {out.value}"

    lib.om_region_edge(w, 1, 2, ctypes.byref(out))
    assert out.value == OMEdge.BORDER, f"former owner edge (1, 2) expected BORDER, got {out.value}"

    lib.om_region_edge(w, 1, 3, ctypes.byref(out))
    assert out.value == OMEdge.BOTH, f"cooperative partner edge (1, 3) expected BOTH, got {out.value}"


