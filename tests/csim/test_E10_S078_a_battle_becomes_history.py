def test_R_078_04_region_s_owner_becomes_player(lib, world_factory):
    """Given a transfer band for the archetype (S-073 table), When applied, Then the region's owner becomes the player's faction with held-since reset and edges updated (E-03 R-024-03)."""
    w = world_factory(n_regions=2)
    player_faction = 1
    enemy_faction = 2

    set_faction(lib, w, player_faction, 0)  # archetype 0 == OMArchetype.PLAYER

    lib.om_region_set_owner(w, 1, enemy_faction, 100)  # region 1 owned by enemy since tick 100
    current_tick = 500
    lib.om_world_set_tick(w, current_tick)

    # Reconquest (archetype 2) total_success (band 4) transfers region 1 to player
    lib.om_mission_apply_consequences(w, 1, 2, OMMissionBand.TOTAL_SUCCESS)

    owner = lib.om_region_get_owner(w, 1)
    assert owner == player_faction

    held_since = lib.om_region_get_held_since(w, 1)
    assert held_since == current_tick


