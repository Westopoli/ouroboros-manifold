def test_R_078_01_each_delta_either_deficit_form(lib, world_factory):
    """Given the archetype's consequence table row for the band, When applied, Then each delta is either deficit form, (100 − current) · pct/100, or current form, current · pct/100, applied to the named target regions and clamped to [0, 100]."""
    w = world_factory(n_regions=1)

    # Test deficit form: current = 20, pct = 15 -> (100 - 20) * 0.15 = 12.0
    delta_deficit = lib.om_consequence_eval_delta_deficit(ctypes.c_double(20.0), ctypes.c_double(15.0))
    assert ctypes.c_double(delta_deficit).value == pytest.approx(12.0, abs=1e-5)

    # Test current form: current = 50, pct = -2 -> 50 * (-0.02) = -1.0
    delta_current = lib.om_consequence_eval_delta_current(ctypes.c_double(50.0), ctypes.c_double(-2.0))
    assert ctypes.c_double(delta_current).value == pytest.approx(-1.0, abs=1e-5)

    # Test clamping to [0, 100]
    val_clamped_high = lib.om_consequence_apply_clamped(ctypes.c_double(95.0), ctypes.c_double(20.0))
    assert ctypes.c_double(val_clamped_high).value == pytest.approx(100.0, abs=1e-5)

    val_clamped_low = lib.om_consequence_apply_clamped(ctypes.c_double(5.0), ctypes.c_double(-10.0))
