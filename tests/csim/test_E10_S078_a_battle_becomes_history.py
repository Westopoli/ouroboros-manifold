def test_R_078_07_delta_applies_to_every_player(lib, world_factory):
    """Given a target of `adjacent_player`, When applied, Then the delta applies to every player-owned neighbor of the mission region."""
    w = world_factory(n_regions=4)
    # Region 0: mission region
    # Region 1: neighbor, owned by player (faction 1)
    # Region 2: neighbor, owned by enemy (faction 2)
    # Region 3: neighbor, owned by player (faction 1)
    lib.om_set_neighbors(w, 0, 1)
    lib.om_set_neighbors(w, 0, 2)
    lib.om_set_neighbors(w, 0, 3)

    set_faction(lib, w, 1, 0)  # archetype 0 == OMArchetype.PLAYER

    # set_region resets faction_id to -1, so ownership is set after it.
    set_region(lib, w, 1, tension=50.0)
    set_region(lib, w, 2, tension=50.0)
    set_region(lib, w, 3, tension=50.0)

    lib.om_region_set_owner(w, 1, 1, 0)
    lib.om_region_set_owner(w, 2, 2, 0)
    lib.om_region_set_owner(w, 3, 1, 0)

    # Apply consequence with adjacent_player target on tension (+5.0)
    lib.om_mission_apply_target_adjacent_player(w, 0, OMField.TENSION, ctypes.c_double(5.0))

    # Neighbors 1 and 3 (player) should have delta applied: 50 -> 55
    assert lib.om_region_field(w, 1, OMField.TENSION) == pytest.approx(55.0, abs=1e-4)
    assert lib.om_region_field(w, 3, OMField.TENSION) == pytest.approx(55.0, abs=1e-4)

    # Neighbor 2 (enemy) should be unaffected: 50
    assert lib.om_region_field(w, 2, OMField.TENSION) == pytest.approx(50.0, abs=1e-4)

