def test_R_075_07_it_ends_on_first_every(lib, world_factory):
    """Given the mission, When it ends, Then it ends on the first of: every primary objective complete or failed; the time limit reached; the player's force eliminated."""
    w = world_factory(n_regions=1)

    # Case 1: Primary complete ends mission
    lib.om_mission_setup_termination(w, 0, 1, 0, 100, 200, 1)
    assert lib.om_mission_check_terminated(w, 0) == 1

    # Case 2: Time limit reached ends mission
    lib.om_mission_setup_termination(w, 0, 0, 0, 200, 200, 1)  # tick = 200, limit = 200
    assert lib.om_mission_check_terminated(w, 0) == 1

    # Case 3: Player force eliminated ends mission
    lib.om_mission_setup_termination(w, 0, 0, 0, 50, 200, 0)  # player_alive = 0
    assert lib.om_mission_check_terminated(w, 0) == 1

    # Case 4: None of the conditions met -> mission does not end
    lib.om_mission_setup_termination(w, 0, 0, 0, 50, 200, 1)
    assert lib.om_mission_check_terminated(w, 0) == 0

