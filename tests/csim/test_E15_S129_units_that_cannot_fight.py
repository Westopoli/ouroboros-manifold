import ctypes

class OMNonCombatKind:
    CONVOY = 0
    EVACUEE = 1
    SCIENCE = 2
    INTELLIGENCE = 3
    CULTURAL = 4


def test_R_129_01_it_never_acquires_target_never(lib, world_factory):
    """Given a non-combat unit, When the decision loop runs, Then it never acquires a target, never returns fire, flinches from damage, and otherwise holds or follows its move order."""
    w = world_factory(n_regions=1)

    # Spawn non-combat unit (e.g. CONVOY)
    unit_id = lib.om_unit_spawn_non_combat(w, OMNonCombatKind.CONVOY, ctypes.c_double(100.0), ctypes.c_double(100.0))

    # Place enemy unit adjacent
    enemy_id = lib.om_unit_spawn_combat(w, 0, ctypes.c_double(105.0), ctypes.c_double(100.0))

    # Run non-combat unit decision loop
    lib.om_unit_tick_decision_loop(w, unit_id)

    # Target acquisition is 0
    target = lib.om_unit_get_target(w, unit_id)
    assert target == 0  # no target

    # Attack enemy against non-combat unit
    lib.om_unit_deal_damage(w, enemy_id, unit_id, ctypes.c_double(20.0))

    # Non-combat unit does not return fire
    can_return_fire = lib.om_unit_can_return_fire(w, unit_id)
    assert can_return_fire == 0

    # Flinches from damage
    is_flinching = lib.om_unit_is_flinching(w, unit_id)
    assert is_flinching == 1


