import pytest

from conftest import OMField, OMTier, read_drift, set_region  # adjust imports to what this epic's fixtures need


class OMUnitType:
    RAIDER = 0
    INTERCEPTOR = 1
    VANGUARD = 2
    WARDEN = 3
    BOMBARD = 4
    BASTION = 5


def test_R_098_01_shot_lands_friendly_units_never(lib, world_factory):
    """Given a ranged unit with an ally between it and its target, When it fires, Then the shot lands; friendly units never block fire."""
    w = world_factory(n_regions=1)

    # Ranged Bombard (faction 0) at (0, 0), attack range 600 wu, flat damage 110.0
    attacker = lib.om_unit_spawn(w, OMUnitType.BOMBARD, 0, 0.0, 0.0, 0)

    # Ally Bastion (faction 0) directly in line of fire at (100, 0)
    ally = lib.om_unit_spawn(w, OMUnitType.BASTION, 0, 100.0, 0.0, 0)
    hp_ally_before = lib.om_unit_get_hp(w, ally)

    # Enemy target at (200, 0)
    enemy = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 200.0, 0.0, 0)
    hp_enemy_before = lib.om_unit_get_hp(w, enemy)

    # Attacker fires at enemy target
    assert lib.om_combat_can_shoot(w, attacker, enemy) == 1
    lib.om_unit_attack(w, attacker, enemy)

    # Friendly unit never blocks fire: shot lands on enemy
    damage_dealt = hp_enemy_before - lib.om_unit_get_hp(w, enemy)
    assert pytest.approx(damage_dealt, abs=1e-4) == 110.0

    # Ally takes 0 damage
    assert pytest.approx(lib.om_unit_get_hp(w, ally), abs=1e-4) == hp_ally_before


def test_R_098_02_shot_blocked_exactly_as_vision(lib, world_factory):
    """Given terrain or cover between them, When it fires, Then the shot is blocked exactly as vision is (E-12, E-01 S-007)."""
    w = world_factory(n_regions=1)

    attacker = lib.om_unit_spawn(w, OMUnitType.BOMBARD, 0, 0.0, 0.0, 0)
    enemy = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 200.0, 0.0, 0)
    hp_enemy_before = lib.om_unit_get_hp(w, enemy)

    # Place blocking cover between attacker and enemy (height >= layer line)
    lib.om_map_add_cover(w, 100.0, 0.0, 20.0, 5.0)

    # Shot is blocked exactly as vision is
    assert lib.om_combat_can_shoot(w, attacker, enemy) == 0

    # Attempt fire: target takes no damage
    lib.om_unit_attack(w, attacker, enemy)
    assert pytest.approx(lib.om_unit_get_hp(w, enemy), abs=1e-4) == hp_enemy_before

