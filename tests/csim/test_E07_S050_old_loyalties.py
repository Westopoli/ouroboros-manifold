def test_R_050_04_region_s_owner_b_held(lib, world_factory):
    """Given a reversion, When applied, Then the region's owner is B, held-since is the current tick, previous owner is cleared, and the same split and floors as R-049-03 apply."""
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.EVENTS, 1)
    lib.om_world_set_feature(w, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=10.0, confidence=5.0)
    set_faction(lib, w, 1, OMArchetype.CONQUEROR, budget=0.0, tech=10.0, confidence=5.0)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)

    for _ in range(15):
        lib.om_world_step(w)

    # Military 50 -> 50 * 0.40 = 20.0
    # Economy 50 -> 50 * 0.60 = 30.0
    # Tension 70 -> capped at 40.0
    # Population 60 -> floored at 25 (remains 60.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=70.0, population=60.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=1)
    lib.om_region_set_previous_owner(w, 0, 1)

    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)

    step_tick = lib.om_world_step(w)
    due = step_tick + 1
    queue_external(lib, w, 0, 100, due_tick=due, probability=1.0)

    force_draws(lib, w, [0.50, 0.10, 0.20])
    current_tick = lib.om_world_step(w)

    assert lib.om_region_owner(w, 0) == 1
    assert lib.om_region_held_since(w, 0) == current_tick
    assert lib.om_region_previous_owner(w, 0) == -1

    assert lib.om_region_field(w, 0, OMField.MILITARY) == pytest.approx(20.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.ECONOMY) == pytest.approx(30.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.TENSION) == pytest.approx(40.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.POPULATION) == pytest.approx(60.0, abs=1e-6)


