class OmReversionRecord(ctypes.Structure):
    _fields_ = [
        ("tick", ctypes.c_uint64),
        ("region_idx", ctypes.c_uint32),
        ("original_faction", ctypes.c_int32),
        ("restored_faction", ctypes.c_int32),
        ("military_stolen", ctypes.c_double),
        ("economy_stolen", ctypes.c_double),
    ]


def read_reversions(lib, w, max_records=64):
    buf = (OmReversionRecord * max_records)()
    n = lib.om_tick_reversions(w, buf, max_records)
    return [buf[i] for i in range(n)]


def test_R_050_01_with_probability_0_5_one(lib, world_factory):
    """Given a region conquered from B 15 ticks ago and B still exists, When a revolt succeeds there, Then with probability 0.5 (one draw) the region reverts to B instead of forming a breakaway."""
    # Case A: draw < 0.5 -> reverts to B (Faction 1)
    w_revert = world_factory(n_regions=2)
    isolate_agents(lib, w_revert)
    lib.om_world_set_feature(w_revert, OMFeature.EVENTS, 1)
    lib.om_world_set_feature(w_revert, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w_revert, 0, OMArchetype.DEFAULT, budget=0.0, tech=10.0, confidence=5.0)
    set_faction(lib, w_revert, 1, OMArchetype.CONQUEROR, budget=0.0, tech=10.0, confidence=5.0)
    set_tech_multipliers(lib, w_revert, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w_revert, 1, 1.0, 1.0, 1.0)

    # Advance world to tick 16 so that conquest at tick 1 was 15 ticks ago (16 - 1 = 15 <= 20)
    for _ in range(15):
        lib.om_world_step(w_revert)

    # Region 0: owned by Faction 0, conquered from Faction 1 at tick 1 (15 ticks ago)
    set_region(lib, w_revert, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=70.0, population=50.0, faction_id=0)
    set_owner(lib, w_revert, 0, 0, held_since=1)
    lib.om_region_set_previous_owner(w_revert, 0, 1)

    # Region 1: owned by Faction 1 (so B still exists)
    set_region(lib, w_revert, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=1)
    set_owner(lib, w_revert, 1, 1, held_since=-1)

    due = lib.om_world_step(w_revert) + 1
    queue_external(lib, w_revert, 0, 100, due_tick=due, probability=1.0)

    # Draws: success rate draw = 0.50 (rate 0.725), success check draw = 0.10 (passes),
    # reversion draw = 0.20 (< 0.50 -> reverts to B)
    force_draws(lib, w_revert, [0.50, 0.10, 0.20])
    lib.om_world_step(w_revert)

    assert lib.om_region_owner(w_revert, 0) == 1
    assert lib.om_faction_count(w_revert) == 2

    # Case B: draw >= 0.5 -> forms breakaway instead of reverting
    w_no_revert = world_factory(n_regions=2)
    isolate_agents(lib, w_no_revert)
    lib.om_world_set_feature(w_no_revert, OMFeature.EVENTS, 1)
    lib.om_world_set_feature(w_no_revert, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w_no_revert, 0, OMArchetype.DEFAULT, budget=0.0, tech=10.0, confidence=5.0)
    set_faction(lib, w_no_revert, 1, OMArchetype.CONQUEROR, budget=0.0, tech=10.0, confidence=5.0)
    set_tech_multipliers(lib, w_no_revert, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w_no_revert, 1, 1.0, 1.0, 1.0)

    for _ in range(15):
        lib.om_world_step(w_no_revert)

    set_region(lib, w_no_revert, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=70.0, population=50.0, faction_id=0)
    set_owner(lib, w_no_revert, 0, 0, held_since=1)
    lib.om_region_set_previous_owner(w_no_revert, 0, 1)
    set_region(lib, w_no_revert, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=1)
    set_owner(lib, w_no_revert, 1, 1, held_since=-1)

    due2 = lib.om_world_step(w_no_revert) + 1
    queue_external(lib, w_no_revert, 0, 100, due_tick=due2, probability=1.0)

    # Reversion draw = 0.70 (>= 0.50 -> does not revert, forms breakaway)
    force_draws(lib, w_no_revert, [0.50, 0.10, 0.70, 0.50])
    lib.om_world_step(w_no_revert)

    assert lib.om_region_owner(w_no_revert, 0) != 1
    assert lib.om_region_owner(w_no_revert, 0) != 0


def test_R_050_02_it_never_reverts(lib, world_factory):
    """Given the conquest was 21 or more ticks ago, When a revolt succeeds, Then it never reverts."""
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.EVENTS, 1)
    lib.om_world_set_feature(w, OMFeature.LIFECYCLE, 1)

