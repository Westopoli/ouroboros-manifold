def test_R_073_04_briefing_notes_it_nothing_mechanical(lib, world_factory):
    """Given "inheritance" framing, When the ledger finds a lineage connection to the mission region, Then the briefing notes it and nothing mechanical changes."""
    w = world_factory(n_regions=2)

    # Setup mission with lineage connection
    lib.om_mission_setup(w, 0, OMMissionArchetype.DEFENSIVE_STAND, 1)  # lineage connection = 1
    text_buf = ctypes.create_string_buffer(512)
    lib.om_mission_get_briefing_text(w, text_buf, 512)
    assert b"lineage" in text_buf.value.lower() or b"ancestor" in text_buf.value.lower()

    # Mechanical fields: enemy power, player parity, time limit
    pwr_with = lib.om_mission_get_enemy_power(w)
    parity_with = lib.om_mission_get_player_parity(w, 0)
    limit_with = lib.om_mission_get_time_limit(w)

    # Setup mission without lineage connection
    lib.om_mission_setup(w, 0, OMMissionArchetype.DEFENSIVE_STAND, 0)  # lineage connection = 0
    pwr_without = lib.om_mission_get_enemy_power(w)
    parity_without = lib.om_mission_get_player_parity(w, 0)
    limit_without = lib.om_mission_get_time_limit(w)

    assert pwr_with == pytest.approx(pwr_without, abs=1e-6)
    assert parity_with == pytest.approx(parity_without, abs=1e-6)
    assert limit_with == limit_without

