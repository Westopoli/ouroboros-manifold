def test_R_073_02_its_asset_profile_ratio_per(lib, world_factory):
    """Given an archetype, When its forces are allocated, Then its asset profile (ratio per unit type) is read from the library, not hard-coded."""
    w = world_factory(n_regions=1)

    # Inject custom asset profile into archetype library (6 unit types)
    custom_profile = (ctypes.c_double * 6)(0.30, 0.20, 0.20, 0.15, 0.10, 0.05)
    lib.om_mission_set_archetype_profile(w, OMMissionArchetype.DEFENSIVE_STAND, custom_profile, 6)

    # Allocate forces for total power budget 10,000
    allocated_ratios = (ctypes.c_double * 6)()
    lib.om_mission_allocate_force_profile(w, OMMissionArchetype.DEFENSIVE_STAND, 10000.0, allocated_ratios)

    for i in range(6):
        assert allocated_ratios[i] == pytest.approx(custom_profile[i], abs=0.05)


