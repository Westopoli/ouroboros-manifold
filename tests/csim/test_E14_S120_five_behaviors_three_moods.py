def test_R_120_02_force_attack_moves_toward_its(lib, world_factory):
    """Given advance, When executed, Then the force attack-moves toward its target (a position, a spine node, or a unit group); given defend, Then it holds position and units auto-engage without pursuit; given patrol, Then it plain-moves through its waypoints in a cycle and auto-engages on contact; given ambush, Then it holds hidden until an enemy enters its trigger radius, then becomes advance_aggressive toward the trigger and never resets; given retreat, Then it plain-moves to its fallback point."""
    w = world_factory(n_regions=1)
    force_id = 0

    # Advance issues attack-move
    cmd_advance = lib.om_macro_execute_behavior(w, force_id, OMMacroBehavior.ADVANCE, OMMacroModifier.AGGRESSIVE)
    assert cmd_advance == OMMacroCommand.ATTACK_MOVE

    # Retreat issues move
    cmd_retreat = lib.om_macro_execute_behavior(w, force_id, OMMacroBehavior.RETREAT, OMMacroModifier.CAUTIOUS)
    assert cmd_retreat == OMMacroCommand.MOVE

    # Ambush holds hidden until enemy in radius, transitions to advance_aggressive, never resets
    lib.om_macro_set_state(w, force_id, OMMacroBehavior.AMBUSH, OMMacroModifier.CAUTIOUS)
    assert lib.om_macro_is_hidden(w, force_id) == 1

    # Enemy triggers ambush
    lib.om_macro_trigger_ambush(w, force_id)
    assert lib.om_macro_get_behavior(w, force_id) == OMMacroBehavior.ADVANCE
    assert lib.om_macro_get_modifier(w, force_id) == OMMacroModifier.AGGRESSIVE

    # Enemy leaves trigger radius: ambush never resets
    lib.om_macro_enemy_leaves_trigger(w, force_id)
    assert lib.om_macro_get_behavior(w, force_id) == OMMacroBehavior.ADVANCE


