def test_R_120_04_it_runs_every_40_ticks(lib, world_factory):
    """Given a macro evaluation, When it runs, Then it runs every 40 ticks (2 s) and issues commands only through move, attack_move, attack_target, activate_ability."""
    w = world_factory(n_regions=1)

    # Macro evaluation interval is 40 ticks
    interval = lib.om_macro_evaluation_interval_ticks()
    assert interval == 40

    # At tick 39, evaluation does not run; at tick 40, evaluation runs
    lib.om_macro_tick(w, 39)
    assert lib.om_macro_has_evaluated(w) == 0

    lib.om_macro_tick(w, 40)
    assert lib.om_macro_has_evaluated(w) == 1

    # Allowed command types are strictly MOVE, ATTACK_MOVE, ATTACK_TARGET, ACTIVATE_ABILITY
    last_cmd = lib.om_macro_get_last_issued_command_type(w, 0)
    assert last_cmd in (
        OMMacroCommand.MOVE,
        OMMacroCommand.ATTACK_MOVE,
        OMMacroCommand.ATTACK_TARGET,
        OMMacroCommand.ACTIVATE_ABILITY,
    )

