def test_R_089_06_b_seeing_computed_independently_asymmetric(lib, world_factory):
    """Given visibility A sees B, When B's set is computed, Then B seeing A is computed independently (asymmetric sensors are normal)."""
    w = world_factory(n_regions=1)

    # Interceptor (Unit A, sensor radius 1000) at (0, 0)
    # Vanguard (Unit B, sensor radius 700) at (850, 0)
    # Distance = 850: A sees B (850 <= 1000), but B does NOT see A (850 > 700)
    unit_a = lib.om_unit_spawn(w, OMUnitType.INTERCEPTOR, 0, 0.0, 0.0, 0)
    unit_b = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 1, 850.0, 0.0, 0)

    lib.om_visibility_compute(w)
    assert lib.om_unit_can_see(w, unit_a, unit_b) == 1
    assert lib.om_unit_can_see(w, unit_b, unit_a) == 0

