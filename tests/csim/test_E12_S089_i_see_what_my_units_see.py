class OMUnitType:
    RAIDER = 0
    INTERCEPTOR = 1
    VANGUARD = 2
    WARDEN = 3
    BOMBARD = 4
    BASTION = 5


def test_R_089_01_its_effective_radius_r_1(lib, world_factory):
    """Given an observer with sensor radius r at interference i, When visibility is computed, Then its effective radius is r × (1 − i), and an enemy on the same layer is visible if its distance ≤ that radius and no cover blocks the line."""
    w = world_factory(n_regions=1)

    # Observer Vanguard has base sensor radius 700.0 wu.
    # At interference 0.5, effective radius = 700 * (1 - 0.5) = 350.0 wu.
    obs = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, 0.0, 0)
    lib.om_map_add_interference_zone(w, 0.0, 0.0, 0, 0.5, 500.0)

    # 1. Three-fixture distance pattern around effective radius 350.0:
    # Strictly below: 349.0 wu -> visible
    e_below = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 349.0, 0.0, 0)
    # Exactly at: 350.0 wu -> visible (<= threshold)
    e_at = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 0.0, 350.0, 0)
    # Strictly above: 351.0 wu -> not visible
    e_above = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 0.0, -351.0, 0)

    # 2. In-range enemy behind blocking cover (height >= layer line)
    e_cover = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, -200.0, 0.0, 0)
    lib.om_map_add_cover(w, -100.0, 0.0, 20.0, 5.0)  # tall blocking cover between observer and e_cover

    lib.om_visibility_compute(w)

    assert lib.om_unit_can_see(w, obs, e_below) == 1
    assert lib.om_unit_can_see(w, obs, e_at) == 1
    assert lib.om_unit_can_see(w, obs, e_above) == 0
    assert lib.om_unit_can_see(w, obs, e_cover) == 0


def test_R_089_02_player_visible_enemy_list_their(lib, world_factory):
    """Given every friendly unit's visible set, When the player's view is built, Then the player-visible enemy list is their union."""
    w = world_factory(n_regions=1)

    # Friendly 1 at (0, 0) sees Enemy 1 at (200, 0)
    f1 = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, 0.0, 0)
    e1 = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 200.0, 0.0, 0)

    # Friendly 2 at (1000, 1000) sees Enemy 2 at (1200, 1000)
    f2 = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 1000.0, 1000.0, 0)
    e2 = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 1200.0, 1000.0, 0)

    # Enemy 3 far from both (5000, 5000)
    e3 = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 5000.0, 5000.0, 0)

    lib.om_visibility_compute(w)

    assert lib.om_unit_can_see(w, f1, e1) == 1
    assert lib.om_unit_can_see(w, f1, e2) == 0

    assert lib.om_unit_can_see(w, f2, e2) == 1
    assert lib.om_unit_can_see(w, f2, e1) == 0

    # Player-visible list is the exact union: contains e1 and e2, not e3
    assert lib.om_player_can_see(w, e1) == 1
    assert lib.om_player_can_see(w, e2) == 1
    assert lib.om_player_can_see(w, e3) == 0


def test_R_089_03_it_not_drawn_its_hp(lib, world_factory):
    """Given an enemy not in the union, When drawn, Then it is not drawn, its HP bar is not drawn, and its position is not in the client's data."""
    w = world_factory(n_regions=1)

    # Friendly unit at (0, 0), enemy at (5000, 5000)
    lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, 0.0, 0)
    unseen_enemy = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 5000.0, 5000.0, 0)

    lib.om_visibility_compute(w)
    assert lib.om_player_can_see(w, unseen_enemy) == 0

    # Verify client snapshot excludes unseen enemy position and HP
    client_data = lib.om_client_snapshot_read(w)
    enemy_ids_in_client = [u.id for u in client_data.units if u.faction_id == 1]
    assert unseen_enemy not in enemy_ids_in_client


def test_R_089_04_it_recomputed_every_tick_from(lib, world_factory):
    """Given visibility, When computed, Then it is recomputed every tick from current positions; there is no memory of last-seen positions [Q-089-01]."""
    w = world_factory(n_regions=1)

    f = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, 0.0, 0)
    e = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 200.0, 0.0, 0)

    # Tick 1: enemy in sensor range (200 wu) -> visible
    lib.om_tactical_step(w)
    assert lib.om_player_can_see(w, e) == 1

    # Tick 2: enemy moves far outside sensor range (1500 wu) -> immediately not visible
    lib.om_unit_teleport(w, e, 1500.0, 0.0, 0)
    lib.om_tactical_step(w)
    assert lib.om_player_can_see(w, e) == 0


