def test_R_025_03_it_passes_through_at_least(lib, world_factory):
    """Given generation is complete, When the shortest path from the player's inhabited regions to any NPC faction's inhabited regions is computed, Then it passes through at least one empty region."""
    w = world_factory(n_regions=0, seed=42)
    rc = generate(lib, w)
    assert rc == 1, "generation failed"
    N = lib.om_region_count(w)
    player_regions = [r for r in range(N) if lib.om_region_owner(w, r) == 0 and lib.om_region_tier(w, r) != OMTier.EMPTY]
    dist = {}
    parent = {}
    queue = collections.deque()
    for pr in player_regions:
        dist[pr] = 0
        queue.append(pr)

    nearest_npc = None
    while queue:
        curr = queue.popleft()
        if lib.om_region_owner(w, curr) > 0:
            nearest_npc = curr
            break
        for nbr in region_neighbors(lib, w, curr):
            if nbr not in dist:
                dist[nbr] = dist[curr] + 1
                parent[nbr] = curr
                queue.append(nbr)

    assert nearest_npc is not None, "no path from player to any NPC region"
    path = []
    curr = nearest_npc
    while curr in parent:
        path.append(curr)
        curr = parent[curr]
    path.append(curr)

    has_empty = any(lib.om_region_tier(w, r) == OMTier.EMPTY for r in path)
    assert has_empty, f"shortest path {path} from player to NPC does not pass through any empty region"


