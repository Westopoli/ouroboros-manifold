class OMUnitType:
    RAIDER = 0
    INTERCEPTOR = 1
    VANGUARD = 2
    WARDEN = 3
    BOMBARD = 4
    BASTION = 5


def test_R_100_01_it_faces_target_moving_with(lib, world_factory):
    """Given a unit attacking a target, When facing updates, Then it faces the target; given moving with no target, it faces its heading; given idle with no target, it keeps its last facing."""
    w = world_factory(n_regions=1)

    # 1. Moving with no target: faces heading
    u = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 0.0, 0.0, 0)
    lib.om_command_move(w, u, 500.0, 0.0)  # heading along +x = 0.0 rad
    for _ in range(5):
        lib.om_world_step(w)
    facing_move = lib.om_unit_get_facing(w, u)
    assert pytest.approx(facing_move, abs=1e-3) == 0.0

    # 2. Idle with no target: keeps its last facing
    lib.om_unit_clear_orders(w, u)
    for _ in range(5):
        lib.om_world_step(w)
    facing_idle = lib.om_unit_get_facing(w, u)
    assert pytest.approx(facing_idle, abs=1e-3) == facing_move

    # 3. Attacking a target: faces the target. The 5 move ticks in step 1
    # left u at x = 37.5 (Raider speed 150 wu/s / 20 tps = 7.5 wu/tick), not
    # at the origin, so the expected angle is read back from the unit's
    # actual position rather than assumed to be (0, 0).
    ux = lib.om_unit_position_x(w, u)
    uy = lib.om_unit_position_y(w, u)
    enemy = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 0.0, 100.0, 0)
    lib.om_command_attack_target(w, u, enemy)
    # Step until turned toward target
    for _ in range(20):
        lib.om_world_step(w)
    facing_target = lib.om_unit_get_facing(w, u)
    expected_facing = math.atan2(100.0 - uy, 0.0 - ux)
    assert pytest.approx(facing_target, abs=1e-2) == expected_facing


def test_R_100_02_turn_rate_capped_at_6(lib, world_factory):
    """Given a facing change, When it turns, Then the turn rate is capped at 6.0 rad/s for Strike, 4.0 for Line, 2.5 for Siege."""
    w = world_factory(n_regions=1)

    # Turn rate per second and per tick (at 20 tps):
    # Strike: 6.0 rad/s -> 0.30 rad/tick
    # Line: 4.0 rad/s   -> 0.20 rad/tick
    # Siege: 2.5 rad/s  -> 0.125 rad/tick

    # Initialize all facing 0.0 rad (+x)
    strike = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 0.0, 0.0, 0)       # Strike
    line = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 100.0, 0.0, 0)     # Line
    siege = lib.om_unit_spawn(w, OMUnitType.BASTION, 0, 200.0, 0.0, 0)     # Siege

    lib.om_unit_set_facing(w, strike, 0.0)
    lib.om_unit_set_facing(w, line, 0.0)
    lib.om_unit_set_facing(w, siege, 0.0)

    # Order all to move directly along +y (target angle = pi/2 = ~1.5708 rad)
    lib.om_command_move(w, strike, 0.0, 500.0)
    lib.om_command_move(w, line, 100.0, 500.0)
    lib.om_command_move(w, siege, 200.0, 500.0)

    # Step exactly 1 tick
    lib.om_world_step(w)

    delta_strike = abs(lib.om_unit_get_facing(w, strike) - 0.0)
    delta_line = abs(lib.om_unit_get_facing(w, line) - 0.0)
    delta_siege = abs(lib.om_unit_get_facing(w, siege) - 0.0)

    # Verify per-tick turn rate caps:
    assert pytest.approx(delta_strike, abs=1e-3) == 6.0 / 20.0   # 0.30 rad
    assert pytest.approx(delta_line, abs=1e-3) == 4.0 / 20.0     # 0.20 rad
    assert pytest.approx(delta_siege, abs=1e-3) == 2.5 / 20.0    # 0.125 rad


def test_R_100_03_it_faces_pursuer(lib, world_factory):
    """Given a unit retreating from a pursuer under attack-target, When facing updates, Then it faces the pursuer."""
    w = world_factory(n_regions=1)

    # Friendly Vanguard at (100, 0) retreating towards (0, 0) (moving -x)
    # Under attack-target on pursuer at (200, 0) (+x)
    retreating_unit = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 100.0, 0.0, 0)
    pursuer = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 200.0, 0.0, 0)

    # Set facing to a different value first: om_unit_get_facing hard-stubs
    # 0.0, which coincidentally equals the expected pursuer angle below.
    lib.om_unit_set_facing(w, retreating_unit, math.pi)
    assert lib.om_unit_get_facing(w, retreating_unit) == pytest.approx(math.pi, abs=1e-6)

    # Issue retreat under attack-target
    lib.om_command_attack_target_kiting(w, retreating_unit, pursuer, 0.0, 0.0)

    lib.om_world_step(w)

    # While moving backwards towards (0, 0), facing points towards pursuer (+x = 0.0 rad, not -x = pi)
    facing = lib.om_unit_get_facing(w, retreating_unit)
    assert pytest.approx(facing, abs=1e-2) == 0.0

