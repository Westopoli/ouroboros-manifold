import ctypes

class OMReplayCommand(ctypes.Structure):
    _fields_ = [
        ("tick", ctypes.c_uint64),
        ("force_id", ctypes.c_uint32),
        ("command_type", ctypes.c_uint32),
        ("target_x", ctypes.c_double),
        ("target_y", ctypes.c_double),
        ("target_id", ctypes.c_uint32),
    ]


def test_R_123_01_every_enemy_command_identical_on(lib, world_factory):
    """Given seed, script, map, and the command stream, When run twice, Then every enemy command is identical on identical ticks."""
    seed = 424242
    w1 = world_factory(n_regions=1)
    w2 = world_factory(n_regions=1)

    lib.om_mission_init_seed(w1, seed)
    lib.om_mission_init_seed(w2, seed)

    # Run 200 ticks on both worlds
    for tick in range(200):
        lib.om_tactical_tick(w1)
        lib.om_tactical_tick(w2)

    count1 = lib.om_replay_command_count(w1)
    count2 = lib.om_replay_command_count(w2)
    # A hard-stub count of 0 would make the per-command loop below run 0
    # times, proving nothing. Require real commands were actually logged.
    assert count1 > 0
    assert count1 == count2

    cmds1 = (OMReplayCommand * count1)()
    cmds2 = (OMReplayCommand * count2)()
    lib.om_replay_get_commands(w1, cmds1, count1)
    lib.om_replay_get_commands(w2, cmds2, count2)

    for c1, c2 in zip(cmds1, cmds2):
        assert c1.tick == c2.tick
        assert c1.force_id == c2.force_id
        assert c1.command_type == c2.command_type
        assert c1.target_x == c2.target_x
        assert c1.target_y == c2.target_y


def test_R_123_02_they_appear_in_same_replay(lib, world_factory):
    """Given the enemy, When its commands are logged, Then they appear in the same replay stream as player commands with a force id."""
    w = world_factory(n_regions=1)

    # Issue player command (force 0)
    lib.om_replay_log_command(w, 10, 0, 1, ctypes.c_double(100.0), ctypes.c_double(200.0), 0)
    # Issue enemy command (force 1)
    lib.om_replay_log_command(w, 15, 1, 0, ctypes.c_double(300.0), ctypes.c_double(400.0), 0)

    total_logged = lib.om_replay_command_count(w)
    assert total_logged == 2

    cmds = (OMReplayCommand * 2)()
    lib.om_replay_get_commands(w, cmds, 2)
    assert cmds[0].force_id == 0
    assert cmds[1].force_id == 1


