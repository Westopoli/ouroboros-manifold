def test_R_116_02_its_direction_archetype_s_defensive(lib, world_factory):
    """Given the region's fields, When the ±30 percent modifier applies, Then its direction is the archetype's (defensive stand grows with wealth, counterinsurgency grows with tension, suppression shrinks)."""
    # 1. Defensive stand (0) grows with wealth (economy 100 vs economy 0)
    dim_def_rich = lib.om_map_compute_modified_canvas(0, ctypes.c_double(100.0), ctypes.c_double(50.0))
    dim_def_poor = lib.om_map_compute_modified_canvas(0, ctypes.c_double(0.0), ctypes.c_double(50.0))
    assert ctypes.c_double(dim_def_rich).value > ctypes.c_double(dim_def_poor).value

    # Maximum scaling is ±30% (ratio between max and base <= 1.30, min >= 0.70)
    base_dim = 16000.0
    assert ctypes.c_double(dim_def_rich).value <= base_dim * 1.3001
    assert ctypes.c_double(dim_def_poor).value >= base_dim * 0.6999

    # 2. Counterinsurgency (9) grows with tension (tension 100 vs tension 0)
    dim_ci_high_ten = lib.om_map_compute_modified_canvas(9, ctypes.c_double(50.0), ctypes.c_double(100.0))
    dim_ci_low_ten = lib.om_map_compute_modified_canvas(9, ctypes.c_double(50.0), ctypes.c_double(0.0))
    assert ctypes.c_double(dim_ci_high_ten).value > ctypes.c_double(dim_ci_low_ten).value

    # 3. Suppression (4) shrinks with higher threat/tension
    dim_sup_high = lib.om_map_compute_modified_canvas(4, ctypes.c_double(50.0), ctypes.c_double(100.0))
    dim_sup_low = lib.om_map_compute_modified_canvas(4, ctypes.c_double(50.0), ctypes.c_double(0.0))
    assert ctypes.c_double(dim_sup_high).value < ctypes.c_double(dim_sup_low).value
