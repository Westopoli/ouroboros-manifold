def test_R_090_03_only_observer_s_own_interference(lib, world_factory):
    """Given an observer outside a zone looking at a target inside it, When visibility is computed, Then only the observer's own interference applies [Q-090-01: the bible says outsiders "can't see as far into the zone"; code samples the observer's position only]."""
    w = world_factory(n_regions=1)

    # Observer Vanguard (sensor radius 700 wu) at (0, 0), outside any interference (i = 0.0)
    obs = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, 0.0, 0)

    # Interference zone at (500, 0), radius 300, intensity 0.8 (covers target, does not cover observer)
    lib.om_map_add_interference_zone(w, 500.0, 0.0, 0, 0.8, 300.0)

    # Target Raider at (500, 0), inside the interference zone (distance 500 wu from observer)
    target = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 500.0, 0.0, 0)

    lib.om_visibility_compute(w)

    # Because only observer's own interference (0.0) applies to effective radius:
    # effective radius = 700 * (1 - 0.0) = 700 wu.
    # Target distance (500 wu) <= 700 wu -> observer sees target.
    assert lib.om_unit_can_see(w, obs, target) == 1

    # Check that interference at observer position is indeed 0.0 and at target is 0.8
    assert pytest.approx(lib.om_zone_sample_interference(w, 0.0, 0.0, 0), abs=1e-4) == 0.0
    assert pytest.approx(lib.om_zone_sample_interference(w, 500.0, 0.0, 0), abs=1e-4) == 0.8


def test_R_090_04_interference_at_fixed_point_changes(lib, world_factory):
    """Given a zone source that moves over the mission, When ticks pass, Then interference at a fixed point changes as the source moves."""
    w = world_factory(n_regions=1)

    # Moving zone source starting at (0, 0) moving towards (200, 0) with velocity vx = 2.0 wu/tick
    lib.om_map_add_moving_interference_zone(w, 0.0, 0.0, 0, 0.6, 100.0, 2.0, 0.0)

    # At tick 0, fixed point (200, 0) is at distance 200 wu (outside radius 100 wu) -> interference 0.0
    val_tick0 = lib.om_zone_sample_interference(w, 200.0, 0.0, 0)
    assert pytest.approx(val_tick0, abs=1e-4) == 0.0

    # Advance 100 ticks -> zone center moves to (200, 0)
    for _ in range(100):
        lib.om_world_step(w)

    # At tick 100, fixed point (200, 0) is at the center of the moving zone -> interference 0.6
    val_tick100 = lib.om_zone_sample_interference(w, 200.0, 0.0, 0)
    assert pytest.approx(val_tick100, abs=1e-4) == 0.6
    assert val_tick100 > val_tick0


