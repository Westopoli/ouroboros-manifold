def read_mission_candidates(lib, w, max_records=64):
    buf = (OMMissionCandidate * max_records)()
    n = lib.om_mission_candidates(w, buf, max_records)
    return [buf[i] for i in range(n)]


class OMChapterPhase:
    BRIEFING = 0
    RECON = 1
    MISSION = 2
    OUTCOME_RESOLUTION = 3
    TIME_JUMP = 4
    CHARACTER_SELECTION = 5
    NEXT_BRIEFING = 6


def test_R_055_01_order_mission_briefing_recon_free(lib, world_factory):
    """Given a new chapter, When it starts, Then the order is: mission briefing, recon (free camera, no mission clock), mission (real time, no pause), outcome resolution, time jump with chronicle, character selection, next briefing."""
    w = world_factory(n_regions=2)
    lib.om_chapter_start(w, 1)

    # Initial phase: Briefing
    assert lib.om_chapter_current_phase(w) == OMChapterPhase.BRIEFING

    # Advance through phases in exact sequence
    lib.om_chapter_advance_phase(w)
    assert lib.om_chapter_current_phase(w) == OMChapterPhase.RECON
    assert lib.om_chapter_recon_has_clock(w) == 0  # free camera, no mission clock

    lib.om_chapter_advance_phase(w)
    assert lib.om_chapter_current_phase(w) == OMChapterPhase.MISSION
    assert lib.om_chapter_mission_realtime(w) == 1  # real time, no pause

    lib.om_chapter_advance_phase(w)
    assert lib.om_chapter_current_phase(w) == OMChapterPhase.OUTCOME_RESOLUTION

    lib.om_chapter_advance_phase(w)
    assert lib.om_chapter_current_phase(w) == OMChapterPhase.TIME_JUMP

    lib.om_chapter_advance_phase(w)
    assert lib.om_chapter_current_phase(w) == OMChapterPhase.CHARACTER_SELECTION

    lib.om_chapter_advance_phase(w)
    assert lib.om_chapter_current_phase(w) == OMChapterPhase.NEXT_BRIEFING


def test_R_055_02_no_strategic_tick_runs_strategic(lib, world_factory):
    """Given a mission is running, When any tactical tick passes, Then no strategic tick runs; the strategic sim is stopped for the mission's duration."""
    w = world_factory(n_regions=2)
    lib.om_chapter_start(w, 1)
    lib.om_chapter_set_phase(w, OMChapterPhase.MISSION)

    strat_tick_start = lib.om_world_strategic_tick(w)

    # Advance tactical simulation by 200 ticks (10 seconds of tactical time at 20 tps)
    for _ in range(200):
        lib.om_tactical_step(w)

    # Strategic tick count has not changed; strategic sim remained stopped
    strat_tick_end = lib.om_world_strategic_tick(w)
    assert strat_tick_end == strat_tick_start

    # om_tactical_step never touches the strategic counter either way, so the
    # check above holds vacuously. Drive the world's own strategic tick entry
    # point while still in MISSION phase and confirm it is still held stopped.
    assert lib.om_chapter_current_phase(w) == OMChapterPhase.MISSION
    lib.om_world_step(w)
    assert lib.om_world_strategic_tick(w) == strat_tick_start


def test_R_055_03_those_field_changes_land_before(lib, world_factory):
    """Given the mission resolves, When the outcome resolver applies its consequence bundle (E-10), Then those field changes land before the first tick of the time jump."""
    w = world_factory(n_regions=2)
    set_region(lib, w, 0, tier=OMTier.HOME, military=30.0, economy=40.0, tension=20.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)

    lib.om_chapter_start(w, 1)
    lib.om_chapter_set_phase(w, OMChapterPhase.OUTCOME_RESOLUTION)

    # Apply consequence bundle: military +10.0 in region 0
    lib.om_outcome_apply_consequences(w, target_region=0, delta_military=10.0, delta_economy=5.0)

    # Field changes landed immediately at outcome resolution
    assert lib.om_region_field(w, 0, OMField.MILITARY) == pytest.approx(40.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.ECONOMY) == pytest.approx(45.0, abs=1e-6)

    # The time jump has not run its first tick yet
    time_jump_start_tick = lib.om_time_jump_start_tick(w)
    current_strat_tick = lib.om_world_strategic_tick(w)
    assert time_jump_start_tick > current_strat_tick


def test_R_055_04_character_selector_runs_after_it(lib, world_factory):
    """Given the time jump completes, When the mission generator runs, Then the character selector runs after it and reads the chosen mission region."""
    w = world_factory(n_regions=4)
    lib.om_chapter_start(w, 1)

    # Register a player faction owning region 2 (a frontier region under
    # attack, the same defensive_stand trigger shape as test_E10_S072's
    # fixture) and a hostile neighbor on region 3, so the mission candidate
    # pool is non-empty -- a bare world with no faction and no owned region
    # falls back to om_mission_fallback_region, which returns 0 when no
    # player faction is found, making chosen_region trivially satisfy a
    # bare "!= 0" check for the wrong reason.
    set_faction(lib, w, 0, OMArchetype.PLAYER, budget=50.0)
    set_faction(lib, w, 1, OMArchetype.CONQUEROR, budget=100.0)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)

    set_region(lib, w, 2, tier=OMTier.HOME, military=30.0, economy=40.0, tension=20.0, population=50.0)
    set_owner(lib, w, 2, 0, held_since=-1)

    set_region(lib, w, 3, tier=OMTier.HOME, military=40.0, economy=50.0, tension=15.0, population=50.0)
    set_owner(lib, w, 3, 1, held_since=-1)

    set_edge(lib, w, 2, 3, OMEdge.BORDER)

    # Complete time jump phase
    lib.om_chapter_set_phase(w, OMChapterPhase.TIME_JUMP)
    lib.om_time_jump_run(w, 50)

    # Mission generator runs and chooses a mission region
    lib.om_mission_generator_run(w)
    chosen_region = lib.om_mission_generator_chosen_region(w)
    # A hard-stub chosen-region accessor returning 0 would make the equality
    # below trivially true against an equally-stubbed reader; a candidate
    # pool was set up above, so 0 alone is not a valid chosen region here.
    assert chosen_region != 0, "chosen region must be a real (nonzero) mission target"

    # om_mission_generator_run already consumed the weighted-draw RNG state
    # internally (it calls om_mission_select once); re-calling om_mission_select
    # here would draw again and could pick a different index, so instead read
    # the candidate pool it built (a side-effect-free accessor) and check that
    # chosen_region names one of the real candidates it scored -- self-consistent
    # whichever region actually scores highest, not a hardcoded region number.
    candidates = read_mission_candidates(lib, w)
    assert any(c.region_idx == chosen_region for c in candidates), (
        "chosen region must be one of the candidates the generator actually built and scored"
    )

    # Character selector runs after mission generator and reads the chosen region
    lib.om_character_selector_run(w)
    read_region = lib.om_character_selector_input_region(w)

    assert read_region == chosen_region


def test_R_055_05_opening_time_jump_runs_before(lib, world_factory):
    """Given the campaign's first chapter, When the world is generated, Then an opening time jump runs before the first briefing and its chronicle shows 3 to 5 world entries only."""
    w = world_factory(n_regions=4)
    lib.om_campaign_start(w, chapter=1)

    # Opening time jump ran
    jump_len = lib.om_campaign_opening_jump_length(w)
    assert 20 <= jump_len <= 50

    # Current phase is first briefing
    assert lib.om_chapter_current_phase(w) == OMChapterPhase.BRIEFING

    # Chronicle shows 3 to 5 world entries only
    chronicle_entries = lib.om_chronicle_entry_count(w)
    assert 3 <= chronicle_entries <= 5

    # No consequence entries and no lineage entries in opening jump chronicle
    assert lib.om_chronicle_consequence_entry_count(w) == 0
    assert lib.om_chronicle_lineage_entry_count(w) == 0

