def test_R_060_05_region_s_named_characters_attached(lib, world_factory):
    """Given an event of significance tier 3 or higher fires in a region, When logged, Then the region's named characters are attached to the event record; the ledger never stores event history itself."""
    w = world_factory(n_regions=2)

    cid = lib.om_character_create_with_rank(w, faction_id=0, region_idx=0, rank=OMRank.REGIONAL_COMMANDER, birth_tick=0, lifespan=200)

    # Fire tier 3 event in region 0
    ev_id = lib.om_event_fire_manual(w, region_idx=0, tier=3)

    # Check attached character on event record
    n_attached = lib.om_event_attached_character_count(w, ev_id)
    assert n_attached >= 1
    attached_cid = lib.om_event_get_attached_character(w, ev_id, 0)
    assert attached_cid == cid

    # Ledger record itself does NOT store event history
    assert lib.om_character_has_event_history(w, cid) == 0


