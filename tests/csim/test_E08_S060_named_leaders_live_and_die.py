    assert sup_rec.faction == 2

    # 2. Region colonized or conquered gives a regional commander
    lib.om_region_assign_regional_commander(w, region_idx=1, faction_id=2)
    reg_id = lib.om_region_regional_commander(w, region_idx=1)
    assert reg_id > 0

    reg_rec = OmCharacterRecord()
    lib.om_character_get_record(w, reg_id, ctypes.byref(reg_rec))
    assert reg_rec.rank == OMRank.REGIONAL_COMMANDER
