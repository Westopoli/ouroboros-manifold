def test_R_060_03_it_becomes_historical_with_death(lib, world_factory):
    """Given a character's age reaches its lifespan, When natural deaths are processed, Then it becomes historical with a death tick, and if its rank is supreme or regional commander a successor is created with a fresh name and lifespan in the same faction and region (regional only if the faction still owns the region)."""
    w = world_factory(n_regions=2)
    set_owner(lib, w, 0, faction_id=1)

    # Supreme commander born at tick 0 with lifespan 150
    cid = lib.om_character_create_with_rank(w, faction_id=1, region_idx=0, rank=OMRank.SUPREME_COMMANDER, birth_tick=0, lifespan=150)

    # Advance world to tick 150 and process natural deaths
    lib.om_world_set_strategic_tick(w, 150)
    lib.om_process_natural_deaths(w, tick=150)

    rec = OmCharacterRecord()
    lib.om_character_get_record(w, cid, ctypes.byref(rec))
    assert rec.status == OMStatus.HISTORICAL
    assert rec.death_tick == 150

    # Successor created with supreme commander rank in same faction & region
    succ_id = lib.om_faction_supreme_commander(w, faction_id=1)
    assert succ_id != cid
    succ_rec = OmCharacterRecord()
    lib.om_character_get_record(w, succ_id, ctypes.byref(succ_rec))
    assert succ_rec.status == OMStatus.ACTIVE
    assert succ_rec.rank == OMRank.SUPREME_COMMANDER
    assert succ_rec.faction == 1
    assert succ_rec.region == 0
    assert 150 <= succ_rec.lifespan <= 350


