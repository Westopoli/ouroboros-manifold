def test_R_059_01_max_1_floor_n_0(lib, world_factory):
    """Given a lineage with n living members and a jump of T ticks, When members are generated at the jump's end, Then max(1, floor(n · 0.03 · T)) descendants are created."""
    w = world_factory(n_regions=4)

    # Lineage with n=2 living members, jump T=50 ticks
    # max(1, floor(2 * 0.03 * 50)) = max(1, floor(3.0)) = 3
    lib.om_lineage_create(w, lineage_id=1, home_region=0)
    lib.om_character_create(w, character_id=1, lineage_id=1, region_idx=0, rank=3, birth_tick=0, lifespan=100)
    lib.om_character_create(w, character_id=2, lineage_id=1, region_idx=0, rank=3, birth_tick=10, lifespan=100)

    count_50 = lib.om_lineage_generate_descendants(w, lineage_id=1, jump_ticks=50)
    assert count_50 == 3

    # Small jump: n=1, T=20 -> max(1, floor(1 * 0.03 * 20)) = max(1, floor(0.6)) = 1
    lib.om_lineage_create(w, lineage_id=2, home_region=1)
    lib.om_character_create(w, character_id=3, lineage_id=2, region_idx=1, rank=3, birth_tick=0, lifespan=100)
    count_20 = lib.om_lineage_generate_descendants(w, lineage_id=2, jump_ticks=20)
    assert count_20 == 1


def test_R_059_02_its_parent_uniform_draw_among(lib, world_factory):
    """Given each descendant, When placed, Then its parent is a uniform draw among living members, its faction is the parent's, and with probability 0.1 it is placed in a uniform-random inhabited neighbor of the parent's region, else the parent's region."""
    w = world_factory(n_regions=4)
    set_edge(lib, w, 0, 1)
    set_region(lib, w, 1, tier=OMTier.FRONTIER, population=30.0, faction_id=2)

    lib.om_lineage_create(w, lineage_id=1, home_region=0)
    lib.om_character_create(w, character_id=1, lineage_id=1, region_idx=0, rank=3, birth_tick=0, lifespan=100)
    lib.om_character_set_faction(w, 1, faction_id=2)

    # Case A: spread draw >= 0.1 (e.g. 0.5) -> stays in parent region (region 0)
    lib.om_rng_force_descendant_spread(w, spread_draw=0.50)
    desc_a_id = lib.om_lineage_spawn_single_descendant(w, lineage_id=1)
    rec_a = OmCharacterRecord()
    lib.om_character_get_record(w, desc_a_id, ctypes.byref(rec_a))
    assert rec_a.region == 0
    assert rec_a.faction == 2

    # Case B: spread draw < 0.1 (e.g. 0.05) -> spreads to inhabited neighbor (region 1)
    lib.om_rng_force_descendant_spread(w, spread_draw=0.05)
    desc_b_id = lib.om_lineage_spawn_single_descendant(w, lineage_id=1)
    rec_b = OmCharacterRecord()
    lib.om_character_get_record(w, desc_b_id, ctypes.byref(rec_b))
    assert rec_b.region == 1
    assert rec_b.faction == 2


def test_R_059_03_it_has_name_region_faction(lib, world_factory):
    """Given a descendant, When recorded, Then it has a name, region, faction, birth tick equal to the jump's end tick, lifespan, lineage id, parent id, and generation = parent's + 1; nothing else."""
    w = world_factory(n_regions=4)
    current_tick = 50

    lib.om_lineage_create(w, lineage_id=1, home_region=0)
    lib.om_character_create(w, character_id=1, lineage_id=1, region_idx=0, rank=3, birth_tick=0, lifespan=100)
    lib.om_character_set_generation(w, 1, generation=2)
    lib.om_character_set_faction(w, 1, faction_id=3)

    desc_id = lib.om_lineage_spawn_descendant_at_tick(w, lineage_id=1, parent_id=1, tick=current_tick)
    rec = OmCharacterRecord()
    lib.om_character_get_record(w, desc_id, ctypes.byref(rec))

    assert rec.birth_tick == current_tick
    assert rec.lineage_id == 1
    assert rec.parent_id == 1
    assert rec.generation == 3  # parent's + 1
    assert rec.faction == 3
    assert len(rec.name) > 0
    assert 150 <= rec.lifespan <= 350


def test_R_059_04_nothing_created(lib, world_factory):
    """Given a lineage with no living members, When generation runs, Then nothing is created."""
    w = world_factory(n_regions=4)

    # Lineage with 0 living members
