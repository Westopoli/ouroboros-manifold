def test_R_064_01_every_region_field_ownership_faction(lib, world_factory):
    """Given any chapter transition, When the next chapter starts, Then every region field, ownership, faction, tech level, edge type, event queue, and ledger record persists unchanged except by the sim itself."""
    w = world_factory(n_regions=4)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=60.0, tension=30.0, population=70.0, faction_id=1)
    set_owner(lib, w, 0, faction_id=1, held_since=5)
    set_faction(lib, w, 1, archetype=1, budget=100.0, tech=25.0)

    lib.om_chapter_transition_start(w)
    lib.om_chapter_transition_complete(w)

    # State persists across chapter transition
    assert lib.om_region_field(w, 0, OMField.MILITARY) == pytest.approx(50.0, abs=1e-5)
    assert lib.om_region_field(w, 0, OMField.ECONOMY) == pytest.approx(60.0, abs=1e-5)
    assert lib.om_region_owner(w, 0) == 1
    assert lib.om_faction_tech(w, 1) == pytest.approx(25.0, abs=1e-5)


def test_R_064_02_they_come_only_from_mission(lib, world_factory):
    """Given a new chapter, When forces are assigned, Then they come only from the mission generator's allocation (E-10); nothing carries from the previous mission's surviving units."""
    w = world_factory(n_regions=4)

    # Mission 1: assign units and leave survivors
    lib.om_force_allocator_run(w, mission_id=1, budget=100.0)
    lib.om_force_set_surviving_units(w, mission_id=1, n_survivors=15)

    # Next chapter / Mission 2: allocation depends only on its own budget/allocation
    lib.om_force_allocator_run(w, mission_id=2, budget=50.0)
    units_m2 = lib.om_force_allocated_unit_count(w, mission_id=2)

    # Run allocation with 0 survivors from previous mission for identical mission 2 parameters
    w_clean = world_factory(n_regions=4)
    lib.om_force_set_surviving_units(w_clean, mission_id=1, n_survivors=0)
    lib.om_force_allocator_run(w_clean, mission_id=2, budget=50.0)
    units_clean = lib.om_force_allocated_unit_count(w_clean, mission_id=2)

    assert units_m2 == units_clean  # Zero carryover from surviving units


