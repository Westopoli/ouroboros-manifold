def test_R_064_04_next_time_jump_produces_same(lib, world_factory):
    """Given a save and load between chapters, When loaded, Then the next time jump produces the same trace as if never saved (determinism includes the RNG state and the chain tag counter)."""
    w1 = world_factory(n_regions=4, seed=12345)
    w2 = world_factory(n_regions=4, seed=99999)  # Will be overwritten by load

    # Run chapter 1 on w1
    lib.om_chapter_start(w1, chapter=1)
    lib.om_time_jump_run(w1, 25)

    # Save w1 state to buffer
    save_size = lib.om_save_state_size(w1)
    buf = (ctypes.c_uint8 * save_size)()
    lib.om_save_state_write(w1, buf, save_size)

    # Load into w2
    lib.om_load_state_read(w2, buf, save_size)

    # Run next time jump on both
    lib.om_time_jump_run(w1, 30)
    lib.om_time_jump_run(w2, 30)

    # Checksums match identically (determinism across save/load)
    cs1 = lib.om_world_checksum(w1)
    cs2 = lib.om_world_checksum(w2)
    assert cs1 == cs2
