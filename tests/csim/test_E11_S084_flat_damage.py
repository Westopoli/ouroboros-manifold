def test_R_084_01_one_attack_lands_for_base(lib, world_factory):
    """Given an attacker in range of its target every tick, When its attack timer elapses (interval × 20 ticks), Then one attack lands for base × matchup × output multiplier × (1 − reduction), with reduction the sum of Brace 0.50, Fortify 0.20, and Warden aura 0.10 where they apply, capped at 0.9."""
    w = world_factory(n_regions=1)

    # Spawn attacker Raider (base damage 9.0, interval 0.8s = 16 ticks, Strike)
    # Target Vanguard (Line): Strike->Line matchup = 0.75
    # Target has Brace (0.50), Fortify (0.20), and Warden aura (0.10) active: reduction = 0.80 (< 0.9 cap)
    attacker = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 0.0, 0.0, 0)
    target = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 1, 100.0, 0.0, 0)

    lib.om_unit_set_brace_active(w, target, 1)        # 0.50 reduction
    lib.om_unit_set_fortify_active(w, target, 1)      # 0.20 reduction
    lib.om_unit_set_warden_aura_active(w, target, 1)  # 0.10 reduction

    # An explicit order suppresses the ability auto-trigger scan
    # (om_tac_unit_ai: u->order != OM_ORDER_NONE -> suppress_auto = 1), so
    # the attacker's own Surge (which else auto-fires the instant an enemy
    # is within its attack range, doubling its output) never starts; this
    # keeps the attack timing and target acquisition otherwise unchanged.
    lib.om_command_attack_target(w, attacker, target)

    hp_initial = lib.om_unit_hp(w, target)

    # Step until attack timer elapses (16 ticks)
    for _ in range(16):
        lib.om_tactical_step(w)

    # Expected damage = base(9.0) * matchup(0.75) * output_mult(1.0) * (1 - 0.80) = 9.0 * 0.75 * 0.20 = 1.35
    dmg_taken = hp_initial - lib.om_unit_hp(w, target)
    assert dmg_taken == pytest.approx(1.35, abs=1e-6)


