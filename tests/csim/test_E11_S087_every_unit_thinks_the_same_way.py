def test_R_087_05_it_anchors_at_its_position(lib, world_factory):
    """Given an attack-moving unit that acquires a target, When it does, Then it anchors at its position, and if the unit itself moves more than 200 wu from the anchor it drops the target and resumes its path (A188: the leash tests the unit's own distance, never the target's)."""
    w = world_factory(n_regions=1)

    vanguard = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 100.0, 0.0, 0)
    enemy = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 250.0, 0.0, 0)

    lib.om_command_attack_move(w, [vanguard], 1, 1000.0, 0.0)
    # Test-defect, A163/A164: 1 step -> 4 steps (first acquisition moved by up to 3 ticks); cause: aligned targeting cohort (parity with the Python, Addendum 63).
    for _ in range(4):
        lib.om_tactical_step(w)
    assert lib.om_unit_target(w, vanguard) == enemy

    # Test-defect, A188: the unit moves > 200 wu from the anchor (anchor was at ~100.0, unit moved to 350.0 -> distance 250 > 200)
    # Test-defect, H-057: the leash is a Vanguard's sensor radius 700; the unit goes to 850 (750 from the anchor), the enemy beside it.
    lib.om_unit_teleport(w, vanguard, 850.0, 0.0, 0)
    lib.om_unit_teleport(w, enemy, 950.0, 0.0, 0)
    lib.om_tactical_step(w)

    # Target is dropped, unit resumes path
    assert lib.om_unit_target(w, vanguard) == -1


def test_R_087_06_it_targets_attacker_return_fire(lib, world_factory):
    """Given an idle unit with no target and no order taking damage, When hit, Then it targets the attacker (return fire); an already-engaged unit ignores incoming damage for targeting."""
    w = world_factory(n_regions=1)

    # Idle unit takes damage
    unit = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, 0.0, 0)
    attacker1 = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 150.0, 0.0, 0)
    attacker2 = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 0.0, 150.0, 0)
    # Same id-collision issue as R-087-03: distinct ids required before the
    # targeting equality checks below mean anything.
    assert len({unit, attacker1, attacker2}) == 3, "spawned unit ids must be distinct"

    lib.om_unit_deal_damage(w, attacker1, unit, 10.0)
    lib.om_tactical_step(w)
    assert lib.om_unit_target(w, unit) == attacker1

    # While already engaged, taking damage from attacker2 is ignored
    lib.om_unit_deal_damage(w, attacker2, unit, 10.0)
    lib.om_tactical_step(w)
    assert lib.om_unit_target(w, unit) == attacker1


