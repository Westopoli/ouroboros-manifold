def test_R_087_03_it_attacks_nearest_such_enemy(lib, world_factory):
    """Given an idle or attack-moving unit with an enemy within attack range on its layer, When targets are evaluated, Then it attacks the nearest such enemy; an engaged target still alive and in range is kept."""
    w = world_factory(n_regions=1)

    vanguard = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, 0.0, 0)
    e_near = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 100.0, 0.0, 0)
    e_far = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 200.0, 0.0, 0)
    # om_unit_spawn always returning 0 would alias every unit to id 0, making
    # om_unit_target's own 0-stub match by coincidence below.
    assert len({vanguard, e_near, e_far}) == 3, "spawned unit ids must be distinct"

    # Step targeting: acquires nearest enemy (e_near)
    # Test-defect, A163/A164: 1 step -> 4 steps (first acquisition moved by up to 3 ticks); cause: aligned targeting cohort (parity with the Python, Addendum 63).
    for _ in range(4):
        lib.om_tactical_step(w)
    assert lib.om_unit_target(w, vanguard) == e_near

    # Move e_far closer than e_near; engaged target is still kept
    lib.om_unit_teleport(w, e_far, 50.0, 0.0, 0)
    lib.om_tactical_step(w)
    assert lib.om_unit_target(w, vanguard) == e_near


