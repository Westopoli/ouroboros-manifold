def test_R_052_01_it_has_zero_regions_its(lib, world_factory):
    """Given the player civilization loses its last region, When the tick ends, Then it has zero regions, its budget still accumulates as 0, and the generational structure (E-08) handles the player's next chapter."""
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w, 0, OMArchetype.PLAYER, budget=0.0, tech=10.0, confidence=5.0)
    set_faction(lib, w, 1, OMArchetype.CONQUEROR, budget=100.0, tech=10.0, confidence=5.0)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)

    # Region 0 is player's only region. Economy pinned at REGION_MAINTENANCE_COST
    # (8.0, ALG-17) so this tick's budget accumulation (3b, which runs before
    # the conquest resolves at 3f -- docs/bible/algorithms.md tick sequence)
    # nets exactly 0 regardless of the region still nominally being owned at
    # 3b. A higher economy (the original 50.0) earns a one-tick income spike
    # before the loss registers, which the "budget still accumulates as 0"
    # assertion below can never satisfy -- the fixture's own numbers never
    # reached the zero-budget branch it claims to test.
    set_region(lib, w, 0, tier=OMTier.HOME, military=2.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)

    # Region 1 is enemy's region
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)

    # Enemy attacks Region 0 with massive commit, causing conquest
    inject_intent(lib, w, 1, OMAction.ATTACK, target_idx=0, source_idx=1, commit=50.0, mode=OMMode.SURPRISE)
    force_draws(lib, w, [1.0, 0.99])  # stochastic draw 1.0, unrest draw
    lib.om_world_step(w)

    # Player has zero regions
    assert lib.om_region_owner(w, 0) == 1
    assert lib.om_faction_territory(w, 0) == 0

    # Step again: budget accumulates as 0
    lib.om_world_step(w)
    assert lib.om_faction_budget(w, 0) == pytest.approx(0.0, abs=1e-6)

    # Generational structure handles player collapse
    assert lib.om_player_faction_collapsed(w, 0) == 1


def test_R_052_02_no_rule_anywhere_checks_whether(lib, world_factory):
    """Given any faction, When attacked, revolted, or absorbed, Then no rule anywhere checks whether it is the player's."""
    # Symmetrical test: Player faction (Faction 0) vs NPC faction (Faction 1)
    # Both defend identical regions against identical attacks
    w = world_factory(n_regions=4)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w, 0, OMArchetype.PLAYER, budget=0.0, tech=10.0, confidence=5.0)
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=0.0, tech=10.0, confidence=5.0)
    set_faction(lib, w, 2, OMArchetype.CONQUEROR, budget=100.0, tech=10.0, confidence=5.0)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 2, 1.0, 1.0, 1.0)

    # Region 0: owned by Player (military 10.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=10.0, economy=40.0, tension=10.0, population=40.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)

    # Region 1: owned by NPC Faction 1 (identical military 10.0)
    set_region(lib, w, 1, tier=OMTier.HOME, military=10.0, economy=40.0, tension=10.0, population=40.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)

    # Regions 2 and 3 owned by Attacker Faction 2
    set_region(lib, w, 2, tier=OMTier.HOME, military=50.0, economy=40.0, tension=0.0, population=40.0, faction_id=2)
    set_owner(lib, w, 2, 2, held_since=-1)
    set_region(lib, w, 3, tier=OMTier.HOME, military=50.0, economy=40.0, tension=0.0, population=40.0, faction_id=2)
    set_owner(lib, w, 3, 2, held_since=-1)

    set_edge(lib, w, 0, 2, OMEdge.BOTH)
    set_edge(lib, w, 1, 3, OMEdge.BOTH)

    # Attack Region 0 (Player) with commit 30.0. Only one forced draw: this
    # attack's damage never brings target military below CONQUEST_THRESHOLD
    # (5.0), so ALG-22's conquest-unrest draw never fires and a second forced
    # value here would sit unconsumed in om_rng_force's FIFO queue -- carried
    # over to leak into the *next* attack's stochastic draw instead of this
    # tick's intended 1.0 (a stale forced-RNG-draw leftover; confirmed via
    # om_rng_forced_remaining()).
    inject_intent(lib, w, 2, OMAction.ATTACK, target_idx=0, source_idx=2, commit=30.0, mode=OMMode.SURPRISE)
    force_draws(lib, w, [1.0])
    lib.om_world_step(w)

    damage_player = lib.om_region_field(w, 0, OMField.MILITARY)
    owner_player = lib.om_region_owner(w, 0)

    # Attack Region 1 (NPC) with identical commit 30.0 -- same one-draw reasoning.
    inject_intent(lib, w, 2, OMAction.ATTACK, target_idx=1, source_idx=3, commit=30.0, mode=OMMode.SURPRISE)
    force_draws(lib, w, [1.0])
    lib.om_world_step(w)

    damage_npc = lib.om_region_field(w, 1, OMField.MILITARY)
    owner_npc = lib.om_region_owner(w, 1)

    # Exact equality: no plot armor, no special modifier for player
    assert damage_player == pytest.approx(damage_npc, abs=1e-6)
    assert (owner_player == 2) == (owner_npc == 2)

