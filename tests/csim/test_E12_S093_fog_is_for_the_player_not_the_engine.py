class OMUnitType:
    RAIDER = 0
    INTERCEPTOR = 1
    VANGUARD = 2
    WARDEN = 3
    BOMBARD = 4
    BASTION = 5


def test_R_093_01_traces_identical(lib, world_factory):
    """Given two identical battles differing only in the player's visibility, When resolved, Then the traces are identical."""
    # Battle 1: Player fog enabled (player visibility restricted)
    w1 = world_factory(seed=42, n_regions=1)
    lib.om_visibility_set_player_fog(w1, 1)

    f1 = lib.om_unit_spawn(w1, OMUnitType.RAIDER, 0, 100.0, 100.0, 0)
    e1 = lib.om_unit_spawn(w1, OMUnitType.RAIDER, 1, 150.0, 100.0, 0)
    lib.om_command_attack_move(w1, f1, 300.0, 100.0)
    lib.om_command_attack_move(w1, e1, 0.0, 100.0)

    # Battle 2: Identical battle, but player fog disabled (omniscient player view)
    w2 = world_factory(seed=42, n_regions=1)
    lib.om_visibility_set_player_fog(w2, 0)

    f2 = lib.om_unit_spawn(w2, OMUnitType.RAIDER, 0, 100.0, 100.0, 0)
    e2 = lib.om_unit_spawn(w2, OMUnitType.RAIDER, 1, 150.0, 100.0, 0)
    lib.om_command_attack_move(w2, f2, 300.0, 100.0)
    lib.om_command_attack_move(w2, e2, 0.0, 100.0)

    # Run both simulations for 50 ticks
    for _ in range(50):
        lib.om_world_step(w1)
        lib.om_world_step(w2)

    # Assert battle traces and state checksums are identical
    cs1 = lib.om_world_get_state_checksum(w1)
    cs2 = lib.om_world_get_state_checksum(w2)
    assert cs1 == cs2

    # Verify unit states are identical
    assert pytest.approx(lib.om_unit_get_hp(w1, f1), abs=1e-4) == lib.om_unit_get_hp(w2, f2)
    assert pytest.approx(lib.om_unit_get_hp(w1, e1), abs=1e-4) == lib.om_unit_get_hp(w2, e2)


def test_R_093_02_it_uses_its_own_visible(lib, world_factory):
    """Given an enemy unit, When it acquires targets, Then it uses its own visible set with the same rules as the player's units."""
    w = world_factory(n_regions=1)

    # Enemy Raider (base sensor radius 300 wu) at (0, 0)
    enemy = lib.om_unit_spawn(w, OMUnitType.RAIDER, 1, 0.0, 0.0, 0)

    # Friendly target 1 inside sensor radius: (200, 0) (distance 200 <= 300)
    friendly_in_range = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 200.0, 0.0, 0)

    # Friendly target 2 outside sensor radius: (500, 0) (distance 500 > 300)
    friendly_out_of_range = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 500.0, 0.0, 0)

    lib.om_visibility_compute(w)

    # Enemy can see target 1, but cannot see target 2
    assert lib.om_unit_can_see(w, enemy, friendly_in_range) == 1
    assert lib.om_unit_can_see(w, enemy, friendly_out_of_range) == 0

    # Enemy acquires target: must choose target 1, not target 2
    lib.om_unit_acquire_target(w, enemy)
    assert lib.om_unit_get_target(w, enemy) == friendly_in_range

    # If target 1 is hidden behind blocking cover, enemy can no longer acquire it
    lib.om_map_add_cover(w, 100.0, 0.0, 20.0, 5.0)
    lib.om_visibility_compute(w)
    assert lib.om_unit_can_see(w, enemy, friendly_in_range) == 0

    lib.om_unit_acquire_target(w, enemy)
    # Enemy acquires nothing because no targets in its visible set
    assert lib.om_unit_get_target(w, enemy) == 0


def test_R_093_03_they_read_every_neighbor_region(lib, world_factory):
    """Given the strategic sim, When faction agents decide, Then they read every neighbor region's fields without fog (E-05)."""
    w = world_factory(n_regions=3)

    # Region 0 is owned by Faction 0; Region 1 is a neighbor
    # Set known field values in neighbor Region 1
    set_region(w, 1, OMField.MILITARY, 0.42)

    # Tactical fog is active; Faction 0 has no units in Region 1
    lib.om_visibility_set_player_fog(w, 1)

    # Faction strategic agent in Region 0 reads neighbor Region 1's fields
    read_val = lib.om_strategic_agent_read_region_field(w, 0, 1, OMField.MILITARY)

    # Agent successfully reads the field without tactical fog masking it
    assert pytest.approx(read_val, abs=1e-4) == 0.42

