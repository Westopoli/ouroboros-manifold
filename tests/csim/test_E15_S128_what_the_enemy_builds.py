import ctypes

class OMUnitCategory:
    LINE = 0
    STRIKE = 1
    SIEGE = 2


class OMCompositionRatio(ctypes.Structure):
    _fields_ = [
        ("line", ctypes.c_double),
        ("strike", ctypes.c_double),
        ("siege", ctypes.c_double),
    ]


def test_R_128_01_it_produces_category_most_below(lib, world_factory):
    """Given the enemy's target ratio (per archetype script), When a structure's timer fires, Then it produces the category most below its target share."""
    target = OMCompositionRatio(line=0.40, strike=0.30, siege=0.30)
    # Current composition: line 0.45, strike 0.35, siege 0.20
    # Deficits: line -0.05, strike -0.05, siege +0.10 (most below target share)
    current = OMCompositionRatio(line=0.45, strike=0.35, siege=0.20)

    chosen_category = lib.om_enemy_production_select_category(
        ctypes.byref(target),
        ctypes.byref(current),
    )
    assert chosen_category == OMUnitCategory.SIEGE


def test_R_128_02_15_percent_target_shifts_to(lib, world_factory):
    """Given the player's composition has a category at 70 percent or more, When the target is computed, Then 15 percent of the target shifts to the counter category (Strike counters Siege, Line counters Strike, Siege counters Line), taken proportionally from the others, then renormalized."""
    # Base target ratio: line 0.33, strike 0.33, siege 0.34
    base_target = OMCompositionRatio(line=0.333, strike=0.333, siege=0.334)

    # 1. Player has 75% Siege -> Strike counters Siege -> Strike gets +15%
    player_siege_heavy = OMCompositionRatio(line=0.10, strike=0.15, siege=0.75)
    adjusted_strike = OMCompositionRatio()
    lib.om_enemy_production_adapt_target(
        ctypes.byref(base_target),
        ctypes.byref(player_siege_heavy),
        ctypes.byref(adjusted_strike),
    )
    assert adjusted_strike.strike > base_target.strike
    assert adjusted_strike.strike + adjusted_strike.line + adjusted_strike.siege == pytest.approx(1.0, abs=1e-5)

    # 2. Player has 70% Strike -> Line counters Strike
    player_strike_heavy = OMCompositionRatio(line=0.15, strike=0.70, siege=0.15)
    adjusted_line = OMCompositionRatio()
    lib.om_enemy_production_adapt_target(
        ctypes.byref(base_target),
        ctypes.byref(player_strike_heavy),
        ctypes.byref(adjusted_line),
    )
    assert adjusted_line.line > base_target.line
    assert adjusted_line.strike + adjusted_line.line + adjusted_line.siege == pytest.approx(1.0, abs=1e-5)

    # 3. Player has 70% Line -> Siege counters Line
    player_line_heavy = OMCompositionRatio(line=0.70, strike=0.15, siege=0.15)
    adjusted_siege = OMCompositionRatio()
    lib.om_enemy_production_adapt_target(
        ctypes.byref(base_target),
        ctypes.byref(player_line_heavy),
        ctypes.byref(adjusted_siege),
    )
    assert adjusted_siege.siege > base_target.siege
    assert adjusted_siege.strike + adjusted_siege.line + adjusted_siege.siege == pytest.approx(1.0, abs=1e-5)


def test_R_128_03_it_never_deviates_from_ratio(lib, world_factory):
    """Given the enemy, When it produces, Then it never deviates from the ratio otherwise."""
    # Player composition is balanced (no category >= 70%)
    base_target = OMCompositionRatio(line=0.40, strike=0.30, siege=0.30)
    player_balanced = OMCompositionRatio(line=0.40, strike=0.30, siege=0.30)

    adjusted = OMCompositionRatio()
    lib.om_enemy_production_adapt_target(
        ctypes.byref(base_target),
        ctypes.byref(player_balanced),
        ctypes.byref(adjusted),
    )

    # When no player category >= 70%, target ratio is identical to base target
    assert adjusted.line == pytest.approx(base_target.line, abs=1e-5)
    assert adjusted.strike == pytest.approx(base_target.strike, abs=1e-5)
    assert adjusted.siege == pytest.approx(base_target.siege, abs=1e-5)

