def test_R_042_03_neither_attacks_other_no_friction(lib, world_factory):
    """Given a neutral pair, When agents decide and friction applies, Then neither attacks the other, no friction applies, and no adjacency bonus crosses their edges."""
    w = world_factory(n_regions=2)
    isolate_agents(lib, w, friction=True)
    lib.om_world_set_feature(w, OMFeature.DIPLOMACY, 1)
    lib.om_world_set_feature(w, OMFeature.DRIFT, 1)
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=100.0, tech=0.0, confidence=5.0)
    set_faction(lib, w, 1, OMArchetype.CONQUEROR, budget=100.0, tech=0.0, confidence=5.0)
    set_stance(lib, w, 0, 1, OMStance.NEUTRAL)

    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=10.0, population=50.0)
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=80.0, tension=10.0, population=50.0)
    set_owner(lib, w, 0, 0, held_since=-1)
    set_owner(lib, w, 1, 1, held_since=-1)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)

    lib.om_diplomacy_step(w)
    lib.om_world_step(w)

