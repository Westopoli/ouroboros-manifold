def test_R_042_05_their_stance_hostile_if_their(lib, world_factory):
    """Given two starting factions, When the world begins, Then their stance is hostile if their archetype pair is in the override table (conqueror with anyone; fortifier with player and opportunist; opportunist with player; schism with player, fortifier, opportunist, warlord) and neutral otherwise; at launch every starting pair is hostile."""
    def is_override_hostile(a, b):
        pair = {a, b}
        if OMArchetype.CONQUEROR in pair:
            return True
        if pair == {OMArchetype.FORTIFIER, OMArchetype.PLAYER}:
            return True
        if pair == {OMArchetype.FORTIFIER, OMArchetype.OPPORTUNIST}:
            return True
        if pair == {OMArchetype.OPPORTUNIST, OMArchetype.PLAYER}:
            return True
        if OMArchetype.SCHISM in pair and (pair & {OMArchetype.PLAYER, OMArchetype.FORTIFIER, OMArchetype.OPPORTUNIST, OMArchetype.WARLORD}):
            return True
        return False

    assert is_override_hostile(OMArchetype.CONQUEROR, OMArchetype.FORTIFIER) is True
    assert is_override_hostile(OMArchetype.FORTIFIER, OMArchetype.PLAYER) is True
    assert is_override_hostile(OMArchetype.FORTIFIER, OMArchetype.OPPORTUNIST) is True
    assert is_override_hostile(OMArchetype.OPPORTUNIST, OMArchetype.PLAYER) is True
    assert is_override_hostile(OMArchetype.SCHISM, OMArchetype.WARLORD) is True
    assert is_override_hostile(OMArchetype.FORTIFIER, OMArchetype.FORTIFIER) is False
    assert is_override_hostile(OMArchetype.OPPORTUNIST, OMArchetype.OPPORTUNIST) is False

    w = world_factory(n_regions=0, seed=1)
    rc = generate(lib, w)
    assert rc == 1
    for a in range(15):
        for b in range(a + 1, 15):
            assert lib.om_faction_stance(w, a, b) == OMStance.HOSTILE


