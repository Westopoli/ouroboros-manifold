    rc, drift = read_drift(lib, w, 0)
    assert rc == 0
    # Region 1 is booming (80 vs 50) across a BOTH edge, but factions are NEUTRAL: adjacency bonus must not cross
    assert drift.economy_adjacency == pytest.approx(0.0, abs=1e-5)



