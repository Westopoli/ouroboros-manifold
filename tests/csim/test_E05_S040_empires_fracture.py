def test_R_040_01_each_region_rolls_at_chance(lib, world_factory):
    """Given a faction with 4 regions, When the admin revolt roll runs, Then each region rolls at chance 0.001."""
    # 4 regions owned by one faction: excess = max(0, 4 - 4) = 0, chance = 0.001 + 0.0005 * 0^2 = 0.001 (ALG-29).
    w = world_factory(n_regions=4)
    isolate_agents(lib, w, admin=True)

    # Neutral archetype/budget/tech/confidence: no attack/colonize candidates exist (no edges,
    # no other faction), so the faction step consumes no RNG draws before the admin roll.
    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)

    for idx in range(4):
        # Neutral fields: tier HOME, military/economy/population mid-range, tension 0, held since
        # the world began (held_since=-1).
        set_region(lib, w, idx, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
        set_owner(lib, w, idx, 0, held_since=-1)

    assert lib.om_faction_territory(w, 0) == 4

    # One roll draw per owned region, region-index ascending (e2e "Draw order"). 0.5 is well above
    # 0.001 so nothing triggers and no chain-length draw is consumed.
    force_draws(lib, w, [0.5, 0.5, 0.5, 0.5])
    lib.om_world_step(w)

    rolls = read_admin_rolls(lib, w)
    assert len(rolls) == 4
    assert {r.region_idx for r in rolls} == {0, 1, 2, 3}
    for roll in rolls:
        assert roll.faction_id == 0
        assert roll.chance == pytest.approx(0.001, abs=1e-6)
        assert roll.draw == pytest.approx(0.5, abs=1e-6)
        assert roll.triggered == 0


