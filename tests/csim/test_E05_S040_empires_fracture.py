def test_R_040_03_one_integer_draw_l_uniform(lib, world_factory):
    """Given a region's roll succeeds on tick t, When resolved, Then one integer draw L uniform in [3, 8] sets the chain length in ticks and an Admin Separatist event is queued for tick t + 1 with probability 1.0, no condition, and chain length L; L in [3, 4] runs the short chain (Separatist, Military Defection, Breakaway), L in [5, 6] the medium chain (Separatist, Political Crisis, Military Defection, Breakaway), L in [7, 8] the long chain (Separatist, Political Crisis, Popular Support, Military Defection, Breakaway); the Breakaway fires on tick t + L, with the surplus ticks beyond one per step added, one each, to the earliest gaps first."""
    # E-05's own ABI only queues ONE marker entry (OM_EVT_ADMIN_SEPARATIST, due t+1) carrying
    # chain_length = L; expanding L into the named chain steps (Separatist, Political Crisis,
    # Popular Support, Military Defection, Breakaway) at their individual due ticks, including the
    # "surplus ticks to the earliest gaps" placement, is E-04's chain resolution (ALG-36, R-027-05;
    # the header: "E-04 resolves the queue ... until E-04 is built the queue is inert"). This test
    # proves the part E-05 owns: the forced integer draw threads correctly into chain_length across
    # the full [3, 8] range, at the documented tick/probability/condition. The short/medium/long
    # labels are recorded only as comments here; there is no reader to independently verify them at
    # the E-05 ABI (see notes.md ABI gap).
    #
    # Per the header's forced-RNG contract, a forced randint takes value a + floor(u * n); here
    # a = 3, n = 8 - 3 + 1 = 6, so u -> L is: u in [0, 1/6) -> 3, [1/6, 1/3) -> 4, [1/3, 1/2) -> 5,
    # [1/2, 2/3) -> 6, [2/3, 5/6) -> 7, [5/6, 1) -> 8.
    cases = [
        (0.0, 3),   # short chain
        (0.2, 4),   # short chain
        (0.4, 5),   # medium chain
        (0.55, 6),  # medium chain
        (0.7, 7),   # long chain
        (0.9, 8),   # long chain
    ]
    for chain_u, expected_l in cases:
        w = world_factory(n_regions=1)
        isolate_agents(lib, w, admin=True)

        set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
        set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
        set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
        set_owner(lib, w, 0, 0, held_since=-1)
        assert lib.om_faction_territory(w, 0) == 1

        # 1 owned region: chance = 0.001 (excess 0). Roll draw 0.0 < 0.001 succeeds; chain_u sets L.
        force_draws(lib, w, [0.0, chain_u])
        lib.om_world_step(w)

        rolls = read_admin_rolls(lib, w)
        assert len(rolls) == 1
        assert rolls[0].chance == pytest.approx(0.001, abs=1e-6)
        assert rolls[0].triggered == 1

        queue = read_event_queue(lib, w)
        assert len(queue) == 1
        evt = queue[0]
        assert evt.template_id == OMEvent.ADMIN_SEPARATIST
        assert evt.region_idx == 0
        assert evt.due_tick == 2  # t + 1, t = 1 (the first tick)
        assert evt.probability == pytest.approx(1.0, abs=1e-6)
        assert evt.chain_length == expected_l
        # "no condition": cond_kind 0 == OM_COND_NONE per the header's om_condition_kind enum.
        assert evt.cond_kind == 0
        # The admin chain is internal to the region's own faction, not an external attacker.
        assert evt.source_faction == 0


def test_R_040_04_chain_still_completes_nothing_interrupts(lib, world_factory):
    """Given the chain is running, When the owner reinforces the region or its fields improve, Then the chain still completes; nothing interrupts it."""
    # Case A: the owner reinforces the region the pending chain targets.
    w = world_factory(n_regions=1)
    isolate_agents(lib, w, admin=True)

    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=20.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)

    # Tick 1: roll draw 0.0 (< chance 0.001) succeeds; chain_u = 0.4 -> L = 3 + floor(0.4*6) = 5 (medium chain).
    force_draws(lib, w, [0.0, 0.4])
    lib.om_world_step(w)

    queue_before = read_event_queue(lib, w)
    assert len(queue_before) == 1
    evt_before = queue_before[0]
    assert evt_before.template_id == OMEvent.ADMIN_SEPARATIST
    assert evt_before.due_tick == 2
    assert evt_before.chain_length == 5

    military_before = lib.om_region_field(w, 0, OMField.MILITARY)

    # Tick 2: the owner reinforces the same region. The injecting faction skips its own 3d decision
    # this tick, so the only draws this tick are the reinforce variance draw (3f) and this tick's
    # admin roll draw (4.1); 0.9 stays above chance 0.001 so no second chain is queued.
    inject_intent(lib, w, 0, OMAction.REINFORCE, target_idx=0, source_idx=0, commit=10.0, mode=OMMode.SURPRISE)
    force_draws(lib, w, [0.5, 0.9])
    lib.om_world_step(w)

    reinforces = read_reinforces(lib, w)
    assert len(reinforces) == 1
    assert reinforces[0].d_military > 0.0
    assert lib.om_region_field(w, 0, OMField.MILITARY) > military_before

    queue_after = read_event_queue(lib, w)
    assert len(queue_after) == 1
    evt_after = queue_after[0]
    assert evt_after.chain_tag == evt_before.chain_tag
    assert evt_after.template_id == evt_before.template_id
    assert evt_after.region_idx == evt_before.region_idx
    assert evt_after.due_tick == evt_before.due_tick
    assert evt_after.chain_length == evt_before.chain_length
    assert evt_after.probability == pytest.approx(evt_before.probability, abs=1e-6)

    # Case B: the region's fields improve on their own (drift) while the chain is pending.
    w2 = world_factory(n_regions=1)
    isolate_agents(lib, w2, admin=True)
    lib.om_world_set_feature(w2, OMFeature.DRIFT, 1)

    set_faction(lib, w2, 0, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w2, 0, 1.0, 1.0, 1.0)
    # Low military and healthy economy/population/tension give clear positive recruitment growth
    # (ALG-03) each tick: fields visibly "improve".
    set_region(lib, w2, 0, tier=OMTier.HOME, military=10.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w2, 0, 0, held_since=-1)

    force_draws(lib, w2, [0.0, 0.4])
    lib.om_world_step(w2)

    queue2_before = read_event_queue(lib, w2)
    assert len(queue2_before) == 1
    evt2_before = queue2_before[0]

    military_after_t1 = lib.om_region_field(w2, 0, OMField.MILITARY)

    # Tick 2: drift does not draw from the RNG stream (per the header's draw-order contract), so
    # the only draw this tick is the admin roll on the region; 0.9 keeps it below success.
    force_draws(lib, w2, [0.9])
    lib.om_world_step(w2)

    assert lib.om_region_field(w2, 0, OMField.MILITARY) > military_after_t1

    queue2_after = read_event_queue(lib, w2)
    assert len(queue2_after) == 1
    evt2_after = queue2_after[0]
    assert evt2_after.chain_tag == evt2_before.chain_tag
    assert evt2_after.template_id == evt2_before.template_id
    assert evt2_after.region_idx == evt2_before.region_idx
    assert evt2_after.due_tick == evt2_before.due_tick
    assert evt2_after.chain_length == evt2_before.chain_length


@pytest.mark.xfail(strict=True, reason="E-07 owns faction creation; this rule turns real when the E-07 block lands and a Breakaway firing creates a faction")
def test_R_040_05_e_07_creates_new_faction(lib, world_factory):
    """Given the Admin Breakaway event fires, When resolved, Then E-07 creates a new faction holding the region."""
    # E-05's part is done once the Admin Separatist chain is queued (R-040-03);
    # the creation itself is E-07's and E-04 only marks the region. Assert the
    # end-to-end fact anyway, as a strict expected failure: it stays xfail
    # until E-07 exists, and becomes a hard failure if it ever passes for the
    # wrong reason before then. Fixture: one faction with 5 regions, a forced
    # admin roll success, then enough ticks for the shortest chain (L = 3).
    w = world_factory(n_regions=5)
    isolate_agents(lib, w, admin=True)
    lib.om_world_set_feature(w, OMFeature.EVENTS, 1)
    lib.om_world_set_feature(w, OMFeature.LIFECYCLE, 1)
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=0.0, confidence=5.0)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    for idx in range(5):
        set_region(lib, w, idx, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0, faction_id=0)
        set_owner(lib, w, idx, 0, held_since=-1)
    before = lib.om_faction_count(w)
    # rolls: region 0 succeeds (draw 0.0 below chance 0.0015), chain length draw 0.0 -> L = 3; others fail
    force_draws(lib, w, [0.0, 0.0, 0.99, 0.99, 0.99, 0.99])
    lib.om_world_step(w)
    for _ in range(4):
        lib.om_world_step(w)
    assert lib.om_faction_count(w) == before + 1
    assert lib.om_region_owner(w, 0) == before