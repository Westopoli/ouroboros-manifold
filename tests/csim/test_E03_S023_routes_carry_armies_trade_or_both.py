def test_R_023_01_edge_between_two_regions_same(lib, world_factory):
    """Given generation is complete, When edge types are assigned, Then an edge between two regions of the same faction is `both` and every other edge (including any edge touching an empty region) is `border`."""
    w = world_factory(n_regions=0, seed=42)
    rc = generate(lib, w)
    assert rc == 1
    N = lib.om_region_count(w)
    same_faction_checked = 0
    other_edge_checked = 0
    for u in range(N):
        owner_u = lib.om_region_owner(w, u)
        for v in region_neighbors(lib, w, u):
            if u < v:
                owner_v = lib.om_region_owner(w, v)
                out = ctypes.c_int()
                rc_edge = lib.om_region_edge(w, u, v, ctypes.byref(out))
                assert rc_edge == 1
                if owner_u >= 0 and owner_u == owner_v:
                    assert out.value == OMEdge.BOTH, f"same-faction edge ({u}, {v}) expected BOTH, got {out.value}"
                    same_faction_checked += 1
                else:
                    assert out.value == OMEdge.BORDER, f"cross-faction or empty edge ({u}, {v}) expected BORDER, got {out.value}"
                    other_edge_checked += 1
    assert same_faction_checked >= 15
    assert other_edge_checked >= 15


def test_R_023_02_it_returns_neighbors_whose_edge(lib, world_factory):
    """Given a query for neighbors of type `border`, When evaluated, Then it returns neighbors whose edge is `border` or `both`; a query for `trade` returns `trade` or `both`; a query with no type returns all."""
    w = world_factory(n_regions=4)
    set_edge(lib, w, 0, 1, OMEdge.BORDER)
    set_edge(lib, w, 0, 2, OMEdge.TRADE)
    set_edge(lib, w, 0, 3, OMEdge.BOTH)
    all_nbrs = region_neighbors(lib, w, 0)
    assert set(all_nbrs) == {1, 2, 3}

    border_nbrs = []
    trade_nbrs = []
    for nbr in all_nbrs:
        out = ctypes.c_int()
        lib.om_region_edge(w, 0, nbr, ctypes.byref(out))
        if out.value in (OMEdge.BORDER, OMEdge.BOTH):
            border_nbrs.append(nbr)
        if out.value in (OMEdge.TRADE, OMEdge.BOTH):
            trade_nbrs.append(nbr)
    assert set(border_nbrs) == {1, 3}
    assert set(trade_nbrs) == {2, 3}


def test_R_023_03_it_names_edge_type_drift(lib, world_factory):
    """Given every "nearby" or "adjacent" read in the sim (drift adjacency, border friction, faction targeting, event propagation, character selector), When it runs, Then it names an edge type; drift adjacency reads `trade`, border friction reads `border`, faction targeting reads all."""
    w = world_factory(n_regions=3)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0)
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=80.0, tension=0.0, population=50.0)
    set_region(lib, w, 2, tier=OMTier.HOME, military=50.0, economy=80.0, tension=0.0, population=50.0)
    set_owner(lib, w, 0, 0, held_since=-1)
    set_owner(lib, w, 1, 0, held_since=-1)
    set_owner(lib, w, 2, 0, held_since=-1)

    set_edge(lib, w, 0, 1, OMEdge.BORDER)
    set_edge(lib, w, 0, 2, OMEdge.TRADE)

    lib.om_world_step(w)
    rc, drift = read_drift(lib, w, 0)
    assert rc == 0
    assert drift.economy_adjacency == pytest.approx(0.04, abs=1e-5)

    w2 = world_factory(n_regions=3)
    isolate_agents(lib, w2, friction=True)
    set_faction(lib, w2, 0, OMArchetype.DEFAULT, budget=0.0, tech=0.0)
    set_faction(lib, w2, 1, OMArchetype.DEFAULT, budget=0.0, tech=0.0)
    set_stance(lib, w2, 0, 1, OMStance.HOSTILE)
    set_region(lib, w2, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=10.0, population=50.0)
    set_region(lib, w2, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=10.0, population=50.0)
    set_owner(lib, w2, 0, 0, held_since=-1)
    set_owner(lib, w2, 1, 1, held_since=-1)
    set_edge(lib, w2, 0, 1, OMEdge.TRADE)
    lib.om_world_step(w2)
    friction_records = read_friction(lib, w2)
    assert not any(fr.region_idx == 0 and fr.hostile_neighbors > 0 for fr in friction_records)


def test_R_023_04_both_directions_report_same_type(lib, world_factory):
    """Given an edge set to a type, When read from either endpoint, Then both directions report the same type."""
    w = world_factory(n_regions=0, seed=42)
    rc = generate(lib, w)
    assert rc == 1
    N = lib.om_region_count(w)
    assert N >= 60
    edges_checked = 0
    for u in range(N):
        for v in region_neighbors(lib, w, u):
            out_uv = ctypes.c_int()
            out_vu = ctypes.c_int()
            rc_uv = lib.om_region_edge(w, u, v, ctypes.byref(out_uv))
            rc_vu = lib.om_region_edge(w, v, u, ctypes.byref(out_vu))
            assert rc_uv == 1 and rc_vu == 1
            assert out_uv.value == out_vu.value
            edges_checked += 1
    assert edges_checked >= 15

