import ctypes

class OMTransitionKind:
    THRESHOLD = 0
    TIMER = 1
    HOOK = 2
    RETREAT = 3
    ESCALATE = 4


def test_R_121_01_condition_compared_against_its_noised(lib, world_factory):
    """Given a transition with a threshold condition (force HP fraction, unit count, elapsed time, timer expired, bus flag, player force in zone, enemy in range), When evaluated, Then the condition is compared against its noised value: noise is one uniform draw in ±noise_pct (default ±0.15 for thresholds, ±0.20 for timers) made at mission start and held for the mission."""
    w = world_factory(n_regions=1)

    # Threshold noise is within [-0.15, 0.15]
    t_noise = lib.om_macro_get_threshold_noise(w, 0)
    assert -0.15 <= ctypes.c_double(t_noise).value <= 0.15

    # Timer noise is within [-0.20, 0.20]
    timer_noise = lib.om_macro_get_timer_noise(w, 0)
    assert -0.20 <= ctypes.c_double(timer_noise).value <= 0.20

    # A hard 0.0 stub is in-range and "held" trivially; a real uniform draw
    # in +-0.15/+-0.20 is (with overwhelming probability) nonzero.
    assert ctypes.c_double(t_noise).value != 0.0
    assert ctypes.c_double(timer_noise).value != 0.0

    # Noise is held for the mission (drawn once at start)
    lib.om_macro_tick(w, 40)
    assert lib.om_macro_get_threshold_noise(w, 0) == t_noise
    assert lib.om_macro_get_timer_noise(w, 0) == timer_noise


def test_R_121_02_it_fires_regardless_tactical_state(lib, world_factory):
    """Given a timer transition with duration D, When elapsed × (1 + noise) ≥ D, Then it fires regardless of tactical state."""
    w = world_factory(n_regions=1)
    duration = 100
    noise = ctypes.c_double(0.10)  # +10% noise -> 1 + noise = 1.10

    # At elapsed = 90: 90 * 1.10 = 99 < 100 -> does not fire
    fired_90 = lib.om_macro_eval_timer_transition(duration, 90, noise)
    assert fired_90 == 0

    # At elapsed = 91: 91 * 1.10 = 100.1 >= 100 -> fires
    fired_91 = lib.om_macro_eval_timer_transition(duration, 91, noise)
    assert fired_91 == 1


def test_R_121_03_threshold_wins_except_that_retreat(lib, world_factory):
    """Given a threshold and a timer both firing on the same evaluation, When resolved, Then the threshold wins, except that a retreat transition always wins over an escalation."""
    # 1. Threshold vs Timer (normal escalation): Threshold wins
