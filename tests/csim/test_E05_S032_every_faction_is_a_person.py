def test_R_032_01_it_has_id_archetype_budget(lib, world_factory):
    """Given any faction, When it is created, Then it has an id, an archetype, a budget starting at 0, a growth rate of 0.025, a tech level, a stance toward every other faction, and an attack confidence drawn once, uniform in its archetype's range (conqueror [2, 6], fortifier [4, 10], player [3, 8], breakaway [2, 5], others [4, 8])."""
    archetype_ranges = [
        (OMArchetype.CONQUEROR, 2.0, 6.0),
        (OMArchetype.FORTIFIER, 4.0, 10.0),
        (OMArchetype.PLAYER, 3.0, 8.0),
        (OMArchetype.BREAKAWAY, 2.0, 5.0),
        (OMArchetype.WARLORD, 4.0, 8.0),
        (OMArchetype.OPPORTUNIST, 4.0, 8.0),
        (OMArchetype.SCHISM, 4.0, 8.0),
        (OMArchetype.DEFAULT, 4.0, 8.0),
    ]

    for fid, (arch, lo, hi) in enumerate(archetype_ranges):
        w = world_factory(n_regions=2)
        isolate_agents(lib, w)

        other_fid = (fid + 1) % 64
        # Neutral unstated values: tier HOME, held_since -1, tech multipliers 1.0
        set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=48.0, tension=0.0, population=50.0)
        set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0)
        set_owner(lib, w, 0, fid, held_since=-1)  # neutral held_since -1 (held since world began)
        set_owner(lib, w, 1, other_fid, held_since=-1)
        set_tech_multipliers(lib, w, fid, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0

        # Create another faction to verify pairwise stance toward other factions
        set_faction(lib, w, other_fid, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)

        # confidence < 0 triggers single uniform draw in archetype's range (R-032-01)
        set_faction(lib, w, fid, arch, budget=0.0, tech=0.0, confidence=-1.0)

        # Faction has valid id and archetype
        assert lib.om_faction_archetype(w, fid) == arch

        # Budget starting at 0
        assert lib.om_faction_budget(w, fid) == pytest.approx(0.0, abs=1e-6)

        # Tech level starting at 0
        assert lib.om_faction_tech(w, fid) == pytest.approx(0.0, abs=1e-6)

        # Stance toward every other faction starts hostile
        assert lib.om_faction_stance(w, fid, other_fid) == OMStance.HOSTILE

        # Attack confidence drawn once uniform in its archetype's range (assert bounds, not point)
        conf = lib.om_faction_confidence(w, fid)
        assert lo <= conf <= hi

        # Growth rate of 0.025: step 1 tick; net economy = 48 - 8 = 40; delta budget = 40 * 0.025 = 1.0
        lib.om_world_step(w)
        assert lib.om_faction_budget(w, fid) == pytest.approx(1.0, abs=1e-6)


def test_R_032_02_it_never_changes(lib, world_factory):
    """Given a faction's attack confidence, When any number of ticks pass, Then it never changes."""
    w = world_factory(n_regions=1)
    isolate_agents(lib, w)

    # Neutral values for unstated fields: stances hostile, tech multipliers 1.0, held_since -1, tier HOME
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0)
    set_owner(lib, w, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0

    # Pinned attack confidence of 4.5
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=100.0, confidence=4.5)

    initial_confidence = lib.om_faction_confidence(w, 0)
    assert initial_confidence == pytest.approx(4.5, abs=1e-6)

    # When any number of ticks pass, attack confidence never changes
    for _ in range(10):
        lib.om_world_step(w)
        assert lib.om_faction_confidence(w, 0) == pytest.approx(initial_confidence, abs=1e-6)


def test_R_032_03_it_uses_attack_weight_0(lib, world_factory):
    """Given the player civilization, When it decides, Then it uses attack weight 0.3, expand weight 0.5, defend weight 1.5, and attractiveness weights weakness 0.60, value 0.25, position 0.15."""
    w = world_factory(n_regions=4)
    isolate_agents(lib, w)

    # Faction 0: Player civilization (w_attack 0.3, w_expand 0.5, w_defend 1.5)
    set_faction(lib, w, 0, OMArchetype.PLAYER, budget=100.0, confidence=5.0)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0

    # Faction 1: Enemy faction
    set_faction(lib, w, 1, OMArchetype.CONQUEROR, budget=0.0, confidence=5.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0

    # Stances: hostile both ways
    set_stance(lib, w, 0, 1, OMStance.HOSTILE, both_ways=True)

    # Region 0: owned by Player (home tier)
    # Neutral unstated fields: tension 0, population 50, held_since -1
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0)
    set_owner(lib, w, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)

    # Region 1: enemy target owned by Faction 1 (military 30, economy 60, population 50)
    set_region(lib, w, 1, tier=OMTier.HOME, military=30.0, economy=60.0, tension=0.0, population=50.0)
    set_owner(lib, w, 1, 1, held_since=-1)  # neutral held_since -1 (entrenchment 2.0)

    # Region 2: non-owned neighbor of Region 1 (economy 40, population 50)
    set_region(lib, w, 2, tier=OMTier.HOME, military=40.0, economy=40.0, tension=0.0, population=50.0)
    set_owner(lib, w, 2, 1, held_since=-1)  # owned by Faction 1

    # Region 3: empty neighbor of Region 0 and Region 1 (unowned)
    set_region(lib, w, 3, tier=OMTier.EMPTY, military=0.0, economy=0.0, tension=0.0, population=0.0)
    set_owner(lib, w, 3, -1, held_since=-1)  # unowned

    # Edges: Region 0 borders 1 and 3; Region 1 borders 0, 2, 3
    set_edge(lib, w, 0, 1, OMEdge.BOTH)
    set_edge(lib, w, 0, 3, OMEdge.BOTH)
    set_edge(lib, w, 1, 2, OMEdge.BOTH)
    set_edge(lib, w, 1, 3, OMEdge.BOTH)

    # Read candidates before the step: om_faction_candidates reads live
    # region state on every call, not a step-3d snapshot (DECISIONS.md R8a).
    # Step 3d computes this same faction's decision from this same
    # pre-resolution region state; reading here (rather than after the step)
    # avoids the colonize decision's own 3f resolution -- taking region 3 --
    # changing what a *later* read of the candidate list would see for
    # region 1's neighbor set.
    # Verify attractiveness weights: weakness 0.60, value 0.25, position 0.15
    candidates = read_candidates(lib, w, 0)
    cand_1 = next(c for c in candidates if c.kind == OMCandKind.ATTACK and c.region_idx == 1)

    # weakness = 1.0 - 30/100 = 0.70
    assert cand_1.weakness == pytest.approx(0.70, abs=1e-6)
    # value = ((60 * 0.60 + 50 * 0.40) / 100) * 2 = 1.12
    assert cand_1.value == pytest.approx(1.12, abs=1e-6)
    # position = mean( (40 * 0.60 + 50 * 0.40)/100, 0.15 ) = mean(0.44, 0.15) = 0.295
    assert cand_1.position == pytest.approx(0.295, abs=1e-6)
    # score = 0.60 * 0.70 + 0.25 * 1.12 + 0.15 * 0.295 = 0.74425
    assert cand_1.attractiveness == pytest.approx(0.74425, abs=1e-6)

    # Empty region 3 colonize candidate: ALG-11 applies the weakness factor to every candidate,
    # 1 - 0/100 = 1.0 for an empty region; value 0 (unowned); position 0.56:
    # 0.60 * 1.0 + 0.25 * 0 + 0.15 * 0.56 = 0.684
    cand_3 = next(c for c in candidates if c.kind == OMCandKind.COLONIZE and c.region_idx == 3)
    assert cand_3.attractiveness == pytest.approx(0.684, abs=1e-6)

    # Pin telegraph mode selection draw for Player's attack decision (pref = 0.6, draw 0.1 < 0.6)
    force_draws(lib, w, [0.1])

    lib.om_world_step(w)

    # Verify decision weights: attack weight 0.3, expand weight 0.5
    # potential commit = 70.0; net = 70 - 30 * 0.55 * 2.0 = 37.0
    # attack_score = (37.0 / 40.0) * 0.3 = 0.2775
    # colonize_score = 0.684 * 0.5 = 0.342
    decisions = read_decisions(lib, w)
    player_dec = next(d for d in decisions if d.faction_id == 0)
    assert player_dec.attack_score == pytest.approx(0.2775, abs=1e-6)
    assert player_dec.colonize_score == pytest.approx(0.342, abs=1e-6)


def test_R_032_04_it_hostile_toward_every_other(lib, world_factory):
    """Given a starting faction, When stances are set, Then it is hostile toward every other faction."""
    w = world_factory(n_regions=4)
    isolate_agents(lib, w)

    factions = [
        (0, OMArchetype.PLAYER),
        (1, OMArchetype.CONQUEROR),
        (2, OMArchetype.FORTIFIER),
        (3, OMArchetype.OPPORTUNIST),
    ]

    # Neutral values for unstated fields: stances hostile, tech multipliers 1.0, held_since -1, tier HOME
    for r, (fid, arch) in enumerate(factions):
        set_region(lib, w, r, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0)
        set_owner(lib, w, r, fid, held_since=-1)  # neutral held_since -1 (held since world began)
        set_tech_multipliers(lib, w, fid, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0
        set_faction(lib, w, fid, arch, budget=0.0, tech=0.0, confidence=5.0)

    # When stances are set, it is hostile toward every other faction (cooperative toward itself)
    for fid_a, _ in factions:
        for fid_b, _ in factions:
            if fid_a == fid_b:
                assert lib.om_faction_stance(w, fid_a, fid_b) == OMStance.COOPERATIVE
            else:
                assert lib.om_faction_stance(w, fid_a, fid_b) == OMStance.HOSTILE
