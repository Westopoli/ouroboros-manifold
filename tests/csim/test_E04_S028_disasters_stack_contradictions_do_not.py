def test_R_028_01_each_delta_computed_against_tick(lib, world_factory):
    """Given two queued events due the same tick in the same region, both passing conditions and probability, When they resolve, Then each delta is computed against the tick-start fields, the deltas sum, and the sum applies once with floors and ceilings."""
    # 2 regions in one step:
    # Region 0 exercises military floor (0.0), economy floor (8.0), and tension ceiling (100.0).
    # Region 1 exercises tension floor (12.0).
    w = world_factory(n_regions=2)
    isolate_events(lib, w)
    load_launch_events(lib, w)
    zero_all_noise(lib, w)

    # Neutral unstated values: tier HOME, unowned (faction_id=-1, held_since=-1), tech multipliers 1.0
    # Region 0: military 2.0, economy 9.0, tension 98.0, population 50.0
    set_region(lib, w, 0, tier=OMTier.HOME, military=2.0, economy=9.0, tension=98.0, population=50.0)
    # Region 1: military 50.0, economy 50.0, tension 14.0, population 50.0
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=14.0, population=50.0)

    # Region 0: Population Crisis (m -2, e -2, t +2, p 0) and War Weariness (m -2, e -1, t +3, p 0)
    # Neither template has chain spawns or exclusion tags.
    tid_pop = template_id(lib, w, "Population Crisis")
    tid_war = template_id(lib, w, "War Weariness")
    queue_external(lib, w, 0, tid_pop, due_tick=1, probability=1.0)
    queue_external(lib, w, 0, tid_war, due_tick=1, probability=1.0)

    # Region 1: Cultural Renaissance (m 0, e +1, t -3, p +1) and Famine Relief (m 0, e +3, t -3, p +2)
    # Neither template has chain spawns or exclusion tags.
    tid_cult = template_id(lib, w, "Cultural Renaissance")
    tid_relief = template_id(lib, w, "Famine Relief")
    queue_external(lib, w, 1, tid_cult, due_tick=1, probability=1.0)
    queue_external(lib, w, 1, tid_relief, due_tick=1, probability=1.0)

    # Force 4 probability draws (all 0.1 <= 1.0, passing probability)
    force_draws(lib, w, [0.1, 0.1, 0.1, 0.1])
    lib.om_world_step(w)

    events = read_events(lib, w)
    assert len(events) == 4

    # Region 0: verify individual event deltas before sum/clamp
    ev_r0 = [e for e in events if e.region_idx == 0]
    assert len(ev_r0) == 2
    pop_ev = [e for e in ev_r0 if e.template_id == tid_pop][0]
    war_ev = [e for e in ev_r0 if e.template_id == tid_war][0]
    assert pop_ev.delta[OMField.MILITARY] == pytest.approx(-2.0, abs=1e-6)
    assert pop_ev.delta[OMField.ECONOMY] == pytest.approx(-2.0, abs=1e-6)
    assert pop_ev.delta[OMField.TENSION] == pytest.approx(2.0, abs=1e-6)
    assert pop_ev.delta[OMField.POPULATION] == pytest.approx(0.0, abs=1e-6)
    assert war_ev.delta[OMField.MILITARY] == pytest.approx(-2.0, abs=1e-6)
    assert war_ev.delta[OMField.ECONOMY] == pytest.approx(-1.0, abs=1e-6)
    assert war_ev.delta[OMField.TENSION] == pytest.approx(3.0, abs=1e-6)
    assert war_ev.delta[OMField.POPULATION] == pytest.approx(0.0, abs=1e-6)

    # Region 0: summed deltas apply once with floors (mil floor 0, eco floor 8) and ceiling (tension 100)
    # military: 2.0 - 4.0 = -2.0 -> clamped to 0.0 (net delta -2.0)
    # economy: 9.0 - 3.0 = 6.0 -> clamped to 8.0 (net delta -1.0)
    # tension: 98.0 + 5.0 = 103.0 -> clamped to 100.0 (net delta +2.0)
    # population: 50.0 + 0.0 = 50.0 (net delta 0.0)
    rc0, deltas_r0 = read_event_delta(lib, w, 0)
    assert rc0 == 0
    assert deltas_r0[OMField.MILITARY] == pytest.approx(-2.0, abs=1e-6)
    assert deltas_r0[OMField.ECONOMY] == pytest.approx(-1.0, abs=1e-6)
    assert deltas_r0[OMField.TENSION] == pytest.approx(2.0, abs=1e-6)
    assert deltas_r0[OMField.POPULATION] == pytest.approx(0.0, abs=1e-6)

    assert lib.om_region_field(w, 0, OMField.MILITARY) == pytest.approx(0.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.ECONOMY) == pytest.approx(8.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.TENSION) == pytest.approx(100.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.POPULATION) == pytest.approx(50.0, abs=1e-6)

    # Region 1: summed deltas apply once with tension floor 12.0
    # deltas sum: m 0.0, e +4.0, t -6.0, p +3.0
    # tension: 14.0 - 6.0 = 8.0 -> clamped to tension floor 12.0 (net delta -2.0)
    rc1, deltas_r1 = read_event_delta(lib, w, 1)
    assert rc1 == 0
    assert deltas_r1[OMField.MILITARY] == pytest.approx(0.0, abs=1e-6)
    assert deltas_r1[OMField.ECONOMY] == pytest.approx(4.0, abs=1e-6)
    assert deltas_r1[OMField.TENSION] == pytest.approx(-2.0, abs=1e-6)
    assert deltas_r1[OMField.POPULATION] == pytest.approx(3.0, abs=1e-6)

    assert lib.om_region_field(w, 1, OMField.MILITARY) == pytest.approx(50.0, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.ECONOMY) == pytest.approx(54.0, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.TENSION) == pytest.approx(12.0, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.POPULATION) == pytest.approx(53.0, abs=1e-6)


def test_R_028_02_entrenched_kept_crushed_re_queued(lib, world_factory):
    """Given "Revolt Crushed" (p 0.45) and "Revolt Entrenched" (p 0.55) both due the same tick in the same region, When resolved, Then Entrenched is kept and Crushed is re-queued for tick + 1 or tick + 2 (one draw)."""
    # Branch 1: re-queue draw 0.2 (< 0.5) yields tick + 1 (delay = 1)
    w1 = world_factory(n_regions=1)
    isolate_events(lib, w1)
    load_launch_events(lib, w1)
    zero_all_noise(lib, w1)

    # Neutral unstated values: tier HOME, unowned (faction_id=-1, held_since=-1), tech multipliers 1.0
    set_region(lib, w1, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0)

    tid_crushed = template_id(lib, w1, "Revolt Crushed")
    tid_entrenched = template_id(lib, w1, "Revolt Entrenched")

    queue_external(lib, w1, 0, tid_crushed, due_tick=1, probability=0.45)
    queue_external(lib, w1, 0, tid_entrenched, due_tick=1, probability=0.55)

    # Draw 0.2: delay = 1 + floor(0.2 * 2) = 1 -> new due = 1 + 1 = 2
    # Draw 0.1: Entrenched probability roll passes (0.1 <= 0.55)
    force_draws(lib, w1, [0.2, 0.1])
    lib.om_world_step(w1)

    # Entrenched is kept and fires
    events1 = read_events(lib, w1)
    assert len(events1) == 1
    assert events1[0].template_id == tid_entrenched
    assert events1[0].creates_faction == 1

    # Crushed is recorded in delayed log with new_due == tick + 1 == 2
    delayed1 = read_delayed(lib, w1)
    assert len(delayed1) == 1
    assert delayed1[0].template_id == tid_crushed
    assert delayed1[0].kept_template_id == tid_entrenched
    assert delayed1[0].exclusion_tag == OMExcl.REVOLT_OUTCOME
    assert delayed1[0].new_due == 2

    # Crushed is re-queued in pending queue with due_tick == 2 and p == 0.45
    q1 = read_event_queue(lib, w1)
    assert len(q1) == 1
    assert q1[0].template_id == tid_crushed
    assert q1[0].due_tick == 2
    assert q1[0].probability == pytest.approx(0.45, abs=1e-6)

    # Branch 2: re-queue draw 0.8 (>= 0.5) yields tick + 2 (delay = 2)
    w2 = world_factory(n_regions=1)
    isolate_events(lib, w2)
    load_launch_events(lib, w2)
    zero_all_noise(lib, w2)

    set_region(lib, w2, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0)

    queue_external(lib, w2, 0, tid_crushed, due_tick=1, probability=0.45)
    queue_external(lib, w2, 0, tid_entrenched, due_tick=1, probability=0.55)

    # Draw 0.8: delay = 1 + floor(0.8 * 2) = 2 -> new due = 1 + 2 = 3
    # Draw 0.1: Entrenched probability roll passes (0.1 <= 0.55)
    force_draws(lib, w2, [0.8, 0.1])
    lib.om_world_step(w2)

    events2 = read_events(lib, w2)
    assert len(events2) == 1
    assert events2[0].template_id == tid_entrenched

    delayed2 = read_delayed(lib, w2)
    assert len(delayed2) == 1
    assert delayed2[0].template_id == tid_crushed
    assert delayed2[0].kept_template_id == tid_entrenched
    assert delayed2[0].exclusion_tag == OMExcl.REVOLT_OUTCOME
    assert delayed2[0].new_due == 3

    q2 = read_event_queue(lib, w2)
    assert len(q2) == 1
    assert q2[0].template_id == tid_crushed
    assert q2[0].due_tick == 3
    assert q2[0].probability == pytest.approx(0.45, abs=1e-6)


def test_R_028_03_one_uniform_draw_decides_below(lib, world_factory):
    """Given two mutually exclusive events with equal probability, When resolved, Then one uniform draw decides: below 0.5 the earlier-queued one is kept, otherwise the later one; the other is re-queued as in R-028-02."""
    tid_name_earlier = "Revolt Crushed"
    tid_name_later = "Revolt Entrenched"

    # Three-fixture pattern for strict inequality at boundary (draw < 0.5 vs >= 0.5):
    # 1. Below boundary: draw = 0.49 (< 0.5) -> earlier-queued kept
    w_below = world_factory(n_regions=1)
    isolate_events(lib, w_below)
    load_launch_events(lib, w_below)
    zero_all_noise(lib, w_below)
    set_region(lib, w_below, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0)

    tid_earlier = template_id(lib, w_below, tid_name_earlier)
    tid_later = template_id(lib, w_below, tid_name_later)

    queue_external(lib, w_below, 0, tid_earlier, due_tick=1, probability=0.50)
    queue_external(lib, w_below, 0, tid_later, due_tick=1, probability=0.50)

    # Draw 0.49: tie-break (< 0.5) keeps earlier
    # Draw 0.2: delay draw for loser (delay = 1, new due = 2)
    # Draw 0.1: winner probability roll passes (0.1 <= 0.50)
    force_draws(lib, w_below, [0.49, 0.2, 0.1])
    lib.om_world_step(w_below)

    ev_below = read_events(lib, w_below)
    assert len(ev_below) == 1
    assert ev_below[0].template_id == tid_earlier

    del_below = read_delayed(lib, w_below)
    assert len(del_below) == 1
    assert del_below[0].kept_template_id == tid_earlier
    assert del_below[0].template_id == tid_later
    assert del_below[0].new_due == 2

    q_below = read_event_queue(lib, w_below)
    assert len(q_below) == 1
    assert q_below[0].template_id == tid_later
    assert q_below[0].due_tick == 2

    # 2. At boundary: draw = 0.50 (not < 0.5) -> later-queued kept
    w_at = world_factory(n_regions=1)
    isolate_events(lib, w_at)
    load_launch_events(lib, w_at)
    zero_all_noise(lib, w_at)
    set_region(lib, w_at, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0)

    queue_external(lib, w_at, 0, tid_earlier, due_tick=1, probability=0.50)
    queue_external(lib, w_at, 0, tid_later, due_tick=1, probability=0.50)

    force_draws(lib, w_at, [0.50, 0.2, 0.1])
    lib.om_world_step(w_at)

    ev_at = read_events(lib, w_at)
    assert len(ev_at) == 1
    assert ev_at[0].template_id == tid_later

    del_at = read_delayed(lib, w_at)
    assert len(del_at) == 1
    assert del_at[0].kept_template_id == tid_later
    assert del_at[0].template_id == tid_earlier
    assert del_at[0].new_due == 2

    q_at = read_event_queue(lib, w_at)
    assert len(q_at) == 1
    assert q_at[0].template_id == tid_earlier
    assert q_at[0].due_tick == 2

    # 3. Above boundary: draw = 0.51 (> 0.5) -> later-queued kept
    w_above = world_factory(n_regions=1)
    isolate_events(lib, w_above)
    load_launch_events(lib, w_above)
    zero_all_noise(lib, w_above)
    set_region(lib, w_above, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0)

    queue_external(lib, w_above, 0, tid_earlier, due_tick=1, probability=0.50)
    queue_external(lib, w_above, 0, tid_later, due_tick=1, probability=0.50)

    force_draws(lib, w_above, [0.51, 0.2, 0.1])
    lib.om_world_step(w_above)

    ev_above = read_events(lib, w_above)
    assert len(ev_above) == 1
    assert ev_above[0].template_id == tid_later

    del_above = read_delayed(lib, w_above)
    assert len(del_above) == 1
    assert del_above[0].kept_template_id == tid_later
    assert del_above[0].template_id == tid_earlier
    assert del_above[0].new_due == 2

    q_above = read_event_queue(lib, w_above)
    assert len(q_above) == 1
    assert q_above[0].template_id == tid_earlier
    assert q_above[0].due_tick == 2


def test_R_028_04_both_fire_neither_delayed(lib, world_factory):
    """Given two same-tick events with no shared exclusion tag, When resolved, Then both fire and neither is delayed."""
    # 2 regions in one step:
    # Region 0: distinct non-zero exclusion tags (MILITARY_RELIEF vs REVOLT_OUTCOME)
    # Region 1: no exclusion tags (OMExcl.NONE on both)
    w = world_factory(n_regions=2)
    isolate_events(lib, w)
    load_launch_events(lib, w)
    zero_all_noise(lib, w)

    # Neutral unstated values: tier HOME, unowned (faction_id=-1, held_since=-1), tech multipliers 1.0
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0)
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0)

    # Region 0: Emergency Levy (tag: MILITARY_RELIEF) and Revolt Crushed (tag: REVOLT_OUTCOME)
    tid_levy = template_id(lib, w, "Emergency Levy")
    tid_crushed = template_id(lib, w, "Revolt Crushed")
    queue_external(lib, w, 0, tid_levy, due_tick=1, probability=1.0)
    queue_external(lib, w, 0, tid_crushed, due_tick=1, probability=1.0)

    # Region 1: Population Crisis (tag: NONE) and War Weariness (tag: NONE)
    tid_pop = template_id(lib, w, "Population Crisis")
    tid_war = template_id(lib, w, "War Weariness")
    queue_external(lib, w, 1, tid_pop, due_tick=1, probability=1.0)
    queue_external(lib, w, 1, tid_war, due_tick=1, probability=1.0)

    # 4 probability draws (all 0.1 <= 1.0, passing probability)
    force_draws(lib, w, [0.1, 0.1, 0.1, 0.1])
    lib.om_world_step(w)

    # Neither event is delayed in either region
    delayed = read_delayed(lib, w)
    assert len(delayed) == 0

    # Both events fire in both regions
    events = read_events(lib, w)
    assert len(events) == 4

    ev_r0 = {e.template_id for e in events if e.region_idx == 0}
    assert ev_r0 == {tid_levy, tid_crushed}

    ev_r1 = {e.template_id for e in events if e.region_idx == 1}
    assert ev_r1 == {tid_pop, tid_war}

    # Pending queue is empty
    queue = read_event_queue(lib, w)
    assert len(queue) == 0


def test_R_028_05_they_processed_in_sorted_tag(lib, world_factory):
    """Given exclusion tags are evaluated, When multiple tags are present, Then they are processed in sorted tag order, and an event removed by one tag is not considered for later tags."""
    w = world_factory(n_regions=1)
    isolate_events(lib, w)
    load_launch_events(lib, w)
    zero_all_noise(lib, w)

    # Neutral unstated values: tier HOME, unowned (faction_id=-1, held_since=-1), tech multipliers 1.0
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0)

    # Multiple exclusion tags present:
    # Tag 1: OMExcl.MILITARY_RELIEF (Emergency Levy)
    # Tag 3: OMExcl.REVOLT_OUTCOME (Revolt Entrenched, Revolt Crushed)
    tid_levy = template_id(lib, w, "Emergency Levy")
    tid_entrenched = template_id(lib, w, "Revolt Entrenched")
    tid_crushed = template_id(lib, w, "Revolt Crushed")

    # Queue two Tag 1 events: Levy A (p 0.8) and Levy B (p 0.4) -> Levy A wins, Levy B delayed
    queue_external(lib, w, 0, tid_levy, due_tick=1, probability=0.80)
    queue_external(lib, w, 0, tid_levy, due_tick=1, probability=0.40)

    # Queue two Tag 3 events: Entrenched (p 0.55) and Crushed (p 0.45) -> Entrenched wins, Crushed delayed
    queue_external(lib, w, 0, tid_entrenched, due_tick=1, probability=0.55)
    queue_external(lib, w, 0, tid_crushed, due_tick=1, probability=0.45)

    # Sorted tag order dictates Tag 1 is evaluated before Tag 3:
    # 1. Loser delay draw for Tag 1 loser (Levy B): draw 0.2 -> delay = 1 (new due = 1 + 1 = 2)
    # 2. Loser delay draw for Tag 3 loser (Crushed): draw 0.8 -> delay = 2 (new due = 1 + 2 = 3)
    # 3. Probability draw for Tag 1 winner (Levy A): draw 0.1 <= 0.80 (fires)
    # 4. Probability draw for Tag 3 winner (Entrenched): draw 0.1 <= 0.55 (fires)
    force_draws(lib, w, [0.2, 0.8, 0.1, 0.1])
    lib.om_world_step(w)

    # Delayed records must appear in sorted tag order (Tag 1 before Tag 3):
    delayed = read_delayed(lib, w)
    assert len(delayed) == 2

    # First delayed record is for Tag 1 (MILITARY_RELIEF)
    assert delayed[0].exclusion_tag == OMExcl.MILITARY_RELIEF
    assert delayed[0].template_id == tid_levy
    assert delayed[0].kept_template_id == tid_levy
    assert delayed[0].new_due == 2

    # Second delayed record is for Tag 3 (REVOLT_OUTCOME)
    assert delayed[1].exclusion_tag == OMExcl.REVOLT_OUTCOME
    assert delayed[1].template_id == tid_crushed
    assert delayed[1].kept_template_id == tid_entrenched
    assert delayed[1].new_due == 3

    # Fired events are the winners of each tag evaluation
    events = read_events(lib, w)
    assert len(events) == 2
    fired_tids = [e.template_id for e in events]
    assert fired_tids.count(tid_levy) == 1
    assert fired_tids.count(tid_entrenched) == 1

    # Both losers remain in the pending queue with their respective new due ticks
    queue = read_event_queue(lib, w)
    assert len(queue) == 2
    q_due_by_tid = {q.template_id: q.due_tick for q in queue}
    assert q_due_by_tid[tid_levy] == 2
    assert q_due_by_tid[tid_crushed] == 3
