def test_R_044_01_each_faction_rolls_once_per(lib, world_factory):
    """Given a cooperative pair, When betrayal is checked, Then each faction rolls once per tick as the potential betrayer, in pair order, and at most one betrayal happens per pair per tick."""
    w = world_factory(n_regions=4)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.DIPLOMACY, 1)

    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=50.0, tech=0.0)
    set_faction(lib, w, 1, OMArchetype.WARLORD, budget=50.0, tech=0.0)
    set_stance(lib, w, 0, 1, OMStance.COOPERATIVE)

    set_region(lib, w, 0, tier=OMTier.HOME, military=60.0, economy=50.0, tension=20.0, population=50.0)
    set_region(lib, w, 1, tier=OMTier.HOME, military=60.0, economy=50.0, tension=20.0, population=50.0)
    set_region(lib, w, 2, tier=OMTier.HOME, military=20.0, economy=50.0, tension=20.0, population=50.0)
    set_region(lib, w, 3, tier=OMTier.HOME, military=20.0, economy=50.0, tension=20.0, population=50.0)
    set_owner(lib, w, 0, 0)
    set_owner(lib, w, 1, 0)
    set_owner(lib, w, 2, 1)
    set_owner(lib, w, 3, 1)
    set_edge(lib, w, 1, 2, OMEdge.BORDER)

    # Case A: Faction 0 betrays on its roll. Only 1 draw is consumed for the pair; faction 1 does not also betray.
    # Force draw 0 to be 0.001 (below p0) and draw 1 to be 0.001 (which would also trigger if evaluated).
    force_draws(lib, w, [0.001, 0.001])
    lib.om_world_step(w)

    attacks = read_attacks(lib, w)
    assert len(attacks) == 1, "at most one betrayal happens per pair per tick"
    assert attacks[0].attacker == 0
    assert attacks[0].defender == 1
    assert lib.om_faction_stance(w, 0, 1) == OMStance.HOSTILE
    assert lib.om_faction_stance(w, 1, 0) == OMStance.HOSTILE


def test_R_044_02_p_0_005_2_5(lib, world_factory):
    """Given a conqueror with border military 60 facing a partner's border military 20, average tension 60, When its chance is computed, Then p = 0.005 · 2.5 · min(3.0, 3.0) · max(1, 1.2) = 0.045."""
