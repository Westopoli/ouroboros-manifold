def test_R_044_06_pair_hostile_at_once_every(lib, world_factory):
    """Given a betrayal fires, When applied, Then the pair is hostile at once, every shared edge becomes `border`, and the betrayer attacks the victim's weakest bordering region."""
    w = world_factory(n_regions=4)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.DIPLOMACY, 1)

    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=40.0, tech=0.0)
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=40.0, tech=0.0)
    set_stance(lib, w, 0, 1, OMStance.COOPERATIVE)

    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0)
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0)
    # Victim's bordering regions: region 2 (mil 40.0), region 3 (mil 15.0, weakest)
    set_region(lib, w, 2, tier=OMTier.HOME, military=40.0, economy=50.0, tension=10.0, population=50.0)
    set_region(lib, w, 3, tier=OMTier.HOME, military=15.0, economy=50.0, tension=10.0, population=50.0)
    set_owner(lib, w, 0, 0)
    set_owner(lib, w, 1, 0)
    set_owner(lib, w, 2, 1)
    set_owner(lib, w, 3, 1)

    set_edge(lib, w, 0, 2, OMEdge.BOTH)
    set_edge(lib, w, 1, 3, OMEdge.TRADE)

    # Force betrayal to fire for faction 0
    force_draws(lib, w, [0.0001])
    lib.om_world_step(w)

    # 1. Stance becomes hostile both ways
    assert lib.om_faction_stance(w, 0, 1) == OMStance.HOSTILE
    assert lib.om_faction_stance(w, 1, 0) == OMStance.HOSTILE

    # 2. Every shared edge becomes border
    out = (ctypes.c_int)()
    rc = lib.om_region_edge(w, 0, 2, ctypes.byref(out))
    assert rc == 1 and out.value == OMEdge.BORDER
    rc = lib.om_region_edge(w, 1, 3, ctypes.byref(out))
    assert rc == 1 and out.value == OMEdge.BORDER

    # 3. Betrayer attacks the victim's weakest bordering region (region 3 with mil 15.0)
    attacks = read_attacks(lib, w)
    assert len(attacks) >= 1
    betrayal_attack = [a for a in attacks if a.attacker == 0 and a.defender == 1]
    assert len(betrayal_attack) == 1
    assert betrayal_attack[0].target_idx == 3


def test_R_044_07_q_045_01_decides_commit(lib, world_factory):
    """Given the betrayal attack, When resolved, Then [Q-045-01 decides commit and mode: current code commits the betrayer's entire budget at full efficiency; the bible says a surprise attack]."""
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.DIPLOMACY, 1)

    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=42.5, tech=0.0)
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=20.0, tech=0.0)
    set_stance(lib, w, 0, 1, OMStance.COOPERATIVE)

    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0)
    set_region(lib, w, 1, tier=OMTier.HOME, military=25.0, economy=50.0, tension=10.0, population=50.0)
    set_owner(lib, w, 0, 0)
    set_owner(lib, w, 1, 1)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)

    force_draws(lib, w, [0.0001, 1.0])  # betrayal draw + attack stochastic draw
    lib.om_world_step(w)

    attacks = read_attacks(lib, w)
    betrayal_attack = [a for a in attacks if a.attacker == 0 and a.defender == 1]
    assert len(betrayal_attack) == 1
    # Q-045-01 (closed, c): betrayer commits its entire budget at fire time (ALG-40).
    # Budget grows in step 3b before betrayal fires in step 3.5 (ALG-17): faction 0
    # owns region 0, economy 50.0, tech 0.0 -> tech_economy multiplier 1.0 (ALG-26).
    # Δbudget = (50.0 - REGION_MAINTENANCE_COST 8.0) * BUDGET_GROWTH_RATE 0.025 * 1.0 = 1.05
    # budget at fire time = 42.5 + 1.05 = 43.55
    assert betrayal_attack[0].commit == pytest.approx(43.55, abs=1e-5)
    # Effective attack with full efficiency (commit * 1.0 + mil * 0.1 * 1.0)
    assert betrayal_attack[0].effective_attack >= 42.5

