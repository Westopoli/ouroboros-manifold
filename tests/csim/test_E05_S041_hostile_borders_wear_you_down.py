    set_region(lib, w, 2, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0, faction_id=0)
    set_owner(lib, w, 2, 0, held_since=-1)
    set_region(lib, w, 3, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0, faction_id=0)
    set_owner(lib, w, 3, 0, held_since=-1)
    set_edge(lib, w, 2, 3, OMEdge.BOTH)

    # Case 3: Region 4 (Faction 0) has a mixed neighborhood:
    # - an empty neighbor (Region 5)
    # - a same-faction neighbor (Region 3)
    # - a hostile neighbor (Region 6, owned by Faction 1)
    set_region(lib, w, 4, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0, faction_id=0)
    set_owner(lib, w, 4, 0, held_since=-1)
    set_region(lib, w, 5, tier=OMTier.EMPTY, military=0.0, economy=0.0, tension=0.0, population=0.0, faction_id=-1)
    set_region(lib, w, 6, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0, faction_id=1)
    set_owner(lib, w, 6, 1, held_since=-1)
    set_edge(lib, w, 4, 5, OMEdge.BOTH)  # empty
    set_edge(lib, w, 4, 3, OMEdge.BOTH)  # same faction
    set_edge(lib, w, 4, 6, OMEdge.BOTH)  # hostile

    # When friction applies
    lib.om_world_step(w)

    # Then empty neighbor and same-faction neighbor contribute nothing
    records = read_friction(lib, w)

    # Case 1: Region 0 with empty neighbor receives 0 friction
    f0 = next((r for r in records if r.region_idx == 0), None)
    if f0 is not None:
        assert f0.hostile_neighbors == 0
        assert f0.d_tension == pytest.approx(0.0, abs=1e-6)
        assert f0.d_economy == pytest.approx(0.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.TENSION) == pytest.approx(20.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.ECONOMY) == pytest.approx(50.0, abs=1e-6)

    # Empty region itself never receives friction
    assert lib.om_region_field(w, 1, OMField.MILITARY) == pytest.approx(0.0, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.ECONOMY) == pytest.approx(0.0, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.TENSION) == pytest.approx(0.0, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.POPULATION) == pytest.approx(0.0, abs=1e-6)

    # Case 2: Region 2 with same-faction neighbor receives 0 friction
    f2 = next((r for r in records if r.region_idx == 2), None)
    if f2 is not None:
        assert f2.hostile_neighbors == 0
        assert f2.d_tension == pytest.approx(0.0, abs=1e-6)
        assert f2.d_economy == pytest.approx(0.0, abs=1e-6)
    assert lib.om_region_field(w, 2, OMField.TENSION) == pytest.approx(20.0, abs=1e-6)
    assert lib.om_region_field(w, 2, OMField.ECONOMY) == pytest.approx(50.0, abs=1e-6)

    # Case 3: In mixed neighborhood, only the genuine hostile neighbor contributes
    f4 = next(r for r in records if r.region_idx == 4)
    assert f4.hostile_neighbors == 1
    assert f4.d_tension == pytest.approx(0.15, abs=1e-6)
    assert f4.d_economy == pytest.approx(-0.05, abs=1e-6)
    assert lib.om_region_field(w, 4, OMField.TENSION) == pytest.approx(20.0 + 0.15, abs=1e-6)
    assert lib.om_region_field(w, 4, OMField.ECONOMY) == pytest.approx(50.0 - 0.05, abs=1e-6)
