def test_R_041_03_it_contributes_nothing(lib, world_factory):
    """Given a neighbor whose faction is neutral or cooperative both ways, When friction applies, Then it contributes nothing."""
    w = world_factory(n_regions=8)
    isolate_agents(lib, w, friction=True)

    # Faction 0 owns evaluated regions (0, 2, 4, 6)
    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)

    # Case 1: Neighbor faction 1 is NEUTRAL both ways
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)
    set_stance(lib, w, 0, 1, OMStance.NEUTRAL, both_ways=True)

    # Case 2: Neighbor faction 2 is COOPERATIVE both ways
    set_faction(lib, w, 2, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w, 2, 1.0, 1.0, 1.0)
    set_stance(lib, w, 0, 2, OMStance.COOPERATIVE, both_ways=True)

    # Case 3: Neighbor faction 3 is NEUTRAL one way, COOPERATIVE the other way (non-hostile both ways)
    set_faction(lib, w, 3, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w, 3, 1.0, 1.0, 1.0)
    set_stance(lib, w, 0, 3, OMStance.NEUTRAL, both_ways=False)
    set_stance(lib, w, 3, 0, OMStance.COOPERATIVE, both_ways=False)

    # Boundary contrast: Neighbor faction 4 is NEUTRAL one way, but HOSTILE the other way
    # (Not neutral/cooperative both ways: either side is hostile, so it DOES contribute friction)
    set_faction(lib, w, 4, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    set_tech_multipliers(lib, w, 4, 1.0, 1.0, 1.0)
    set_stance(lib, w, 0, 4, OMStance.NEUTRAL, both_ways=False)
    set_stance(lib, w, 4, 0, OMStance.HOSTILE, both_ways=False)

    # Set regions with neutral fields: tier HOME, military 50.0, economy 50.0, tension 20.0, population 50.0, held_since -1
    for idx in range(8):
        f_id = 0 if idx % 2 == 0 else (idx // 2 + 1)
        set_region(lib, w, idx, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0, faction_id=f_id)
        set_owner(lib, w, idx, f_id, held_since=-1)

    # Edges between each pair across BOTH (neutral edge type)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)
    set_edge(lib, w, 2, 3, OMEdge.BOTH)
    set_edge(lib, w, 4, 5, OMEdge.BOTH)
    set_edge(lib, w, 6, 7, OMEdge.BOTH)

    # When friction applies
    lib.om_world_step(w)

    # Then it contributes nothing for neutral/cooperative both ways
    records = read_friction(lib, w)

    # Case 1: NEUTRAL both ways contributes nothing
    f0 = next((r for r in records if r.region_idx == 0), None)
    if f0 is not None:
        assert f0.hostile_neighbors == 0
        assert f0.d_tension == pytest.approx(0.0, abs=1e-6)
        assert f0.d_economy == pytest.approx(0.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.TENSION) == pytest.approx(20.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.ECONOMY) == pytest.approx(50.0, abs=1e-6)

    # Case 2: COOPERATIVE both ways contributes nothing
    f2 = next((r for r in records if r.region_idx == 2), None)
    if f2 is not None:
        assert f2.hostile_neighbors == 0
        assert f2.d_tension == pytest.approx(0.0, abs=1e-6)
        assert f2.d_economy == pytest.approx(0.0, abs=1e-6)
    assert lib.om_region_field(w, 2, OMField.TENSION) == pytest.approx(20.0, abs=1e-6)
    assert lib.om_region_field(w, 2, OMField.ECONOMY) == pytest.approx(50.0, abs=1e-6)

    # Case 3: NEUTRAL/COOPERATIVE mixed both ways contributes nothing
    f4 = next((r for r in records if r.region_idx == 4), None)
    if f4 is not None:
        assert f4.hostile_neighbors == 0
        assert f4.d_tension == pytest.approx(0.0, abs=1e-6)
        assert f4.d_economy == pytest.approx(0.0, abs=1e-6)
    assert lib.om_region_field(w, 4, OMField.TENSION) == pytest.approx(20.0, abs=1e-6)
    assert lib.om_region_field(w, 4, OMField.ECONOMY) == pytest.approx(50.0, abs=1e-6)

    # Boundary contrast: hostile one way IS counted as hostile (1 hostile neighbor)
    f6 = next(r for r in records if r.region_idx == 6)
    assert f6.hostile_neighbors == 1
    assert f6.d_tension == pytest.approx(0.15, abs=1e-6)
    assert f6.d_economy == pytest.approx(-0.05, abs=1e-6)
    assert lib.om_region_field(w, 6, OMField.TENSION) == pytest.approx(20.0 + 0.15, abs=1e-6)
    assert lib.om_region_field(w, 6, OMField.ECONOMY) == pytest.approx(50.0 - 0.05, abs=1e-6)


def test_R_041_04_economy_stays_8_0(lib, world_factory):
    """Given friction would push economy below 8.0, When applied, Then economy stays 8.0."""
    # Three-fixture boundary pattern:
    # 1. At boundary (economy = 8.0): friction would push to 7.90 (< 8.0), clamped to stay 8.0.
    # 2. Pushing across boundary (economy = 8.04): friction would push to 7.99 (< 8.0), clamped to stay 8.0.
    # 3. Above boundary (economy = 8.10): friction pushes to 8.05 (>= 8.0), unclamped.
    w = world_factory(n_regions=6)
    isolate_agents(lib, w, friction=True)

    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)
    set_faction(lib, w, 2, OMArchetype.DEFAULT, budget=0.0, tech=0.0, confidence=5.0)

    # Tech multipliers 1.0 (neutral baseline, no tech bonuses)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 2, 1.0, 1.0, 1.0)

    # Pairwise stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    set_stance(lib, w, 0, 2, OMStance.HOSTILE)

    # Fixture 1: Region 0 at economy 8.0 with two hostile neighbors (Region 3 and Region 4).
    # Unclamped delta would be -0.10, pushing economy to 7.90; clamped at 8.0.
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=20.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)

    # Fixture 2: Region 1 at economy 8.04 with one hostile neighbor (Region 3).
    # Unclamped delta would be -0.05, pushing economy to 7.99; clamped at 8.0.
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=8.04, tension=20.0, population=50.0, faction_id=0)
    set_owner(lib, w, 1, 0, held_since=-1)

    # Fixture 3: Region 2 at economy 8.10 with one hostile neighbor (Region 4).
    # Delta is -0.05, resulting in 8.05 (> 8.0); stays above floor without clamping.
    set_region(lib, w, 2, tier=OMTier.HOME, military=50.0, economy=8.10, tension=20.0, population=50.0, faction_id=0)
    set_owner(lib, w, 2, 0, held_since=-1)

    # Hostile neighbor regions: neutral fields, owned by enemy factions
    set_region(lib, w, 3, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0, faction_id=1)
    set_owner(lib, w, 3, 1, held_since=-1)
    set_region(lib, w, 4, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0, faction_id=2)
    set_owner(lib, w, 4, 2, held_since=-1)

    # Region 5: dummy/isolated region to complete 6 regions
    set_region(lib, w, 5, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0, faction_id=1)
    set_owner(lib, w, 5, 1, held_since=-1)

    # Edges: Region 0 connected to 3 and 4; Region 1 connected to 3; Region 2 connected to 4
    set_edge(lib, w, 0, 3, OMEdge.BOTH)
    set_edge(lib, w, 0, 4, OMEdge.BOTH)
    set_edge(lib, w, 1, 3, OMEdge.BOTH)
    set_edge(lib, w, 2, 4, OMEdge.BOTH)

    # When friction applies
    lib.om_world_step(w)

    # Then economy stays 8.0 when pushed below, and unclamped when remaining above
    records = read_friction(lib, w)

    # Fixture 1 (at boundary 8.0):
    f0 = next(r for r in records if r.region_idx == 0)
    assert f0.hostile_neighbors == 2
    assert f0.d_tension == pytest.approx(0.30, abs=1e-6)
    assert f0.d_economy == pytest.approx(0.0, abs=1e-6)  # clamped at floor: delta applied to economy is 0.0
    assert lib.om_region_field(w, 0, OMField.ECONOMY) == pytest.approx(8.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.TENSION) == pytest.approx(20.0 + 0.30, abs=1e-6)

    # Fixture 2 (pushing below boundary from 8.04):
    f1 = next(r for r in records if r.region_idx == 1)
    assert f1.hostile_neighbors == 1
    assert f1.d_tension == pytest.approx(0.15, abs=1e-6)
    assert f1.d_economy == pytest.approx(-0.04, abs=1e-6)  # clamped at floor: 8.04 -> 8.0 is delta -0.04
    assert lib.om_region_field(w, 1, OMField.ECONOMY) == pytest.approx(8.0, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.TENSION) == pytest.approx(20.0 + 0.15, abs=1e-6)

    # Fixture 3 (above boundary at 8.10 -> 8.05):
    f2 = next(r for r in records if r.region_idx == 2)
    assert f2.hostile_neighbors == 1
    assert f2.d_tension == pytest.approx(0.15, abs=1e-6)
    assert f2.d_economy == pytest.approx(-0.05, abs=1e-6)  # full unclamped delta: 8.10 - 0.05 = 8.05
    assert lib.om_region_field(w, 2, OMField.ECONOMY) == pytest.approx(8.05, abs=1e-6)
    assert lib.om_region_field(w, 2, OMField.TENSION) == pytest.approx(20.0 + 0.15, abs=1e-6)


