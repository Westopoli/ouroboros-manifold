    # Stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)

    # Case 1: Hostile neighbor across a TRADE-only edge (regions 0 and 1)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)
    set_edge(lib, w, 0, 1, OMEdge.TRADE)

    # Case 2: Hostile neighbor across a BORDER edge (regions 2 and 3)
    set_region(lib, w, 2, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0, faction_id=0)
