    #   Step 1: Separatist (tick 1) -> delay 1+1=2 -> Political Crisis (tick 3) -> delay 1 -> Defection (tick 4) -> delay 1 -> Breakaway (tick 5 = L)
    #   Skips: Popular Support
    # Region 2: Long chain (L = 8, step count S = 5, surplus 3):
    #   Step 1: Separatist (tick 1) -> delay 2 -> Crisis (tick 3) -> delay 2 -> Support (tick 5) -> delay 2 -> Defection (tick 7) -> delay 1 -> Breakaway (tick 8 = L)
    #   Skips: none (all 5 steps included)
