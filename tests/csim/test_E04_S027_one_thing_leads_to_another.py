def test_R_027_06_its_chain_tag_equals_root(lib, world_factory):
    """Given any spawned event, When it is read from the log, Then its chain tag equals the root event's tag, and the tag is unique per chain start (`chain_NNNN`, sequential)."""
    # 2 regions start two distinct chains on tick 4 via threshold crossings:
    # Region 0: Garrison Collapse (crosses military below 30.0) -> root of Chain 1
    # Region 1: Trade Boom (crosses economy above 55.0) -> root of Chain 2
    w = world_factory(n_regions=2)
    isolate_events(lib, w)
    load_launch_events(lib, w)
    zero_all_noise(lib, w)

    tid_collapse = template_id(lib, w, "Garrison Collapse")
    tid_border = template_id(lib, w, "Border Incursion")
    tid_revolt = template_id(lib, w, "Regional Revolt")
    tid_boom = template_id(lib, w, "Trade Boom")
    tid_unrest = template_id(lib, w, "Prosperity Unrest")

    # Neutral starting fields unbreached for ticks 1..3
    set_region(lib, w, 0, tier=OMTier.HOME, military=40.0, economy=50.0, tension=50.0, population=50.0)  # neutral tier HOME
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=20.0, population=50.0)  # neutral tier HOME
    for r in range(2):
        set_owner(lib, w, r, 0, held_since=-1)  # neutral held_since -1 (held since the world began)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0

    # Step grace period ticks 1 through 3
    for _ in range(3):
        lib.om_world_step(w)

    # Tick 4 crossings:
    # Region 0 military drops to 25.0 (< 30.0 Garrison Collapse)
    set_region(lib, w, 0, tier=OMTier.HOME, military=25.0, economy=50.0, tension=50.0, population=50.0)  # neutral tier HOME
    # Region 1 economy rises to 60.0 (> 55.0 Trade Boom)
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=60.0, tension=20.0, population=50.0)  # neutral tier HOME

    # Per region (e2e "Draw order", ALG-34): the regional-revolt roll comes before the fired
    # threshold template's own spawn draws, regardless of the template's table position, so
    # Region 0's revolt-roll (0.99, safe) precedes Garrison Collapse's (template id 0) two
    # spawn draws.
    # Region 0: revolt-roll 0.99; Garrison Collapse spawns Border Incursion [3, 7] (delay draw
    # 0.0 -> delay 3 -> due tick 7) and Emergency Levy [2, 5] (delay draw 1.0 -> delay 5 -> due tick 9)
    # Region 1: revolt-roll 0.99; Trade Boom spawns Prosperity Unrest [8, 15] (delay draw 0.0 -> delay 8 -> due tick 12)
    force_draws(lib, w, [0.99, 0.00, 1.00, 0.99, 0.00])
    lib.om_world_step(w)  # tick 4

    events_4 = read_events(lib, w)
    assert len(events_4) == 2
    ev0 = [e for e in events_4 if e.region_idx == 0][0]
    ev1 = [e for e in events_4 if e.region_idx == 1][0]
    assert ev0.template_id == tid_collapse
    assert ev1.template_id == tid_boom

    root_tag_0 = ev0.chain_tag
    root_tag_1 = ev1.chain_tag

    # Chain tags are unique per chain start and sequential
    assert root_tag_0 != root_tag_1
    assert root_tag_1 == root_tag_0 + 1

    # Advance to tick 7 when Border Incursion (first generation spawn of Chain 1) resolves
    for _ in range(2):  # ticks 5 and 6
        lib.om_world_step(w)

    # Tick 7: Border Incursion condition is military < 18 (military is 25.0; set to 15.0 so condition is met)
    set_region(lib, w, 0, tier=OMTier.HOME, military=15.0, economy=50.0, tension=50.0, population=50.0)  # neutral tier HOME
    # Force prob draw 0.1 <= 0.55 (passes) + delay draw 0.00 for its spawn Regional Revolt (delay 3 -> due tick 10)
    force_draws(lib, w, [0.1, 0.00])
    lib.om_world_step(w)  # tick 7

    events_7 = read_events(lib, w)
    assert len(events_7) == 1
    ev_spawn1 = events_7[0]
    assert ev_spawn1.template_id == tid_border
    # Spawned event's chain tag equals root event's tag
    assert ev_spawn1.chain_tag == root_tag_0

    # Advance to tick 10 when Regional Revolt (second generation spawn of Chain 1) resolves
    for _ in range(2):  # ticks 8 and 9
        # Neutral fields; keep economy low (20.0 <= 25.0) so Emergency Levy due tick 9 drops without firing
        set_region(lib, w, 0, tier=OMTier.HOME, military=15.0, economy=20.0, tension=50.0, population=50.0)  # neutral tier HOME
        lib.om_world_step(w)

    # Tick 10: Regional Revolt condition is tension > 40 (tension is 50.0, condition met)
    # Force prob draw 0.1 <= 0.60 (passes) + 2 delay draws for its spawns
    force_draws(lib, w, [0.1, 0.50, 0.50])
    lib.om_world_step(w)  # tick 10

    events_10 = read_events(lib, w)
    assert len(events_10) == 1
    ev_spawn2 = events_10[0]
    assert ev_spawn2.template_id == tid_revolt
    # Second-generation spawn's chain tag still equals root event's tag
    assert ev_spawn2.chain_tag == root_tag_0

    # Advance to tick 12 when Prosperity Unrest (spawn of Chain 2) resolves
    lib.om_world_step(w)  # tick 11

    # Tick 12: Prosperity Unrest condition is tension > 40 (set tension = 45.0 in Region 1)
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=60.0, tension=45.0, population=50.0)  # neutral tier HOME
    force_draws(lib, w, [0.1])  # prob draw 0.1 <= 0.25
    lib.om_world_step(w)  # tick 12

    events_12 = read_events(lib, w)
    assert len(events_12) == 1
    ev_unrest = events_12[0]
    assert ev_unrest.template_id == tid_unrest
    # Spawn of Chain 2 carries root_tag_1, strictly distinct from Chain 1
    assert ev_unrest.chain_tag == root_tag_1
    assert ev_unrest.chain_tag != root_tag_0


def test_R_027_07_it_holds_pruned_record_with(lib, world_factory):
    """Given a queued event dropped by R-027-02, When the tick log is read, Then it holds a `pruned` record with the template, region, tick, chain tag, and the condition that failed, so the chronicle (E-09) can tell the revolt that almost happened."""
    # 2 regions test pruned records for both failed condition directions:
    # Region 0: "Regional Revolt" (condition: tension above 40.0; at resolution tension = 30.0 <= 40.0)
    # Region 1: "Border Incursion" (condition: military below 18.0; at resolution military = 35.0 >= 18.0,
    # kept above Garrison Collapse's fresh-trigger threshold of 30.0 so that template does not
    # also fire fresh on tick 4, R-026-02)
    w = world_factory(n_regions=2)
    isolate_events(lib, w)
    load_launch_events(lib, w)
    zero_all_noise(lib, w)

    tid_border = template_id(lib, w, "Border Incursion")
    tid_collapse = template_id(lib, w, "Garrison Collapse")
    tid_revolt = template_id(lib, w, "Regional Revolt")

    for r in range(2):
        set_region(lib, w, r, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0)  # neutral tier HOME
        set_owner(lib, w, r, 0, held_since=-1)  # neutral held_since -1 (held since the world began)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0

    # Tick 1: queue parents to spawn follow-ups due tick 4
    queue_external(lib, w, 0, tid_border, due_tick=1, probability=1.0)
    queue_external(lib, w, 1, tid_collapse, due_tick=1, probability=1.0)

    # Region 0 Border Incursion: prob draw 0.1, delay draw 0.00 -> delay 3 -> due tick 4
    # Region 1 Garrison Collapse: prob draw 0.1, Border Incursion delay draw 0.00 -> delay 3 -> due tick 4, Emergency Levy delay 1.00 -> delay 5 -> due tick 6
    force_draws(lib, w, [0.1, 0.00, 0.1, 0.00, 1.00])
    lib.om_world_step(w)  # tick 1

    events_1 = read_events(lib, w)
    tag0 = [e for e in events_1 if e.region_idx == 0][0].chain_tag
    tag1 = [e for e in events_1 if e.region_idx == 1][0].chain_tag

    # Advance ticks 2 and 3
    lib.om_world_step(w)  # tick 2
    lib.om_world_step(w)  # tick 3

    # Arrange failing tick-start fields on tick 4:
    # Region 0: tension = 30.0 (fails tension above 40.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=30.0, population=50.0)  # neutral tier HOME
    # Region 1: military = 35.0 (fails military below 18.0; stays above Garrison Collapse's
    # 30.0 so that template is not also crossed fresh)
    set_region(lib, w, 1, tier=OMTier.HOME, military=35.0, economy=50.0, tension=20.0, population=50.0)  # neutral tier HOME

    # Neither region has a fresh threshold crossing this tick, so the only tick 4 draws are
    # the fresh-trigger phase's regional-revolt roll, once per inhabited region (e2e "Draw
    # order", ALG-34): region 0 then region 1, both forced safely away from their tiny p.
    force_draws(lib, w, [0.99, 0.99])
    lib.om_world_step(w)  # tick 4

    # Both revolt-roll draws consumed, nothing else
    assert lib.om_rng_forced_remaining(w) == 0

    # Neither event fired
    assert len(read_events(lib, w)) == 0

    # Tick log holds pruned records with template, region, tick, chain tag, and the condition that failed
    pruned = read_pruned(lib, w)
    assert len(pruned) == 2

    # Region 0: Regional Revolt pruned for failed `above` condition
    p0 = [p for p in pruned if p.region_idx == 0][0]
    assert p0.template_id == tid_revolt
    assert p0.region_idx == 0
    assert p0.tick == 4
    assert p0.chain_tag == tag0
    assert p0.cond_kind == OMCond.ABOVE
    assert p0.cond_field == OMField.TENSION
    assert p0.cond_value == pytest.approx(40.0, abs=1e-6)
    assert p0.field_value == pytest.approx(30.0, abs=1e-6)

    # Region 1: Border Incursion pruned for failed `below` condition
    p1 = [p for p in pruned if p.region_idx == 1][0]
    assert p1.template_id == tid_border
    assert p1.region_idx == 1
    assert p1.tick == 4
    assert p1.chain_tag == tag1
    assert p1.cond_kind == OMCond.BELOW
    assert p1.cond_field == OMField.MILITARY
    assert p1.cond_value == pytest.approx(18.0, abs=1e-6)
    assert p1.field_value == pytest.approx(35.0, abs=1e-6)

    # Events were dropped from the pending queue
    assert not any(q.due_tick == 4 for q in read_event_queue(lib, w))
