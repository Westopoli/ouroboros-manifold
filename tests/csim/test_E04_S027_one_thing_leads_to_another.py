    assert q1_1.template_id == tid_crisis
    assert q1_1.due_tick == 3
    assert q1_1.probability == pytest.approx(1.0, abs=1e-6)
    assert q1_1.cond_kind == OMCond.NONE

    # Region 2 (L=8, long): next is Crisis due tick 3 (delay 1 + 1 surplus = 2)
