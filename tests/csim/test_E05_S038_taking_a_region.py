def test_R_038_01_region_s_owner_becomes_attacker(lib, world_factory):
    """Given an attack leaves defender military below 5.0 and the outcome is not repelled, When resolved, Then the region's owner becomes the attacker, garrison = commit · 0.65 is added to military after damage, economy −5 more (may go below 8), tension +8 more, population −2 more."""
    # Arrange: Attacker committing 42.0 (budget = 60.0, potential_commit = 42.0)
    # Defender military is engineered so post-damage military is 4.0 (< 5.0).
    # Telegraph attack declared on tick 1, resolves on tick 4 (tick t + 3).
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=60.0, confidence=2.0)
    set_faction(lib, w, 1, OMArchetype.FORTIFIER, budget=0.0)
    # Stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    # Tech multipliers 1.0 (neutral baseline, no tech)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)
    # Attacker region economy set to 8.0 (maintenance baseline) so Δbudget = 0
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)
    # Defender region with initial military 20.0, economy 16.0, tension 10.0, population 50.0
