def test_R_038_02_conquest_happens_exactly_as_after(lib, world_factory):
    """Given a contested attack that takes military from 6 to 4, When resolved, Then conquest happens exactly as after a breakthrough."""
    # Given: Contested attack reducing defender military from 6 to 4 (Δm = -2.0)
    # In contested attack (0 < net <= 15.0), Δm = -0.5 * net, so net = 4.0
    # Defender military 6 held from start (entrenchment 2.0): effective defense = 6 * 0.55 * 2.0 = 6.6
    # effective_attack = 6.6 + 4.0 = 10.6 -> commit = 10.6 in telegraph mode (budget = 10.6 / 0.70)
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=10.6 / 0.70, confidence=2.0)
    set_faction(lib, w, 1, OMArchetype.FORTIFIER, budget=0.0)
    # Stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    # Tech multipliers 1.0 (neutral baseline, no tech)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)
    # Defender initial military = 6.0, economy = 50.0, tension = 10.0, population = 50.0
    set_region(lib, w, 1, tier=OMTier.HOME, military=6.0, economy=50.0, tension=10.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)

    # Tick 1: Telegraph attack declared (commit = 10.6)
    force_draws(lib, w, [0.1, 0.5])
    lib.om_world_step(w)

    # Ticks 2 and 3: Sits in pending list
    lib.om_world_step(w)
    lib.om_world_step(w)

    # Tick 4: Resolves in step 3c with draw 1.0 (net = (10.6 - 6.6) * 1.0 = 4.0)
    # draw 0.8 for conquest unrest probability draw
    force_draws(lib, w, [1.0, 0.8])
    lib.om_world_step(w)

    attacks = read_attacks(lib, w)
    assert len(attacks) == 1
    att = attacks[0]
    assert att.outcome == OMOutcome.CONTESTED
    assert att.net == pytest.approx(4.0, abs=1e-6)
    assert att.d_military == pytest.approx(-2.0, abs=1e-6)
    assert att.d_economy == pytest.approx(-0.8, abs=1e-6)  # -0.2 * 4 = -0.8
    assert att.d_tension == pytest.approx(1.6, abs=1e-6)   # +0.4 * 4 = +1.6
    assert att.conquest == 1

    # Conquest happens exactly as after a breakthrough:
    # garrison = commit · 0.65 = 10.6 · 0.65 = 6.89 added to military after damage (4.0 + 6.89 = 10.89)
    garrison_expected = 10.6 * 0.65
    assert att.garrison == pytest.approx(garrison_expected, abs=1e-6)
    assert lib.om_region_owner(w, 1) == 0
    assert lib.om_region_field(w, 1, OMField.MILITARY) == pytest.approx(4.0 + garrison_expected, abs=1e-6)
    # economy −5 more: 50.0 - 0.8 - 5.0 = 44.2
    assert lib.om_region_field(w, 1, OMField.ECONOMY) == pytest.approx(50.0 - 0.8 - 5.0, abs=1e-6)
    # tension +8 more: 10.0 + 1.6 + 8.0 = 19.6
    assert lib.om_region_field(w, 1, OMField.TENSION) == pytest.approx(10.0 + 1.6 + 8.0, abs=1e-6)
    # population −2 more: 50.0 - 2.0 = 48.0
    assert lib.om_region_field(w, 1, OMField.POPULATION) == pytest.approx(50.0 - 2.0, abs=1e-6)


def test_R_038_03_no_conquest_ever_happens(lib, world_factory):
    """Given a repelled attack, When resolved, Then no conquest ever happens."""
    # Given: Repelled attack against defender with military below 5.0 (military 4.0)
    # Proves the invariant that conquest NEVER happens on a repelled attack, even when defender military is < 5.0.
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=3.0 / 0.70, confidence=0.5)
    set_faction(lib, w, 1, OMArchetype.FORTIFIER, budget=0.0)
    # Stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    # Tech multipliers 1.0 (neutral baseline, no tech)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)
    # At tick 1, target has low military (1.0) so attack is viable at declaration
    set_region(lib, w, 1, tier=OMTier.HOME, military=1.0, economy=50.0, tension=10.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)

    # Tick 1: Telegraph attack declared (commit = 3.0)
    force_draws(lib, w, [0.1, 0.5])
    lib.om_world_step(w)

    # Tick 2: Sits in pending list
    lib.om_world_step(w)

    # Tick 3: Defender military set to 4.0 held from start (entrenchment 2.0), simulating defender defense < 5.0
    # effective_defense = 4.0 * 0.55 * 2.0 = 4.4 > commit 3.0
    set_region(lib, w, 1, tier=OMTier.HOME, military=4.0, economy=50.0, tension=10.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)
    lib.om_world_step(w)

    # Tick 4: Resolves with draw 1.0 in step 3c
    # net = (3.0 - 4.4) * 1.0 = -1.4 <= 0 -> REPELLED
    # defender Δmilitary = -0.10 * effective_attack = -0.10 * 3.0 = -0.30
    # post-damage military = 4.0 - 0.30 = 3.70 (< 5.0)
    force_draws(lib, w, [1.0])
    lib.om_world_step(w)

    attacks = read_attacks(lib, w)
    assert len(attacks) == 1
    att = attacks[0]
    assert att.outcome == OMOutcome.REPELLED
    assert att.net < 0.0
    assert att.net == pytest.approx(-1.4, abs=1e-6)
    assert att.d_military == pytest.approx(-0.30, abs=1e-6)
    assert att.d_economy == pytest.approx(0.0, abs=1e-6)
    assert att.d_tension == pytest.approx(2.0, abs=1e-6)

    # Invariant: No conquest ever happens
    assert att.conquest == 0
    assert att.garrison == 0.0
    assert lib.om_region_owner(w, 1) == 1
    assert lib.om_region_field(w, 1, OMField.MILITARY) == pytest.approx(3.70, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.ECONOMY) == pytest.approx(50.0, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.TENSION) == pytest.approx(10.0 + 2.0, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.POPULATION) == pytest.approx(50.0, abs=1e-6)


def test_R_038_04_with_probability_0_60_conquest(lib, world_factory):
    """Given a conquest on tick t, When one draw is made, Then with probability 0.60 a Conquest Unrest event is queued for tick t + round(triangular(4, 8, 6))."""
    # Case 1: Probability roll succeeds (draw = 0.30 <= 0.60)
    # Delay draw u = 0.5 -> triangular(4, 8, 6) = 6 -> due_tick = t + 6
    w_success = world_factory(n_regions=2)
    isolate_agents(lib, w_success)
    set_faction(lib, w_success, 0, OMArchetype.CONQUEROR, budget=100.0, confidence=2.0)
    set_faction(lib, w_success, 1, OMArchetype.FORTIFIER, budget=0.0)
    set_stance(lib, w_success, 0, 1, OMStance.HOSTILE)
    set_tech_multipliers(lib, w_success, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w_success, 1, 1.0, 1.0, 1.0)
    set_region(lib, w_success, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w_success, 0, 0, held_since=-1)
    # Defender military 10.0 held from start: effective defense = 11.0
    set_region(lib, w_success, 1, tier=OMTier.HOME, military=10.0, economy=50.0, tension=10.0, population=50.0, faction_id=1)
    set_owner(lib, w_success, 1, 1, held_since=-1)
    set_edge(lib, w_success, 0, 1, OMEdge.BOTH)

    # Tick 1: Surprise attack with commit 70.0 (effective attack = 35.0)
    # Draw order:
    # 1. mode draw: 0.95 (>= 0.7 selects surprise mode)
    # 2. combat stochastic draw: 1.0 -> net = (35.0 - 11.0) * 1.0 = 24.0 -> Δm = -19.2 -> post-damage m = 0.0 < 5.0 (conquest!)
    # 3. conquest unrest probability draw: 0.30 <= 0.60 (triggers event)
    # 4. delay draw: 0.5 -> triangular(4, 8, 6) = 6 -> due tick = 1 + 6 = 7
    force_draws(lib, w_success, [0.95, 1.0, 0.30, 0.5])
    lib.om_world_step(w_success)

    assert read_attacks(lib, w_success)[0].conquest == 1
    queue_success = read_event_queue(lib, w_success)
    assert len(queue_success) == 1
    evt = queue_success[0]
    assert evt.template_id == OMEvent.CONQUEST_UNREST
    assert evt.region_idx == 1
    assert evt.due_tick == 1 + 6

    # Case 2: Probability roll fails (draw = 0.80 > 0.60) -> no event queued
    w_fail = world_factory(n_regions=2)
    isolate_agents(lib, w_fail)
    set_faction(lib, w_fail, 0, OMArchetype.CONQUEROR, budget=100.0, confidence=2.0)
    set_faction(lib, w_fail, 1, OMArchetype.FORTIFIER, budget=0.0)
