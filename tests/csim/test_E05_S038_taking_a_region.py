    assert lib.om_region_owner(w_at, 1) == 1
    assert lib.om_region_field(w_at, 1, OMField.MILITARY) == pytest.approx(5.0, abs=1e-6)
    # Economy without conquest disruption (-5)
    assert lib.om_region_field(w_at, 1, OMField.ECONOMY) == pytest.approx(16.0 + att_at.d_economy, abs=1e-6)
    assert lib.om_region_field(w_at, 1, OMField.TENSION) == pytest.approx(10.0 + att_at.d_tension, abs=1e-6)
    assert lib.om_region_field(w_at, 1, OMField.POPULATION) == pytest.approx(50.0, abs=1e-6)

