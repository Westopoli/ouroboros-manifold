    set_region(lib, w, 1, tier=OMTier.HOME, military=20.0, economy=16.0, tension=10.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)

    # Tick 1: Attacker declares telegraphed attack (commit = 42.0)
    # Mode draw 0.1 < 0.5 selects telegraph mode; 0.5 for reinforce
    force_draws(lib, w, [0.1, 0.5])
    lib.om_world_step(w)

    pending = read_telegraphs(lib, w)
    assert len(pending) == 1
    assert pending[0].commit == pytest.approx(42.0, abs=1e-6)

    # Ticks 2 and 3: Attack sits in pending list
    lib.om_world_step(w)
    lib.om_world_step(w)

    # Tick 4 (t + 3): Resolves in step 3c with stochastic draw 1.0
    # effective_attack = 42.0, effective_defense = 20.0 * 0.55 * 2.0 = 22.0
    # net = (42.0 - 22.0) * 1.0 = 20.0 (> 15.0, breakthrough)
    # Δm = -0.8 * 20.0 = -16.0 -> post-damage military = 20.0 - 16.0 = 4.0 (< 5.0)
    # Conquest triggers! garrison = 42.0 * 0.65 = 27.3
    force_draws(lib, w, [1.0, 0.8])  # draw 0.8 for conquest unrest roll
    lib.om_world_step(w)

    attacks = read_attacks(lib, w)
    assert len(attacks) == 1
    att = attacks[0]
    assert att.tick == 4
    assert att.outcome == OMOutcome.BREAKTHROUGH
    assert att.net == pytest.approx(20.0, abs=1e-6)
    assert att.d_military == pytest.approx(-16.0, abs=1e-6)
    assert att.d_economy == pytest.approx(-6.0, abs=1e-6)  # -0.3 * 20 = -6.0
    assert att.d_tension == pytest.approx(10.0, abs=1e-6)  # +0.5 * 20 = +10.0
    assert att.conquest == 1
    assert att.garrison == pytest.approx(27.3, abs=1e-6)  # 42.0 * 0.65 = 27.3

    # Assert region state after conquest:
    # Owner becomes attacker
    assert lib.om_region_owner(w, 1) == 0
    # Garrison = commit * 0.65 is added to military after damage: 4.0 + 27.3 = 31.3
    assert lib.om_region_field(w, 1, OMField.MILITARY) == pytest.approx(4.0 + 27.3, abs=1e-6)
    # Economy: initial 16.0 - 6.0 damage - 5.0 conquest disruption = 5.0 (may go below 8)
