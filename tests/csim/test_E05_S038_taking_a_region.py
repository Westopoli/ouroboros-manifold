    set_owner(lib, w_at, 0, 0, held_since=-1)
    set_region(lib, w_at, 1, tier=OMTier.HOME, military=38.6 / 1.88, economy=16.0, tension=10.0, population=50.0, faction_id=1)
    set_owner(lib, w_at, 1, 1, held_since=-1)
    set_edge(lib, w_at, 0, 1, OMEdge.BOTH)
    force_draws(lib, w_at, [0.1, 0.5])
    lib.om_world_step(w_at)
    lib.om_world_step(w_at)
