    # Three-fixture strict inequality boundary test on post-damage military < 5.0:
    # At boundary: post-damage military exactly 5.0 (no conquest occurs)
    # m = 38.6 / 1.88 -> effective_defense = 22.585106 -> net = 19.414894 -> Δm = -15.531915 -> post-damage m = 5.0
