    set_region(lib, w_bound_above, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w_bound_above, 0, 0, held_since=-1)
    set_region(lib, w_bound_above, 1, tier=OMTier.HOME, military=10.0, economy=50.0, tension=10.0, population=50.0, faction_id=1)
