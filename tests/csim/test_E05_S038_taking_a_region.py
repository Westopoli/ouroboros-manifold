    set_owner(lib, w_fail, 0, 0, held_since=-1)
    set_region(lib, w_fail, 1, tier=OMTier.HOME, military=10.0, economy=50.0, tension=10.0, population=50.0, faction_id=1)
    set_owner(lib, w_fail, 1, 1, held_since=-1)
    set_edge(lib, w_fail, 0, 1, OMEdge.BOTH)

    # Draw 0.80 > 0.60 fails probability roll; no delay draw consumed
    force_draws(lib, w_fail, [0.95, 1.0, 0.80])
    lib.om_world_step(w_fail)

    assert read_attacks(lib, w_fail)[0].conquest == 1
    assert len(read_event_queue(lib, w_fail)) == 0

    # Boundary check: draw = 0.59 (< 0.60 queues) vs draw = 0.61 (> 0.60 does not queue)
    w_bound_below = world_factory(n_regions=2)
    isolate_agents(lib, w_bound_below)
    set_faction(lib, w_bound_below, 0, OMArchetype.CONQUEROR, budget=100.0, confidence=2.0)
    set_faction(lib, w_bound_below, 1, OMArchetype.FORTIFIER, budget=0.0)
    set_stance(lib, w_bound_below, 0, 1, OMStance.HOSTILE)
    set_tech_multipliers(lib, w_bound_below, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w_bound_below, 1, 1.0, 1.0, 1.0)
    set_region(lib, w_bound_below, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w_bound_below, 0, 0, held_since=-1)
    set_region(lib, w_bound_below, 1, tier=OMTier.HOME, military=10.0, economy=50.0, tension=10.0, population=50.0, faction_id=1)
    set_owner(lib, w_bound_below, 1, 1, held_since=-1)
