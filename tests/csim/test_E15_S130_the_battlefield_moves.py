def test_R_130_05_convoy_keeps_its_move_order(lib, world_factory):
    """Given a battle in transit (convoy moving), When engaged, Then the convoy keeps its move order and the fight happens around it."""
    w = world_factory(n_regions=1)
    convoy_id = lib.om_unit_spawn_non_combat(w, 0, ctypes.c_double(100.0), ctypes.c_double(100.0))
    lib.om_unit_order_move(w, convoy_id, ctypes.c_double(500.0), ctypes.c_double(500.0))

