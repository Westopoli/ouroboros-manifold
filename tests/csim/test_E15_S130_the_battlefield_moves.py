import ctypes

class OMDriftMode:
    PING_PONG = 0
    LOOP = 1


class OMVec2(ctypes.Structure):
    _fields_ = [
        ("x", ctypes.c_double),
        ("y", ctypes.c_double),
    ]


def test_R_130_01_its_position_interpolation_along_its(lib, world_factory):
    """Given a spine node of type objective or reinforcement_structure with waypoints, a period in ticks, and a mode, When ticks pass, Then its position is the interpolation along its waypoints, ping-pong (out and back) or loop, at tick mod period."""
    # 2 waypoints: (0, 0) to (100, 100), period = 100 ticks
    waypoints = (OMVec2 * 2)(OMVec2(0.0, 0.0), OMVec2(100.0, 100.0))
    period = 100

    pos_out = OMVec2()

    # In LOOP mode: at tick 50 (50 mod 100 = 50 / 100 = 0.5) -> (50, 50)
    lib.om_drift_interpolate(waypoints, 2, period, OMDriftMode.LOOP, 50, ctypes.byref(pos_out))
    assert pos_out.x == pytest.approx(50.0, abs=1e-4)
    assert pos_out.y == pytest.approx(50.0, abs=1e-4)

    # In PING_PONG mode: at tick 50 (halfway out) -> (100, 100), at tick 75 (halfway back) -> (50, 50)
    lib.om_drift_interpolate(waypoints, 2, period, OMDriftMode.PING_PONG, 50, ctypes.byref(pos_out))
    assert pos_out.x == pytest.approx(100.0, abs=1e-4)
    assert pos_out.y == pytest.approx(100.0, abs=1e-4)

    lib.om_drift_interpolate(waypoints, 2, period, OMDriftMode.PING_PONG, 75, ctypes.byref(pos_out))
    assert pos_out.x == pytest.approx(50.0, abs=1e-4)
    assert pos_out.y == pytest.approx(50.0, abs=1e-4)


