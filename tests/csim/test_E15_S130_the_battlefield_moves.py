    # Convoy continues its move order toward (500, 500)
    dest = OMVec2()
    lib.om_unit_get_order_destination(w, convoy_id, ctypes.byref(dest))
    assert dest.x == pytest.approx(500.0, abs=1e-3)
    assert dest.y == pytest.approx(500.0, abs=1e-3)

