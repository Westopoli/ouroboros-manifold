def test_R_125_03_command_streams_outcomes_captured_for(lib, world_factory):
    """Given external playtesters, When sessions run, Then command streams and outcomes are captured for the future learned-opponent target (A-156, data capture only)."""
    w = world_factory(n_regions=1)

    lib.om_session_capture_enable(w, 1)
    is_enabled = lib.om_session_capture_is_enabled(w)
    assert is_enabled == 1

    # Run session actions
    lib.om_replay_log_command(w, 1, 0, 0, ctypes.c_double(10.0), ctypes.c_double(20.0), 0)
    lib.om_mission_end(w)

    capture_size = lib.om_session_capture_get_size(w)
    assert capture_size > 0

    capture_buf = ctypes.create_string_buffer(capture_size)
    lib.om_session_capture_read(w, capture_buf, capture_size)
    assert len(capture_buf.raw) == capture_size

