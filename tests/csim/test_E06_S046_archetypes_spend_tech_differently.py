def test_R_046_04_effective_attack_multiplied_by_it(lib, world_factory):
    """Given the attack multiplier, When an attack resolves (E-05 S-037), Then effective attack is multiplied by it; the defender's defense multiplier multiplies effective defense."""
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.TECHNOLOGY, 1)

    # Attacker 0: Conqueror at tech 60.0 -> attack multiplier = 1.096
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=100.0, tech=60.0)
    # Defender 1: Fortifier at tech 60.0 -> defense multiplier = 1.054
    set_faction(lib, w, 1, OMArchetype.FORTIFIER, budget=100.0, tech=60.0)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)

    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=10.0, population=50.0)
    set_region(lib, w, 1, tier=OMTier.HOME, military=40.0, economy=50.0, tension=10.0, population=50.0, faction_id=1)
    set_owner(lib, w, 0, 0, held_since=0)
    set_owner(lib, w, 1, 1, held_since=0)
    set_edge(lib, w, 0, 1, OMEdge.BORDER)

    # Inject attack: commit 20.0, mode SURPRISE (mode multiplier 0.5)
    # Base attack = 20.0 * 0.5 + 50.0 * 0.1 * 0.5 = 10.0 + 2.5 = 12.5
    # Expected effective_attack = base_attack * 1.096 = 12.5 * 1.096 = 13.7
    # Base defense = 40.0 + 0 entrenchment (held_since=now) = 40.0
    # Expected effective_defense = 40.0 * 1.054 = 42.16
    inject_intent(lib, w, 0, OMAction.ATTACK, 1, 0, 20.0, OMMode.SURPRISE)
    force_draws(lib, w, [1.0])  # stochastic draw 1.0

    lib.om_world_step(w)

    attacks = read_attacks(lib, w)
    assert len(attacks) == 1
    att = attacks[0]
    assert att.effective_attack == pytest.approx(12.5 * 1.096, abs=1e-3)
    assert att.effective_defense == pytest.approx(40.0 * 1.054, abs=1e-3)


def test_R_046_05_q_048_01_nothing_in(lib, world_factory):
    """Given the economy multiplier, When read, Then [Q-048-01: nothing in the sim consumes it today]."""
    w = world_factory(n_regions=1)
    lib.om_world_set_feature(w, OMFeature.TECHNOLOGY, 1)

    set_faction(lib, w, 0, OMArchetype.FORTIFIER, budget=0.0, tech=60.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=10.0, population=50.0)
    set_owner(lib, w, 0, 0)

    # Multiplier is computed per ALG-26
    atk, df, eco = _read_multipliers(lib, w, 0)
    assert eco == pytest.approx(1.048, abs=1e-5)

    # But nothing in the sim consumes it: step with DRIFT on, economy delta follows ALG-01 drift only
    lib.om_world_set_feature(w, OMFeature.DRIFT, 1)
    lib.om_world_step(w)
    # The economy field changed only according to standard drift, not multiplied by 1.048
    assert lib.om_region_field(w, 0, OMField.ECONOMY) != 50.0 * 1.048

