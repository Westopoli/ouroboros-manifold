def _read_multipliers(lib, w, faction_id):
    """Read the ALG-26 attack, defense, economy multipliers for faction_id."""
    if hasattr(lib, "om_faction_tech_multipliers"):
        atk, df, eco = ctypes.c_double(), ctypes.c_double(), ctypes.c_double()
        lib.om_faction_tech_multipliers(
            w, faction_id, ctypes.byref(atk), ctypes.byref(df), ctypes.byref(eco)
        )
        return atk.value, df.value, eco.value
    return (
        lib.om_faction_tech_attack(w, faction_id),
        lib.om_faction_tech_defense(w, faction_id),
        lib.om_faction_tech_economy(w, faction_id),
    )


def test_R_046_01_attack_1_096_defense_1(lib, world_factory):
    """Given a conqueror at tech 60, When multipliers are read, Then attack 1.096, defense 1.012, economy 1.012."""
    w = world_factory(n_regions=1)
    lib.om_world_set_feature(w, OMFeature.TECHNOLOGY, 1)

    # Conqueror coeff: attack 0.16, defense 0.02, economy 0.02
    # mult = 1 + 0.6 * coeff: attack 1.096, defense 1.012, economy 1.012
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=0.0, tech=60.0)

    atk, df, eco = _read_multipliers(lib, w, 0)
    assert atk == pytest.approx(1.096, abs=1e-5)
    assert df == pytest.approx(1.012, abs=1e-5)
    assert eco == pytest.approx(1.012, abs=1e-5)


