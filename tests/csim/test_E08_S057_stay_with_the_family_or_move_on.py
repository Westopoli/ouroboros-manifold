def test_R_057_03_p_0_8_min_1(lib, world_factory):
    """Given the home region's total field delta over the jump is D, When the base rotation probability is computed, Then p = 0.8 + min(1, D/200) · (0.1 − 0.8), so a quiet jump (D = 0) rotates at 0.8 and an active one (D ≥ 200) at 0.1."""
    w = world_factory(n_regions=2)

    # D = 0: quiet jump rotates at 0.8
    p0 = lib.om_selector_base_rotation_prob(w, delta=0.0)
    assert p0 == pytest.approx(0.8, abs=1e-5)

    # D = 100: half-way
    p100 = lib.om_selector_base_rotation_prob(w, delta=100.0)
    assert p100 == pytest.approx(0.8 + 0.5 * (0.1 - 0.8), abs=1e-5)  # 0.45

    # D = 200: active jump rotates at 0.1
    p200 = lib.om_selector_base_rotation_prob(w, delta=200.0)
    assert p200 == pytest.approx(0.1, abs=1e-5)

    # D = 300: clamped to 0.1
    p300 = lib.om_selector_base_rotation_prob(w, delta=300.0)
    assert p300 == pytest.approx(0.1, abs=1e-5)


def test_R_057_04_it_decays_with_c_never(lib, world_factory):
    """Given chapters played in the lineage is c ≥ 2, When the stay probability is computed, Then it decays with c and never reaches 0 or a hard cap [Q-057-01: proposed p_rotate = base p + (1 − base p) · (1 − 0.75^(c − 2))]."""
    w = world_factory(n_regions=2)
    base_p = 0.5

    # For c = 2: p_rotate = base_p + (1 - base_p) * (1 - 1.0) = base_p; stay_p = 1 - base_p
    p_rot_c2 = lib.om_selector_decayed_rotation_prob(w, base_p=base_p, chapters=2)
    assert p_rot_c2 == pytest.approx(base_p, abs=1e-5)

    # For c = 3: p_rotate = base_p + (1 - base_p) * 0.25; stay_p = (1 - base_p) * 0.75
    p_rot_c3 = lib.om_selector_decayed_rotation_prob(w, base_p=base_p, chapters=3)
    assert p_rot_c3 == pytest.approx(base_p + (1.0 - base_p) * (1.0 - 0.75), abs=1e-5)

    # For c = 10: stay prob > 0, never hard-caps at 1.0 rotation
    p_rot_c10 = lib.om_selector_decayed_rotation_prob(w, base_p=base_p, chapters=10)
    stay_prob_c10 = 1.0 - p_rot_c10
    assert stay_prob_c10 > 0.0
    assert p_rot_c10 < 1.0


