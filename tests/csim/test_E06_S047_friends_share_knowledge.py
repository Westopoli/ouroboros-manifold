def test_R_047_04_growth_applies_first_convergence_reads(lib, world_factory):
    """Given tech growth and convergence on the same tick, When applied, Then growth applies first, then convergence reads the updated levels in faction order."""
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.TECHNOLOGY, 1)

    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=30.0)
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=0.0, tech=70.0)
    set_stance(lib, w, 0, 1, OMStance.COOPERATIVE)

    # Faction 0 has 0 growth (eco 0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=0.0, tension=10.0, population=0.0)
    # Faction 1 has growth: eco 60, pop 50 -> growth = 0.35 * 0.6 * 0.5 = 0.105 -> post-growth tech = 70.105
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=60.0, tension=10.0, population=50.0)
    set_owner(lib, w, 0, 0)
    set_owner(lib, w, 1, 1)

    lib.om_world_step(w)

    # If growth applied first: partner B has tech 70.105; diff = 70.105 - 30.0 = 40.105; bonus = 0.040105
    # Faction 0 final tech = 30.040105.
    # If convergence ran before growth: diff = 40.0; bonus = 0.04; tech = 30.04.
    assert lib.om_faction_tech(w, 0) == pytest.approx(30.040105, abs=1e-5)

