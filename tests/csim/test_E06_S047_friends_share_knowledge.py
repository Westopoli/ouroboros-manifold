def test_R_047_01_bonus_0_1_40_100(lib, world_factory):
    """Given faction A at tech 30 cooperative with B at tech 70 and C at tech 50, When convergence runs for A, Then bonus = 0.1 · 40/100 = 0.04 from B only."""
    w = world_factory(n_regions=3)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.TECHNOLOGY, 1)

    # 3 factions: A(0) at 30, B(1) at 70, C(2) at 50
    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=30.0)
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=0.0, tech=70.0)
    set_faction(lib, w, 2, OMArchetype.DEFAULT, budget=0.0, tech=50.0)

    set_stance(lib, w, 0, 1, OMStance.COOPERATIVE)
    set_stance(lib, w, 0, 2, OMStance.COOPERATIVE)

    # Regions with 0 economy so growth is 0, isolating convergence bonus
    for i in range(3):
        set_region(lib, w, i, tier=OMTier.HOME, military=50.0, economy=0.0, tension=10.0, population=0.0)
        set_owner(lib, w, i, i)

    lib.om_world_step(w)

    # Max partner above A is B(70) with diff 40 -> bonus = 0.1 * 40 / 100 = 0.04 (from B only, not sum)
    assert lib.om_faction_tech(w, 0) == pytest.approx(30.04, abs=1e-5)


