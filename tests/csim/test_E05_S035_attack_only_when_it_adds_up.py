def test_R_035_06_colonize_score_0_30_1(lib, world_factory):
    """Given best colonize attractiveness 0.30 and a conqueror, When scored, Then colonize score = 0.30 · 1.0 = 0.30, so attack wins."""
    # Given: Best colonize attractiveness 0.30 and a Conqueror (w_attack = 1.2, w_expand = 1.0)
    w = world_factory(n_regions=3)
    isolate_agents(lib, w)
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=100.0, confidence=2.0)
    set_faction(lib, w, 1, OMArchetype.DEFAULT)
    # Stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    # Tech multipliers 1.0 (neutral baseline, no tech)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)
    # Attacker home region 0
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)
    # Enemy attack candidate region 1: net = 26.0 -> attack score = 0.78
    set_region(lib, w, 1, tier=OMTier.HOME, military=40.0, economy=50.0, tension=0.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)
    # Unowned colonize candidate region 2: military=25.0 gives factor_1 = 0.75; 0.40 * 0.75 = 0.30 attractiveness
    set_region(lib, w, 2, tier=OMTier.EMPTY, military=25.0, economy=0.0, tension=0.0, population=0.0, faction_id=-1)
    set_edge(lib, w, 0, 2, OMEdge.BOTH)

    force_draws(lib, w, [0.5])
    lib.om_world_step(w)

    candidates = read_candidates(lib, w, 0)
    col_cand = [cand for cand in candidates if cand.region_idx == 2 and cand.kind == OMCandKind.COLONIZE][0]
    assert col_cand.attractiveness == pytest.approx(0.30, abs=1e-6)

    att_cand = [cand for cand in candidates if cand.region_idx == 1 and cand.kind == OMCandKind.ATTACK][0]
    assert att_cand.net == pytest.approx(26.0, abs=1e-6)

    decisions = read_decisions(lib, w)
    assert len(decisions) >= 1  # one record per faction that ran 3d; faction 0 is first (ascending id)
    d = decisions[0]
    # Colonize score = 0.30 * 1.0 = 0.30; Attack score = 0.78; attack wins
    assert d.colonize_score == pytest.approx(0.30, abs=1e-6)
    assert d.attack_score == pytest.approx(0.78, abs=1e-6)
