def test_R_035_03_break_even_20_0_55(lib, world_factory):
    """Given budget 100, the weakest candidate at military 20, and attack confidence 5, When budget pressure is computed, Then break-even = 20·0.55/0.70 = 15.714, ratio = 6.364, pressure = 0.8/6.364, effective confidence = 5 · 0.1257 = 0.6286."""
