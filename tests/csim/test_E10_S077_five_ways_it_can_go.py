    r = ctypes.c_double(0.60)
    expected = 0.75 * 0.80 + 0.25 * 0.60  # 0.60 + 0.15 = 0.75

    final_score = lib.om_mission_compute_final_score(o, r)
    assert ctypes.c_double(final_score).value == pytest.approx(expected, abs=1e-5)

    # Test retention calculation: deployed power 200, unit 1 (power 100) at 50% HP, unit 2 (power 100) dead
    # surviving power = 100 * 0.5 = 50 -> retention = 50 / 200 = 0.25
    retention = lib.om_mission_compute_retention(
        ctypes.c_double(200.0),  # deployed power
        ctypes.c_double(50.0),   # surviving power weighted by HP
    )
    assert ctypes.c_double(retention).value == pytest.approx(0.25, abs=1e-5)


