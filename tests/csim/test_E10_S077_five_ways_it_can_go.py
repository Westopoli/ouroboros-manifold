def test_R_077_03_commander_fate_killed_else_survived(lib, world_factory):
    """Given the mission ends, When the commander's unit is dead, Then commander fate is killed, else survived [Q-077-01: the hub also names wounded]."""
    w = world_factory(n_regions=1)

    # 1. Commander killed: HP = 0
    fate_dead = lib.om_mission_eval_commander_fate(ctypes.c_double(0.0), ctypes.c_double(100.0))
    assert fate_dead == OMCommanderFate.KILLED

    # 2. Commander wounded: HP = 25 / 100 (< 30%)
    fate_wounded = lib.om_mission_eval_commander_fate(ctypes.c_double(25.0), ctypes.c_double(100.0))
    assert fate_wounded == OMCommanderFate.WOUNDED

    # 3. Commander survived: HP = 50 / 100 (>= 30%)
    fate_survived = lib.om_mission_eval_commander_fate(ctypes.c_double(50.0), ctypes.c_double(100.0))
    assert fate_survived == OMCommanderFate.SURVIVED


def test_R_077_04_band_revealed_only_at_mission(lib, world_factory):
    """Given the result, When shown, Then the band is revealed only at mission end, never during play."""
    w = world_factory(n_regions=1)
    lib.om_mission_setup_tactical(w, 0, 1000)

    # During play: mission has not ended
    assert lib.om_mission_is_ended(w) == 0
    band_during_play = lib.om_mission_get_band(w)
    assert band_during_play == OMMissionBand.UNKNOWN

    # At mission end
    lib.om_mission_end(w)
    assert lib.om_mission_is_ended(w) == 1
    band_at_end = lib.om_mission_get_band(w)
    assert band_at_end != OMMissionBand.UNKNOWN

