def test_R_077_01_final_0_75_o_0(lib, world_factory):
    """Given objective score o (weighted completion, failed objectives count 0) and retention r (surviving unit power/deployed power, capped at 1, with damaged units counted by HP fraction), When the final score is computed, Then final = 0.75 · o + 0.25 · r."""
    # Test formula directly with lib function
