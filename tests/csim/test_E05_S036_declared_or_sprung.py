def test_R_036_06_base_10_0_5_60(lib, world_factory):
    """Given a reinforce of commit 10 on a frontier region with military 30 and tension 50, When resolved, Then base = 10 · 0.5 · (60 − 30)/60 = 2.5 and Δmilitary = 2.5 · U(0.75, 1.25)."""
    # Frontier tier region with military 30.0 and tension 50.0
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    # Attacker commit = 50.0 (budget = 50/0.7)
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=50.0 / 0.70, confidence=2.0)
    # Defender budget = 10/0.3 so budget * 0.30 = 10.0 (smaller than attacker commit * 0.5 = 25.0)
    set_faction(lib, w, 1, OMArchetype.FORTIFIER, budget=10.0 / 0.30)
    # Stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    # Tech multipliers 1.0 (neutral baseline, no tech)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)
    # Held since -1 indicates held since the world began (entrenchment 2.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)
    set_region(lib, w, 1, tier=OMTier.FRONTIER, military=30.0, economy=60.0, tension=50.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)

    # Pin mode draw (0.1 < 0.9 -> telegraph) and reinforce prob draw (0.5 <= 1.0)
    # The rule states the distribution U(0.75, 1.25) without pinning it; we assert bounds
    force_draws(lib, w, [0.1, 0.5])
    lib.om_world_step(w)

    reinforces = read_reinforces(lib, w)
    assert len(reinforces) == 1
    r = reinforces[0]
    assert r.commit == pytest.approx(10.0, abs=1e-6)
    assert r.headroom == pytest.approx(0.5, abs=1e-6)
    assert r.base == pytest.approx(2.5, abs=1e-6)
    # Assert bounds of U(0.75, 1.25) and resulting delta
    assert 0.75 <= r.variance <= 1.25
    assert 2.5 * 0.75 <= r.d_military <= 2.5 * 1.25
    assert r.d_military == pytest.approx(r.base * r.variance, abs=1e-6)
    # Target region military updated by delta
    assert lib.om_region_field(w, 1, OMField.MILITARY) == pytest.approx(30.0 + r.d_military, abs=1e-6)

    # Tier ceiling boundary: frontier region at military 60.0 has headroom 0, receiving base = 0 and delta = 0
    w_cap = world_factory(n_regions=2)
    isolate_agents(lib, w_cap)
    set_faction(lib, w_cap, 0, OMArchetype.CONQUEROR, budget=50.0 / 0.70, confidence=2.0)
    set_faction(lib, w_cap, 1, OMArchetype.FORTIFIER, budget=10.0 / 0.30)
    set_stance(lib, w_cap, 0, 1, OMStance.HOSTILE)
    set_tech_multipliers(lib, w_cap, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w_cap, 1, 1.0, 1.0, 1.0)
    set_region(lib, w_cap, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w_cap, 0, 0, held_since=-1)
    set_region(lib, w_cap, 1, tier=OMTier.FRONTIER, military=60.0, economy=60.0, tension=50.0, population=50.0, faction_id=1)
    set_owner(lib, w_cap, 1, 1, held_since=-1)
    set_edge(lib, w_cap, 0, 1, OMEdge.BOTH)
    force_draws(lib, w_cap, [0.1, 0.5])
    lib.om_world_step(w_cap)
    r_cap = read_reinforces(lib, w_cap)[0]
    assert r_cap.headroom == pytest.approx(0.0, abs=1e-6)
    assert r_cap.base == pytest.approx(0.0, abs=1e-6)
    assert r_cap.d_military == pytest.approx(0.0, abs=1e-6)
