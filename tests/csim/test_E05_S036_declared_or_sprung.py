def test_R_036_03_it_resolves_in_step_3c(lib, world_factory):
    """Given a telegraphed attack declared on tick t, When tick t + 3 runs, Then it resolves in step 3c before any new decisions, at full efficiency; on ticks t + 1 and t + 2 it sits in the pending list; the defender's one reactive reinforce (R-036-05) happens in step 3e of tick t, the tick of declaration, not again on the waiting ticks."""
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=100.0, confidence=2.0)
    set_faction(lib, w, 1, OMArchetype.FORTIFIER, budget=50.0)
    # Stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    # Tech multipliers 1.0 (neutral baseline, no tech)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)
    # Held since -1 indicates held since the world began (entrenchment 2.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)
    set_region(lib, w, 1, tier=OMTier.HOME, military=40.0, economy=60.0, tension=0.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)

    # Tick t (tick 1): Attacker declares telegraphed attack (commit = 70.0)
    # Draws: mode selection < 0.9 (0.1), reactive reinforce prob <= 1.0 (0.5), variance (0.5)
    force_draws(lib, w, [0.1, 0.5, 0.5])
    lib.om_world_step(w)

    pending_t1 = read_telegraphs(lib, w)
    assert len(pending_t1) == 1
    assert pending_t1[0].declared_tick == 1
    assert pending_t1[0].attacker == 0
    assert pending_t1[0].target_idx == 1
    assert pending_t1[0].commit == pytest.approx(70.0, abs=1e-6)
    assert len(read_attacks(lib, w)) == 0
    # The one reactive reinforce fires in step 3e of the declaration tick
    reinforces_t1 = read_reinforces(lib, w)
    assert len(reinforces_t1) == 1
    assert reinforces_t1[0].commit > 0.0

    # Tick t + 1 (tick 2): sits in the pending list; no second reinforce
    force_draws(lib, w, [0.5, 0.5])
    lib.om_world_step(w)

    pending_t2 = read_telegraphs(lib, w)
    assert len(pending_t2) == 1
    assert pending_t2[0].declared_tick == 1
    assert len(read_attacks(lib, w)) == 0
    assert len(read_reinforces(lib, w)) == 0

    # Tick t + 2 (tick 3): still pending; still no reinforce
    force_draws(lib, w, [0.5, 0.5])
    lib.om_world_step(w)

    pending_t3 = read_telegraphs(lib, w)
    assert len(pending_t3) == 1
    assert pending_t3[0].declared_tick == 1
    assert len(read_attacks(lib, w)) == 0
    assert len(read_reinforces(lib, w)) == 0

    # Tick t + 3 (tick 4): Resolves in step 3c at full efficiency before new decisions
    force_draws(lib, w, [1.0])
    lib.om_world_step(w)

    pending_t4 = read_telegraphs(lib, w)
    assert len(pending_t4) == 0

    attacks_t4 = read_attacks(lib, w)
    assert len(attacks_t4) == 1
    att = attacks_t4[0]
    assert att.tick == 4
    assert att.mode == OMMode.TELEGRAPH
    assert att.commit == pytest.approx(70.0, abs=1e-6)
    # Full efficiency: effective attack multiplier is 1.0 (no surprise penalty)
    assert att.effective_attack == pytest.approx(70.0, abs=1e-6)


