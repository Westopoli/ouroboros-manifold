import pytest

from conftest import OMField, OMTier, read_drift, set_region  # adjust imports to what this epic's fixtures need


import ctypes

class OMDifficulty:
    EASY = 0
    MEDIUM = 1
    HARD = 2


class OMUnitProfile(ctypes.Structure):
    _fields_ = [
        ("unit_type", ctypes.c_uint32),
        ("hp", ctypes.c_double),
        ("base_damage", ctypes.c_double),
        ("attack_interval", ctypes.c_double),
        ("power", ctypes.c_double),
    ]


def test_R_080_01_both_sides_draw_from_same(lib, world_factory):
    """Given any difficulty, When forces are generated, Then both sides draw from the same unit profiles; no stat differs by difficulty."""
    # Unit profiles must have identical stats across EASY, MEDIUM, HARD
    for unit_type in range(6):  # 6 unit types in roster
        prof_easy = OMUnitProfile()
        prof_med = OMUnitProfile()
        prof_hard = OMUnitProfile()

        lib.om_unit_get_profile(unit_type, OMDifficulty.EASY, ctypes.byref(prof_easy))
        lib.om_unit_get_profile(unit_type, OMDifficulty.MEDIUM, ctypes.byref(prof_med))
        lib.om_unit_get_profile(unit_type, OMDifficulty.HARD, ctypes.byref(prof_hard))

        # An accessor that leaves `out` zeroed for every difficulty would
        # satisfy the cross-difficulty equality below with no roster at all.
        assert prof_easy.hp > 0, "unit profile must be a real (nonzero) roster baseline"
        assert prof_easy.hp == prof_med.hp == prof_hard.hp
        assert prof_easy.base_damage == prof_med.base_damage == prof_hard.base_damage
        assert prof_easy.attack_interval == prof_med.attack_interval == prof_hard.attack_interval
        assert prof_easy.power == prof_med.power == prof_hard.power


def test_R_080_02_r_074_03_applies_nothing(lib, world_factory):
    """Given easy, medium, hard, When parity is computed, Then R-074-03 applies and nothing else changes at launch [Q-080-01]."""
    # base_parity = 1.2 (R-074-03: easy floor 0.95, hard ceiling 0.85)
    # easy: max(0.95, 1.2) = 1.2
    # medium: 1.2
    # hard: min(0.85, 1.2) = 0.85
    p_easy = lib.om_mission_compute_parity(ctypes.c_double(1.2), OMDifficulty.EASY)
    p_med = lib.om_mission_compute_parity(ctypes.c_double(1.2), OMDifficulty.MEDIUM)
    p_hard = lib.om_mission_compute_parity(ctypes.c_double(1.2), OMDifficulty.HARD)

    assert ctypes.c_double(p_easy).value == pytest.approx(1.2, abs=1e-5)
    assert ctypes.c_double(p_med).value == pytest.approx(1.2, abs=1e-5)
    assert ctypes.c_double(p_hard).value == pytest.approx(0.85, abs=1e-5)

    # base_parity = 0.8
    # easy: max(0.95, 0.8) = 0.95
    # medium: 0.8
    # hard: min(0.85, 0.8) = 0.8
    p_easy_low = lib.om_mission_compute_parity(ctypes.c_double(0.8), OMDifficulty.EASY)
    p_med_low = lib.om_mission_compute_parity(ctypes.c_double(0.8), OMDifficulty.MEDIUM)
    p_hard_low = lib.om_mission_compute_parity(ctypes.c_double(0.8), OMDifficulty.HARD)

    assert ctypes.c_double(p_easy_low).value == pytest.approx(0.95, abs=1e-5)
    assert ctypes.c_double(p_med_low).value == pytest.approx(0.8, abs=1e-5)
    assert ctypes.c_double(p_hard_low).value == pytest.approx(0.8, abs=1e-5)


def test_R_080_03_rare_archetype_can_still_be(lib, world_factory):
    """Given a mission preference marked rare, When the world has no other viable candidate, Then the rare archetype can still be chosen (preference 0.1, never 0)."""
    w = world_factory(n_regions=1)

    # Archetype 0 marked rare -> preference factor = 0.1
    pref_weight = lib.om_mission_get_archetype_preference_weight(w, 0, 1)  # is_rare = 1
    assert ctypes.c_double(pref_weight).value == pytest.approx(0.1, abs=1e-5)

    # Set up situation where archetype 0 is the only viable candidate
    lib.om_mission_set_candidate_viable(w, 0, 1)
    for other_arch in range(1, 10):
        lib.om_mission_set_candidate_viable(w, other_arch, 0)

    chosen_arch = lib.om_mission_select_candidate(w)
    assert chosen_arch == 0

