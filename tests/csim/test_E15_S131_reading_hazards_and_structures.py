import ctypes

class OMHazardType:
    SENSOR_INTERFERENCE = 0
    DRAG = 1
    DAMAGE = 2
    BOOST = 3
    DISRUPTION = 4


def test_R_131_01_structures_distinguishable_by_owner_color(lib, world_factory):
    """Given a T2 screenshot, When inspected, Then structures are distinguishable by owner color and from every unit silhouette; interference zones read as obscuring volumes; convoys read as non-combat."""
    w = world_factory(n_regions=1)

    # Settlement/structure silhouette differs from unit silhouettes (Q-131-01)
    structure_sil = lib.om_render_get_structure_silhouette_id()
    for unit_type in range(6):
        unit_sil = lib.om_render_get_unit_silhouette_id(unit_type)
        assert structure_sil != unit_sil

    # Distinguishable colors by owner: player (1), enemy (2), neutral (0)
    color_p = lib.om_render_get_owner_color(1)
    color_e = lib.om_render_get_owner_color(2)
    color_n = lib.om_render_get_owner_color(0)
    assert color_p != color_e
    assert color_p != color_n
    assert color_e != color_n

    # Interference zone reads as obscuring volume
    is_obscuring = lib.om_render_is_volume_obscuring(OMHazardType.SENSOR_INTERFERENCE)
    assert is_obscuring == 1


def test_R_131_02_it_exactly_one_type_sensor(lib, world_factory):
    """Given the launch hazard list, When read, Then it is exactly one type, sensor interference; drag, damage, boost, and disruption zones are future gradient tags with no engine change."""
    # Launch hazard count is exactly 1
    hazard_count = lib.om_hazard_launch_type_count()
    assert hazard_count == 1

    hazard_types = (ctypes.c_uint32 * hazard_count)()
    lib.om_hazard_get_launch_types(hazard_types, hazard_count)

    # Exactly one type: SENSOR_INTERFERENCE
    assert hazard_types[0] == OMHazardType.SENSOR_INTERFERENCE

    # Others are not enabled at launch
    assert lib.om_hazard_is_enabled_at_launch(OMHazardType.DRAG) == 0
    assert lib.om_hazard_is_enabled_at_launch(OMHazardType.DAMAGE) == 0
    assert lib.om_hazard_is_enabled_at_launch(OMHazardType.BOOST) == 0
    assert lib.om_hazard_is_enabled_at_launch(OMHazardType.DISRUPTION) == 0

