def test_R_083_02_it_modifies_one_stat_or(lib, world_factory):
    """Given a trait, When applied, Then it modifies one stat or one multiplier by a fixed amount stated in the profile [Q-083-01: no trait exists in code]."""
    w = world_factory(n_regions=1)

    # Apply a trait with a fixed stat modifier (e.g., +20.0 max HP) to a unit
    u = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 0.0, 0.0, 0)
    base_hp = lib.om_unit_hp(w, u)

    lib.om_unit_apply_trait_modifier(w, u, 0, 20.0)  # stat_field=HP, delta=+20.0
    modified_hp = lib.om_unit_hp(w, u)
    assert modified_hp == pytest.approx(base_hp + 20.0, abs=1e-6)


def test_R_083_03_that_unit_takes_10_percent(lib, world_factory):
    """Given a Warden, When any friendly unit is within 300 wu, Then that unit takes 10 percent less damage and regains 0.075 HP per tick (the Warden's passive aura), stacking with no other Warden."""
    w = world_factory(n_regions=1)

    # Spawn friendly Vanguard within 300 wu of Warden (distance 100 wu)
    warden = lib.om_unit_spawn(w, OMUnitType.WARDEN, 0, 0.0, 0.0, 0)
    friendly_in = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 100.0, 0.0, 0)
    lib.om_unit_set_hp(w, friendly_in, 400.0)  # damaged (max 500)

    # Spawn friendly Vanguard outside 300 wu (distance 350 wu)
    friendly_out = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 350.0, 0.0, 0)
    lib.om_unit_set_hp(w, friendly_out, 400.0)

    # Enemy attacker: same category (Line) as the Vanguard targets so the
    # R-081-01 category multiplier (Strike->Line 0.75x, see ALG-60) does not
    # confound the aura reduction this rule is testing.

    # Advance 1 tick: Warden aura repairs friendly_in by 0.075 HP, friendly_out by 0.0
    lib.om_tactical_step(w)
    assert lib.om_unit_hp(w, friendly_in) == pytest.approx(400.075, abs=1e-6)
    assert lib.om_unit_hp(w, friendly_out) == pytest.approx(400.0, abs=1e-6)

    # Test-defect, A163/A164: enemy spawned after the first tick, was spawned before it; cause: aligned targeting cohort (parity with the Python, Addendum 63): the enemy's first shot moved to tick 1, which broke the 400.075 pin of the aura heal alone.
    enemy = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 1, 100.0, 50.0, 0)

    # Damage test: 10% reduction for friendly_in
    base_hit = 50.0
    hp_before_in = lib.om_unit_hp(w, friendly_in)
    lib.om_unit_deal_damage(w, enemy, friendly_in, base_hit)
    dmg_in = hp_before_in - lib.om_unit_hp(w, friendly_in)
    # With 10% reduction: takes 50.0 * 0.9 = 45.0
    assert dmg_in == pytest.approx(base_hit * 0.90, abs=1e-6)

    # Friendly outside takes 0% reduction (full 50.0)
    hp_before_out = lib.om_unit_hp(w, friendly_out)
    lib.om_unit_deal_damage(w, enemy, friendly_out, base_hit)
    dmg_out = hp_before_out - lib.om_unit_hp(w, friendly_out)
    assert dmg_out == pytest.approx(base_hit, abs=1e-6)

    # Multiple Wardens: Q-084-01 closed 2026-10-20 "no stacking" (R-083-03): a second Warden changes neither the reduction (0.10) nor the heal (0.075 HP/tick)
    # Test-defect, F4 engine rule fixes 2026-11-08: the pin was the old diminishing/stacking numbers (0.150 HP/tick); cause: R-083-03 and Q-084-01 say Wardens do not stack, the test was stale.
    # Test-defect, A163/A164: enemy stays in range -> enemy moved out of reach before the heal tick; cause: aligned targeting cohort (parity with the Python, Addendum 63): the enemy now fires within the tick and would mask the 0.150 heal delta.
    lib.om_unit_teleport(w, enemy, 5000.0, 5000.0, 0)
    warden2 = lib.om_unit_spawn(w, OMUnitType.WARDEN, 0, 50.0, 0.0, 0)
    hp_pre_multi = lib.om_unit_hp(w, friendly_in)
    lib.om_tactical_step(w)
    assert lib.om_unit_hp(w, friendly_in) - hp_pre_multi == pytest.approx(0.075, abs=1e-6)

