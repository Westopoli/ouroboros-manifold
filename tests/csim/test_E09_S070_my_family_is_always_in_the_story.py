def test_R_070_03_it_military_rank_no_lineage(lib, world_factory):
    """Given a lineage member appears in a fragment, When their rank is rendered, Then it is a military rank; no lineage member is ever framed as a governor, trader, or political leader."""
    w = world_factory(n_regions=2)

    lib.om_lineage_create(w, lineage_id=1, home_region=0)
    lib.om_character_create(w, character_id=5, lineage_id=1, region_idx=0, rank=3, birth_tick=0, lifespan=100)

    rank_str_ptr = lib.om_chronicle_render_character_rank(w, character_id=5)
    rank_str = ctypes.string_at(rank_str_ptr).decode("utf-8").lower()

    # Must not be civilian or political
    for forbidden in ["governor", "trader", "political leader", "magistrate", "senator", "merchant"]:
        assert forbidden not in rank_str

    # Must be a military designation
    military_terms = ["commander", "captain", "officer", "lieutenant", "general", "soldier", "vanguard", "marshal"]
    assert any(term in rank_str for term in military_terms)
