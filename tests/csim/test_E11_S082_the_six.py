def test_R_082_03_bastion_has_most_by_at(lib, world_factory):
    """Given the roster, When ordered by HP, Then the Bastion has the most by at least 2× the next, and the Raider the least."""
    w = world_factory(n_regions=1)

    all_units = [
        OMUnitType.RAIDER,
        OMUnitType.INTERCEPTOR,
        OMUnitType.VANGUARD,
        OMUnitType.WARDEN,
        OMUnitType.BOMBARD,
        OMUnitType.BASTION,
    ]
    hps = {u: lib.om_unit_profile_max_hp(w, u) for u in all_units}

    bastion_hp = hps[OMUnitType.BASTION]
    other_hps = [hp for u, hp in hps.items() if u != OMUnitType.BASTION]
    next_highest_hp = max(other_hps)

    assert bastion_hp >= 2.0 * next_highest_hp
    assert hps[OMUnitType.RAIDER] == min(hps.values())


