def test_R_030_01_it_contains_exactly_26_templates(lib, world_factory):
    """Given the launch library, When loaded, Then it contains exactly the 26 templates in the table below with these triggers, effects, spawns, and exclusion tags, and a contract test compares the loaded library to the table field by field."""
    # Unstated values neutral: HOME tier region, hostile stances, 1.0 tech multipliers.
    w = world_factory(n_regions=1)
    isolate_events(lib, w)
    load_launch_events(lib, w)

    count = lib.om_event_template_count(w)
    assert count == 26

    for tid, exp in enumerate(LAUNCH_TEMPLATES):
        t = get_template(lib, w, tid)

        # Field-by-field verification against the S-030 table
        assert t.id == tid
        raw_name = t.name.decode("utf-8").rstrip("\x00")
        assert raw_name == exp["name"]
        assert template_id(lib, w, exp["name"]) == tid

        assert t.trigger_kind == exp["trigger_kind"]
        if exp["trigger_kind"] != OMTrigger.NONE:
            assert t.trigger_field == exp["trigger_field"]

        if exp["trigger_kind"] in (OMTrigger.ABOVE, OMTrigger.BELOW):
            assert t.threshold == pytest.approx(exp["threshold"], abs=1e-6)
        elif exp["trigger_kind"] == OMTrigger.PROBABILITY:
            assert t.prob_base == pytest.approx(exp["prob_base"], abs=1e-6)
            assert t.prob_exponent == pytest.approx(exp["prob_exponent"], abs=1e-6)
            assert t.cooldown_ticks == exp["cooldown_ticks"]

        for f_idx, exp_delta in enumerate(exp["effect"]):
            assert t.effect[f_idx] == pytest.approx(exp_delta, abs=1e-6)

        assert t.exclusion_tag == exp["exclusion_tag"]
        assert t.creates_faction == exp["creates_faction"]
        assert t.admin_chain_step == exp["admin_chain_step"]

        assert t.n_spawns == len(exp["spawns"])
        for s_idx, (exp_target, s_min, s_max, s_prob, c_kind, c_field, c_val) in enumerate(exp["spawns"]):
            spawn = t.spawns[s_idx]
            assert spawn.template_id == template_id(lib, w, exp_target)
            assert spawn.delay_min == s_min
            assert spawn.delay_max == s_max
            assert spawn.probability == pytest.approx(s_prob, abs=1e-6)
            assert spawn.cond_kind == c_kind
            assert spawn.cond_field == c_field
            assert spawn.cond_value == pytest.approx(c_val, abs=1e-6)


def test_R_030_02_a_it_never_starts_chain_it(lib, world_factory):
    """Given a template with no trigger, When triggers are evaluated, Then it never starts a chain.
    Split from the original R-030-02 test (audit 2026-09-21, R14): this half
    reaches only om_tick_events (208b3's symbol, and om_event_set_noise,
    208b1's, both released before 209c owns the "fires only as a spawn"
    half below) -- card 208b3's own acceptance."""
    # Unstated values neutral: HOME tier region, hostile stances, 1.0 tech multipliers.
    w = world_factory(n_regions=1)
    isolate_events(lib, w)
    load_launch_events(lib, w)
    zero_all_noise(lib, w)

    # Pick a representative template with no trigger: "Border Incursion"
    tid = template_id(lib, w, "Border Incursion")
    t = get_template(lib, w, tid)
    assert t.trigger_kind == OMTrigger.NONE

    # Set region fields such that no other triggers fire
    set_region(lib, w, 0, tier=OMTier.HOME, military=40.0, economy=45.0, tension=0.0, population=45.0)

    # Step through grace period ticks 1..3 (ALG-33, R-026-05)
    for _ in range(3):
        lib.om_world_step(w)

    # Tick 4: triggers actively evaluated across all inhabited regions
    lib.om_world_step(w)
    events_t4 = read_events(lib, w)

    # A template with no trigger never starts a chain when triggers evaluate
    assert not any(e.template_id == tid for e in events_t4)
    assert not any(e.source == OMSource.TRIGGER for e in events_t4 if e.template_id == tid)


def test_R_030_02_b_it_fires_only_as_a_spawn(lib, world_factory):
    """Given a template with no trigger already queued externally, When the queue resolves, Then it fires only as a spawn.
    Split from the original R-030-02 test (audit 2026-09-21, R14): this half
    reaches om_event_queue_external (209c's own symbol) -- card 209c's
    acceptance. Repeats the same fixture through tick 4 as the _a half
    above (each test is independent); om_tick_events and om_event_set_noise
    are 208b3's and 208b1's symbols, both released before 209c."""
    w = world_factory(n_regions=1)
    isolate_events(lib, w)
    load_launch_events(lib, w)
    zero_all_noise(lib, w)

    tid = template_id(lib, w, "Border Incursion")
    assert get_template(lib, w, tid).trigger_kind == OMTrigger.NONE

    set_region(lib, w, 0, tier=OMTier.HOME, military=40.0, economy=45.0, tension=0.0, population=45.0)

    for _ in range(3):
        lib.om_world_step(w)
    lib.om_world_step(w)  # tick 4

    # Now queue it as a spawn due on tick 5
    assigned_tag = queue_external(lib, w, region_idx=0, tid=tid, due_tick=5, probability=1.0)
    assert assigned_tag >= 0

    # Step tick 5: queue resolution evaluates due entries
    lib.om_world_step(w)
    events_t5 = read_events(lib, w)

    # It fires only as a spawn
    spawn_firings = [e for e in events_t5 if e.template_id == tid]
    assert len(spawn_firings) == 1
    fired = spawn_firings[0]
    assert fired.source in (OMSource.SPAWN, OMSource.EXTERNAL)
    assert fired.chain_tag == assigned_tag


