def test_R_118_03_no_unit_teleports_units_path(lib, world_factory):
    """Given a moving node, When it moves, Then no unit teleports; units path to the new position under their standing orders."""
    w = world_factory(n_regions=1)
    node_id = 0
    lib.om_map_setup_drifting_node(w, node_id, 200)

    # Unit parked at node's initial location (100, 100)
    unit_id = lib.om_unit_spawn_combat(w, 0, ctypes.c_double(100.0), ctypes.c_double(100.0))
    lib.om_unit_order_hold_node(w, unit_id, node_id)

    # Advance 1 tick: node moves slightly
    lib.om_tactical_tick(w)

    unit_pos = OMVec2()
    lib.om_unit_get_position(w, unit_id, ctypes.byref(unit_pos))

    # Unit does NOT instantly teleport to new node pos
    # Unit position delta in 1 tick is bounded by max unit move speed per tick (e.g. <= 10 wu)
    dx = unit_pos.x - 100.0
    dy = unit_pos.y - 100.0
    dist_moved = (dx * dx + dy * dy) ** 0.5
    assert dist_moved < 20.0  # reasonable step, no teleportation

