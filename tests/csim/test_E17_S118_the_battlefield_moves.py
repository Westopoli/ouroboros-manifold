def test_R_118_01_its_position_follows_path_ping(lib, world_factory):
    """Given a spine node of type objective or reinforcement_structure with a drift path, When ticks pass, Then its position follows the path (ping-pong or loop over waypoints with a period in ticks) and the objective zone moves with it."""
    w = world_factory(n_regions=1)
    lib.om_map_setup_drifting_node(w, 0, 100)  # node 0, period 100 ticks

    start_pos = OMVec2()
    lib.om_map_get_node_pos(w, 0, ctypes.byref(start_pos))

    # Advance 50 ticks
    lib.om_tactical_tick_to(w, 50)
    mid_pos = OMVec2()
    lib.om_map_get_node_pos(w, 0, ctypes.byref(mid_pos))

    assert mid_pos.x != start_pos.x or mid_pos.y != start_pos.y

    # Objective zone moves with the node
    zone_pos = OMVec2()
    lib.om_objective_get_center(w, 0, ctypes.byref(zone_pos))
    assert zone_pos.x == pytest.approx(mid_pos.x, abs=1e-4)
    assert zone_pos.y == pytest.approx(mid_pos.y, abs=1e-4)


