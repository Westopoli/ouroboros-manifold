def test_R_065_02_they_form_one_consequence_cluster(lib, world_factory):
    """Given events flagged as consequences of the last mission, When clusters are ranked, Then they form one consequence cluster that is entry 1, categorized success, failure, or mixed by the mission outcome."""
    w = world_factory(n_regions=4)

    # Flag consequence event with mission outcome success
    lib.om_chronicle_add_consequence_event(w, region_idx=1, outcome=OMOutcomeCategory.SUCCESS)
    lib.om_chronicle_distill_and_assemble(w)

    # Entry 1 (index 0) must be the consequence cluster
