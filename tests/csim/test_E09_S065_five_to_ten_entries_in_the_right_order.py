def test_R_065_03_every_lineage_cluster_included_regardless(lib, world_factory):
    """Given the player's lineage, When clusters are ranked, Then every lineage cluster is included regardless of score, one per region the lineage touched."""
    w = world_factory(n_regions=4)

    lib.om_lineage_create(w, lineage_id=1, home_region=0)
    # Add lineage events in regions 1 and 2 with low scores
    lib.om_chronicle_add_lineage_event(w, lineage_id=1, region_idx=1, category=4, score=1.0)
    lib.om_chronicle_add_lineage_event(w, lineage_id=1, region_idx=2, category=4, score=1.2)

    # Add 10 non-lineage events with high scores (e.g. 10.0)
    for r in range(10):
        lib.om_chronicle_add_event(w, region_idx=3, score=10.0)

    lib.om_chronicle_distill_and_assemble(w)

    # Both lineage regions must be present in chronicle clusters
    lineage_regions = set()
    n = lib.om_chronicle_entry_count(w)
    for i in range(n):
        c = OmChronicleCluster()
        lib.om_chronicle_get_cluster(w, i, ctypes.byref(c))
        if c.type == OMClusterType.LINEAGE:
            lineage_regions.add(c.region)

    assert 1 in lineage_regions
    assert 2 in lineage_regions


def test_R_065_04_one_lineage_quiet_cluster_included(lib, world_factory):
    """Given no event touched the lineage, When clusters are ranked, Then one `lineage_quiet` cluster is included, placed in the lineage's most recent region."""
    w = world_factory(n_regions=4)

    lib.om_lineage_create(w, lineage_id=1, home_region=2)
    lib.om_lineage_record_history_region(w, lineage_id=1, region_idx=3)  # most recent region

    # No events touch lineage
    lib.om_chronicle_mock_populate_events(w, n_events=10)
    lib.om_chronicle_distill_and_assemble(w)

    # One lineage_quiet cluster in region 3
    has_lineage_quiet = False
    n = lib.om_chronicle_entry_count(w)
    for i in range(n):
        c = OmChronicleCluster()
        lib.om_chronicle_get_cluster(w, i, ctypes.byref(c))
        if c.type == OMClusterType.LINEAGE:
            cat_name = lib.om_chronicle_category_name(c.category)
            if b"quiet" in ctypes.string_at(cat_name):
                has_lineage_quiet = True
                assert c.region == 3

    assert has_lineage_quiet


def test_R_065_05_they_taken_in_descending_peak(lib, world_factory):
    """Given the remaining clusters, When the budget is filled, Then they are taken in descending peak score, skipping any category that already has 2 entries, until 10 entries."""
    w = world_factory(n_regions=6)

    # Create 5 clusters in category 10 with peak scores 9.0, 8.0, 7.0, 6.0, 5.0
    for i, s in enumerate([9.0, 8.0, 7.0, 6.0, 5.0]):
        lib.om_chronicle_add_cluster_direct(w, cluster_type=OMClusterType.REGIONAL, category=10, score=s)

    # Create 3 clusters in category 11 with scores 8.5, 7.5, 6.5
    for i, s in enumerate([8.5, 7.5, 6.5]):
        lib.om_chronicle_add_cluster_direct(w, cluster_type=OMClusterType.REGIONAL, category=11, score=s)

    lib.om_chronicle_select_clusters(w)

    # Count entries per category in selected entries
    cat10_count = lib.om_chronicle_selected_category_count(w, category=10)
    cat11_count = lib.om_chronicle_selected_category_count(w, category=11)

    # Cap of 2 entries per category: 2 from category 10, 2 from category 11.
    # R-065-06 (Q-065-01 ruling 2026-10-01): the cap wins over the minimum of
    # 5, so the scroll stops at 4. Reversed from the earlier expectation of
    # cat10 == 3 and 5 entries (test-defect, push ledger).
    assert cat10_count == 2
    assert cat11_count == 2
    assert lib.om_chronicle_entry_count(w) == 4


def test_R_065_06_skipped_clusters_added_in_score(lib, world_factory):
    """Given fewer than 5 entries after ranking, When the budget is filled, Then skipped clusters are added in score order only from categories that still have fewer than 2 entries; the cap wins, so a quiet jump may show 4."""
    w = world_factory(n_regions=4)

    # One category with 5 clusters: the cap holds it to 2 even though that is below 5.
    for s in [10.0, 9.0, 8.0, 7.0, 6.0]:
        lib.om_chronicle_add_cluster_direct(w, cluster_type=OMClusterType.REGIONAL, category=10, score=s)
    lib.om_chronicle_select_clusters(w)
    assert lib.om_chronicle_entry_count(w) == 2
    assert lib.om_chronicle_selected_category_count(w, category=10) == 2


def test_R_065_06_a_quiet_jump_may_show_four_entries(lib, world_factory):
    """Given two categories with 3 clusters each, When the budget is filled, Then 4 entries are selected (2 per category) and the minimum of 5 does not break the cap."""
    w = world_factory(n_regions=4)

    for s in [10.0, 9.0, 8.0]:
        lib.om_chronicle_add_cluster_direct(w, cluster_type=OMClusterType.REGIONAL, category=10, score=s)
    for s in [9.5, 8.5, 7.5]:
        lib.om_chronicle_add_cluster_direct(w, cluster_type=OMClusterType.REGIONAL, category=11, score=s)
    lib.om_chronicle_select_clusters(w)

    assert lib.om_chronicle_entry_count(w) == 4
    assert lib.om_chronicle_selected_category_count(w, category=10) == 2
    assert lib.om_chronicle_selected_category_count(w, category=11) == 2


