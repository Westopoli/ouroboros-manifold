def test_R_091_01_cross_layer_factors_double_extend(lib, world_factory):
    """Given a unit within a vantage node's radius (default 100 wu), When visibility is computed, Then cross-layer factors double and extend one layer (E-01 R-005-06)."""
    w = world_factory(n_regions=1)

    # Vantage node placed at (0, 0) with default radius 100.0 wu
    lib.om_map_add_vantage_node(w, 0.0, 0.0, 100.0)

    # Unit within vantage node radius (e.g. at (50, 0), d = 50 <= 100) on layer 0
    obs_inside = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 50.0, 0.0, 0)

    # Per E-01 R-005-06:
    # Adjacent layer factor doubles from 0.50 to 1.00
    # Two-layer factor doubles from 0.20 to 0.40
    # Three-layer factor extends one layer to 0.20
    adj_factor = lib.om_unit_get_cross_layer_factor(w, obs_inside, 1)
    two_layer_factor = lib.om_unit_get_cross_layer_factor(w, obs_inside, 2)
    three_layer_factor = lib.om_unit_get_cross_layer_factor(w, obs_inside, 3)

    assert pytest.approx(adj_factor, abs=1e-4) == 1.00
    assert pytest.approx(two_layer_factor, abs=1e-4) == 0.40
    assert pytest.approx(three_layer_factor, abs=1e-4) == 0.20

    # Unit outside vantage radius (at (150, 0), d = 150 > 100): normal factors apply (0.50, 0.20, 0.00)
    obs_outside = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 150.0, 0.0, 0)
    assert pytest.approx(lib.om_unit_get_cross_layer_factor(w, obs_outside, 1), abs=1e-4) == 0.50
    assert pytest.approx(lib.om_unit_get_cross_layer_factor(w, obs_outside, 2), abs=1e-4) == 0.20
    assert pytest.approx(lib.om_unit_get_cross_layer_factor(w, obs_outside, 3), abs=1e-4) == 0.00


def test_R_091_02_observer_s_effective_radius_multiplied(lib, world_factory):
    """Given an elevation tier difference of d between observer and target, When the era enables elevation sensor bonus, Then the observer's effective radius is multiplied by 1 + 0.15 · d [Q-092-01: the tier is read at csrc/fog.c:462-464]."""
    w = world_factory(n_regions=1)

    # Enable elevation sensor bonus era flag
    lib.om_set_era_flag(w, b"elevation_sensor_bonus", 1)

    # Observer Vanguard (base sensor radius 700 wu) at elevation tier 3
    obs = lib.om_unit_spawn_with_elevation(w, OMUnitType.VANGUARD, 0, 0.0, 0.0, 0, 3)

    # Target at elevation tier 1 -> elevation tier diff d = 3 - 1 = 2
    # Expected multiplier = 1 + 0.15 * 2 = 1.30
    # Effective radius = 700 * 1.30 = 910.0 wu
    eff_radius = lib.om_unit_get_effective_sensor_radius_to_target_elevation(w, obs, 1)
    assert pytest.approx(eff_radius, abs=1e-4) == 910.0

    # Three-fixture distance check around 910.0 wu:
    # 909 wu -> visible
    target_below = lib.om_unit_spawn_with_elevation(w, OMUnitType.RAIDER, 1, 909.0, 0.0, 0, 1)
    # 910 wu -> visible
    target_at = lib.om_unit_spawn_with_elevation(w, OMUnitType.RAIDER, 1, 0.0, 910.0, 0, 1)
    # 911 wu -> not visible
    target_above = lib.om_unit_spawn_with_elevation(w, OMUnitType.RAIDER, 1, 0.0, -911.0, 0, 1)

    lib.om_visibility_compute(w)
    assert lib.om_unit_can_see(w, obs, target_below) == 1
    assert lib.om_unit_can_see(w, obs, target_at) == 1
    assert lib.om_unit_can_see(w, obs, target_above) == 0


def test_R_091_03_it_affects_sensors_only_never(lib, world_factory):
    """Given the Settled Reach, When elevation is read, Then it affects sensors only, never damage (E-11 R-084-06)."""
    w = world_factory(n_regions=1)

    # Settled Reach era configuration
    lib.om_set_era_name(w, b"Settled Reach")

    # Attacker Raider at elevation tier 3, Defender Raider at elevation tier 1 (tier diff d = 2)
    # Raider base damage per the S-082 roster (OM_ROSTER_RAIDER_DAMAGE,
    # csrc/unit.c) is 9.0 flat damage; Strike-vs-Strike matchup is 1.0.
    attacker = lib.om_unit_spawn_with_elevation(w, OMUnitType.RAIDER, 0, 0.0, 0.0, 0, 3)
    target = lib.om_unit_spawn_with_elevation(w, OMUnitType.RAIDER, 1, 100.0, 0.0, 0, 1)

    hp_before = lib.om_unit_get_hp(w, target)
    lib.om_unit_attack(w, attacker, target)
    hp_after = lib.om_unit_get_hp(w, target)

    # In Settled Reach, elevation does NOT increase damage (bonus is 0.0, damage dealt is exact flat 9.0)
    damage_dealt = hp_before - hp_after
    assert pytest.approx(damage_dealt, abs=1e-4) == 9.0

    # But sensors DO receive the elevation bonus. Raider base sensor radius
    # per the roster (OM_ROSTER_RAIDER_SENSOR) is 800.0, not 300.0.
    eff_radius = lib.om_unit_get_effective_sensor_radius_to_target_elevation(w, attacker, 1)
    assert pytest.approx(eff_radius, abs=1e-4) == 800.0 * (1.0 + 0.15 * 2)  # Raider base 800 * 1.3 = 1040.0

