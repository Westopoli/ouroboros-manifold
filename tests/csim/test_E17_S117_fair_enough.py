def test_R_117_02_q_113_01_map_regenerated(lib, world_factory):
    """Given the launch build, When the score is outside the acceptable range, Then [Q-113-01: the map is regenerated with a new seed up to 5 times (bible), or accepted and logged (code, A-393)]."""
    w = world_factory(n_regions=1)

    # Per Q-113-01: at launch, fairness evaluator is logger only and does not trigger map regeneration
    lib.om_map_generate(w, 0, 42)
    # Set an unacceptable fairness score
    lib.om_fairness_force_score(w, ctypes.c_double(0.10))  # outside acceptable range

    initial_seed = lib.om_map_get_active_seed(w)
    lib.om_fairness_run_post_generation_check(w)
    current_seed = lib.om_map_get_active_seed(w)

    # Seed is unchanged (no regeneration, logger only)
    assert initial_seed == current_seed
    assert lib.om_fairness_is_score_logged(w) == 1


