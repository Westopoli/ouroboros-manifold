    assert r3 == OMRegionalCategory.DECLINE

    # 4. stable
    r4 = lib.om_chronicle_categorize_regional_cluster(w, has_conquest_or_revolt=0, net_eco_pop=0.5)
    assert r4 == OMRegionalCategory.STABLE


