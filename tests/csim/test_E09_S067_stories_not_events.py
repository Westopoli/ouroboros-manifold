def test_R_067_04_any_revolt_template_gives_chain(lib, world_factory):
    """Given a chain cluster, When categorized, Then: any "revolt" template gives `chain_revolt_spawned`; else any "expansion" or "coloniz" gives `chain_expansion`; else 4 or more events gives `chain_cascade`; else net military > 2 and net tension < 3 gives `chain_conflict_victory`; else net military < −2 and net tension > 3 gives `chain_conflict_defeat`; else |net military| ≤ 2 and net tension > 2 gives `chain_conflict_stalemate`; else net economy > 0 and net tension ≤ 0 gives `chain_crisis_resolved_well`; else `chain_crisis_resolved_badly`."""
    w = world_factory(n_regions=2)

    # 1. revolt
    c1 = lib.om_chronicle_categorize_chain_cluster(w, template_name=b"evt_revolt_step", n_events=1, net_mil=0.0, net_eco=0.0, net_ten=0.0)
    assert c1 == OMChainCategory.REVOLT_SPAWNED

    # 2. expansion
    c2 = lib.om_chronicle_categorize_chain_cluster(w, template_name=b"evt_colonize_step", n_events=1, net_mil=0.0, net_eco=0.0, net_ten=0.0)
    assert c2 == OMChainCategory.EXPANSION

    # 3. cascade: 4 or more events
    c3 = lib.om_chronicle_categorize_chain_cluster(w, template_name=b"evt_plain", n_events=5, net_mil=0.0, net_eco=0.0, net_ten=0.0)
    assert c3 == OMChainCategory.CASCADE

    # 4. victory: net military > 2 and net tension < 3
    c4 = lib.om_chronicle_categorize_chain_cluster(w, template_name=b"evt_conflict", n_events=2, net_mil=3.0, net_eco=0.0, net_ten=1.0)
    assert c4 == OMChainCategory.CONFLICT_VICTORY

    # 5. defeat: net military < -2 and net tension > 3
    c5 = lib.om_chronicle_categorize_chain_cluster(w, template_name=b"evt_conflict", n_events=2, net_mil=-3.0, net_eco=0.0, net_ten=4.0)
    assert c5 == OMChainCategory.CONFLICT_DEFEAT

    # 6. stalemate: |net military| <= 2 and net tension > 2
    c6 = lib.om_chronicle_categorize_chain_cluster(w, template_name=b"evt_conflict", n_events=2, net_mil=1.0, net_eco=0.0, net_ten=3.0)
    assert c6 == OMChainCategory.CONFLICT_STALEMATE

    # 7. crisis well: net economy > 0 and net tension <= 0
    c7 = lib.om_chronicle_categorize_chain_cluster(w, template_name=b"evt_economy", n_events=2, net_mil=0.0, net_eco=1.5, net_ten=-0.5)
    assert c7 == OMChainCategory.CRISIS_RESOLVED_WELL

    # 8. crisis badly: else
    c8 = lib.om_chronicle_categorize_chain_cluster(w, template_name=b"evt_economy", n_events=2, net_mil=0.0, net_eco=-1.0, net_ten=0.0)
    assert c8 == OMChainCategory.CRISIS_RESOLVED_BADLY


def test_R_067_05_they_group_by_region_into(lib, world_factory):
    """Given events with no chain tag and no lineage link, When clustered, Then they group by region into a regional cluster categorized `regional_faction_shift` if any conquest, revolt, or faction-creating event is present, else `regional_growth` if net economy + population > 3, else `regional_decline` if < −3, else `regional_stable`."""
    w = world_factory(n_regions=2)

    # 1. faction shift
    r1 = lib.om_chronicle_categorize_regional_cluster(w, has_conquest_or_revolt=1, net_eco_pop=0.0)
    assert r1 == OMRegionalCategory.FACTION_SHIFT

    # 2. growth: net eco + pop > 3
    r2 = lib.om_chronicle_categorize_regional_cluster(w, has_conquest_or_revolt=0, net_eco_pop=3.5)
