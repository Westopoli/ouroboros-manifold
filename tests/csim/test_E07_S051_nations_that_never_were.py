def test_R_051_05_it_never_removed(lib, world_factory):
    """Given a non-breakaway faction (starting faction) with zero regions, When cleanup runs, Then it is never removed."""
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=0.0, tech=10.0, confidence=5.0)
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=50.0, tech=10.0, confidence=5.0)

    # Starting faction 0 owns 0 regions (both owned by Faction 1)
    for r in (0, 1):
        set_region(lib, w, r, tier=OMTier.HOME, military=40.0, economy=40.0, tension=10.0, population=40.0, faction_id=1)
        set_owner(lib, w, r, 1, held_since=-1)

    for _ in range(100):
        lib.om_world_step(w)

    # Starting faction with 0 regions is never removed
    assert lib.om_faction_is_active(w, 0) == 1


def test_R_051_06_those_regions_become_unowned_with(lib, world_factory):
    """Given a removed faction still owned regions, When removal happens, Then those regions become unowned with held-since cleared."""
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w, 0, OMArchetype.BREAKAWAY, budget=0.0, tech=10.0, confidence=3.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=20.0, economy=25.0, tension=20.0, population=30.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=1)

    # Trigger forced removal of faction 0
    lib.om_faction_remove(w, 0)

    # Regions become unowned with held-since cleared (< 0)
    assert lib.om_region_owner(w, 0) == -1
    assert lib.om_region_held_since(w, 0) < 0

