class OmAbsorptionRecord(ctypes.Structure):
    _fields_ = [
        ("tick", ctypes.c_uint64),
        ("absorbed_faction", ctypes.c_int32),
        ("absorbing_faction", ctypes.c_int32),
        ("region_idx", ctypes.c_uint32),
    ]


def read_absorptions(lib, w, max_records=64):
    buf = (OmAbsorptionRecord * max_records)()
    n = lib.om_tick_absorptions(w, buf, max_records)
    return [buf[i] for i in range(n)]


def test_R_051_01_it_removed_from_registry_every(lib, world_factory):
    """Given a breakaway faction with zero regions, When 5 or more ticks have passed since its creation tick, Then it is removed from the registry and every faction's stance table."""
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=10.0, confidence=5.0)
    set_faction(lib, w, 1, OMArchetype.BREAKAWAY, budget=0.0, tech=10.0, confidence=3.0)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)

    # Breakaway faction 1 created at tick 1, owns 0 regions
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 1, 0, held_since=-1)

    lib.om_faction_set_created_tick(w, 1, 1)

    # Advance 5 ticks: tick 6 >= 1 + 5
    for _ in range(5):
        lib.om_world_step(w)

    # When cleanup runs, it is removed from registry and stance table
    assert lib.om_faction_is_active(w, 1) == 0
    assert lib.om_faction_stance(w, 0, 1) == -1


def test_R_051_02_its_region_passes_to_bordering(lib, world_factory):
    """Given a breakaway with exactly one region, created 50 or more ticks ago, with budget below 20, When cleanup runs, Then its region passes to the bordering faction with the most regions, held-since resets, previous owner is the breakaway, and the breakaway is removed."""
    # 7 regions: Region 0 (breakaway), Regions 1,2 (Faction 1: 2 regions), Regions 3,4,5,6 (Faction 2: 4 regions)
    w = world_factory(n_regions=7)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w, 0, OMArchetype.BREAKAWAY, budget=10.0, tech=10.0, confidence=3.0)
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=50.0, tech=10.0, confidence=5.0)
    set_faction(lib, w, 2, OMArchetype.DEFAULT, budget=50.0, tech=10.0, confidence=5.0)

    set_region(lib, w, 0, tier=OMTier.HOME, military=20.0, economy=25.0, tension=20.0, population=30.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=1)

    for r in (1, 2):
        set_region(lib, w, r, tier=OMTier.HOME, military=40.0, economy=40.0, tension=10.0, population=40.0, faction_id=1)
        set_owner(lib, w, r, 1, held_since=-1)

    for r in (3, 4, 5, 6):
        set_region(lib, w, r, tier=OMTier.HOME, military=40.0, economy=40.0, tension=10.0, population=40.0, faction_id=2)
        set_owner(lib, w, r, 2, held_since=-1)

    # Borders: Region 0 borders Region 1 (Faction 1) and Region 3 (Faction 2)
    set_edge(lib, w, 0, 1, OMEdge.BORDER)
    set_edge(lib, w, 0, 3, OMEdge.BORDER)

    lib.om_faction_set_created_tick(w, 0, 1)

    # Advance 50 ticks so created >= 50 ticks ago
    for _ in range(50):
        lib.om_world_step(w)

    current_tick = lib.om_world_step(w)

    # Region 0 passes to Faction 2 (most regions: 4 > 2)
    assert lib.om_region_owner(w, 0) == 2
    assert lib.om_region_held_since(w, 0) == current_tick
    assert lib.om_region_previous_owner(w, 0) == 0
    assert lib.om_faction_is_active(w, 0) == 0

    absorptions = read_absorptions(lib, w)
    assert len(absorptions) == 1
    assert absorptions[0].absorbed_faction == 0
    assert absorptions[0].absorbing_faction == 2
    assert absorptions[0].region_idx == 0


