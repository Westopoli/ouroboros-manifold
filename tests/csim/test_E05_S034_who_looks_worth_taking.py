    isolate_agents(lib, w)

    # Faction 0: Conqueror (attractiveness weights: weakness 0.40, value 0.25, position 0.35)
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=100.0, confidence=5.0)
    # Faction 1: Enemy faction owning evaluated region and neighbor
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=0.0, confidence=5.0)

    # Pairwise stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    # Tech multipliers 1.0 (neutral baseline, no tech bonuses)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)

    # Region 0: Owned by Conqueror (neutral baseline fields)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)

    # Region 1: Evaluated enemy target (military 30, economy 60, population 50)
    set_region(lib, w, 1, tier=OMTier.HOME, military=30.0, economy=60.0, tension=0.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)

    # Region 2: Enemy neighbor of Region 1 (economy 40, population 50, neutral military 50)
    set_region(lib, w, 2, tier=OMTier.HOME, military=50.0, economy=40.0, tension=0.0, population=50.0, faction_id=1)
    set_owner(lib, w, 2, 1, held_since=-1)

    # Region 3: Empty neighbor of Region 1 (tier EMPTY, unowned, all fields 0.0)
    set_region(lib, w, 3, tier=OMTier.EMPTY, military=0.0, economy=0.0, tension=0.0, population=0.0, faction_id=-1)

    # Topology: Region 0 borders Region 1; Region 1 borders 2 and 3
    set_edge(lib, w, 0, 1, OMEdge.BOTH)
    set_edge(lib, w, 1, 2, OMEdge.BOTH)
    set_edge(lib, w, 1, 3, OMEdge.BOTH)

    # Pin telegraph mode selection draw for any attack decision
    force_draws(lib, w, [0.5])
    lib.om_world_step(w)

    candidates = read_candidates(lib, w, 0)
    c = next(cand for cand in candidates if cand.region_idx == 1)
    assert c.kind == OMCandKind.ATTACK
    # weakness = 1 - 30/100 = 0.70
    assert c.weakness == pytest.approx(0.70, abs=1e-6)
    # value = ((60 · 0.60 + 50 · 0.40)/100) · 2 = ((36 + 20)/100) · 2 = 1.12
    assert c.value == pytest.approx(1.12, abs=1e-6)
    # position = mean( (40 · 0.60 + 50 · 0.40)/100, 0.15 ) = mean(0.44, 0.15) = 0.295
    assert c.position == pytest.approx(0.295, abs=1e-6)
    # score = 0.40·0.70 + 0.25·1.12 + 0.35·0.295 = 0.66325
    assert c.attractiveness == pytest.approx(0.66325, abs=1e-6)


