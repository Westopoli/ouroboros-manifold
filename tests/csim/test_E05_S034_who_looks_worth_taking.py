    lib.om_world_step(w_above)
    c_above = [cand for cand in read_candidates(lib, w_above, 0) if cand.region_idx == 1]
    assert len(c_above) == 1
    assert c_above[0].value == pytest.approx(0.068, abs=1e-6)
