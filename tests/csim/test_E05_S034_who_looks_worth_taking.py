def test_R_034_03_factor_one_0_80_tension(lib, world_factory):
    """Given a schism evaluating an enemy region with tension 80, When computed, Then factor one is 0.80 (tension), not weakness, and an empty region is never a candidate for it."""
    w = world_factory(n_regions=3)
    isolate_agents(lib, w)

    # Faction 0: Schism (tension-primary: yes, can_colonize: no)
    set_faction(lib, w, 0, OMArchetype.SCHISM, budget=100.0, confidence=5.0)
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=0.0, confidence=5.0)

    # Pairwise stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    # Tech multipliers 1.0 (neutral baseline, no tech bonuses)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)

    # Region 0: Owned by Schism (neutral baseline fields)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)

    # Region 1: Enemy region with tension 80, military 30 (so 1 - m/100 = 0.70 != 0.80)
    set_region(lib, w, 1, tier=OMTier.HOME, military=30.0, economy=60.0, tension=80.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)

    # Region 2: Empty region adjacent to Schism (tier EMPTY, unowned)
    set_region(lib, w, 2, tier=OMTier.EMPTY, military=0.0, economy=0.0, tension=0.0, population=0.0, faction_id=-1)

    set_edge(lib, w, 0, 1, OMEdge.BOTH)
    set_edge(lib, w, 0, 2, OMEdge.BOTH)

    force_draws(lib, w, [0.5])
    lib.om_world_step(w)

    candidates = read_candidates(lib, w, 0)
    c1 = next(cand for cand in candidates if cand.region_idx == 1)
    assert c1.kind == OMCandKind.ATTACK
    # Factor one is 0.80 (tension / 100), not military weakness (1 - military / 100 = 0.70)
    assert c1.weakness == pytest.approx(0.80, abs=1e-6)
    assert c1.weakness != pytest.approx(1.0 - 30.0 / 100.0, abs=1e-6)

    # An empty region is never a candidate for a schism (can_colonize = no per ALG-11)
    assert not any(cand.region_idx == 2 for cand in candidates)
    assert not any(cand.kind == OMCandKind.COLONIZE for cand in candidates)

    # Contrast control: For a conqueror (can_colonize = yes), the empty region IS a colonize candidate
    w_ctrl = world_factory(n_regions=3)
    isolate_agents(lib, w_ctrl)
    set_faction(lib, w_ctrl, 0, OMArchetype.CONQUEROR, budget=100.0, confidence=5.0)
    set_faction(lib, w_ctrl, 1, OMArchetype.DEFAULT, budget=0.0, confidence=5.0)
    set_stance(lib, w_ctrl, 0, 1, OMStance.HOSTILE)
    set_tech_multipliers(lib, w_ctrl, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w_ctrl, 1, 1.0, 1.0, 1.0)
    set_region(lib, w_ctrl, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w_ctrl, 0, 0, held_since=-1)
    set_region(lib, w_ctrl, 1, tier=OMTier.HOME, military=30.0, economy=60.0, tension=80.0, population=50.0, faction_id=1)
    set_owner(lib, w_ctrl, 1, 1, held_since=-1)
    set_region(lib, w_ctrl, 2, tier=OMTier.EMPTY, military=0.0, economy=0.0, tension=0.0, population=0.0, faction_id=-1)
    set_edge(lib, w_ctrl, 0, 1, OMEdge.BOTH)
    set_edge(lib, w_ctrl, 0, 2, OMEdge.BOTH)
    force_draws(lib, w_ctrl, [0.5])
    lib.om_world_step(w_ctrl)
    ctrl_candidates = read_candidates(lib, w_ctrl, 0)
    assert any(cand.region_idx == 2 and cand.kind == OMCandKind.COLONIZE for cand in ctrl_candidates)


def test_R_034_04_value_1_8_1_6(lib, world_factory):
    """Given an enemy region with economy 3 and population 4, When evaluated, Then value = ((1.8 + 1.6)/100) · 2 = 0.068 and it is a candidate; Given economy 2 and population 2, Then value = 0.040 and it is not a candidate (minimum attack value 0.05)."""
    # Above boundary: economy 3 and population 4 -> value = ((1.8 + 1.6)/100) · 2 = 0.068 >= 0.05 -> candidate
    w_above = world_factory(n_regions=2)
    isolate_agents(lib, w_above)
    set_faction(lib, w_above, 0, OMArchetype.CONQUEROR, budget=100.0, confidence=5.0)
    set_faction(lib, w_above, 1, OMArchetype.DEFAULT, budget=0.0, confidence=5.0)
    set_stance(lib, w_above, 0, 1, OMStance.HOSTILE)  # neutral unstated stance
    set_tech_multipliers(lib, w_above, 0, 1.0, 1.0, 1.0)  # neutral baseline tech
    set_tech_multipliers(lib, w_above, 1, 1.0, 1.0, 1.0)
    set_region(lib, w_above, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w_above, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)
    set_region(lib, w_above, 1, tier=OMTier.HOME, military=30.0, economy=3.0, tension=0.0, population=4.0, faction_id=1)
    set_owner(lib, w_above, 1, 1, held_since=-1)
    set_edge(lib, w_above, 0, 1, OMEdge.BOTH)
