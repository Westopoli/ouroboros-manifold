def test_R_034_05_it_scored_once(lib, world_factory):
    """Given a region adjacent to two of the faction's owned regions, When candidates are gathered, Then it is scored once."""
    w = world_factory(n_regions=3)
    isolate_agents(lib, w)

    # Faction 0 owns regions 0 and 1
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=100.0, confidence=5.0)
    set_faction(lib, w, 1, OMArchetype.DEFAULT, budget=0.0, confidence=5.0)

    # Stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    # Tech multipliers 1.0 (neutral baseline, no tech bonuses)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)

    # Regions 0 and 1: Owned by Faction 0 (neutral baseline fields)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)  # neutral held_since -1 (held since world began)
    set_region(lib, w, 1, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 1, 0, held_since=-1)

    # Region 2: Enemy region owned by Faction 1 (military 30, economy 60, population 50)
    set_region(lib, w, 2, tier=OMTier.HOME, military=30.0, economy=60.0, tension=0.0, population=50.0, faction_id=1)
    set_owner(lib, w, 2, 1, held_since=-1)

    # Region 2 is adjacent to BOTH Region 0 and Region 1
    set_edge(lib, w, 0, 2, OMEdge.BOTH)
    set_edge(lib, w, 1, 2, OMEdge.BOTH)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)

    force_draws(lib, w, [0.5])
    lib.om_world_step(w)

    candidates = read_candidates(lib, w, 0)
    # Region 2 must be scored exactly once
    c2 = [cand for cand in candidates if cand.region_idx == 2]
    assert len(c2) == 1
    assert c2[0].kind == OMCandKind.ATTACK
    assert c2[0].attractiveness > 0.0
    # Regions 0 and 1 are owned by Faction 0, so only Region 2 is an eligible candidate
    assert len(candidates) == 1


