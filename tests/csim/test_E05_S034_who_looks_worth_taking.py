def test_R_034_01_weakness_0_70_value_36(lib, world_factory):
    """Given a conqueror evaluating an enemy region with military 30, economy 60, population 50, whose non-owned neighbors are one enemy region (economy 40, population 50) and one empty region, When attractiveness is computed, Then weakness = 0.70, value = ((36 + 20)/100) · 2 = 1.12, position = mean(0.44, 0.15) = 0.295, score = 0.40·0.70 + 0.25·1.12 + 0.35·0.295 = 0.66325."""
