    set_owner(lib, w_below, 1, 1, held_since=-1)
    set_edge(lib, w_below, 0, 1, OMEdge.BOTH)
    lib.om_world_step(w_below)
    c_below = [cand for cand in read_candidates(lib, w_below, 0) if cand.region_idx == 1]
    assert len(c_below) == 0

    # At boundary: economy 2.5 and population 2.5 -> value = ((1.5 + 1.0)/100) · 2 = 0.050 == 0.05 -> candidate
