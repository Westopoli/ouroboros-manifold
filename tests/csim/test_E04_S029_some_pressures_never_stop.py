    isolate_events(lib, w)
    load_launch_events(lib, w)
    zero_all_noise(lib, w)

    tid_revolt = template_id(lib, w, "Regional Revolt")
    tid_crushed = template_id(lib, w, "Revolt Crushed")
    tid_entrenched = template_id(lib, w, "Revolt Entrenched")

    # Verify template definition matches the rule's effects and spawns
    tmpl = get_template(lib, w, tid_revolt)
    assert tmpl.effect[OMField.MILITARY] == pytest.approx(-2.0, abs=1e-6)
    assert tmpl.effect[OMField.ECONOMY] == pytest.approx(-2.0, abs=1e-6)
    assert tmpl.effect[OMField.TENSION] == pytest.approx(4.0, abs=1e-6)
    assert tmpl.effect[OMField.POPULATION] == pytest.approx(0.0, abs=1e-6)
    assert tmpl.n_spawns == 2

    # Spawn 0: "Revolt Crushed" [2, 5] at 0.45 if military above 35
    assert tmpl.spawns[0].template_id == tid_crushed
    assert tmpl.spawns[0].delay_min == 2
    assert tmpl.spawns[0].delay_max == 5
    assert tmpl.spawns[0].probability == pytest.approx(0.45, abs=1e-6)
    assert tmpl.spawns[0].cond_kind == OMCond.ABOVE
    assert tmpl.spawns[0].cond_field == OMField.MILITARY
    assert tmpl.spawns[0].cond_value == pytest.approx(35.0, abs=1e-6)

    # Spawn 1: "Revolt Entrenched" [3, 8] at 0.55 if tension above 40
    assert tmpl.spawns[1].template_id == tid_entrenched
    assert tmpl.spawns[1].delay_min == 3
    assert tmpl.spawns[1].delay_max == 8
    assert tmpl.spawns[1].probability == pytest.approx(0.55, abs=1e-6)
    assert tmpl.spawns[1].cond_kind == OMCond.ABOVE
    assert tmpl.spawns[1].cond_field == OMField.TENSION
    assert tmpl.spawns[1].cond_value == pytest.approx(40.0, abs=1e-6)

    # Neutral values for unstated fields: tier HOME, military 50.0, economy 50.0, population 50.0
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=64.0, population=50.0)  # neutral tier HOME
    set_owner(lib, w, 0, 0, held_since=-1)  # neutral held_since -1 (held since the world began)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0

    # Step grace period ticks 1 through 3
    for _ in range(3):
        lib.om_world_step(w)

    # Tick 4: revolt fires
    # Draw 0.0 triggers Regional Revolt
    # Draws 0.0 and 1.0 pin spawn delays to delay_min (2) for Crushed and delay_max (8) for Entrenched
    force_draws(lib, w, [0.0, 0.0, 1.0])
    lib.om_world_step(w)  # tick 4

    events = read_events(lib, w)
    fired_revolt = [e for e in events if e.template_id == tid_revolt]
    assert len(fired_revolt) == 1
    ev = fired_revolt[0]
    assert ev.tick == 4
    assert ev.n_spawned == 2

    # 1. Effects: military -2, economy -2, tension +4
    assert ev.delta[OMField.MILITARY] == pytest.approx(-2.0, abs=1e-6)
    assert ev.delta[OMField.ECONOMY] == pytest.approx(-2.0, abs=1e-6)
    assert ev.delta[OMField.TENSION] == pytest.approx(4.0, abs=1e-6)
    assert ev.delta[OMField.POPULATION] == pytest.approx(0.0, abs=1e-6)

    rc, applied_deltas = read_event_delta(lib, w, 0)
    assert rc == 0
    assert applied_deltas[OMField.MILITARY] == pytest.approx(-2.0, abs=1e-6)
    assert applied_deltas[OMField.ECONOMY] == pytest.approx(-2.0, abs=1e-6)
