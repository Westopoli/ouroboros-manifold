def test_R_029_01_p_0_007_0_64(lib, world_factory):
    """Given a region with tension 64, When the regional revolt roll runs, Then p = 0.007 · 0.64^0.8, within 1e-6 of 0.004898."""
    # Compute expected p from the rule's formula
    expected_p = 0.007 * (0.64 ** 0.8)
    assert expected_p == pytest.approx(0.004898, abs=1e-6)

    # 1. Three-fixture pattern for strict inequality at boundary (draw < p):
    # Below boundary: draw = p - 1e-4 (< p) -> regional revolt fires
    w_below = world_factory(n_regions=1)
    isolate_events(lib, w_below)
    load_launch_events(lib, w_below)
    zero_all_noise(lib, w_below)

    tid_revolt = template_id(lib, w_below, "Regional Revolt")
    tmpl = get_template(lib, w_below, tid_revolt)
    assert tmpl.trigger_kind == OMTrigger.PROBABILITY
    assert tmpl.trigger_field == OMField.TENSION
    assert tmpl.prob_base == pytest.approx(0.007, abs=1e-6)
    assert tmpl.prob_exponent == pytest.approx(0.8, abs=1e-6)
    assert tmpl.cooldown_ticks == 12

    # Verify probability formula from template fields
    p = tmpl.prob_base * ((64.0 / 100.0) ** tmpl.prob_exponent)
    assert p == pytest.approx(0.004898, abs=1e-6)
    assert p == pytest.approx(expected_p, abs=1e-9)

    # Neutral values for unstated fields: tier HOME, military 40.0, economy 48.0, population 45.0
    set_region(lib, w_below, 0, tier=OMTier.HOME, military=40.0, economy=48.0, tension=64.0, population=45.0)  # neutral tier HOME
    set_owner(lib, w_below, 0, 0, held_since=-1)  # neutral held_since -1 (held since the world began)
    set_tech_multipliers(lib, w_below, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0

    # Step grace period ticks 1 through 3: trigger state primed, nothing fires
    for _ in range(3):
        lib.om_world_step(w_below)

    # Tick 4: first active trigger evaluation tick
    # Draw strictly below p triggers the revolt; extra draws pin follow-up spawn delays
    force_draws(lib, w_below, [p - 1e-4, 0.5, 0.5])
    lib.om_world_step(w_below)

    events_below = [e for e in read_events(lib, w_below) if e.template_id == tid_revolt]
    assert len(events_below) == 1
    assert events_below[0].tick == 4
    assert events_below[0].source == OMSource.TRIGGER
    assert lib.om_event_last_fired(w_below, 0, tid_revolt) == 4

    # 2. At boundary: draw = p (draw < p is False) -> regional revolt does not fire
    w_at = world_factory(n_regions=1)
    isolate_events(lib, w_at)
    load_launch_events(lib, w_at)
    zero_all_noise(lib, w_at)

    set_region(lib, w_at, 0, tier=OMTier.HOME, military=40.0, economy=48.0, tension=64.0, population=45.0)  # neutral tier HOME
    set_owner(lib, w_at, 0, 0, held_since=-1)  # neutral held_since -1 (held since the world began)
    set_tech_multipliers(lib, w_at, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0

    for _ in range(3):
        lib.om_world_step(w_at)

    force_draws(lib, w_at, [p, 0.5, 0.5])
    lib.om_world_step(w_at)

    events_at = [e for e in read_events(lib, w_at) if e.template_id == tid_revolt]
    assert len(events_at) == 0
    assert lib.om_event_last_fired(w_at, 0, tid_revolt) == -1

    # 3. Above boundary: draw = p + 1e-4 (> p) -> regional revolt does not fire
    w_above = world_factory(n_regions=1)
    isolate_events(lib, w_above)
    load_launch_events(lib, w_above)
    zero_all_noise(lib, w_above)

    set_region(lib, w_above, 0, tier=OMTier.HOME, military=40.0, economy=48.0, tension=64.0, population=45.0)  # neutral tier HOME
    set_owner(lib, w_above, 0, 0, held_since=-1)  # neutral held_since -1 (held since the world began)
    set_tech_multipliers(lib, w_above, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0

    for _ in range(3):
        lib.om_world_step(w_above)

    force_draws(lib, w_above, [p + 1e-4, 0.5, 0.5])
    lib.om_world_step(w_above)

    events_above = [e for e in read_events(lib, w_above) if e.template_id == tid_revolt]
    assert len(events_above) == 0
    assert lib.om_event_last_fired(w_above, 0, tid_revolt) == -1


