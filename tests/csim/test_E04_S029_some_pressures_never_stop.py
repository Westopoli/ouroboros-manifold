    assert qc.region_idx == 0
    assert qc.probability == pytest.approx(0.45, abs=1e-6)
    assert qc.cond_kind == OMCond.ABOVE
    assert qc.cond_field == OMField.MILITARY
    assert qc.cond_value == pytest.approx(35.0, abs=1e-6)
