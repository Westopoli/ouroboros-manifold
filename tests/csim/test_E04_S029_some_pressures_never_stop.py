    q_crushed = [q for q in queue if q.template_id == tid_crushed]
    q_entrenched = [q for q in queue if q.template_id == tid_entrenched]
    assert len(q_crushed) == 1
    assert len(q_entrenched) == 1

    # Follow-up "Revolt Crushed" [2, 5] at 0.45 if military above 35
