class OMPhase:
    FRAGMENTATION = 0
    OVEREXTENSION = 1
    CONFLICT = 2
    EXPANSION = 3
    CONSOLIDATION = 4
    EQUILIBRIUM = 5


def test_R_053_01_its_phase_fragmentation(lib, world_factory):
    """Given a faction's recent event window, When the revolt-and-reversion share of events is at least 0.02, Then its phase is fragmentation."""
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=10.0, confidence=5.0)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=50.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)

    # In a window of 100 events, 2 are revolts/reversions: share = 2/100 = 0.02 >= 0.02
    lib.om_faction_set_event_window_counts(w, 0, total_events=100, revolts=2, attacks=0, colonizations=0)

    assert lib.om_faction_phase(w, 0) == OMPhase.FRAGMENTATION


