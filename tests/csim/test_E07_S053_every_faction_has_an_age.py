def test_R_053_04_expansion(lib, world_factory):
    """Given none of the above, When empty regions bordering the faction number at least 30 percent of all inhabited regions, Then expansion."""
    # 10 inhabited regions total in the world; faction owns Region 0
    # Region 0 borders 3 distinct empty regions (3 / 10 = 0.30 >= 30%)
    w = world_factory(n_regions=14)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=10.0, confidence=5.0)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)

    # Faction 0 owns region 0 (economy 50 -> not overextended)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=10.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)

    # Regions 1..9: other inhabited regions
    for r in range(1, 10):
        set_region(lib, w, r, tier=OMTier.HOME, military=30.0, economy=30.0, tension=10.0, population=30.0, faction_id=1)
        set_owner(lib, w, r, 1, held_since=-1)

    # Regions 10..12: empty regions bordering Region 0
    for r in range(10, 13):
        set_region(lib, w, r, tier=OMTier.EMPTY, military=0.0, economy=0.0, tension=0.0, population=0.0, faction_id=-1)
        set_owner(lib, w, r, -1, held_since=-1)
        set_edge(lib, w, 0, r, OMEdge.BORDER)

    lib.om_faction_set_event_window_counts(w, 0, total_events=100, revolts=0, attacks=0, colonizations=0)

    assert lib.om_faction_phase(w, 0) == OMPhase.EXPANSION


