def test_R_053_07_they_evaluated_in_exactly_this(lib, world_factory):
    """Given the six checks, When evaluated, Then they are evaluated in exactly this order and the first match wins."""
    w = world_factory(n_regions=5)
    isolate_agents(lib, w)
    lib.om_world_set_feature(w, OMFeature.LIFECYCLE, 1)

    set_faction(lib, w, 0, OMArchetype.DEFAULT, budget=0.0, tech=10.0, confidence=5.0)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)

    # Overextension condition met: 5 regions, maintenance 40, total eco 80 (ratio 0.50 > 0.40)
    for r in range(5):
        set_region(lib, w, r, tier=OMTier.HOME, military=20.0, economy=16.0, tension=10.0, population=30.0, faction_id=0)
        set_owner(lib, w, r, 0, held_since=-1)

    # Fragmentation ALSO met: 2 revolts in 100 events (0.02 >= 0.02)
    # Attack ALSO met: 10 attacks in 100 events (0.10 >= 0.05)
    lib.om_faction_set_event_window_counts(w, 0, total_events=100, revolts=2, attacks=10, colonizations=5)

    # Fragmentation is evaluated first, so it wins over overextension and conflict
    assert lib.om_faction_phase(w, 0) == OMPhase.FRAGMENTATION

    # Without revolts, overextension is evaluated second, winning over conflict
    lib.om_faction_set_event_window_counts(w, 0, total_events=100, revolts=0, attacks=10, colonizations=5)
    assert lib.om_faction_phase(w, 0) == OMPhase.OVEREXTENSION

