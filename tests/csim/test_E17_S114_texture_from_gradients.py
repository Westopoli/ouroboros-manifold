def test_R_114_02_its_contribution_intensity_falloff_r(lib, world_factory):
    """Given a gradient source (position, type, radius, intensity, falloff), When sampled at distance r ≤ radius, Then its contribution is intensity × falloff(r/radius), and overlapping sources combine [Q-115-01: sum clamped or max]."""
    # Falloff at r = radius/2: e.g. linear falloff = 0.5 -> contribution = 0.8 * 0.5 = 0.4
    val = lib.om_gradient_sample_single(
        ctypes.c_double(0.8),   # intensity
        ctypes.c_double(600.0), # radius
        ctypes.c_double(300.0), # distance r
        0,                      # falloff type: LINEAR
    )
    assert ctypes.c_double(val).value == pytest.approx(0.4, abs=1e-4)

    # Overlapping sources combine via sum clamped to 1.0 (Q-115-01: min(1.0, i1 + i2))
    combined = lib.om_gradient_combine_overlap(ctypes.c_double(0.6), ctypes.c_double(0.7))
    assert ctypes.c_double(combined).value == pytest.approx(1.0, abs=1e-5)

    combined_under = lib.om_gradient_combine_overlap(ctypes.c_double(0.3), ctypes.c_double(0.4))
    assert ctypes.c_double(combined_under).value == pytest.approx(0.7, abs=1e-5)


