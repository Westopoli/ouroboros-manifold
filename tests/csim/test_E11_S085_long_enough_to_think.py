def test_R_085_05_at_least_30_percent_force(lib, world_factory):
    """Given a fight the player is losing, When they issue a move away at the 45 s mark, Then at least 30 percent of the force escapes alive."""
    w = world_factory(n_regions=1)

    # Losing fight: 10 player units vs 20 enemy units
    player_units = [lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, float(i * 30), 0) for i in range(10)]
    enemy_units = [lib.om_unit_spawn(w, OMUnitType.VANGUARD, 1, 250.0, float(i * 20), 0) for i in range(20)]

    # Run until 45 seconds (900 ticks)
    lib.om_tactical_run(w, 900)

    # Issue move order away from combat zone to retreat point
    lib.om_command_move(w, player_units, len(player_units), -1000.0, 0.0)

    # Run for retreat distance (e.g. 30 seconds = 600 ticks)
    lib.om_tactical_run(w, 600)

    surviving_player_count = sum(1 for u in player_units if lib.om_unit_alive(w, u))
    assert surviving_player_count >= 0.30 * len(player_units)

