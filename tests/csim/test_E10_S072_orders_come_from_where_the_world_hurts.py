class OMMissionArchetype:
    DEFENSIVE_STAND = 0
    SIEGE_BREAKING = 1
    RECONQUEST = 2
    ASSAULT = 3
    SUPPRESSION = 4
    MULTI_FRONT_DEFENSE = 5
    INTERCEPTION = 6
    EVACUATION = 7
    CONTAINMENT = 8
    COUNTERINSURGENCY = 9
    COUNT = 10


class OMMissionCandidate(ctypes.Structure):
    _fields_ = [
        ("region_idx", ctypes.c_uint32),
        ("archetype", ctypes.c_uint32),
        ("urgency", ctypes.c_double),
        ("relevance", ctypes.c_double),
        ("preference", ctypes.c_double),
        ("score", ctypes.c_double),
    ]


def read_mission_candidates(lib, w, max_records=64):
    buf = (OMMissionCandidate * max_records)()
    n = lib.om_mission_candidates(w, buf, max_records)
    return [buf[i] for i in range(n)]


def test_R_072_01_each_region_archetype_pair_whose(lib, world_factory):
    """Given the player's regions and every region adjacent to them, When the candidate pool is built, Then each (region, archetype) pair whose trigger condition holds enters the pool; a region with no trigger produces nothing."""
    w = world_factory(n_regions=4)

    # Faction 0: Player, Faction 1: Hostile neighbor
    set_faction(lib, w, 0, OMArchetype.PLAYER, budget=50.0)
    set_faction(lib, w, 1, OMArchetype.CONQUEROR, budget=100.0)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)

    # Region 0: Player frontier under attack (trigger: defensive_stand)
    set_region(lib, w, 0, tier=OMTier.HOME, military=30.0, economy=40.0, tension=20.0, population=50.0)
    set_owner(lib, w, 0, 0, held_since=-1)

    # Region 1: Quiet player region, no enemy attack (no trigger)
    set_region(lib, w, 1, tier=OMTier.HOME, military=70.0, economy=80.0, tension=10.0, population=60.0)
    set_owner(lib, w, 1, 0, held_since=-1)

    # Region 2: Hostile enemy region adjacent to player, scored as attack target (trigger: assault)
    set_region(lib, w, 2, tier=OMTier.HOME, military=40.0, economy=50.0, tension=15.0, population=50.0)
    set_owner(lib, w, 2, 1, held_since=-1)

    # Region 3: Distant enemy region, not adjacent to player
    set_region(lib, w, 3, tier=OMTier.HOME, military=50.0, economy=50.0, tension=10.0, population=50.0)
    set_owner(lib, w, 3, 1, held_since=-1)

    set_edge(lib, w, 0, 1, OMEdge.BOTH)
    set_edge(lib, w, 0, 2, OMEdge.BORDER)
    set_edge(lib, w, 2, 3, OMEdge.BOTH)

    lib.om_mission_build_candidate_pool(w)
    candidates = read_mission_candidates(lib, w)

    # Each (region, archetype) pair whose trigger condition holds enters the pool
    assert any(c.region_idx == 0 and c.archetype == OMMissionArchetype.DEFENSIVE_STAND for c in candidates)
    assert any(c.region_idx == 2 and c.archetype == OMMissionArchetype.ASSAULT for c in candidates)

    # A region with no trigger produces nothing
    assert not any(c.region_idx == 1 for c in candidates)
    # Non-adjacent region produces nothing
    assert not any(c.region_idx == 3 for c in candidates)


def test_R_072_02_urgency_clamp_0_4_deficit(lib, world_factory):
    """Given a candidate, When urgency is computed, Then urgency = clamp(0.4 · deficit + 0.4 · conflict + 0.2 · chain, 0, 1), where deficit = mean of (100 − military, 100 − economy, 100 − stability)/100, conflict = clamp(min(1, max hostile neighbor military/70) + 0.5 · min(1, 0.5 · recent attacks + Σ attack budget/600) + 0.3 · min(1, 0.5 · adjacent regions lost), 0, 1), chain = min(1, 0.3 · recent revolt events in the region)."""
    w = world_factory(n_regions=3)

    set_faction(lib, w, 0, OMArchetype.PLAYER, budget=50.0)
    set_faction(lib, w, 1, OMArchetype.CONQUEROR, budget=300.0)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)

    # Region 0: Evaluated region with military 40, economy 40, tension 40, population 50.
    # "stability" in the deficit term is the ALG-09 composite, not raw tension (M0 ruling, 2026-09-22):
    # s = m*0.40 + (100-t)*0.35 + p*0.25 = 40*0.40 + 60*0.35 + 50*0.25 = 16.0 + 21.0 + 12.5 = 49.5
    # (no penalty: m=40 >= STAB_MILITARY_THRESHOLD=10, p=50 >= STAB_POPULATION_THRESHOLD=20)
    # deficit = ((100-40) + (100-40) + (100-49.5))/300 = (60 + 60 + 50.5)/300 = 170.5/300 = 0.5683333...
    set_region(lib, w, 0, tier=OMTier.HOME, military=40.0, economy=40.0, tension=40.0, population=50.0)
    set_owner(lib, w, 0, 0, held_since=-1)

    # Region 1: Hostile neighbor with military 70 -> max hostile neighbor military / 70 = 70/70 = 1.0
    set_region(lib, w, 1, tier=OMTier.HOME, military=70.0, economy=50.0, tension=10.0, population=50.0)
    set_owner(lib, w, 1, 1, held_since=-1)

    # Region 2: Unused neutral neighbor
    set_region(lib, w, 2, tier=OMTier.HOME, military=50.0, economy=50.0, tension=0.0, population=50.0)
    set_owner(lib, w, 2, 0, held_since=-1)

    set_edge(lib, w, 0, 1, OMEdge.BORDER)
    set_edge(lib, w, 0, 2, OMEdge.BOTH)

    # Set conflict context: 1 recent attack, 300 sum budget, 0 adjacent regions lost
    # conflict = clamp(min(1, 70/70) + 0.5 * min(1, 0.5*1 + 300/600) + 0.3 * min(1, 0), 0, 1) = clamp(1.0 + 0.5 * 1.0 + 0, 0, 1) = 1.0
    lib.om_mission_set_conflict_context(w, 0, 1, 300.0, 0)
    # 2 recent revolt events -> chain = min(1, 0.3 * 2) = 0.60
    lib.om_mission_set_revolt_events(w, 0, 2)

    urgency = lib.om_mission_compute_urgency(w, 0, OMMissionArchetype.DEFENSIVE_STAND)

    # Expected: clamp(0.4 * 0.568333... + 0.4 * 1.0 + 0.2 * 0.60, 0, 1)
    #         = 0.227333... + 0.40 + 0.12 = 0.747333...
    # (test defect fix, M0 ruling 2026-09-22: the prior 0.60 used raw tension as "stability";
    # the bible's single definition of stability is the ALG-09 composite computed below)
    alg09_stability = 40.0 * 0.40 + (100.0 - 40.0) * 0.35 + 50.0 * 0.25
    expected_deficit = ((100.0 - 40.0) + (100.0 - 40.0) + (100.0 - alg09_stability)) / 300.0
    expected_conflict = 1.0
    expected_chain = 0.60
    expected_urgency = min(1.0, max(0.0, 0.4 * expected_deficit + 0.4 * expected_conflict + 0.2 * expected_chain))
    assert urgency == pytest.approx(expected_urgency, abs=1e-6)


def test_R_072_03_relevance_clamp_0_4_lineage(lib, world_factory):
    """Given a candidate, When relevance is computed, Then relevance = clamp(0.4 · lineage + 0.3 · proximity + 0.3 · fit, 0, 1), lineage = 1.0 if a lineage member lives in the region, 0.5 if the lineage ever operated there, else 0; proximity = 1 − hops from the lineage home/5 (capped at 5 hops); fit = min(1, times the lineage has run this archetype/3)."""
    w = world_factory(n_regions=3)

    set_faction(lib, w, 0, OMArchetype.PLAYER, budget=50.0)
    set_owner(lib, w, 0, 0, held_since=-1)
    set_owner(lib, w, 1, 0, held_since=-1)
    set_owner(lib, w, 2, 0, held_since=-1)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)
    set_edge(lib, w, 1, 2, OMEdge.BOTH)

    # Candidate at Region 2:
    # Lineage member lives in region (lineage = 1.0)
    # Hops from lineage home (Region 0) = 2 -> proximity = 1 - 2/5 = 0.60
    # Times run archetype = 1 -> fit = min(1, 1/3) = 0.333333
    lib.om_mission_set_lineage_context(w, 2, 1.0, 2, 1)
    relevance = lib.om_mission_compute_relevance(w, 2, OMMissionArchetype.DEFENSIVE_STAND)

    expected_lineage = 1.0
    expected_proximity = 1.0 - 2.0 / 5.0
    expected_fit = 1.0 / 3.0
    expected_relevance = min(1.0, max(0.0, 0.4 * expected_lineage + 0.3 * expected_proximity + 0.3 * expected_fit))
    assert relevance == pytest.approx(expected_relevance, abs=1e-6)


def test_R_072_04_it_0_1_for_archetype(lib, world_factory):
    """Given a candidate, When preference is computed, Then it is 0.1 for an archetype the player marked rare, else the player's weight, default 0.5."""
    w = world_factory(n_regions=1)
