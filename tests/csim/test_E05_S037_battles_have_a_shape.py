def test_R_037_05_net_50_88_38_region(lib, world_factory):
    """Given a defender with military 80 and an attacker committing 50, When resolved at draw 1.0, Then net = 50 − 88 = −38 and the region loses only 5.0 military."""
    # Given: Defender with military 80.0 held from start and attacker committing 50.0
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=50.0 / 0.70, confidence=2.0)
    set_faction(lib, w, 1, OMArchetype.FORTIFIER, budget=0.0)
    # Stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    # Tech multipliers 1.0 (neutral baseline, no tech)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)
    # On tick 1, target has low military (10.0) so attack is viable at declaration (net = 50 - 11 = 39 > 2)
    set_region(lib, w, 1, tier=OMTier.HOME, military=10.0, economy=50.0, tension=20.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)

    # Tick 1: Telegraph attack declared (commit = 50.0)
    force_draws(lib, w, [0.1, 0.5])
    lib.om_world_step(w)

    # Tick 2: Sits in pending list
    lib.om_world_step(w)

    # Tick 3: Defender military set to 80 held from start (entrenchment 2.0), simulating strong garrison
    set_region(lib, w, 1, tier=OMTier.HOME, military=80.0, economy=50.0, tension=20.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)
    lib.om_world_step(w)

    # Tick 4: Resolves with draw 1.0 in step 3c
    force_draws(lib, w, [1.0])
    lib.om_world_step(w)

    attacks = read_attacks(lib, w)
    assert len(attacks) == 1
    att = attacks[0]
    assert att.tick == 4
    assert att.mode == OMMode.TELEGRAPH
    assert att.commit == pytest.approx(50.0, abs=1e-6)
    assert att.effective_attack == pytest.approx(50.0, abs=1e-6)
    # Effective defense = 80 * 0.55 * 2.0 = 88.0
    assert att.effective_defense == pytest.approx(88.0, abs=1e-6)
    # Net = 50 - 88 = -38
    assert att.net == pytest.approx(-38.0, abs=1e-6)
    assert att.outcome == OMOutcome.REPELLED
    # Repelled delta: Δmilitary = -0.10 * effective_attack = -0.10 * 50.0 = -5.0
    assert att.d_military == pytest.approx(-5.0, abs=1e-6)
    assert att.d_economy == pytest.approx(0.0, abs=1e-6)
    assert att.d_tension == pytest.approx(2.0, abs=1e-6)
    assert att.conquest == 0
    # Region loses only 5.0 military: 80.0 - 5.0 = 75.0
    assert lib.om_region_field(w, 1, OMField.MILITARY) == pytest.approx(80.0 - 5.0, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.MILITARY) == pytest.approx(75.0, abs=1e-6)


