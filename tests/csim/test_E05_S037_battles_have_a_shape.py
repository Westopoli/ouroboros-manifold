def test_R_037_01_effective_attack_50_effective_defense(lib, world_factory):
    """Given commit 50, defender military 30 held from the start, no tech, telegraph mode, and a stochastic draw of 1.0, When resolved, Then effective attack = 50, effective defense = 30·0.55·2.0 = 33, net = 17, breakthrough: Δmilitary −13.6, Δeconomy −5.1, Δtension +8.5."""
    # Given: Attacker commits 50 (budget = 50 / 0.70), defender military 30 held from start, no tech, telegraph mode
    w = world_factory(n_regions=2)
    isolate_agents(lib, w)
    set_faction(lib, w, 0, OMArchetype.CONQUEROR, budget=50.0 / 0.70, confidence=2.0)
    set_faction(lib, w, 1, OMArchetype.FORTIFIER, budget=0.0)
    # Stances hostile both ways (neutral unstated stance)
    set_stance(lib, w, 0, 1, OMStance.HOSTILE)
    # Tech multipliers 1.0 (neutral baseline, no tech)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)
    set_tech_multipliers(lib, w, 1, 1.0, 1.0, 1.0)
    # Held since -1 indicates held since the world began (entrenchment 2.0)
    # Attacker region economy set to 8.0 (maintenance baseline) so budget accumulation delta is 0
    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=8.0, tension=0.0, population=50.0, faction_id=0)
    set_owner(lib, w, 0, 0, held_since=-1)
    set_region(lib, w, 1, tier=OMTier.HOME, military=30.0, economy=50.0, tension=0.0, population=50.0, faction_id=1)
    set_owner(lib, w, 1, 1, held_since=-1)
    set_edge(lib, w, 0, 1, OMEdge.BOTH)

    # Tick 1: Attacker declares telegraphed attack (commit = 50.0)
    # Mode selection draw 0.1 < 0.7 selects telegraph mode; 0.5 for reinforce probability
    force_draws(lib, w, [0.1, 0.5])
    lib.om_world_step(w)

    pending_t1 = read_telegraphs(lib, w)
    assert len(pending_t1) == 1
    assert pending_t1[0].commit == pytest.approx(50.0, abs=1e-6)
    assert len(read_attacks(lib, w)) == 0

    # Ticks 2 and 3: Attack sits in pending telegraph list
    lib.om_world_step(w)
    assert len(read_attacks(lib, w)) == 0
    lib.om_world_step(w)
    assert len(read_attacks(lib, w)) == 0

    # Tick 4 (t + 3): Resolves in step 3c with stochastic draw 1.0
    force_draws(lib, w, [1.0])
    lib.om_world_step(w)

    attacks = read_attacks(lib, w)
    assert len(attacks) == 1
    att = attacks[0]
    assert att.tick == 4
    assert att.mode == OMMode.TELEGRAPH
    assert att.commit == pytest.approx(50.0, abs=1e-6)
    # Effective attack = 50 (full efficiency in telegraph mode)
    assert att.effective_attack == pytest.approx(50.0, abs=1e-6)
    # Effective defense = 30 * 0.55 * 2.0 = 33
    assert att.effective_defense == pytest.approx(33.0, abs=1e-6)
    # Net = (50 - 33) * 1.0 = 17
    assert att.net == pytest.approx(17.0, abs=1e-6)
    # Breakthrough outcome (net > 15.0)
    assert att.outcome == OMOutcome.BREAKTHROUGH
    assert att.d_military == pytest.approx(-13.6, abs=1e-6)  # -0.8 * 17 = -13.6
    assert att.d_economy == pytest.approx(-5.1, abs=1e-6)    # -0.3 * 17 = -5.1
    assert att.d_tension == pytest.approx(8.5, abs=1e-6)     # +0.5 * 17 = +8.5
    assert att.conquest == 0                                 # 30 - 13.6 = 16.4 >= 5.0
    assert lib.om_region_field(w, 1, OMField.MILITARY) == pytest.approx(30.0 - 13.6, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.ECONOMY) == pytest.approx(50.0 - 5.1, abs=1e-6)
    assert lib.om_region_field(w, 1, OMField.TENSION) == pytest.approx(0.0 + 8.5, abs=1e-6)

    # Strict inequality boundary: Breakthrough requires net strictly greater than 15.0 (contested if net <= 15.0)
    # At boundary: commit 48.0 -> net = (48.0 - 33.0) * 1.0 = 15.0 -> contested outcome
    w_at = world_factory(n_regions=2)
    isolate_agents(lib, w_at)
