    set_owner(lib, w_at, 1, 1, held_since=-1)
    set_edge(lib, w_at, 0, 1, OMEdge.BOTH)
    force_draws(lib, w_at, [0.1, 0.5])
    lib.om_world_step(w_at)
    lib.om_world_step(w_at)
    lib.om_world_step(w_at)
    force_draws(lib, w_at, [1.0])
    lib.om_world_step(w_at)
    att_at = read_attacks(lib, w_at)[0]
    assert att_at.net == pytest.approx(15.0, abs=1e-6)
    assert att_at.outcome == OMOutcome.CONTESTED
    assert att_at.d_military == pytest.approx(-0.5 * 15.0, abs=1e-6)

