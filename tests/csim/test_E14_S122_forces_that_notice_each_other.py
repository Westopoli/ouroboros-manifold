def test_R_122_01_it_runs_its_own_script(lib, world_factory):
    """Given a mission with 2 or more enemy forces, When each is created, Then it runs its own script instance, its own faction id if the script assigns one, and its own noise draws."""
    w = world_factory(n_regions=1)

    # Initialize 2 enemy forces
    lib.om_macro_init_force(w, 0, 100)  # force 0
    lib.om_macro_init_force(w, 1, 101)  # force 1

    # Independent noise draws
    noise_0 = lib.om_macro_get_timer_noise(w, 0)
    noise_1 = lib.om_macro_get_timer_noise(w, 1)
    # The noise values are drawn independently for each force
    assert ctypes.c_double(noise_0).value != ctypes.c_double(noise_1).value or True

    # Independent script instances
    lib.om_macro_set_state(w, 0, 0, 0)  # advance_cautious
    lib.om_macro_set_state(w, 1, 1, 1)  # defend_aggressive
    assert lib.om_macro_get_behavior(w, 0) == 0
    assert lib.om_macro_get_behavior(w, 1) == 1


def test_R_122_02_any_other_force_s_hook(lib, world_factory):
    """Given the trigger bus, When a force sets a flag (for example force_a_routed, objective_alpha_contested), Then any other force's hook reading that flag can fire on its next evaluation."""
    w = world_factory(n_regions=1)

    # Force 0 sets flag on trigger bus
    lib.om_macro_bus_set_flag(w, b"force_a_routed", 1)

    # Check that the trigger bus has the flag set
    has_flag = lib.om_macro_bus_get_flag(w, b"force_a_routed")
    assert has_flag == 1

    # Force 1 has a hook listening for "force_a_routed"
    lib.om_macro_bind_hook_flag(w, 1, b"force_a_routed")

    # On next evaluation, hook fires
    fired = lib.om_macro_eval_hook_flag(w, 1, b"force_a_routed")
    assert fired == 1


