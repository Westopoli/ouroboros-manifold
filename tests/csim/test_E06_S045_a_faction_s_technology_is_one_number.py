    set_region(lib, w, 0, tier=OMTier.HOME, military=50.0, economy=50.0, tension=10.0, population=50.0)
    set_region(lib, w, 1, tier=OMTier.FRONTIER, military=30.0, economy=30.0, tension=80.0, population=30.0)
    set_owner(lib, w, 0, 0)
    set_owner(lib, w, 1, 0)

