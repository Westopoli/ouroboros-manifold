def test_R_095_05_group_terminated(lib, world_factory):
    """Given a move group, When its centroid reaches the destination or every unit reaches its slot (within 1.5 × collision radius), Then the group is terminated."""
    w = world_factory(n_regions=1)

    # Collision radius is 15.0 wu; arrival tolerance is 1.5 * 15 = 22.5 wu
    u1 = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 100.0, 100.0, 0)
    u2 = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 120.0, 100.0, 0)

    selection = (ctypes.c_uint32 * 2)(u1, u2)
    group_id = lib.om_command_group_move(w, selection, 2, 200.0, 100.0)

    assert lib.om_group_is_active(w, group_id) == 1

    # Simulate until units arrive
    for _ in range(50):
        lib.om_world_step(w)

    # Once within arrival tolerance (<= 22.5 wu) of destination/slot, group is terminated
    assert lib.om_group_is_active(w, group_id) == 0


def test_R_095_06_that_subset_forms_new_group(lib, world_factory):
    """Given the player selects a subset and issues a new move, When they do, Then that subset forms a new group at its own slowest pace and the old group continues without it."""
    w = world_factory(n_regions=1)

    # 2 Raiders (150 wu/s) and 2 Bastions (40 wu/s)
    r1 = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 100.0, 100.0, 0)
    r2 = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 110.0, 100.0, 0)
    b1 = lib.om_unit_spawn(w, OMUnitType.BASTION, 0, 120.0, 100.0, 0)
    b2 = lib.om_unit_spawn(w, OMUnitType.BASTION, 0, 130.0, 100.0, 0)

    all_units = (ctypes.c_uint32 * 4)(r1, r2, b1, b2)
    g1 = lib.om_command_group_move(w, all_units, 4, 3000.0, 100.0)

    # Player selects subset of 2 Raiders and issues a new move
    raider_subset = (ctypes.c_uint32 * 2)(r1, r2)
    g2 = lib.om_command_group_move(w, raider_subset, 2, 3000.0, 500.0)

    # Subset forms new group g2 != g1
    assert g2 != g1
    assert lib.om_group_is_active(w, g1) == 1
    assert lib.om_group_is_active(w, g2) == 1

    # g2 pace is slowest among {r1, r2} which is 150 wu/s
    assert pytest.approx(lib.om_unit_get_current_speed(w, r1), abs=1e-4) == 150.0
    assert pytest.approx(lib.om_unit_get_current_speed(w, r2), abs=1e-4) == 150.0

    # Old group g1 continues without the Raiders, at Bastion pace (40 wu/s)
    assert pytest.approx(lib.om_unit_get_current_speed(w, b1), abs=1e-4) == 40.0
    assert pytest.approx(lib.om_unit_get_current_speed(w, b2), abs=1e-4) == 40.0


