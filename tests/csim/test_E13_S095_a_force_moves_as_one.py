def test_R_095_02_each_unit_s_destination_click(lib, world_factory):
    """Given the selection, When destinations are assigned, Then each unit's destination is the click point plus its offset from the selection's centroid at command time; offsets are computed once and never updated."""
    w = world_factory(n_regions=1)

    # Unit 1 at (100, 100), Unit 2 at (200, 100) -> centroid is (150, 100)
    # Unit 1 offset = (100 - 150, 100 - 100) = (-50, 0)
    # Unit 2 offset = (200 - 150, 100 - 100) = (+50, 0)
    u1 = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 100.0, 100.0, 0)
    u2 = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 200.0, 100.0, 0)

    selection = (ctypes.c_uint32 * 2)(u1, u2)
    # Click point at (1000, 500)
    lib.om_command_group_move(w, selection, 2, 1000.0, 500.0)

    # Destination = click + offset
    # u1 destination = (1000 - 50, 500 + 0) = (950, 500)
    # u2 destination = (1000 + 50, 500 + 0) = (1050, 500)
    d1_x, d1_y = lib.om_unit_get_destination(w, u1)
    d2_x, d2_y = lib.om_unit_get_destination(w, u2)

    assert pytest.approx(d1_x, abs=1e-4) == 950.0
    assert pytest.approx(d1_y, abs=1e-4) == 500.0
    assert pytest.approx(d2_x, abs=1e-4) == 1050.0
    assert pytest.approx(d2_y, abs=1e-4) == 500.0

    # Advance a few ticks and verify offsets are not recomputed
    lib.om_world_step(w)
    d1_x_after, d1_y_after = lib.om_unit_get_destination(w, u1)
    assert pytest.approx(d1_x_after, abs=1e-4) == 950.0
    assert pytest.approx(d1_y_after, abs=1e-4) == 500.0


