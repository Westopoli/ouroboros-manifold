    rc1, deltas1 = read_event_delta(lib, w, 1)
    assert rc1 == 0
    assert deltas1[OMField.TENSION] == pytest.approx(-1.0, abs=1e-6)
    assert deltas1[OMField.ECONOMY] == pytest.approx(1.0, abs=1e-6)
