    set_region(lib, w, 2, tier=OMTier.HOME, military=40.0, economy=41.0, tension=20.0, population=45.0)  # neutral tier HOME

    # Step tick 4
    lib.om_world_step(w)

    events_tick4 = read_events(lib, w)

    # 1. Both regions A and B fire on tick 4 against tick-start fields
    fired_a_decay = [e for e in events_tick4 if e.region_idx == 0 and e.template_id == tid_decay and e.source == OMSource.TRIGGER]
    assert len(fired_a_decay) == 1
    assert fired_a_decay[0].tick == 4

    fired_b_collapse = [e for e in events_tick4 if e.region_idx == 1 and e.template_id == tid_collapse and e.source == OMSource.TRIGGER]
    assert len(fired_b_collapse) == 1
    assert fired_b_collapse[0].tick == 4

    # 2. Region A's fired deltas sum with due-queue deltas and apply once:
    # Queued Border Incursion: (-2, -2, +2, 0)
    # Fired Infrastructure Decay: (0, -3, +2, -1)
    # Sum: military -2.0, economy -5.0, tension +4.0, population -1.0
    rc0, deltas0 = read_event_delta(lib, w, 0)
    assert rc0 == 0
    assert deltas0[OMField.MILITARY] == pytest.approx(-2.0, abs=1e-6)
    assert deltas0[OMField.ECONOMY] == pytest.approx(-5.0, abs=1e-6)
    assert deltas0[OMField.TENSION] == pytest.approx(4.0, abs=1e-6)
    assert deltas0[OMField.POPULATION] == pytest.approx(-1.0, abs=1e-6)

    # Final fields in Region 0 reflect single application of the sum against tick-start:
    assert lib.om_region_field(w, 0, OMField.MILITARY) == pytest.approx(40.0 - 2.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.ECONOMY) == pytest.approx(38.0 - 5.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.TENSION) == pytest.approx(20.0 + 4.0, abs=1e-6)
    assert lib.om_region_field(w, 0, OMField.POPULATION) == pytest.approx(45.0 - 1.0, abs=1e-6)

    # 3. Region C (Region 2) had Border Incursion resolve on tick 4 (economy delta -2.0, economy becomes 39.0 < 40.0).
    # Because triggers on tick 4 are evaluated against tick-start fields (41.0 >= 40.0),
    # Infrastructure Decay did NOT fire on tick 4:
    fired_c_decay_tick4 = [e for e in events_tick4 if e.region_idx == 2 and e.template_id == tid_decay]
    assert len(fired_c_decay_tick4) == 0
    assert lib.om_region_field(w, 2, OMField.ECONOMY) == pytest.approx(39.0, abs=1e-6)
    assert lib.om_event_breached(w, 2, tid_decay) == 0

    # Step tick 5: Region C crosses on tick t + 1
    lib.om_world_step(w)

    events_tick5 = read_events(lib, w)
    fired_c_decay_tick5 = [e for e in events_tick5 if e.region_idx == 2 and e.template_id == tid_decay and e.source == OMSource.TRIGGER]
    assert len(fired_c_decay_tick5) == 1
    assert fired_c_decay_tick5[0].tick == 5
    assert lib.om_event_breached(w, 2, tid_decay) == 1

    # 4. Region order independence: reverse order (Region 1 as A, Region 0 as B)
    w_rev = world_factory(n_regions=2)
    isolate_events(lib, w_rev)
    load_launch_events(lib, w_rev)
    zero_all_noise(lib, w_rev)

    for r in range(2):
        set_region(lib, w_rev, r, tier=OMTier.HOME, military=40.0, economy=48.0, tension=20.0, population=45.0)  # neutral tier HOME
        set_owner(lib, w_rev, r, 0, held_since=-1)  # neutral held_since -1 (held since the world began)
    set_tech_multipliers(lib, w_rev, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0
    force_draws(lib, w_rev, [1.0] * 50)

    for _ in range(3):
        lib.om_world_step(w_rev)

    # Reverse: region 0 crosses Garrison Collapse, region 1 crosses Infrastructure Decay
    set_region(lib, w_rev, 0, tier=OMTier.HOME, military=25.0, economy=48.0, tension=20.0, population=45.0)  # neutral tier HOME
    set_region(lib, w_rev, 1, tier=OMTier.HOME, military=40.0, economy=38.0, tension=20.0, population=45.0)  # neutral tier HOME

    lib.om_world_step(w_rev)
    rev_events = read_events(lib, w_rev)

    assert any(e.region_idx == 0 and e.template_id == tid_collapse for e in rev_events)
    assert any(e.region_idx == 1 and e.template_id == tid_decay for e in rev_events)
