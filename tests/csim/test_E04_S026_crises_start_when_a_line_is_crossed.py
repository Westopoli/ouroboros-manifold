def test_R_026_01_template_fires_once_on_this(lib, world_factory):
    """Given a region and a threshold template with field F, direction `above`, threshold T, When the region's F was ≤ T + offset last tick and is > T + offset this tick, Then the template fires once on this tick; for direction `below` the mirror holds with <."""
    w = world_factory(n_regions=6)
    isolate_events(lib, w)
    load_launch_events(lib, w)
    zero_all_noise(lib, w)

    tid_boom = template_id(lib, w, "Trade Boom")  # economy above 55.0
    tid_decay = template_id(lib, w, "Infrastructure Decay")  # economy below 40.0

    # Test with non-zero noise offsets per the rule's 'T + offset'
    # For Trade Boom (above, T=55.0): offset=2.0 -> effective threshold 57.0
    # For Infrastructure Decay (below, T=40.0): offset=-2.0 -> effective threshold 38.0
    for r in (0, 1, 2):
        set_noise(lib, w, r, tid_boom, 2.0)
    for r in (3, 4, 5):
        set_noise(lib, w, r, tid_decay, -2.0)

    # Neutral values for unstated fields: tier HOME, military 40.0, tension 20.0, population 45.0
    # Set tick 1..3 fields on the unbreached side of the effective threshold:
    # Regions 0, 1, 2 (above, threshold 57.0): economy 48.0 <= 57.0
    # Regions 3, 4, 5 (below, threshold 38.0): economy 48.0 >= 38.0
    for r in range(6):
        set_region(lib, w, r, tier=OMTier.HOME, military=40.0, economy=48.0, tension=20.0, population=45.0)  # neutral tier HOME
        set_owner(lib, w, r, 0, held_since=-1)  # neutral held_since -1 (held since the world began)
    set_tech_multipliers(lib, w, 0, 1.0, 1.0, 1.0)  # neutral tech multipliers 1.0
    force_draws(lib, w, [1.0] * 50)  # pin draws so no probability triggers or spawns fire

    # Step grace period ticks 1 through 3: trigger state primed, nothing fires
    for _ in range(3):
        lib.om_world_step(w)

    for r in (0, 1, 2):
        assert lib.om_event_breached(w, r, tid_boom) == 0
    for r in (3, 4, 5):
        assert lib.om_event_breached(w, r, tid_decay) == 0

    # Three-fixture boundary pattern for direction `above` (effective threshold 57.0):
    # Region 0: strictly below (56.0 <= 57.0)
    # Region 1: exactly at threshold (57.0 <= 57.0)
    # Region 2: strictly above (58.0 > 57.0)
    set_region(lib, w, 0, tier=OMTier.HOME, military=40.0, economy=56.0, tension=20.0, population=45.0)  # neutral tier HOME
    set_region(lib, w, 1, tier=OMTier.HOME, military=40.0, economy=57.0, tension=20.0, population=45.0)  # neutral tier HOME
    set_region(lib, w, 2, tier=OMTier.HOME, military=40.0, economy=58.0, tension=20.0, population=45.0)  # neutral tier HOME

    # Three-fixture boundary pattern for direction `below` (effective threshold 38.0):
    # Region 3: strictly above (39.0 >= 38.0)
    # Region 4: exactly at threshold (38.0 >= 38.0)
    # Region 5: strictly below (37.0 < 38.0)
    set_region(lib, w, 3, tier=OMTier.HOME, military=40.0, economy=39.0, tension=20.0, population=45.0)  # neutral tier HOME
    set_region(lib, w, 4, tier=OMTier.HOME, military=40.0, economy=38.0, tension=20.0, population=45.0)  # neutral tier HOME
    set_region(lib, w, 5, tier=OMTier.HOME, military=40.0, economy=37.0, tension=20.0, population=45.0)  # neutral tier HOME

    # Step tick 4: first active crossing evaluation tick
    lib.om_world_step(w)

    events = read_events(lib, w)

    # Direction `above`: below and at do not fire; strictly above fires once
    assert not any(e.region_idx == 0 and e.template_id == tid_boom for e in events)
    assert lib.om_event_breached(w, 0, tid_boom) == 0

    assert not any(e.region_idx == 1 and e.template_id == tid_boom for e in events)
    assert lib.om_event_breached(w, 1, tid_boom) == 0

    fired_above = [e for e in events if e.region_idx == 2 and e.template_id == tid_boom]
    assert len(fired_above) == 1
    assert fired_above[0].tick == 4
    assert fired_above[0].source == OMSource.TRIGGER
    assert lib.om_event_breached(w, 2, tid_boom) == 1

    # Direction `below`: above and at do not fire; strictly below fires once
    assert not any(e.region_idx == 3 and e.template_id == tid_decay for e in events)
    assert lib.om_event_breached(w, 3, tid_decay) == 0

    assert not any(e.region_idx == 4 and e.template_id == tid_decay for e in events)
    assert lib.om_event_breached(w, 4, tid_decay) == 0

    fired_below = [e for e in events if e.region_idx == 5 and e.template_id == tid_decay]
    assert len(fired_below) == 1
    assert fired_below[0].tick == 4
    assert fired_below[0].source == OMSource.TRIGGER
    assert lib.om_event_breached(w, 5, tid_decay) == 1


