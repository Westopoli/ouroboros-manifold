def test_R_097_09_repulsion_opposes_move_units_following(lib, world_factory):
    """Given a direct-move unit (no route waypoints), When obstacle density ahead within 50 wu exceeds 0.3, Then a repulsion opposes the move; units following route waypoints are exempt."""
    w = world_factory(n_regions=1)

    # Place terrain with obstacle density 0.50 within 50 wu ahead of (100, 100)
    lib.om_map_set_obstacle_density(w, 1, 1, 0, 0.50)

    # 1. Direct-move unit (no waypoints)
    u_direct = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 100.0, 100.0, 0)
    lib.om_command_direct_move(w, u_direct, 140.0, 100.0)

    repulsion_x, repulsion_y = lib.om_steering_get_obstacle_repulsion(w, u_direct)
    # Repulsion opposes forward movement (negative x)
    assert repulsion_x < 0.0

    # 2. Waypoint-following unit is exempt
