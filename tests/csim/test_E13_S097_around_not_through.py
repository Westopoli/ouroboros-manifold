    lib.om_command_move(w, u_waypoint, 140.0, 100.0)  # standard move computes waypoints
    rep_wp_x, rep_wp_y = lib.om_steering_get_obstacle_repulsion(w, u_waypoint)
    assert pytest.approx(rep_wp_x, abs=1e-4) == 0.0
    assert pytest.approx(rep_wp_y, abs=1e-4) == 0.0

