class OMUnitType:
    RAIDER = 0
    INTERCEPTOR = 1
    VANGUARD = 2
    WARDEN = 3
    BOMBARD = 4
    BASTION = 5


def test_R_099_01_strike_wing_reaches_flank_slots(lib, world_factory):
    """Given a Strike wing and a Line force both approaching an engaged, immovable friendly front, When they arrive, Then the Strike wing reaches the flank slots first, purely from the steering rules of S-097."""
    w = world_factory(n_regions=1)

    # Immovable engaged friendly front at x = 300, y = 100
    front = lib.om_unit_spawn(w, OMUnitType.BASTION, 0, 300.0, 100.0, 0)
    enemy = lib.om_unit_spawn(w, OMUnitType.BASTION, 1, 350.0, 100.0, 0)
    lib.om_unit_engage(w, front, enemy)

    # Flank destination is at (300.0, 130.0) -- see docs/northstar/proving_ground/evidence/push_2026-09-22/test_defects_fixed.md
    flank_x, flank_y = 300.0, 130.0

    # Strike unit (Raider, 150 wu/s) and Line unit (Vanguard, 65 wu/s) starting at (0, 100)
    strike = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 0.0, 100.0, 0)
    line = lib.om_unit_spawn(w, OMUnitType.VANGUARD, 0, 0.0, 100.0, 0)

    lib.om_command_move(w, strike, 400.0, 100.0)
    lib.om_command_move(w, line, 400.0, 100.0)

    # Run ticks and record arrival at flank slots
    strike_arrival_tick = None
    line_arrival_tick = None

    for tick in range(100):
        lib.om_world_step(w)
        s_x, s_y = lib.om_unit_get_pos(w, strike)
        l_x, l_y = lib.om_unit_get_pos(w, line)

        if strike_arrival_tick is None and math.hypot(s_x - flank_x, s_y - flank_y) < 30.0:
            strike_arrival_tick = tick
        if line_arrival_tick is None and math.hypot(l_x - flank_x, l_y - flank_y) < 30.0:
            line_arrival_tick = tick

    assert strike_arrival_tick is not None
    assert line_arrival_tick is not None
    # Strike wing reaches flank slots first
    assert strike_arrival_tick < line_arrival_tick


def test_R_099_02_it_covers_150_wu_per(lib, world_factory):
    """Given a Raider, When it moves, Then it covers 150 wu per second at 20 ticks per second, 7.5 wu per tick."""
    w = world_factory(n_regions=1)

    # Spawn Raider at (0, 0) with move order to (1000, 0)
    raider = lib.om_unit_spawn(w, OMUnitType.RAIDER, 0, 0.0, 0.0, 0)
    lib.om_command_move(w, raider, 1000.0, 0.0)

    # 1. After 1 tick: covers exactly 7.5 wu
    lib.om_world_step(w)
    x1, y1 = lib.om_unit_get_pos(w, raider)
    dist_1_tick = math.hypot(x1, y1)
    assert pytest.approx(dist_1_tick, abs=1e-3) == 7.5

    # 2. After 19 more ticks (total 20 ticks = 1.0 second at 20 tps): covers exactly 150.0 wu
    for _ in range(19):
        lib.om_world_step(w)

    x20, y20 = lib.om_unit_get_pos(w, raider)
    dist_20_ticks = math.hypot(x20, y20)
    assert pytest.approx(dist_20_ticks, abs=1e-3) == 150.0

