#!/usr/bin/env python3
"""Emit one positive-control test skeleton per "Ways this could be wrong" item
in an epic, matching the tests/csim/controls/ convention: clone a clean
fixture, inject the corresponding OM_BUG_* enum member via the debug build,
and assert the detector trips (something that held clean now fails).

The OM_BUG_* enum member itself is not generated here — it has to exist in
csrc/ouroboros_sim.h and the debug build before the control can pass its own
red-then-green cycle (the control test is a detector, not free-standing; it
needs the bug to actually be injectable). This script only emits the test
shape and names the enum member it expects, exactly like gen_test_skeleton.py
does for rules.

Usage:
    scripts/specfactory/gen_controls.py E-03 [--out DIR] [--force]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO / "scripts"))
from derive_agora_rules import EPICS_DIR, EPIC_FILE_RE, parse_epic  # noqa: E402

DEFAULT_OUT = REPO / "tests" / "csim" / "controls"


def bug_name(item: str) -> str:
    words = re.findall(r"[a-zA-Z0-9]+", item.lower())
    return "_".join(words[:6])


def render_control_file(epic_id: str, item: str, index: int) -> str:
    name = bug_name(item)
    enum_member = name.upper()
    fn = f"test_control_{name}_trips_the_detector"
    item_safe = item.replace('"""', "'''")
    return f'''"""Positive control for OM_BUG_{enum_member}.

Watch-for (from docs/bible/epics/{epic_id}-*.md, "Ways this could be wrong"):
"{item_safe}"

Generated by scripts/specfactory/gen_controls.py. Requires OM_BUG_{enum_member}
to exist in csrc/ouroboros_sim.h and be injectable via om_debug_inject on the
debug build (dbg fixture) before this can be filled in. Clone a clean fixture
proven to pass without the bug, inject OM_BUG_{enum_member}, and assert the
detector trips -- something that held clean now fails.
"""
from conftest import OMBug, OMField, OMTier, set_region


def {fn}(dbg, dbg_world_factory):
    w = dbg_world_factory(n_regions=1)
    # TODO: clone the clean fixture this bug should violate.
    dbg.om_debug_inject(w, OMBug.{enum_member})
    dbg.om_world_step(w)
    # TODO: assert the invariant now fails (inverted from the clean-case assertion).
    raise NotImplementedError(
        "fill in the clean fixture and inverted assertion for OM_BUG_{enum_member}"
    )
'''


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("epic", help="Epic id, e.g. E-03")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)

    epic_paths = list(EPICS_DIR.glob(f"{args.epic}-*.md"))
    if not epic_paths:
        print(f"no epic file matches {args.epic}", file=sys.stderr)
        return 1
    epic_path = epic_paths[0]
    m = EPIC_FILE_RE.match(epic_path.name)
    epic_id = m.group(1)
    epic = parse_epic(epic_path)
    wrong_text = epic.get("wrong", "")
    items = [line.lstrip("- ").strip() for line in wrong_text.splitlines() if line.strip().startswith("-")]
    if not items:
        print(f"{epic_id}: no 'Ways this could be wrong' bullet items found", file=sys.stderr)
        return 1

    args.out.mkdir(parents=True, exist_ok=True)
    written, skipped = [], []
    for i, item in enumerate(items, start=1):
        fname = f"test_control_{epic_id.replace('-', '').lower()}_{bug_name(item)}.py"
        target = args.out / fname
        if target.exists() and not args.force:
            skipped.append(target)
            continue
        target.write_text(render_control_file(epic_id, item, i), encoding="utf-8")
        written.append(target)

    def rel(p: Path) -> str:
        try:
            return str(p.relative_to(REPO))
        except ValueError:
            return str(p)

    for t in written:
        print(f"wrote {rel(t)}")
    for t in skipped:
        print(f"skipped (exists, use --force): {rel(t)}")
    print(f"{epic_id}: {len(items)} watch-for item(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
