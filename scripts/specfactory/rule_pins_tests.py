#!/usr/bin/env python3
# spec: docs/northstar/plans/2026-10-19-harness-enforcement-spec.md section 1 HARNESS-C1b, sections 3 and 4
# See also: rule_pins.py (pins of [B] tags in specs; the pin formula lives in spec_provenance.rule_pin)
"""rule_pins_tests.py check <repo> [--only <file>...] | --write-sidecar <repo> | --write-line <file>: rule pins of tests.
Standard library only."""
import ast
import re
import sys
import tomllib
from pathlib import Path

import spec_provenance as sp

SIDECAR = "scripts/specfactory/rule_pins.toml"
HEADER = ("# Rule pins of existing tests (HARNESS-C1b sidecar): [[file]] path = \"tests/...\" "
          "pins = [\"R-###-##@xxxxxx\", ...].\n"
          "# Generated by `rule_pins_tests.py --write-sidecar <repo>`; an empty sidecar means no pins. A test with its own\n"
          "# `Rule pins:` line is read from that line, never from here.\n")
RULE_TOKEN = re.compile(r"R-\d{3}-\d{2}")  # [P spec section 1 HARNESS-C1b: "an `R-\d{3}-\d{2}` token"]
PINS_LINE = re.compile(r"Rule pins:\s*(.*)")
PIN_TOKEN = re.compile(r"(R-\d+-\d+)@([0-9a-f]{6}|\?)")
OWN_LINES = 40


def test_files(repo):
    """{relative path: ids mentioned} for every .py and .gd under tests/ that holds an R-id."""
    out = {}
    for f in sorted(p for s in ("*.py", "*.gd") for p in (repo / "tests").rglob(s)):
        ids = set(RULE_TOKEN.findall(f.read_text(errors="replace")))
        if ids:
            out[f.relative_to(repo).as_posix()] = ids
    return out


def own_pins(path):
    """Pins of the file's own `Rule pins:` line (first 40 lines, or the module docstring), None without one."""
    text = path.read_text(errors="replace")
    lines = text.splitlines()[:OWN_LINES]
    if path.suffix == ".py":
        try:
            lines += (ast.get_docstring(ast.parse(text), clean=False) or "").splitlines()
        except SyntaxError:
            pass
    for ln in lines:
        if (m := PINS_LINE.search(ln)):
            return dict(PIN_TOKEN.findall(m.group(1)))
    return None


def sidecar(repo):
    f = repo / SIDECAR
    rows = tomllib.loads(f.read_text()).get("file", []) if f.is_file() else []
    return {r["path"]: dict(PIN_TOKEN.findall(" ".join(r["pins"]))) for r in rows}


def cmd_check(args):
    repo = Path(args[0]).resolve()
    only = {(repo / a).resolve() for a in args[args.index("--only") + 1:]} if "--only" in args else None
    rules, side, files = sp.load_context(repo)["rule_lines"], sidecar(repo), test_files(repo)
    rejects, warns = [], []
    for rel, ids in files.items():
        mine = own_pins(repo / rel)
        named = only is not None and (repo / rel).resolve() in only
        if named and mine is None:
            rejects.append(f"PINS REJECT {rel} has no Rule pins line")
            continue
        pins = mine if mine is not None else side.get(rel, {})
        bad = []
        for rid in sorted(ids):
            right = pin_value(rules, rid)
            if rid not in pins or (rid in rules and pins[rid] != right):
                bad.append(f"PINS REJECT {rel} {rid} {'stale' if rid in pins else 'missing'} {pins.get(rid, '-')} {right}")
            elif rid not in rules and mine is None:
                warns.append(f"PINS WARN unknown rule {rid} in {rel}")
        if bad and (only is None or named):
            rejects += bad
        elif bad:
            warns.append(f"outside:{len(bad)}")
    outside = sum(int(w.split(":")[1]) for w in warns if w.startswith("outside:"))
    out = rejects + sorted(w for w in warns if not w.startswith("outside:"))
    if outside:
        out.append(f"PINS WARN {outside} stale outside the diff")
    print("\n".join(out) if out else f"PINS OK {len(files)} files {sum(map(len, files.values()))} ids")
    return 1 if rejects else 0


def pin_value(rules, rid):
    return sp.rule_pin(rules[rid]) if rid in rules else "?"


def cmd_write_sidecar(args):
    repo = Path(args[0]).resolve()
    rules = sp.load_context(repo)["rule_lines"]
    rows = "".join(f'[[file]]\npath = "{rel}"\npins = [{", ".join(chr(34) + r + "@" + pin_value(rules, r) + chr(34) for r in sorted(ids))}]\n\n'
                   for rel, ids in test_files(repo).items())
    (repo / SIDECAR).write_text(HEADER + ("\n" + rows.rstrip("\n") + "\n" if rows else ""))
    return 0


def cmd_write_line(args):
    path = Path(args[0])
    lines = path.read_text().splitlines(keepends=True)
    if own_pins(path) is not None:
        return 0
    rules = sp.load_context(sp.find_root(path))["rule_lines"]
    ids = sorted(set(RULE_TOKEN.findall("".join(lines))))
    at = 1 if lines and (lines[0].startswith("#!") or lines[0].startswith("extends ")) else 0
    lines.insert(at, "# Rule pins: " + ", ".join(f"{r}@{pin_value(rules, r)}" for r in ids) + "\n")
    path.write_text("".join(lines))
    return 0


if __name__ == "__main__":
    a = sys.argv[1:]
    cmd = {"check": cmd_check, "--write-sidecar": cmd_write_sidecar, "--write-line": cmd_write_line}.get(a[0] if len(a) > 1 else "")
    sys.exit(cmd(a[1:]) if cmd else print("usage: rule_pins_tests.py check <repo> [--only <file>...] | --write-sidecar <repo> | --write-line <file>", file=sys.stderr) or 2)
