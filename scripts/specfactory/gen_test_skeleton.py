#!/usr/bin/env python3
"""Emit one pytest skeleton file per story in an epic, one stub function per
rule, matching the naming convention already in tests/csim/ (test_R_###_##_*).
Every stub fails loudly until an agy draft pass (or a human) fills in the
arrange/act/assert body from the rule's own numbers — this script never
invents test logic, only the shape every rule needs.

Reuses the epic parser from scripts/derive_agora_rules.py so rule/story
extraction has exactly one implementation.

Usage:
    scripts/specfactory/gen_test_skeleton.py E-03 [--out DIR] [--force]

Refuses to overwrite an existing file unless --force is given, since a filled
test file must never be silently clobbered by a re-run.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO / "scripts"))
from derive_agora_rules import EPICS_DIR, EPIC_FILE_RE, parse_epic  # noqa: E402

DEFAULT_OUT = REPO / "tests" / "csim"


def slugify(title: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "_", title.strip().lower()).strip("_")
    return s


STOPWORDS = {"given", "when", "then", "the", "a", "an", "is", "are", "and", "of"}


def rule_slug(rule_text: str) -> str:
    then_clause = rule_text.split("Then", 1)[-1] if "Then" in rule_text else rule_text
    words = [w for w in re.findall(r"[a-zA-Z0-9]+", then_clause.lower()) if w not in STOPWORDS]
    return "_".join(words[:5]) or "rule"


def render_story_file(epic_id: str, epic_title: str, story: dict, rel_path: str) -> str:
    rule_ids = ", ".join(rid for rid, _ in story["rules"])
    lines = [
        f'"""{story["id"]} -- {story["title"]}.',
        "",
        f"{rule_ids}. Skeleton generated by scripts/specfactory/gen_test_skeleton.py",
        f"from {rel_path}. Fill each stub from its rule's Given/When/Then numbers;",
        "do not change a rule's assertion to match wrong behavior -- a failing test",
        "here is the spec, not a bug in the test.",
        '"""',
        "import pytest",
        "",
        "from conftest import OMField, OMTier, read_drift, set_region  # adjust imports to what this epic's fixtures need",
        "",
        "",
    ]
    for rid, rule_text in story["rules"]:
        fn_name = f"test_{rid.replace('-', '_')}_{rule_slug(rule_text)}"
        docstring_body = rule_text.replace('"""', "'''")
        fail_msg = repr(f"TODO fill arrange/act/assert for {rid}: {rule_text[:80]}")
        lines += [
            f"def {fn_name}(lib, world_factory):",
            f'    """{docstring_body}"""',
            f"    pytest.fail({fail_msg})",
            "",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("epic", help="Epic id, e.g. E-03")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)

    epic_paths = list(EPICS_DIR.glob(f"{args.epic}-*.md"))
    if not epic_paths:
        print(f"no epic file matches {args.epic}", file=sys.stderr)
        return 1
    epic_path = epic_paths[0]
    m = EPIC_FILE_RE.match(epic_path.name)
    epic_id = m.group(1)
    epic = parse_epic(epic_path)
    rel = epic_path.relative_to(REPO).as_posix()

    args.out.mkdir(parents=True, exist_ok=True)
    written, skipped = [], []
    for story in epic["stories"]:
        fname = f"test_{epic_id.replace('-', '')}_{story['id'].replace('-', '')}_{slugify(story['title'])}.py"
        target = args.out / fname
        if target.exists() and not args.force:
            skipped.append(target)
            continue
        text = render_story_file(epic_id, epic["title"], story, rel)
        target.write_text(text, encoding="utf-8")
        written.append(target)

    def rel(p: Path) -> str:
        try:
            return str(p.relative_to(REPO))
        except ValueError:
            return str(p)

    for t in written:
        print(f"wrote {rel(t)}")
    for t in skipped:
        print(f"skipped (exists, use --force): {rel(t)}")
    total_rules = sum(len(s["rules"]) for s in epic["stories"])
    print(f"{epic_id}: {len(epic['stories'])} stories, {total_rules} rule stubs")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
