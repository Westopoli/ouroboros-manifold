#!/usr/bin/env python3
"""Runs pytest against a set of newly generated test files and confirms every
one fails or errors -- none may pass. A passing new test before any C code
exists for it is a defect (either the test is trivially true, or it is
testing something already implemented elsewhere by accident); this script
turns that into a loud, scriptable check instead of a manual read of pytest
output.

Usage:
    scripts/specfactory/red_check.py tests/csim/test_E03_*.py tests/csim/controls/test_control_e03_*.py
    scripts/specfactory/red_check.py --forbid TypeError,ArgumentError,AttributeError \\
        [--placeholder-list FILE] tests/csim/test_E0[6-9]*.py tests/csim/test_E1*.py
    scripts/specfactory/red_check.py --list-placeholders tests/csim/controls

Exit code 0 if every collected test failed or errored (red, as required).
Exit code 1 if pytest could not even collect the files, or if any test passed.

--forbid (the freeze control, F1b): the tests run under --junit-xml and every
failure or error whose message names one of the given exception classes is
listed; exit 1 when any is found (or any test passed). A red test must be red
on an assertion or a STUB, never on a dropped keyword (TypeError), a wrong
ctypes row (ArgumentError) or a missing symbol or binding (AttributeError).
The placeholder controls gen_controls.py wrote (they raise NotImplementedError
after reaching an OMBug member that does not exist yet) are excluded by their
marker, or by --placeholder-list, one file path or node id per line;
--list-placeholders prints the marker-detected files so that list can be
generated. A pytest process that dies mid-run (a segfault inside a C call)
makes the check fall back to one process per file and report the crashing
test ids as CRASH findings.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from xml.etree import ElementTree

REPO = Path(__file__).resolve().parent.parent.parent

SUMMARY_RE = re.compile(
    r"=+ (?:(\d+) failed)?,? ?(?:(\d+) passed)?,? ?(?:(\d+) error)?[^=]*=+"
)
CLASS_RE = re.compile(r"^([A-Za-z_][\w.]*?)(?::|$)")
PLACEHOLDER_MARKERS = ("Generated by scripts/specfactory/gen_controls.py", "raise NotImplementedError(")


def python_bin() -> str:
    venv_python = REPO / ".venv" / "bin" / "python3"
    return str(venv_python) if venv_python.exists() else sys.executable


def is_placeholder_control(path: Path) -> bool:
    try:
        text = path.read_text()
    except OSError:
        return False
    return all(marker in text for marker in PLACEHOLDER_MARKERS)


def list_placeholders(dirs: list[str]) -> list[str]:
    found: list[str] = []
    for d in dirs:
        base = Path(d)
        files = sorted(base.rglob("test_*.py")) if base.is_dir() else [base]
        for f in files:
            if is_placeholder_control(f):
                try:
                    found.append(str(f.resolve().relative_to(REPO)))
                except ValueError:
                    found.append(str(f))
    return found


def load_placeholder_list(path: str | None) -> set[str]:
    if not path:
        return set()
    return {ln.strip() for ln in Path(path).read_text().splitlines() if ln.strip() and not ln.startswith("#")}


def failure_class(message: str | None) -> str | None:
    if not message:
        return None
    m = CLASS_RE.match(message.strip())
    if not m:
        return None
    return m.group(1).rsplit(".", 1)[-1]


def run_pytest(paths: list[str], xml_path: Path) -> subprocess.CompletedProcess:
    # The per-test outcome and message come from the junit report, not the
    # terminal summary: pytest 9's -rfE lines carry no exception text.
    return subprocess.run(
        [python_bin(), "-m", "pytest", *paths, "-q", "--no-header", "-p", "no:cacheprovider", "--tb=line",
         f"--junit-xml={xml_path}", "-o", "junit_family=xunit1"],
        cwd=str(REPO), capture_output=True, text=True,
    )


def process_died(proc: subprocess.CompletedProcess, xml_path: Path) -> bool:
    return proc.returncode < 0 or proc.returncode in (134, 139) or not xml_path.is_file()


def parse_junit(xml_path: Path) -> list[dict]:
    """One {node, file, status, message} per testcase; status is passed, failed,
    error or skipped, message the reprcrash text (class first, e.g.
    'AttributeError: ...', or 'assert 0 > 0' for a bare assertion)."""
    out: list[dict] = []
    root = ElementTree.parse(xml_path).getroot()
    for case in root.iter("testcase"):
        file_part = case.get("file") or case.get("classname", "").replace(".", "/") + ".py"
        node = f"{file_part}::{case.get('name')}"
        status, message = "passed", ""
        for tag in ("error", "failure", "skipped"):
            child = case.find(tag)
            if child is not None:
                status = {"error": "error", "failure": "failed", "skipped": "skipped"}[tag]
                message = child.get("message") or (child.text or "")
                break
        out.append({"node": node, "file": file_part, "status": status, "message": message})
    return out


def collect_ids(path: str) -> list[str]:
    proc = subprocess.run(
        [python_bin(), "-m", "pytest", path, "-q", "--collect-only", "-p", "no:cacheprovider"],
        cwd=str(REPO), capture_output=True, text=True,
    )
    return [ln.strip() for ln in proc.stdout.splitlines() if "::" in ln]


def expand_files(paths: list[str]) -> list[str]:
    files: list[str] = []
    for p in paths:
        path = Path(p)
        if path.is_dir():
            files += [str(f) for f in sorted(path.rglob("test_*.py"))]
        else:
            files.append(p)
    return files


def run_cases(paths: list[str], scratch: Path) -> tuple[list[dict], list[str]]:
    """Every testcase of the run; a process that dies mid-run is retried one
    file at a time, then one test at a time, and the ids that still kill the
    process come back as crashes."""
    xml = scratch / "run.xml"
    proc = run_pytest(paths, xml)
    if not process_died(proc, xml):
        return parse_junit(xml), []
    print("pytest process died mid-run; falling back to one process per file", file=sys.stderr)
    cases: list[dict] = []
    crashes: list[str] = []
    for i, f in enumerate(expand_files(paths)):
        fxml = scratch / f"file{i}.xml"
        fp = run_pytest([f], fxml)
        if not process_died(fp, fxml):
            cases += parse_junit(fxml)
            continue
        for j, node in enumerate(collect_ids(f)):
            nxml = scratch / f"file{i}_{j}.xml"
            np = run_pytest([node], nxml)
            if process_died(np, nxml):
                crashes.append(node)
            else:
                cases += parse_junit(nxml)
    return cases, crashes


def resolve_case_file(file_part: str, paths: list[str]) -> Path:
    """The junit `file` attribute is relative to pytest's rootdir, or a bare
    name for a file outside it; map it back to the path that was run."""
    candidate = REPO / file_part
    if candidate.is_file():
        return candidate.resolve()
    by_name = {Path(p).name: Path(p).resolve() for p in expand_files(paths)}
    return by_name.get(Path(file_part).name, candidate)


def run_forbid(paths: list[str], forbid: set[str], placeholders: set[str]) -> int:
    with tempfile.TemporaryDirectory(prefix="red_check_") as tmp:
        cases, crashes = run_cases(paths, Path(tmp))

    placeholder_files = {str((REPO / p).resolve()) for p in placeholders if "::" not in p}
    placeholder_nodes = {str((REPO / p.split("::", 1)[0]).resolve()) + "::" + p.split("::", 1)[1]
                         for p in placeholders if "::" in p}
    counts = {"passed": 0, "failed": 0, "error": 0, "skipped": 0}
    forbidden: list[str] = []
    passed_ids: list[str] = []
    placeholder_hits = 0
    for case in cases:
        counts[case["status"]] += 1
        if case["status"] == "passed":
            passed_ids.append(case["node"])
        if case["status"] not in ("failed", "error"):
            continue
        cls = failure_class(case["message"])
        if cls not in forbid:
            continue
        case_file = resolve_case_file(case["file"], paths)
        node_abs = f"{case_file}::{case['node'].split('::', 1)[1]}"
        if node_abs in placeholder_nodes or str(case_file) in placeholder_files or is_placeholder_control(case_file):
            placeholder_hits += 1
            continue
        forbidden.append(f"{case['node']} - {case['message'].splitlines()[0] if case['message'] else ''}")

    print(f"passed={counts['passed']} failed={counts['failed']} errors={counts['error']} "
          f"skipped={counts['skipped']} crashes={len(crashes)} "
          f"placeholders_excluded={placeholder_hits} forbidden={len(forbidden)}")
    for line in forbidden:
        print(f"FORBIDDEN {line}")
    for node in crashes:
        print(f"CRASH {node}")
    for node in passed_ids:
        print(f"PASSED {node}")
    rc = 0
    if forbidden or crashes:
        print(f"RED CHECK FAILED: {len(forbidden)} test(s) red on a forbidden class "
              f"({', '.join(sorted(forbid))}) and {len(crashes)} crash(es)", file=sys.stderr)
        rc = 1
    if counts["passed"] > 0:
        print(f"RED CHECK FAILED: {counts['passed']} test(s) passed; every new test must fail or error",
              file=sys.stderr)
        rc = 1
    if rc == 0:
        print("RED CHECK OK: every collected test failed or errored, none on a forbidden class")
    return rc


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("paths", nargs="*")
    ap.add_argument("--forbid", help="comma-separated exception class names a red test may not fail on")
    ap.add_argument("--placeholder-list", help="file of test paths or node ids excluded from --forbid")
    ap.add_argument("--list-placeholders", nargs="+", metavar="DIR",
                    help="print the placeholder control files under DIR (marker-detected) and exit")
    args = ap.parse_args(argv)

    if args.list_placeholders:
        for f in list_placeholders(args.list_placeholders):
            print(f)
        return 0
    if not args.paths:
        print("usage: red_check.py [--forbid CLASSES] <test files/globs...>", file=sys.stderr)
        return 1
    if args.forbid:
        forbid = {c.strip() for c in args.forbid.split(",") if c.strip()}
        return run_forbid(args.paths, forbid, load_placeholder_list(args.placeholder_list))

    proc = subprocess.run(
        [python_bin(), "-m", "pytest", *args.paths, "-q", "--no-header"],
        cwd=str(REPO),
        capture_output=True,
        text=True,
    )
    output = proc.stdout + proc.stderr
    print(output)

    passed = len(re.findall(r"^(.+) PASSED", output, re.MULTILINE))
    if passed == 0:
        m = re.search(r"(\d+) passed", output)
        if m:
            passed = int(m.group(1))

    collected_nothing = "no tests ran" in output.lower() or "error in configuration" in output.lower()
    if collected_nothing and "collected 0 items" in output.lower():
        print("RED CHECK FAILED: nothing was collected", file=sys.stderr)
        return 1

    skipped = 0
    m_skip = re.search(r"(\d+) skipped", output)
    if m_skip:
        skipped = int(m_skip.group(1))
    ran = len(re.findall(r"(\d+) (?:failed|error)", output)) > 0
    if skipped > 0 and not ran:
        print(f"RED CHECK FAILED: {skipped} test(s) skipped and none ran; a skipped suite is not red "
              f"(run from tests/csim so conftest finds the library)", file=sys.stderr)
        return 1
    if passed > 0:
        print(f"RED CHECK FAILED: {passed} test(s) passed; every new test must fail or error", file=sys.stderr)
        return 1

    print("RED CHECK OK: every collected test failed or errored")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
